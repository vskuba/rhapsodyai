"""Оснастка браузерных тестов: живой Chromium и контейнер-браузер.

## ⚠⚠ Сами эти тесты не запускаются. Никогда

Папки **нет в `testpaths`**, и это не забывчивость. Живой браузер — источник
плавучести, с которым ничего не сделать изнутри теста:

* **выход в интернет.** `test_browser_pool_refresh` открывает страницу через
  контейнер-браузер, и запрос делает Chromium, а не наш процесс. Сторож сети его
  не видит и видеть не может: он стоит в процессе тестов;
* **общий пул вкладок.** У контейнера 25 мест на всех, и рядом работает человек.
  Прогон занимает места, а прерванный (Ctrl-C, SIGKILL) оставляет их занятыми —
  TTL у сессий нет вовсе;
* **гонки отрисовки.** Страница «обновилась без перезагрузки» — утверждение про
  время, а не про код: медленная машина, занятый пул, лишние полсекунды сети — и
  тест красный при исправном коде.

Плавающий тест в общем прогоне **хуже отсутствующего**: он приучает не смотреть
на красное. Поэтому гоняет их человек, явным путём и по своему решению:

    .venv/bin/python3 -m pytest tests_browser -q

⚠ Правишь страницу панели, мини-приложение Telegram или контейнер-браузер —
**предложи прогон и дождись ответа**. Предложение входит в работу; запуск без
ответа — нет. Подробности — `.claude/docs/testing_browser.md`.

## Что здесь лежит

| Файл | Что поднимает | Ходит наружу |
|---|---|---|
| `test_browser_pool_refresh.py` | Chromium + контейнер | **да**, пробная страница |
| `test_browser_site_open.py` | Chromium + контейнер | нет: свой сайт-закладка |
| `test_team_task_pages.py` | Chromium | нет: своя панель |
| `test_workflow_*.py` | Chromium | нет: своя панель |
| `test_telegram_app_task_*.py` | Chromium | нет: местная разметка |

⚠ Телеграмные рисуют местную разметку и в интернет не ходят вовсе. Они здесь по
второму признаку — **живой Chromium**: запуск браузера стоит секунд и роняется
сам по себе на занятой машине.

## ⚠ Чего здесь нет

Сторожа сети (`no_outside_http` в `tests/conftest.py`). Он здесь и не поможет:
единственный выход наружу делает контейнер, а не наш процесс. Запретить это можно
только сменив адрес пробной страницы на локальный — правкой теста, а не сторожа.
"""

import os
from contextlib import suppress

import httpx
import pytest

# Сайт, чьи вкладки открывает `test_browser_site_open`: кнопка «Открыть» берёт имя
# из закладки. Только их и подметаем — чужую мёртвую страницу мог оставить человек,
# и она его, а не наша.
BROWSER_TEST_SITE_NAME = 'Админка RhapsodyAi'


@pytest.fixture(scope='session', autouse=True)
def cleanup_browser_sessions():
    """Погасить страницы, забытые прерванным прогоном, — до и после сюиты.

    Фикстура теста убирает за собой сама, но убитый pytest (Ctrl-C, SIGKILL) хвост
    не выполняет. Проверено: сессия пережила SIGINT. У контейнера-браузера TTL нет
    вовсе — она живёт до явного DELETE или до его перезапуска, а пул общий и мал
    (25 мест). Переполни его — и работать перестанет уже не тест, а человек в
    админке.

    ⚠ **Гасим только мёртвые страницы своего сайта.** Признак — `chrome-error://`:
    переход не удался, показывать там нечего, и такая сессия никому не нужна. Живую
    не трогаем никогда: рядом работает человек, у него может быть открыта
    авторизованная страница под сценарий, и снести её значило бы отобрать работу.
    Сайт сверяем по `name`, чтобы не задеть чужие вкладки с той же бедой.

    ⚠ Контейнер не отвечает или порт не проброшен — молчим: браузерные тесты и так
    пропускаются, а ронять из-за уборки весь прогон незачем.

    ⚠⚠ Фикстура живёт **здесь**, а не в общем `tests/conftest.py`: она про
    контейнер-браузер, то есть про эту папку. В общей сюите она ходила бы к нему
    на каждом прогоне впустую — и вдобавок мимо сторожа сети, который там стоит.
    """
    def _sweep() -> None:
        with suppress(Exception):
            headers = ({'X-Browser-Token': os.getenv('BROWSER_API_TOKEN', '')}
                       if os.getenv('BROWSER_API_TOKEN', '') else {})
            base = os.getenv('BROWSER_TEST_URL', 'http://127.0.0.1:8014')

            response = httpx.get(f'{base}/browser/session', timeout=10.0,
                                 headers=headers)
            response.raise_for_status()

            for row in response.json().get('sessions') or []:
                if not str(row.get('url') or '').startswith('chrome-error://'):
                    continue
                if str(row.get('name') or '') != BROWSER_TEST_SITE_NAME:
                    continue
                with suppress(Exception):
                    httpx.delete(f"{base}/browser/session/{row['session_id']}",
                                 timeout=10.0, headers=headers)

    _sweep()
    yield
    _sweep()
