"""Чем «отвечает» модель на шагах `dating_mail_vars`. Только данные.

Массивы пар `[ключ ответа, значение]`; как они превращаются в сценарий подмены —
`tests_llm/plan.py`.

## ⚠⚠ Что проверяется

Занятие придумывает значения переменных письма по реестру сайта. Развилка одна и
важная: **не все значения пришли** (`vars_empty`) — заход уходит на круг и
просит недостающие, до трёх раз (`vars_try < 3`).

Живым прогоном это не поставить: заставить модель забыть ровно одну переменную
на первом круге и вспомнить на втором нельзя.

## ⚠⚠ Формат — JSON, и это не вкусовщина

Проверку делает `dict_fields_check`, и довод `data` у него — **словарь или
JSON-строка**. Здесь лежала строка вида «имя: значение» построчно, и разбиралась
она в пустой словарь: `filled_qty: 0`, `json: '{}'`.

Последствие было тихим и полным: **каждый** прогон `mail_vars` упирался в потолок
(«Значения» ×3 на прогон, 84 прохода на 28 прогонов), а удачный путь — «все
значения с первого раза» — не проверялся ни одним тестом. Тесты при этом были
зелёные: они смотрели на промпт и на конверт ответа, а не на число заходов.

⚠ Имена ключей обязаны совпадать с `VARS_NAMES` из `conftest.py`
(`girl_name,girl_city,girl_job`): их же шаг проверки и требует. Разойдись они —
вернётся та же тихая беда, только уже с другим ключом.
"""

# Значения всех переменных реестра — заход удаётся сразу.
VALUES_FULL = ('{"girl_name": "Zinaida", "girl_city": "Vardo", '
               '"girl_job": "lighthouse keeper"}')

# Не хватает одного значения — то, что ловит проверка.
#
# ⚠ Ключ на месте, но значение пустое: `dict_fields_check` считает незаполненным и
# отсутствующий ключ, и пустую строку. Пустое значение ближе к жизни — модель
# чаще возвращает ключ с прочерком, чем забывает его вовсе.
VALUES_PART = '{"girl_name": "Zinaida", "girl_city": "Vardo", "girl_job": ""}'


# ── Заготовка: все значения с первого раза ──────────────────────────────────

PLAN_OK = [
    ['values', {'values': VALUES_FULL}],
]


# ── Отличия: кладутся **перед** заготовкой ──────────────────────────────────

# Модель вернула не все значения — заход уходит на круг «Чего не хватает».
PLAN_PART = [
    ['values', {'values': VALUES_PART}],
]
