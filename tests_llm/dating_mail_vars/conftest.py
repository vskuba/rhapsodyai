"""Оснастка workflow `dating_mail_vars` — значения переменных писем у анкеты.

## Из чего он состоит

    Значения        llm_to_json → values
    Проверка        dict_fields_check → vars_json, vars_empty
    Попытка         counter_increment
    Чего не хватает собирает незаполненные и возвращает к сочинению
    Готово          %vars_json%

## ⚠⚠ Зачем он есть

Человек заводит на сайте имена переменных (`girl_name`, `girl_city`, …), а
значения нужны у **каждой** анкеты — по десятку полей на сорок учёток. Руками это
работа на день.

## ⚠⚠ Разбор ответа — в DatingAi, а не здесь

Движок соседа умеет `llm_to_json`, но тот требует **заранее известных ключей**:
они перечислены в метаданных шага. Здесь ключи знает только вызывающий — их
заводит человек, и у каждого сайта свои. Поэтому workflow отдаёт JSON, а сверяет
его с реестром DatingAi (`mail_agent._values`): выдуманное имя молча
отбрасывается.

Отсюда же главный предмет проверок этого файла: **заготовка ответа**
(`mail_vars_json`) уходит агенту с настоящими ключами. Прежде промпт давал пример
с выдуманными именами и надеялся, что модель переложит на них имена из списка, —
лишняя работа для неё и лишний повод ошибиться.

## ⚠ Пустое значение лучше выдуманного

Письмо с незаполненной переменной не уйдёт — и это правильный исход. Письмо с
выдуманным городом уйдёт живому человеку и будет выглядеть ровно тем, чем
является.
"""

import pytest

from tests_llm.datingai import CARD_GIRL
from tests_llm.conftest import LLM_SITE

# ⚠ Имя собирает DatingAi (`MAIL_AGENT_NAME`).
AGENT = f'mail_vars_{LLM_SITE}'

QUESTION = 'Заполни переменные писем по сведениям об анкете.'

# ── Приметы маршрута ────────────────────────────────────────────────────────

STEP_FILL = 'Значения'
STEP_CHECK = 'Проверка'
STEP_WHY = 'Чего не хватает'
STEP_OUT = 'Готово'

# ── Приметы промпта ─────────────────────────────────────────────────────────

HEAD_HINT = 'НЕ ЗАПОЛНЕНО:'

# Предел повторов — живёт в переходе шага «Чего не хватает» (`vars_try < 3`).
TRIES_MAX = 3

# Реестр сайта: имя, тире, подпись для модели. ⚠ Берутся только `profile`-поля —
# значение `companion`-переменной зависит от адресата, а анкета о нём ничего не
# знает.
VARS_TEXT = ('girl_name — имя девушки\n'
             'girl_city — город, где она живёт\n'
             'girl_job — чем она занимается')

VARS_NAMES = 'girl_name,girl_city,girl_job'

# ⚠⚠ Заготовка ответа с **настоящими** ключами: собирает её DatingAi
# (`_blank_json`), а не промпт. Ключи известны нам точно, и собрать их — одна
# строка; заставлять модель выводить их из списка значило бы платить за это
# ошибками.
VARS_JSON = '{"girl_name": "", "girl_city": "", "girl_job": ""}'


@pytest.fixture
async def fill(ask):
    """Попросить значения переменных. Возвращает `Talk` со всей трассой."""

    async def _fill(**over):
        return await ask(AGENT, QUESTION, {
            'girl_card': CARD_GIRL,
            'mail_vars': VARS_TEXT,
            'mail_vars_json': VARS_JSON,
            'mail_var_names': VARS_NAMES,
            'user_language': 'en',
            **over})

    return _fill
