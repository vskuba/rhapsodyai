# Шаг, сочиняющий реплику **в обычном заходе** — то есть ветка чата.
#
# ⚠ Не путать с `STEP_ANSWER`: тот отдаёт готовое наружу, а здесь собирается
# промпт — то, что вправду видит модель.
#
# ⚠⚠ Звался «Генерация ответа» и был один на все занятия; разбиение на ветки
# (`…_wf_talk_branches.sql`) переименовало его в «Ответ в чат», а письма и
# инициатива получили свои шаги. Примета с прежним именем не совпадала ни с чем,
# и тесты, смотрящие в промпт сочинения, падали на «промпт не прочитался» —
# причём все разом и без намёка на настоящую причину.
#
# ⚠ Письма и инициатива сюда **не** заходят: у них свои шаги, и промпт надо
# спрашивать у них (`STEP_MAIL_WRITE` и соседние).
STEP_MAKE = STEP_CHAT

