# ── Сценарий ответов модели ─────────────────────────────────────────────────
#
# ⚠⚠ **Один паттерн на все тесты этого workflow, и живёт он здесь.** Приметы и
# типовые ответы тянет к себе каждый новый тест — а разойдясь по файлам, они
# расходятся и по смыслу: у одного «тема разговора» ловится так, у другого иначе,
# и правка промпта чинится в пяти местах вместо одного.
#
# Правило простое: **приметы и заготовки — здесь, отличия — в тесте**.
#
#     await llm_answers(talk_plan(topic='photo_mail'))
#
# Приметы (`ASK_*`) — куски **промпта**, а не имена шагов: имени шага в запросе к
# модели нет вовсе.
#
# ⚠⚠ Примета — **имя ключа, который шаг просит вернуть**, вместе с кавычками. Это
# самый однозначный кусок промпта: слова вокруг переписывают при каждой правке
# формулировок, а имя ключа держит договор с движком и меняется вместе с ним.
#
# Поймано сразу: примета «тема разговора: photo_mail или usual» не совпала —
# промпт просит `- "talk_topic": "photo_mail" или "usual"`, с кавычками и без
# двоеточия в том месте, где я его написал.
#
# ⚠ Кавычка на конце обязательна: без неё `"girl_response` совпало бы и с
# `"girl_response_skip"` — то есть ответ ветки чата уехал бы судье.

ASK_ANALYSE = '"session_messages_result_processed"'
ASK_TOPIC = '"talk_topic"'
ASK_CHAT = '"girl_response"'
ASK_JUDGE = '"girl_response_skip"'

# Что «отвечает» разбор реплики, когда всё обычно: отвечать нужно, фактов нет.
#
# ⚠ `0` у фактов — не выдумка, а то, что просит сам промпт («Если явных фактов
# нет - 0»): подпрогон сохранения разбирает это значение по-настоящему, и строка
# вместо нуля роняет его с «не удалось распарсить как JSON-массив».
ANSWER_ANALYSE = {
    'session_messages_result_processed': '',
    'prompt_user_category': 'small talk',
    'prompt_user_tags': 'weather',
    'prompt_user_question': '0',
    'search_query': 'fake query',
    'prompt_user_facts_companion': '0',
    'prompt_user_facts_talk': '0',
    'prompt_user_ignore': '0',
}


def talk_plan(answer: str = 'hi there', skip: str = '0', topic: str = 'usual',
              ignore: str = '0', extra: list = None) -> list:
    """Сценарий ответов модели для обычного захода — с нужными отличиями.

    Args:
        answer: что «сочинила» модель в ветке чата.
        skip: решение судьи; `'1'` уводит на «Тишину».
        topic: тема разговора; `'photo_mail'` уводит в ветку письма-фото.
        ignore: решение разбора; `'1'` значит «отвечать не нужно».
        extra: правила поверх — для шагов, которых в обычном заходе нет
            (ветки письма, инициатива, судья подпрогона).

    Returns:
        Список пар `(примета, ответ)` для `llm_answers`.

    ⚠ Отличия — **доводами**, а не своим списком в каждом тесте: так видно, чем
    именно этот заход отличается от обычного, и правка промпта чинится здесь.
    """
    # ⚠ Судья **раньше** ветки чата: его промпт просит и `girl_response_fixed`, и
    # сервис берёт первое совпавшее правило. Поставь чат впереди — судья получил
    # бы ответ ветки и решал бы не своё.
    plan = [
        (ASK_ANALYSE, {**ANSWER_ANALYSE, 'prompt_user_ignore': str(ignore)}),
        (ASK_TOPIC, {'talk_topic': str(topic)}),
        (ASK_JUDGE, {'girl_response_skip': str(skip), 'girl_response_fixed': ''}),
        (ASK_CHAT, {'girl_response': str(answer)}),
    ]

    # ⚠ Свои правила идут **впереди**: сервис берёт первое совпавшее, и тест
    # обязан иметь возможность перебить заготовку, а не подстроиться под неё.
    return list(extra or []) + plan


# ── Переменные вызова: приметы и проверка ───────────────────────────────────
#
# ⚠⚠ **Один паттерн на все тесты передачи, и живёт он здесь.** Проверка «доехала
# ли переменная до промпта» нужна каждой ветке и каждому новому занятию, а
# написанная по месту она расходится: у одного теста примета такая, у другого
# другая, и правка промпта чинится в пяти файлах.
#
# Тест говорит **что и где** искать, а как — знает `marks_missing`.
#
#     got = await talk('Hi!', variables=marks_vars())
#     assert not marks_missing(got, STEP_CHAT, ('companion_bio',)), …
#
# ⚠ Приметы редкие и вместе не встречающиеся: увидев «Vardo» в промпте, тест
# знает, что туда попало **наше** значение, а не совпадение с чем-то из самого
# промпта. «Анна из Киева» такой уверенности не даёт.
MARKS = {
    'companion_bio': 'Occupation: lighthouse keeper in Vardo',
    'girl_bio': 'Hobby: restoring antique barometers',
    'girl_name': 'Zinaida-Test',
    'companion_title': 'Bartholomew-Test',
    'talk_history_chat': '[23.09 12:00] он: Как там маяк?',
    'talk_history_mail': '[22.09 10:15] она: Писала тебе про Карпаты',
    'mail_length': 'ровно два абзаца по 40-60 слов',
}

# Переменные, которые **не** несут приметы: их значение правит маршрут, а не
# текст. Подставь сюда примету — и заход ушёл бы не той веткой.
MARKS_SKIP = ('mail_mode', 'mail_kind', 'make_initiative', 'answer_anyway')


def marks_vars(**extra) -> dict:
    """Переменные вызова с приметными значениями — для проверки передачи.

    Args:
        extra: что добавить или перебить (флаги ветки, доли жребия).

    ⚠ Истории здесь же, хотя фикстура `talk` принимает их отдельными доводами:
    так весь набор примет лежит одним местом, и тест не выбирает, где что
    передать.
    """
    return {**MARKS, **extra}


def marks_missing(got, step: str, names: tuple) -> tuple:
    """Какие приметы не доехали до промпта шага. Пусто — все на месте.

    Args:
        got: результат прогона.
        step: шаг, чей промпт смотрим.
        names: имена переменных из `MARKS`.

    ⚠⚠ Смотрим **вход шага**, а не ответ модели: по ответу о входе судить
    нельзя. Живой пример — на «Занятие: lighthouse keeper» модель ответила «i
    bet you're good with lights»: данные дошли, а слова в ответе нет.
    """
    prompt = got.prompt_of(step)

    return tuple(name for name in names
                 if MARKS.get(name) and MARKS[name] not in prompt)
