    plan = [
        # ⚠ Ключи шага разбора спрашиваются у самого шага (`analyse_answer`), а
        # не перечисляются здесь: добавленная в него переменная иначе красит всю
        # сюиту сообщением про «обязательные ключи».
        (ASK_ANALYSE, analyse_answer(
            prompt_user_ignore=ignore,
            prompt_user_question=question,
            prompt_user_facts_companion=facts_man,
            prompt_user_facts_talk=facts_talk)),
        (ASK_TOPIC, {'talk_topic': str(topic)}),
        (ASK_JUDGE, {'girl_response_skip': str(skip), 'girl_response_fixed': ''}),
        (ASK_CHAT, {'girl_response': str(answer)}),
    ]

    # ⚠⚠ Правило подпрогона идёт **впереди** разбора: тот просит ключ
    # `prompt_user_facts_girl` своим же именем, и подмена берёт первое совпавшее
    # правило. Поставь его следом — подпрогон получил бы ответ разбора.
    if facts_girl:
        plan.insert(0, (ASK_INVENT, {'prompt_user_facts_girl': facts_girl}))

    # ⚠ Свои правила идут **впереди**: сервис берёт первое совпавшее, и тест
    # обязан иметь возможность перебить заготовку, а не подстроиться под неё.
    return list(extra or []) + plan


