"""Анкета девушки доезжает до промпта, когда фактов о ней не нашлось.

## Что здесь проверяется

То же, что у `companion_bio` (`test_dating_talk_bio.py`), но про неё саму — и с
одним отличием, из-за которого файл отдельный: **поисков фактов о девушке два**.

    по тегам реплики → нашлось? → берём их
                     ↘ нет → откат без тегов → нашлось? → берём их
                                             ↘ нет → берём анкету

Три ветки вместо двух, и каждая должна работать сама.

## ⚠⚠ ПРАВИЛО: утверждения — только по трассе

Ни один тест не смотрит на текст ответа. Всё берётся из трассы: маршрут, вывод
шага, промпт после подстановки. Правило и цена, которой оно куплено, —
`.claude/docs/testing_llm.md`.

## ⚠⚠ Почему у девушки нельзя просто «взять пустой ключ»

У собеседника изоляция проста: ключ случайный на каждый тест, документ заведомо
пуст. У девушки ключ **постоянный** (`LLM_GIRL_ID`), и факты в нём копятся: шаг
`girl_fact_invent` дописывает придуманное на каждом разговоре.

Значит «фактов нет» — состояние, которое тест не может себе обеспечить: первый
прогон их и создаст. Поэтому проверки устроены так, чтобы **не зависеть от
того, нашлось ли**: смотрим, какая из трёх веток сработала, и требуем от неё
верного поведения.

⚠ Тест, написанный как «фактов нет, значит анкета» — зеленел бы ровно один раз,
на чистом Qdrant, и краснел бы всегда потом. Самый неприятный вид плавучести:
виноватым выглядит код.
"""

import pytest

from tests_llm.mark import TEST_GIRL_ID, mark_key
from tests_llm.dating_talk.conftest import (STEP_FACTS_PLAIN, STEP_FACTS_TAGS,
                                            STEP_MAKE)

pytestmark = pytest.mark.llm_live

# ⚠ Ответ обязателен — иначе прогон вправе уйти в «Тишину», и проверять нечего.
ANYWAY = {'answer_anyway': '1'}

# Анкета в том же виде, в каком её кладёт DatingAi (`agent_bio`): связный рассказ
# от первого лица, по-английски. Разойдись вид здесь и там — тест проверял бы
# выдуманный формат.
GIRL_BIO = ('My name is Vera. I am 29 years old. I live in Lviv. '
            'I teach piano at a music school and bake bread on weekends.')

# Заголовок ветки анкеты в промпте.
BIO_HEAD = 'Твоя анкета на сайте знакомств'

# Заголовок ветки фактов — он один на обе «факты» ветки.
FACTS_HEAD = 'в базе данных'


@pytest.fixture
def stranger():
    """Собеседник свой на тест: его факты не должны мешать поиску по девушке."""
    return mark_key('girlbio')


class TestTheGirlBioReachesThePrompt:
    """⚠ Анкета доезжает — или не доезжает, смотря что нашёл поиск.

    Оба теста **не плавают**: промпт собирает код, а не модель. Плавает лишь то,
    какая ветка сработает, — и это учтено ветвлением в самих проверках.
    """

    async def test_one_of_the_three_branches_fires(self, talk, stranger):
        """⚠⚠ Главное: блок про девушку не исчезает молча.

        До этой правки он исчезал — условие стояло только на обычном поиске, а
        печатались оба. Нашлось по тегам — шаг обычного поиска пропускался, его
        переменная оставалась пустой, и блок скрывался **целиком**, хотя факты
        были найдены.

        То есть удачный поиск работал хуже неудачного. Тест сторожит именно это:
        что-то про девушку в промпте есть всегда — факты либо анкета.
        """
        got = await talk('Tell me about your weekends.',
                         variables={'companion_name': stranger,
                                    'girl_bio': GIRL_BIO, **ANYWAY})

        prompt = got.prompt_of(STEP_MAKE)

        assert prompt, f'промпт шага сочинения не прочитался.{got}'
        assert FACTS_HEAD in prompt or BIO_HEAD in prompt, \
            f'о девушке в промпте нет ничего — ни фактов, ни анкеты.{got}'

    async def test_facts_win_over_the_bio(self, talk, stranger):
        """⚠ Нашлись факты — анкета не подставляется.

        Два источника об одном человеке расходятся: в анкете «учу играть на
        фортепиано», а в фактах за месяц разговоров — что угодно ещё. Модель не
        знает, что свежее, и возьмёт удобное фразе.

        ⚠⚠ Проверка идёт **по тому, что вправду нашлось** (`output_of`), а не по
        предположению: состояние памяти девушки от прогона к прогону меняется, и
        тест, ждущий одной ветки, краснел бы через раз.
        """
        got = await talk('Tell me about your weekends.',
                         variables={'companion_name': stranger,
                                    'girl_bio': GIRL_BIO, **ANYWAY})

        prompt = got.prompt_of(STEP_MAKE)
        found = (got.output_of(STEP_FACTS_TAGS).strip()
                 or got.output_of(STEP_FACTS_PLAIN).strip())

        if found:
            assert BIO_HEAD not in prompt, \
                f'факты нашлись, а анкета всё равно подставлена.{got}'
            assert FACTS_HEAD in prompt, \
                f'факты нашлись, а в промпт не попали.{got}'
        else:
            assert BIO_HEAD in prompt, \
                f'фактов нет, а анкета не подставилась.{got}'
            assert GIRL_BIO[:24] in prompt, \
                f'заголовок анкеты есть, а самой анкеты нет.{got}'

    async def test_without_the_bio_the_block_is_absent(self, talk, stranger):
        """⚠ Не передали анкету — заголовка нет вовсе, а не пустой.

        Пустой заголовок «Твоя анкета ===» без строк под ним модель читает как
        факт «анкета пуста». Оттого внутри стоит второй `%if%`.

        ⚠⚠ Проверка условная и здесь: нашлись факты — ветка анкеты не при чём, и
        требовать от неё чего-либо бессмысленно.
        """
        got = await talk('Tell me about your weekends.',
                         variables={'companion_name': stranger, **ANYWAY})

        prompt = got.prompt_of(STEP_MAKE)

        assert prompt, f'промпт шага сочинения не прочитался.{got}'
        assert BIO_HEAD not in prompt, \
            f'заголовок анкеты в промпте, хотя анкету не передавали.{got}'


class TestTheGirlKeyIsTheTestOne:
    """⚠⚠ Сторож изоляции: факты уходят в тестовый документ, а не в рабочий.

    Шаг `girl_fact_invent` **дописывает** придуманное в документ девушки. Без
    своего ключа каждый прогон засорял бы память анкеты, которая пишет живым
    людям на сайте знакомств.

    ⚠ Здесь проверяется, что ключ **доходит до хранилища**, — для этого нужен
    прогон. Что сама метка помечена, проверяет `tests/test_llm_tests_guarded.py`:
    там она стоит без модели и потому идёт со всей сюитой.
    """

    async def test_the_key_reaches_the_fact_filter(self, talk, stranger):
        """Ключ доходит до фильтра поиска — то есть до самого хранилища."""
        got = await talk('Tell me about your weekends.',
                         variables={'companion_name': stranger, **ANYWAY})

        where = str(got.vars.get('fact_collection_girl_filter') or '')

        assert TEST_GIRL_ID in where, \
            f'в фильтре фактов девушки не тестовый ключ: {where}.{got}'
