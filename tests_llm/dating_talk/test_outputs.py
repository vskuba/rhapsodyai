def _topic_instruction(topic: str) -> str:
    """Инструкция темы по её коду. Пусто — темы в базе нет.

    ⚠ Спрашивается у базы, а не повторяется константой: текст инструкции
    человек правит на вкладке «Topic & Action», и копия здесь расходилась бы с
    ним на первой же правке — тест падал бы на верной работе.
    """
    from mysql_.mysql_query import mysql_query_run

    got = mysql_query_run(
        'SELECT instructions FROM agent_workflow_topic WHERE name = %s LIMIT 1',
        (topic,))
    rows = got.get('rows') or []

    return str((rows[0] if rows else {}).get('instructions') or '')


def _step_outputs(title: str):
    """Имена выходов шага темы по его заголовку. `None` — шага в базе нет."""
    import json

    from mysql_.mysql_query import mysql_query_run

    got = mysql_query_run(
        'SELECT s.metadata FROM agent_workflow_step s'
        '  JOIN agent_workflow w ON w.id = s.workflow_id'
        ' WHERE w.name = %s AND s.title = %s LIMIT 1',
        ('dating_talk', title))
    rows = got.get('rows') or []

    if not rows:
        return None

    return set((json.loads(rows[0]['metadata']).get('topic_action')
                or {}).get('outputs_map') or {})
