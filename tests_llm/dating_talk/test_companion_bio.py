"""Анкета собеседника доезжает до промпта, когда фактов о нём ещё нет.

## ⚠⚠ Что здесь проверяется

Что `companion_bio` **дошла до шага сочинения** — целиком, под своим заголовком
и ровно тогда, когда должна. Смотрим в промпт из трассы: там анкета лежит
дословно, и проверка не зависит от того, как модель распорядится прочитанным.

## ⚠⚠ ПРАВИЛО: утверждения — только по трассе

Здесь стояли ещё два теста — они задавали вопрос о факте из анкеты и искали
примету в ответе. Убраны, и вот чем это куплено.

Модель **пересказывает своими словами**. На `Занятие: lighthouse keeper` живой
ответ был «i bet you're good with lights»: анкета дошла, слова в ответе нет.
Тест объявлял поломку там, где всё работало.

Вопрос переписывался трижды — «угадай, кем я работаю», «назови мой город»,
прямой «кем я работаю» — и давал 1 из 5, 0 из 5, 0 из 5. Это лотерея, а не
проверка: зелёный в ней означает удачу.

Подробное правило и другие примеры — `.claude/docs/testing_llm.md`.

## ⚠ Что осталось непроверенным, и это честнее умолчания

Что модель анкетой **пользуется**. Живые прогоны показали, что чаще не
пользуется: отвечает «не знаю» или гадает. Это настоящая беда занятия, и чинится
она промптом — но стеречь её тестом нельзя, он будет плавать. Смотрят глазами по
трассе (`/admin/workflow_trace`).

## ⚠⚠ Собеседник у каждого прогона свой

Анкета подставляется **вместо** фактов, а факты о собеседнике копятся в Qdrant
от прогона к прогону: тот же шаг `companion_fact_extract` их туда и кладёт.
Возьми тест общего собеседника — на второй запуск факты о нём нашлись бы, ветка
анкеты не сработала, и тест краснел бы через раз «без причины».

Поэтому `companion_name` — свой на каждый вызов: документ с таким ключом пуст
по построению.

## Запуск — руками, путём к папке

    .venv/bin/python3 -m pytest tests_llm/dating_talk -q

⚠ Сами они не идут: папки нет в `testpaths`. Модель одна на тесты и на прод.
"""

import pathlib

import pytest

from tests_llm.conftest import LLM_COMPANION_TITLE
from tests_llm.mark import mark_key
from tests_llm.dating_talk.conftest import STEP_MAKE

pytestmark = pytest.mark.llm_live

# ⚠ Ремесло и город, которые вместе не встречаются в частых сюжетах. Модель,
# не получившая анкеты, не назовёт их: проверено вторым тестом пары.
BIO_CITY = 'Tórshavn'
BIO_COUNTRY = 'Faroe Islands'
BIO_JOB = 'lighthouse keeper'

# ⚠ Вид ровно тот, что кладёт DatingAi (`companion_bio.py`): подписи по-русски,
# значения — как на сайте знакомств. Разойдись вид здесь и там, тест проверял бы
# выдуманный формат.
#
# ⚠⚠ **Имя берём то же, каким агент зовёт собеседника.** Заголовок блока
# подставляет `companion_title` из карточки («Gerard»), и своё имя в анкете
# («Eirik») дало бы модели двух разных людей в одном абзаце — первый прогон так
# и вышел. В бою такого не бывает: имя в анкете и в заголовке приходят из одной
# карточки.
BIO = (f'Имя: {LLM_COMPANION_TITLE}\n'
       f'Возраст: 52\n'
       f'Живёт: {BIO_CITY}, {BIO_COUNTRY}\n'
       f'О себе: quiet life by the sea, raised two sons\n'
       f'Занятие: {BIO_JOB}\n'
       f'Образование: College')

# Приметы в **промпте**: там анкета лежит дословно, и искать надо точно.
PROMPT_MARKS = (BIO_CITY, BIO_COUNTRY, BIO_JOB)

# Вопрос один на оба теста: разные вопросы сравнивать нельзя. ⚠ Каким он будет,
# теперь **неважно** — утверждения смотрят в промпт, а он собирается до модели.
# Берём обычную реплику, чтобы разговор шёл своим чередом.
QUESTION = "Do you know what my job is?"

# ⚠⚠ **`answer_anyway` — в каждом вызове теста, и это не украшение.**
#
# Без него девушке разрешено промолчать на то, чего она не поняла, — и она этим
# пользуется: в замере два прогона из пяти возвращали пустую строку и уходили в
# шаг «Тишина». Тест при этом краснел, ничего не проверив: молчание — законный
# исход, а не поломка.
#
# Строкой `'1'`, а не `True`: у соседа `%if%` считает ложными пустое, `'0'` и
# отсутствие, а `True` превратился бы в `'True'` — то есть тоже в истину, но
# случайно. Тот же приём, что в бою (`answer.py`).
ANYWAY = {'answer_anyway': '1'}


@pytest.fixture
def stranger():
    """Собеседник, о котором фактов нет и быть не может: ключ свой на прогон."""
    return mark_key('bio')


class TestTheBioReachesThePrompt:
    """⚠⚠ Доказательство передачи — в **промпте**, а не в ответе.

    По ответу о входе судить нельзя: модель пересказывает своими словами. На
    «Занятие: lighthouse keeper» живой ответ был «i bet you're good with
    lights» — данные дошли, а искомого слова в ответе нет. Проверка «вошло ли»
    обязана смотреть на вход, иначе она проверяет красноречие.

    Эти два теста **не плавают**: промпт собирается кодом, а не моделью.
    """

    async def test_the_bio_lands_in_the_prompt(self, talk, stranger):
        """Анкета лежит в промпте шага сочинения — дословно и под своим
        заголовком."""
        got = await talk(QUESTION, variables={'companion_name': stranger,
                                              'companion_bio': BIO,
                                              **ANYWAY})

        prompt = got.prompt_of(STEP_MAKE)

        assert prompt, f'промпт шага «{STEP_MAKE}» не прочитался.{got}'

        for one in PROMPT_MARKS:
            assert one in prompt, (
                f'в промпте нет «{one}» — переменная не доехала либо ветка '
                f'`[<else>]` не сработала.{got}')

        # ⚠ И под своим заголовком: он отделяет «он написал это в профиле» от
        # «он сказал это мне». Без заголовка модель сочла бы анкету репликой.
        assert 'Анкета' in prompt and 'на сайте знакомств' in prompt, \
            f'анкета попала в промпт без своего заголовка.{got}'

    async def test_without_the_bio_the_block_is_absent(self, talk, stranger):
        """⚠ Не передали — блока нет вовсе, а не пустой заголовок.

        Пустой заголовок «Анкета … ===» без строк под ним модель читает как
        факт «анкета пуста». Оттого внутри стоит второй `%if%`.
        """
        got = await talk(QUESTION, variables={'companion_name': stranger,
                                              **ANYWAY})

        prompt = got.prompt_of(STEP_MAKE)

        assert prompt, f'промпт шага «{STEP_MAKE}» не прочитался.{got}'
        assert 'на сайте знакомств' not in prompt, \
            f'заголовок анкеты попал в промпт без самой анкеты.{got}'

        for one in PROMPT_MARKS:
            assert one not in prompt, \
                f'в промпте есть «{one}», хотя анкету не передавали.{got}'


class TestTheRuleItself:
    """⚠⚠ Сторож правила: ни один LLM-тест не смотрит на текст ответа.

    Правило легко нарушить по привычке — `got.text` лежит под рукой и читается
    естественно. А нарушение стоит дорого и не сразу видно: тест зеленеет на
    удачной формулировке и краснеет на другой, одинаково ничего не проверяя.

    ⚠ Этот тест **не ходит к модели** и денег не стоит: читает исходники папки.
    Оттого он и живёт здесь, среди дорогих, — его красное не требует прогона.
    """

    def test_no_llm_test_reads_the_answer_text(self):
        """`got.text` в утверждении запрещён.

        ⚠⚠ **Смотрим разобранный код, а не строки файла.** Первая проверка
        искала подстроку — и поймала три ложных: объяснение в докстринге, где
        `got.text` упомянут нарочно, и саму себя. Правило про **обращения в
        коде**, а комментарии и описания к коду не относятся: запретив их, мы
        запретили бы объяснять, почему так делать нельзя.
        """
        import ast
        import pathlib

        bad = []
        for path in sorted(pathlib.Path('tests_llm').glob('test_*.py')):
            tree = ast.parse(path.read_text(encoding='utf-8'))

            for node in ast.walk(tree):
                # `что-то.text` — обращение к полю. Строки и комментарии сюда не
                # попадают вовсе: разбор их не видит.
                if isinstance(node, ast.Attribute) and node.attr == 'text':
                    bad.append(f'{path.name}:{node.lineno}')

        assert not bad, ('тест смотрит на текст ответа — так нельзя '
                         '(`.claude/docs/testing_llm.md`): ' + ', '.join(bad))

    def test_every_step_marker_exists_in_the_workflow(self, workflow_steps):
        """⚠⚠ Приметы шагов сверяются с базой — иначе они тихо умирают.

        Имя шага живёт в двух местах: в админке и здесь. Переименуй шаг — и
        примета перестаёт совпадать ни с чем, а `prompt_of` возвращает пустоту.
        Тест падает на «промпт не прочитался», и настоящая причина в этих словах
        не названа.

        Так уже было: разбиение на ветки переименовало «Генерация ответа» в
        «Ответ в чат», и семь проверок в трёх файлах оказались красными разом —
        каждая жаловалась на промпт, ни одна на имя.

        ⚠ Этот тест **не ходит к модели**: одна ручка списка шагов. Оттого он и
        стоит первым в папке — его красное чинится без прогона дорогих соседей.
        """
        import re

        marks = dict(re.findall(
            r"^(STEP_[A-Z_]+) = '([^']+)'",
            (pathlib.Path(__file__).parent / 'conftest.py').read_text(
                encoding='utf-8'), re.M))
        dead = {name: value for name, value in marks.items()
                if value not in workflow_steps}

        assert not dead, (
            'приметы шагов не совпадают ни с одним шагом workflow — '
            'их переименовали в админке: '
            + ', '.join(f'{n} = «{v}»' for n, v in sorted(dead.items())))
