"""Чем «отвечает» модель на шагах инвайтов. Только данные.

Массивы пар `[ключ ответа, значение]` (третьим элементом — «сработать один раз»);
механика — `tests_llm/plan.py`.

## ⚠⚠ Что проверяется

`dating_invite_write` гонит цикл: на каждую реплику зовётся подпрогон
`dating_invite_one`, а в нём — жребий, черновик и судья. Развилку решает модель, и
дорог у неё две:

    invite_ok = yes    черновик годен → «Накопить», реплика уходит в пул
    invite_ok ≠ yes    брак → назад к «Жребию»: новый приём, новый черновик

⚠⚠ **Брак отправляет заход не вперёд, а назад.** Отдельного шага правки больше
нет (26.09.2026, `20260926120000_wf_invite_one_dice`): текст пишется заново — с
другим приёмом, выпавшим на новом броске.

⚠ Замечание судьи (`invite_why`) при этом сочинителю **показывают**: в его
промпте стоит блок «template draft that was prepared and declined by judge» с
самим черновиком и замечанием. Здесь прежде было написано обратное — правка
шаблона в админке опередила эту страницу (сверено с продом 05.10.2026).

Живым прогоном вторую дорогу не поставить: заставить судью забраковать конкретный
черновик нельзя, он решает сам. Здесь это строка массива.

⚠ Шаблон уходит **полусотне людей** без человеческого взгляда, и брак портит
весь пул — оттого судья и заведён, оттого же его обе дороги стерегутся.
"""

# Годный черновик: один абзац, без имён словами.
#
# ⚠ Имена ставятся **метками** (`[[companion_name]]`), а не текстом: шаблон один
# на пул, и вписанное имя уехало бы полусотне чужих людей.
DRAFT_GOOD = 'Hi [[companion_name]], your photo by the water made me smile.'

# Годный черновик для **второй** реплики цикла.
#
# ⚠⚠ Он нужен устройством цикла, а не разнообразия ради. Шаг «Проверка на
# вхождение» сверяет новый черновик с накопленным за заход
# (`text_substr(text=invite_done, substr=invite_draft)`) и при совпадении уводит
# заход **назад к жребию** — писать заново. Отдай подменная модель один текст на
# обе реплики, и этот возврат станет вечным: жребий → черновик → совпал →
# жребий, до предела шагов движка (300).
#
# ⚠ Так и было: шесть тестов цикла падали «агент не ответил за 2 попытки», и
# виноватым выглядел движок соседа. Проход с одной репликой при этом зеленел —
# близнецу там взяться негде, — и это сбивало со следа вернее всего.
DRAFT_GOOD_TOO = 'Hi [[companion_name]], your smile in that shot is unfair.'

# Черновик, который судья забракует. ⚠ Текст **другой**, и это не украшение: по
# нему тест отличает первый заход от второго и видит, что в пул уехал не он.
DRAFT_WEAK = 'Hi [[companion_name]], how are you doing today?'

# Чем плох забракованный черновик — словами судьи.
#
# ⚠ Уезжает в промпт второго захода: сочинитель видит и свой забракованный
# текст, и замечание к нему. Поэтому фраза внятная, а не «плохо».
WHY_WEAK = 'слишком похоже на шаблон'


# ── Заготовка: судья пропускает с первого раза ──────────────────────────────

# ⚠⚠ Черновик — **строка на реплику**, а не один ответ на все: сторож близнецов
# уводит повтор назад к жребию (см. `DRAFT_GOOD_TOO`). Первая помечена
# «однократно», последняя живёт весь прогон.
#
# ⚠ Отсюда предел: сценарий держит столько реплик, сколько здесь строк, — сейчас
# две, и это `TWICE` самого щедрого теста цикла. Попросишь три — третья получит
# текст второй, сторож увидит близнеца, и прогон оборвётся пределом шагов. Нужна
# третья реплика — нужна и третья строка.
PLAN_OK = [
    ['invite_draft', {'invite_draft': DRAFT_GOOD}, True],
    ['invite_draft', {'invite_draft': DRAFT_GOOD_TOO}],
    ['invite_ok', {'invite_ok': 'yes', 'invite_why': ''}],
]


# ── Отличия: кладутся **перед** заготовкой ──────────────────────────────────

# Судья забраковал первый черновик — заход возвращается к жребию и пишет второй.
#
# ⚠⚠ Оба правила помечены «однократно» (третий элемент), и без этого сценарий не
# работает вовсе. Примета правила — кусок промпта, а у двух проходов одного шага
# промпт **один и тот же**: вечное «нет» гоняло бы круг «жребий → черновик →
# судья» до предела шагов движка (300), и прогон обрывался бы вместо развилки.
#
# Сработав по разу, оба правила уходят, и второй круг достаётся заготовке: она
# даёт `DRAFT_GOOD` и вердикт `yes`.
PLAN_JUDGE_REFUSES = [
    ['invite_draft', {'invite_draft': DRAFT_WEAK}, True],
    ['invite_ok', {'invite_ok': 'no', 'invite_why': WHY_WEAK}, True],
]
