"""Что доезжает до промпта инвайта: жребий, доли, язык и время.

## ⚠⚠ Почему это отдельный предмет проверки

Разнообразие пула задаёт **не модель**: «будь разной» она не понимает — живой
прогон дал три шаблона из трёх, начинавшихся с «you're trouble». Выбирает кто-то
снаружи её, и с 26.09.2026 это **шаг жребия** (`dice` в `dating_invite_one`), а не
панель: она присылает лишь доли — проценты из настроек сайта.

Значит договор стал двухзвенным, и рвётся он молча в трёх местах:

* доля не доехала → жребий отказал бы («доля не число»), но с умолчанием молчит;
* жребий не положил переменную → в промпте пустая секция;
* условный блок не сработал → пустой заголовок, и модель читает его как факт.

⚠ Проверки здесь **не про сочинение**, а про подстановку: блок либо развернулся,
либо нет, и удача на это не влияет.

⚠⚠ **Доля 0 или 100 — не «крайний случай», а способ сделать жребий
предсказуемым.** Проверять подстановку на доле 10 значило бы гонять тест, который
краснеет один раз из десяти; поэтому здесь доли только нулевые и полные.
"""

import re

import pytest

from tests_llm.dating_invite_write.conftest import (STEP_DICE, STEP_DRAFT, STEP_JUDGE)

pytestmark = pytest.mark.llm

# Заголовок секции, в которой промпт перечисляет запрошенные метки.
HEAD_MARKS = '=== Метки в тексте ==='


def _marks_section(prompt: str) -> str:
    """Только секция меток — от её заголовка до следующего.

    ⚠ Нужна потому, что метки упоминаются в промпте **дважды и по-разному**: здесь
    их просят (по жребию), а ниже, в правилах, поясняют, что каждая означает — и
    то пояснение безусловно. Проверять по всему тексту значит путать эти два
    места.
    """
    at = prompt.find(HEAD_MARKS)
    if at < 0:
        return ''

    # ⚠ Режем по **пустой строке**, а не по следующему `===`: соседний заголовок
    # стоит внутри условного блока (`[<if invite_done>]=== …`), и в отрисованном
    # промпте его может не быть вовсе — тогда «до следующего ===» захватило бы
    # половину правил вместе с пояснением к меткам.
    return prompt[at + len(HEAD_MARKS):].split('\n\n', 1)[0]

# Что уже писали этому сайту. ⚠ Строка приметная: по ней видно, что в промпт
# попал именно наш список, а не совпадение.
AVOID = 'так уже было: «спорим, ты сейчас улыбнулся»'


class TestTheDiceReachThePrompt:
    """⚠⚠ Приём и длину бросает **шаг жребия**, и они обязаны быть видны модели.

    Прежде их присылала панель готовым значением, и тест проверял «что положили —
    то и показано». Теперь звено два: жребий выбирает вариант, промпт его
    подставляет. Проверяем оба — и что жребий сходил, и что выбранное доехало.
    """

    async def test_the_dice_step_runs(self, invite):
        """⚠ Шаг жребия обязан быть на маршруте: без него промпт получит пустые
        приём и длину, а модель выберет их сама — то самое «you're trouble»."""
        got = await invite()

        assert got.went_through(STEP_DICE), \
            f'жребий не брошен вовсе.{got}'

    async def test_the_angle_is_shown(self, invite):
        """⚠ Сверяем **с выпавшим**, а не с ожидаемым текстом: вариантов восемь, и
        какой выпадет — дело случая. Тест «приём из списка» краснел бы каждый
        восьмой раз, ничего не проверяя по существу."""
        got = await invite()
        angle = got.vars.get('dice_invite_angle')

        assert angle, f'жребий не положил приём.{got}'
        assert angle in got.prompt_of(STEP_DRAFT), \
            f'выпавший приём не доехал до промпта — модель выберет свой.{got}'

    async def test_the_length_is_shown(self, invite):
        got = await invite()
        length = got.vars.get('dice_invite_length')

        assert length, f'жребий не положил длину.{got}'
        assert length in got.prompt_of(STEP_DRAFT), \
            f'выпавшая длина не доехала до промпта.{got}'


class TestTheMarksAreOrdered:
    """⚠⚠ Метки имён просит **жребий**, а не решает модель.

    «Вставляй имя иногда» модель понимает как «вставляй всегда» — вероятность у неё
    не считается, она стилистическая. Поэтому в промпт уходит прямое указание, и
    собирают его два условных блока по выпавшему жребию.

    ⚠ Прежде указание присылала панель готовой фразой (`mail_agent._slots`) — одной
    на четыре сочетания. Стало двумя независимыми жребиями: у каждого своя доля из
    настройки сайта, и перемножать их не надо (`dice` этого и не умеет).
    """

    async def test_no_marks_asked_means_none_is_named(self, invite):
        """⚠ Обе доли нулевые — ни одна метка не выпала, и секция меток ни одной
        не называет.

        ⚠⚠ Что промпт вдобавок **говорит запрет прямо** («имён в тексте быть не
        должно вовсе»), сюита не утверждает: в шаблоне это предложение стоит
        безусловно, вне `%if%`, — то есть нашлось бы при любых долях, и проверка
        зеленела бы, ничего не проверив. Доли стережёт секция ниже.
        """
        got = await invite()
        prompt = got.prompt_of(STEP_DRAFT)

        # ⚠⚠ Смотрим **секцию меток**, а не весь промпт. Первая версия искала
        # `[[companion_name]]` в целом тексте и падала — правильно падала, но не на
        # том: метку упоминает ещё и пункт правил («[[companion_name]] — имя того,
        # кому пишешь»), и он стоит **всегда**, безусловно. Это не поломка, а
        # пояснение к метке; убрать его значило бы оставить модель без объяснения,
        # когда метку всё-таки просят.
        section = _marks_section(prompt)

        assert '[[companion_name]]' not in section, \
            f'метки не просили, а секция меток её называет.{got}'
        assert '[[girl_name]]' not in section, \
            f'своего имени не просили, а секция меток его называет.{got}'

    async def test_the_man_mark_is_asked_by_name(self, invite):
        """⚠ Метка названа **дословно**: выдуманная уедет человеку прямо в
        скобках, и панель её не подставит."""
        got = await invite(invite_name_percent='100')
        prompt = got.prompt_of(STEP_DRAFT)

        assert got.vars.get('dice_invite_man_name') == '1', \
            f'доля 100, а жребий имени не выпал.{got}'
        assert '[[companion_name]]' in prompt, \
            f'метка имени собеседника не названа в промпте.{got}'

    async def test_the_girl_mark_is_asked_by_name(self, invite):
        """⚠ Своё имя — **отдельный** жребий со своей долей, а не часть первого.

        Ради этого метки и разведены на две переменные: одна на сочетания
        требовала бы перемножения долей, чего инструмент не умеет.
        """
        got = await invite(invite_girl_name_percent='100')
        prompt = got.prompt_of(STEP_DRAFT)

        assert got.vars.get('dice_invite_girl_name') == '1', \
            f'доля 100, а жребий своего имени не выпал.{got}'
        assert '[[girl_name]]' in prompt, \
            f'метка имени девушки не названа в промпте.{got}'

    async def test_both_marks_can_come_together(self, invite):
        """⚠⚠ Оба жребия **независимы**: при полных долях выпадают вместе.

        Прежнее устройство (одна переменная на сочетания) этого не умело: доля
        «оба имени» была произведением, и в форме стояла нулём.
        """
        got = await invite(invite_name_percent='100',
                          invite_girl_name_percent='100')
        prompt = got.prompt_of(STEP_DRAFT)

        assert '[[companion_name]]' in prompt and '[[girl_name]]' in prompt, \
            f'полные доли, а вместе метки не выпали.{got}'

    async def test_the_judge_knows_what_was_asked(self, invite):
        """⚠⚠ Судья обязан знать, что просили, — иначе он не отличит пропущенную
        метку от той, которой не просили вовсе.

        ⚠ Блоки имён стоят в **трёх** промптах (черновик, судья, правка), и это
        цена разведения на две переменные. Пропусти любой — судья требовал бы
        метки, которых черновику не заказывали.
        """
        got = await invite(invite_name_percent='100')

        assert '[[companion_name]]' in got.prompt_of(STEP_JUDGE), \
            f'судья не знает, каких меток ждать.{got}'


class TestTimeAndPlaceAreGone:
    """⚠⚠ Времени и страны в инвайте больше нет — вместе с шагом часов.

    Довод, по которому время заводили, стоит знать: в пуле прода лежал шаблон «My
    thoughts have turned sideways **tonight**» — модель писала про вечер, не зная,
    который час, а перепутанное время суток выдаёт робота вернее любой другой
    приметы.

    ⚠ Но показывать время **всегда** оказалось хуже: она поминала его почти в
    каждой реплике — 94 из 202 за сутки. Меру искали долей, а 26.09.2026 решили
    убрать вовсе: ни секции в промпте, ни доли в жребии, ни шага
    `datetime_current_get`, ни часового пояса.

    ⚠⚠ Класс оставлен **сторожем обратного**: вернуть время «наполовину» нельзя.
    Нужны четыре вещи разом — шаг, пояс, доля и секция, — и любая одна без
    остальных ломает заход: без шага метка ссылается на пустоту, без пояса шаг
    считает не тот час, без доли жребий отказывает «доля не число».
    """

    async def test_the_clock_step_is_gone(self, invite):
        """⚠ Шага часов нет на маршруте: он считал время, которое никто не читает."""
        got = await invite()

        assert not got.went_through('datetime_current_get'), \
            f'шаг часов вернулся, а читать его некому.{got}'

    async def test_the_prompt_says_nothing_about_time(self, invite):
        """⚠ И в промпте ни секции времени, ни следа метки часов.

        ⚠⚠ Проверяется **метка**, а не заголовок секции: заголовок человек
        вправе переписать в админке, а метка ссылается на шаг, которого больше
        нет, — и такая ссылка не собралась бы вовсе, сторож меток остановил бы
        прогон.
        """
        prompt = (await invite()).prompt_of(STEP_DRAFT)

        assert 'datetime_current_get' not in prompt, \
            'в промпте осталась метка часов — она ссылается на удалённый шаг'

    async def test_no_marker_is_left_unsubstituted(self, invite):
        """⚠⚠ Ни одной неподставленной метки в промпте — вот чем стережётся
        «убранное не вернулось наполовину».

        Страну убрали тем же решением, что и время, но следа вроде шага часов она
        не оставила: сторожить её отсутствие было нечем, кроме заголовка секции,
        а заголовок — слово шаблона (см. `.claude/docs/testing_llm.md`).

        Эта проверка сильнее и не знает ни одного слова: верни в шаблон ссылку
        на переменную, которой больше нет, — и `%girl_country%` останется в
        собранном промпте текстом. Заодно ловит любую будущую опечатку в метке,
        а не только эти две.
        """
        prompt = (await invite()).prompt_of(STEP_DRAFT)
        left = re.findall(r'%[a-z][a-z0-9_]*%', prompt)

        assert not left, f'в промпте остались неподставленные метки: {left}'
