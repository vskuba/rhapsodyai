"""Признак тестовых данных: чем метим и как потом находим.

## ⚠⚠ Зачем отдельным модулем

Признак нужен двоим, и живут они в разных мирах: оснастке тестов (`conftest`) и
чистилке (`test_cleanup.py`), которая запускается руками и о pytest ничего не
знает.

Объявленный дважды, он бы разошёлся при первой же правке — причём молча: тесты
метили бы одним, уборка искала другое, и мусор копился бы «при работающей
уборке». Поэтому владелец один, а импортируют его оба.

⚠ Модуль **ничего не тянет** — ни pytest, ни httpx. Иначе чистилка, которой всё
это не нужно, платила бы за импорт при каждом запуске.

## ⚠⚠ Почему приставка именно `pytest_`

Потому что `test` едва не стоил рабочих данных. Первая версия уборки чистила по
нему и насчитала 225 переменных workflow к удалению: двести двадцать были
мусором прошлых прогонов, а **пять принадлежали настоящему** workflow
`workflow_shell_test` — `test_dialog`, `test_message`, `test_workflow_id`,
`test_iteration`, `test_iterations_limit`. Снеси их, и workflow перестал бы
собираться, а причину искали бы в промптах.

Спасло только то, что уборка по умолчанию ничего не удаляет: 225 строк из 480 не
бывают тестовыми, и это видно глазом.

Признак обязан быть таким, чтобы совпасть с рабочим **не мог**. У `pytest_` ноль
совпадений по всей базе — проверено запросом.
"""

import uuid

# Приставка всего, что заводят тесты: строк в MySQL, ключей документов в Qdrant.
TEST_MARK = 'pytest'

# Ключ девушки для LLM-тестов.
#
# ⚠⚠ Своё значение здесь — защита памяти рабочей анкеты. Факты о девушке лежат в
# Qdrant под `document_id = girl_id`, а шаг `girl_fact_invent` их **дописывает**:
# каждый прогон добавляет придуманное. Без подмены тесты писали бы прямо в
# документ агента, который отвечает живым людям на сайте знакомств.
#
# ⚠ Ключ **постоянный**, а не случайный на прогон: случайный оставлял бы новый
# документ после каждого запуска — сотню за месяц. Постоянный копит в одном, и
# приставка говорит, что это не человек.
TEST_GIRL_ID = f'{TEST_MARK}_llm_girl'


def mark_key(what: str) -> str:
    """Уникальный ключ тестовой записи: `pytest_<что>_<случайное>`.

    Args:
        what: о чём запись — `facts`, `bio`. Уходит в имя, чтобы по мусору было
            видно, какой тест его оставил.

    ⚠ Уникальность нужна **внутри** прогона: два теста не должны видеть данные
    друг друга. Приставка — **снаружи**: чтобы потом всё это найти и снести.

    ⚠⚠ Имя функции не начинается с `test`, хотя по смыслу просилось: pytest
    собирает всё такое как тесты и падает с «fixture 'what' not found». Поймано
    прогоном — в выдаче появился `ERROR ::test_key`.
    """
    return f'{TEST_MARK}_{what}_{uuid.uuid4().hex[:10]}'
