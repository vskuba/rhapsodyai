"""Анкета собеседника доезжает до ответа, когда фактов о нём ещё нет.

## ⚠⚠ Что здесь проверяется

Что `companion_bio` **дошла до промпта и была прочитана**. Проверяем это
единственным доступным способом — спрашиваем о том, что есть только в ней, и
смотрим, знает ли девушка ответ.

## ⚠⚠ Почему одного вопроса мало

Спроси мы «где я живу» с анкетой и получи в ответ «Reykjavik» — это ещё ничего
не доказывает: модель могла бы угадать, а могла бы взять город из истории
переписки или из имени. Поэтому тестов **два и они пара**:

* с анкетой — приметы в ответе быть **должно**;
* без анкеты, вопрос тот же — приметы быть **не должно**.

Второй и делает первый доказательством. Порознь они проверяют веру в модель.

## ⚠ Примета выбрана так, чтобы её нельзя было угадать

Не «Берлин» и не «инженер»: эти слова модель произносит сама, без всякой
анкеты, — и тест зеленел бы при выключенной передаче. Взяты редкое ремесло и
редкий город, вместе не встречающиеся ни в одном частом сюжете.

## ⚠⚠ Собеседник у каждого прогона свой

Анкета подставляется **вместо** фактов, а факты о собеседнике копятся в Qdrant
от прогона к прогону: тот же шаг `companion_fact_extract` их туда и кладёт.
Возьми тест общего собеседника — на второй запуск факты о нём нашлись бы, ветка
анкеты не сработала, и тест краснел бы через раз «без причины».

Поэтому `companion_name` — свой на каждый вызов: документ с таким ключом пуст
по построению.

## ⚠ Запуск — только руками

    .venv/bin/python3 -m pytest tests_llm/test_dating_talk_bio.py -v -s

Тесты плавающие: модель вправе ответить уклончиво. Красное — повод открыть
трассу (`/admin/workflow_trace`), а не перезапустить.
"""

import uuid

import pytest

from tests_llm.conftest import (LLM_COMPANION_TITLE, STEP_ANSWER, STEP_BRANCH,
                                STEP_MAKE)

pytestmark = pytest.mark.llm

# ⚠ Ремесло и город, которые вместе не встречаются в частых сюжетах. Модель,
# не получившая анкеты, не назовёт их: проверено вторым тестом пары.
BIO_CITY = 'Tórshavn'
BIO_COUNTRY = 'Faroe Islands'
BIO_JOB = 'lighthouse keeper'

# ⚠ Вид ровно тот, что кладёт DatingAi (`companion_bio.py`): подписи по-русски,
# значения — как на сайте знакомств. Разойдись вид здесь и там, тест проверял бы
# выдуманный формат.
#
# ⚠⚠ **Имя берём то же, каким агент зовёт собеседника.** Заголовок блока
# подставляет `companion_title` из карточки («Gerard»), и своё имя в анкете
# («Eirik») дало бы модели двух разных людей в одном абзаце — первый прогон так
# и вышел. В бою такого не бывает: имя в анкете и в заголовке приходят из одной
# карточки.
BIO = (f'Имя: {LLM_COMPANION_TITLE}\n'
       f'Возраст: 52\n'
       f'Живёт: {BIO_CITY}, {BIO_COUNTRY}\n'
       f'О себе: quiet life by the sea, raised two sons\n'
       f'Занятие: {BIO_JOB}\n'
       f'Образование: College')

# Приметы в **промпте**: там анкета лежит дословно, и искать надо точно.
PROMPT_MARKS = (BIO_CITY, BIO_COUNTRY, BIO_JOB)

# Приметы в **ответе** — смысловое поле, а не цитата. Девушка пересказывает
# своими словами: на «Занятие: lighthouse keeper» живой ответ был «i bet you're
# good with lights». Требовать точного слова значило бы требовать цитаты, а
# промпт учит её обратному — говорить коротко и по-человечески.
#
# ⚠ Что список не слишком широк, доказывает второй тест пары: без анкеты ни одна
# из этих примет в ответе не появляется.
ANSWER_MARKS = ('lighthouse', 'light', 'beacon', 'sea', 'ocean', 'coast',
                'torshavn', 'tórshavn', 'faroe')

# Вопрос один на оба теста: разные вопросы сравнивать нельзя.
#
# ⚠ Спрашиваем **не «помнишь ли ты»**: промпт прямо запрещает ссылаться на
# анкету словами «ты же говорил», и на такой вопрос честный ответ — «нет».
#
# ⚠⚠ И **не мнение**. Первая попытка звучала «не скучной ли тебе кажется моя
# жизнь в маленьком городке» — девушка ответила по существу («sounds peaceful,
# not boring»), но повода назвать город у неё не было, и тест краснел при
# работающем коде.
#
# ⚠⚠⚠ И **не «назови мой город»**. Такой вопрос требует процитировать анкету, а
# промпт прямо запрещает ссылаться на неё как на сказанное в разговоре — прогон
# ушёл в «Тишину», то есть девушка предпочла промолчать. Вопрос обязан
# укладываться в правила, которым её учат, иначе тест проверяет их нарушение.
#
# «Угадай, кем я работаю» — укладывается: она отвечает догадкой, и догадка эта
# берётся из анкеты.
QUESTION = ("Guess what I do for a living — I'll be impressed if you get it "
            "right on the first try.")


def _mark(text: str) -> str:
    """Какая примета анкеты нашлась в ответе. Пусто — ни одной."""
    low = str(text or '').lower()

    return next((one for one in ANSWER_MARKS if one in low), '')


@pytest.fixture
def stranger():
    """Собеседник, о котором фактов нет и быть не может: ключ свой на прогон."""
    return f'llm-bio-{uuid.uuid4().hex[:10]}'


class TestTheBioReachesThePrompt:
    """⚠⚠ Доказательство передачи — в **промпте**, а не в ответе.

    По ответу о входе судить нельзя: модель пересказывает своими словами. На
    «Занятие: lighthouse keeper» живой ответ был «i bet you're good with
    lights» — данные дошли, а искомого слова в ответе нет. Проверка «вошло ли»
    обязана смотреть на вход, иначе она проверяет красноречие.

    Эти два теста **не плавают**: промпт собирается кодом, а не моделью.
    """

    async def test_the_bio_lands_in_the_prompt(self, talk, stranger):
        """Анкета лежит в промпте шага сочинения — дословно и под своим
        заголовком."""
        got = await talk(QUESTION, variables={'companion_name': stranger,
                                              'companion_bio': BIO})

        prompt = got.prompt_of(STEP_MAKE)

        assert prompt, f'промпт шага «{STEP_MAKE}» не прочитался.{got}'

        for one in PROMPT_MARKS:
            assert one in prompt, (
                f'в промпте нет «{one}» — переменная не доехала либо ветка '
                f'`%else%` не сработала.{got}')

        # ⚠ И под своим заголовком: он отделяет «он написал это в профиле» от
        # «он сказал это мне». Без заголовка модель сочла бы анкету репликой.
        assert 'Анкета' in prompt and 'на сайте знакомств' in prompt, \
            f'анкета попала в промпт без своего заголовка.{got}'

    async def test_without_the_bio_the_block_is_absent(self, talk, stranger):
        """⚠ Не передали — блока нет вовсе, а не пустой заголовок.

        Пустой заголовок «Анкета … ===» без строк под ним модель читает как
        факт «анкета пуста». Оттого внутри стоит второй `%if%`.
        """
        got = await talk(QUESTION, variables={'companion_name': stranger})

        prompt = got.prompt_of(STEP_MAKE)

        assert prompt, f'промпт шага «{STEP_MAKE}» не прочитался.{got}'
        assert 'на сайте знакомств' not in prompt, \
            f'заголовок анкеты попал в промпт без самой анкеты.{got}'

        for one in PROMPT_MARKS:
            assert one not in prompt, \
                f'в промпте есть «{one}», хотя анкету не передавали.{got}'


class TestTheBioReachesTheAnswer:
    """⚠ Второе: анкету не только передали, но и прочитали.

    Здесь уже модель, и тесты плавающие: она вправе ответить уклончиво.
    Красное — повод посмотреть трассу, а не перезапустить.
    """

    async def test_a_fact_only_in_the_bio_comes_back(self, talk, stranger):
        """Девушка отвечает, зная то, чего ей никто не говорил в разговоре."""
        got = await talk(QUESTION, variables={'companion_name': stranger,
                                              'companion_bio': BIO})

        assert got.status == 'success', f'прогон не дошёл до конца.{got}'
        assert got.text.strip(), f'ответ пустой.{got}'
        assert STEP_ANSWER in got.route or STEP_BRANCH in got.route, \
            f'прогон не дошёл до ответа.{got}'

        assert _mark(got.text), (
            f'в ответе нет ни одной приметы анкеты — она не доехала до промпта '
            f'либо ветка `%else%` не сработала.{got}')

    async def test_without_the_bio_the_same_question_is_blank(self, talk,
                                                              stranger):
        """⚠⚠ Второй тест пары, и без него первый ничего не значит.

        Вопрос тот же, собеседник такой же безымянный, анкеты нет. Найдись
        примета и здесь — значит модель её придумала, и зелёный первый тест был
        бы совпадением, а не доказательством.

        ⚠ Это **контроль, а не проверка модели**: покраснев, он говорит «примета
        выбрана плохо, возьми более редкую», а не «код сломан».
        """
        got = await talk(QUESTION, variables={'companion_name': stranger})

        assert got.status == 'success', f'прогон не дошёл до конца.{got}'

        found = _mark(got.text)

        assert not found, (
            f'без анкеты модель сама назвала «{found}» — примета не годится в '
            f'доказательство, нужна реже.{got}')
