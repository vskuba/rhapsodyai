"""Как загружается сценарий ответов модели — механика, общая на все workflow.

## ⚠⚠ Три слоя, и смешивать их нельзя

    tests_llm/plan.py                ← этот файл: **как** устроено
    tests_llm/<workflow>/fixtures.py ← **чем** наполнено: массивы ответов
    tests_llm/<workflow>/conftest.py ← фикстуры pytest: что берётся по умолчанию
    tests_llm/<workflow>/test_*.py   ← только поток: позвал → проверил

Увидев в тесте примету шага, текст ответа или сборку сценария — перенеси в
`fixtures.py`. Увидев в `fixtures.py` логику — сюда.

Причина не в красоте. Промпты правят часто, и правка обязана чиниться **в одном
месте**: разложи ответы по тестам — и один и тот же ключ придётся искать в семи
файлах, а найдя, гадать, почему в двух из них он другой.

## ⚠ Фикстура — массив пар «ключ ответа, значение»

    PLAN_OK = [
        ['letter', {'letter': '…', 'letter_title': '…'}],
        ['letter_lang_ok', {'letter_lang_ok': '1'}],
    ]

Первый элемент — **имя ключа, который шаг просит вернуть**. По нему `plan_load`
и узнаёт шаг: имени шага в запросе к модели нет вовсе, движок его не шлёт.
"""


class Marks(dict):
    """Приметы переменных: имя → приметное значение.

    Наследник `dict`, и это удобство, а не выдумка: приметы одновременно
    **подставляют** в вызов (`marks.vars()`) и **ищут** в промпте
    (`marks.missing(...)`).

    ⚠⚠ Значения берут редкие и вместе не встречающиеся. Увидев «Vardo» в
    промпте, тест знает, что туда попало **наше** значение, а не совпадение с
    чем-то из самого промпта. «Анна из Киева» такой уверенности не даёт.
    """

    def vars(self, **extra) -> dict:
        """Переменные вызова: приметы плюс то, что нужно этому тесту.

        ⚠ `extra` побеждает: тест вправе перебить примету флагом ветки, ради
        которой он и написан.
        """
        return {**self, **extra}

    def missing(self, got, step: str, names=()) -> tuple:
        """Какие приметы не доехали до промпта шага. Пусто — все на месте.

        Args:
            got: результат прогона.
            step: шаг, чей промпт смотрим.
            names: что проверять; пусто — все приметы разом.

        ⚠⚠ Смотрим **вход шага**, а не ответ модели: по ответу о входе судить
        нельзя. Живой пример — на «Занятие: lighthouse keeper» модель ответила
        «i bet you're good with lights»: данные дошли, а слова в ответе нет.

        ⚠ Пустая примета (`''`) пропускается: так помечают переменную, которая
        в промпт не попадает по смыслу — флаг ветки, доля жребия.
        """
        prompt = got.prompt_of(step)
        want = tuple(names) or tuple(self)

        return tuple(name for name in want
                     if self.get(name) and self[name] not in prompt)


def plan_load(*plans) -> list:
    """Сценарий подмены из массивов фикстур.

    Args:
        plans: массивы `[[ключ, ответ], …]`. Первый побеждает.

    Returns:
        Список пар `(примета промпта, ответ)` для `llm_answers`.

    ⚠⚠ **Порядок значим: отличия идут первыми, заготовка последней.** Подмена
    берёт первое совпавшее правило, и `plan_load(PLAN_LANG_BAD, PLAN_OK)`
    читается как «всё обычное, кроме языка». Поменяй местами — заготовка
    победит, а тест позеленеет, ничего не проверив.
    """
    out = []

    for plan in plans:
        for key, answer in (plan or ()):
            out.append((_asked(key), answer))

    return out


def _asked(name: str) -> str:
    """Примета шага: имя ключа в том виде, в каком его просит промпт.

    ⚠⚠ Именно ключ, а не слова вокруг. Формулировки промпта переписывают при
    каждой правке, а имя ключа держит договор с движком и меняется вместе с ним.
    Поймано сразу: примета «тема разговора: photo_mail или usual» не совпала —
    промпт просит `- "talk_topic": "photo_mail" или "usual"`, с кавычками и без
    двоеточия там, где его ждали.

    ⚠ Кавычки с обеих сторон обязательны: без хвостовой `"girl_response` совпало
    бы и с `"girl_response_skip"`, то есть ответ ветки чата уехал бы судье.
    """
    return f'"{name}"'
