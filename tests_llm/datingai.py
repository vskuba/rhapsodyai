"""Что кладёт и чего ждёт DatingAi: копия его стороны договора.

## ⚠⚠ Зачем отдельным модулем

Все семь занятий зовёт один чужой модуль — `src/dating/mail_agent.py` в DatingAi.
Он собирает карточки участников, формулирует указание про метки и разбирает
ответ по трём приметам конверта. Для нас это **одно** знание: «как выглядит то,
что приезжает от соседа, и чего он ждёт обратно».

Разложи его по папкам workflow — и оно немедленно разъедется. Так и вышло до этой
правки: `ENVELOPE` и указания про метки стояли слово в слово в двух папках
(`dating_invite_write`, `dating_favorite_mail_write`), хотя источник у них один и
тот же `mail_agent`. Поправь метку в DatingAi — и чинить пришлось бы в двух
местах, а забыв одно, получить зелёный тест при сломанном разборе.

## ⚠ Это копия, а не источник

Держит договор **сосед**. Здесь повторено то, что он делает, — чтобы тесты
подставляли ровно тот вид, который разбирает боевой код. Разъедутся — тесты
станут проверять формат, которого нет: они подставят свой, workflow разберёт
свой, и всё будет зелено при сломанной работе.

⚠ Поэтому рядом с каждой величиной названо, **откуда** она: имя константы или
функции в `mail_agent.py`. Правка там обязана доехать сюда.
"""

