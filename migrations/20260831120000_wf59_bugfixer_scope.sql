-- Багфиксер: журнал по делу и каталог названный всегда (шаг 555, WF59).
--
-- Разбор по замечанию. Предыдущая миграция (`20260831110000`) выдала багфиксеру тот же
-- блок журнала, что у разработчика, — а роли устроены по-разному, и мерка не подошла.
--
-- **Хронология ему не нужна.** `.task-log.md` ценен там, где работа переходит из рук в
-- руки: QA читает, что делал разработчик, и наоборот. У багфиксера передачи нет —
-- один прогон, один ответ, кругов «не сошлось» у бага не бывает (`_run_bugfix`). Читать
-- хронологию собственных шагов внутри одной сессии незачем, а файл у живой строки
-- разрастается: у #5219 он дошёл до 120 КБ, и каждое чтение стоит токенов.
--
-- Что остаётся ценным — состояние. Повтор у бага всё-таки бывает, но по одной причине:
-- прогон сорвался, оболочка не ответила, Claude Code мёртв. Тогда её перезапускают, и
-- агент не помнит ничего — а в ветке уже могут лежать коммиты прошлой попытки. Об этом
-- и говорим: коротко, с упором на git, потому что он честнее любого файла.
--
-- **Каталог называем в обоих случаях.** Блок «работай в каталоге» стоял под
-- `%if task_work_dir%`, и когда выкладку создать не удалось (нет прав, занята ветка,
-- битый git — `_subtask_dir` возвращает пустую строку), промпт не говорил о каталоге
-- ничего вовсе. Агент правил бы код там, где стоит оболочка, то есть в общем чекауте
-- проекта — по живому мастеру. Так уже случалось: #4799 ушла коммитом прямо в master.
--
-- У QA и разработчика ветка `%else%` для этого случая есть, у багфиксера не было.
-- Теперь есть, и она предупреждает прямо: изоляции нет, ветку заводи сам, в master не
-- коммить.
--
-- Идемпотентность: каждое условие проверяет, что заменяемый текст ещё на месте.

-- 1. Журнал — короче и по существу роли.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '%if task_work_dir%=== СНАЧАЛА ПОСМОТРИ ЖУРНАЛ ===\\n'
        'Прогон мог оборваться по таймауту: оболочку тогда перезапускают, и ты не помнишь\\n'
        'ничего, — а работа и записи о ней остались в каталоге бага. Поэтому первым делом,\\n'
        'до чтения кода проекта:\\n'
        '  cat .task-state.md   — итог последнего круга и что уже лежит в ветке\\n'
        '  cat .task-log.md     — хронология по кругам, шаг за шагом\\n'
        '  git log master..HEAD и git status --porcelain — что из этого в коммитах\\n\\n'
        'Журнал ведётся сам, дописывать его не нужно. Файлов нет и коммитов нет — это\\n'
        'первый круг, разбирай с нуля.\\n\\n%endif%',
        '%if task_work_dir%=== ЭТОТ ПРОГОН МОЖЕТ БЫТЬ НЕ ПЕРВЫМ ===\\n'
        'Прошлый мог оборваться по таймауту: оболочку тогда перезапускают, и ты не помнишь\\n'
        'ничего, — а сделанное осталось в ветке. Прежде чем чинить, посмотри, что уже есть:\\n'
        '  git log master..HEAD и git status --porcelain — коммиты и незакоммиченное\\n'
        '  cat .task-state.md — итог прошлого круга, если он был\\n\\n'
        'Пусто — это первый круг, разбирай с нуля. Есть — доделывай начатое, а не начинай\\n'
        'заново.\\n\\n%endif%')
 WHERE `id` = 555
   AND `metadata` LIKE '%хронология по кругам, шаг за шагом%';

-- 2. Каталог: ветка `%else%` на случай, когда выкладки нет.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '%if task_work_dir%\\nРаботай в каталоге %task_work_dir% — это отдельная выкладка репозитория, ветка бага\\n'
        'в ней уже выкачена. Начни с перехода в этот каталог.\\n%endif%',
        '%if task_work_dir%\\nРаботай в каталоге %task_work_dir% — это отдельная выкладка репозитория, ветка бага\\n'
        'в ней уже выкачена. Начни с перехода в этот каталог.\\n'
        '%else%\\nОтдельную выкладку завести не удалось, и ты работаешь в общем каталоге проекта —\\n'
        'том самом, где сидит человек. Изоляции нет: в master не коммить, ветку под правку\\n'
        'заведи сам от origin/master и работай в ней.\\n%endif%')
 WHERE `id` = 555
   AND `metadata` LIKE '%Начни с перехода в этот каталог%'
   AND `metadata` NOT LIKE '%Отдельную выкладку завести не удалось%';
