-- Шаговые таймауты ролей: обрывать прогон должен потолок, а не шаг.
--
-- Разбор. Вчера подняли `timeout_developer_run` 7000 -> 14400, а прогоны продолжили
-- рваться. Последний обрыв #5219 назвал цифру прямо: «Агент developer не ответил за
-- 1200с». Не 14400 и не 4800 — тысяча двести. Рвал не потолок прогона, а таймаут
-- отдельного шага, зашитый в `tool_invoke.inputs_map.timeout` как `_const_1200`.
--
-- Потолок при таком раскладе не работал вовсе: до него дело не доходило, шаг умирал
-- раньше.
--
-- Улику видно в замерах (`project_task_metric`): максимум шага совпадает с его лимитом
-- до секунды. Так выглядит обрезанный шаг, а не медленный — «долгих» ходов ровно
-- столько, сколько разрешено, и ни одного дольше.
--
--   шаг                      лимит  среднее  максимум  дошли до лимита
--   Разработчик: реализация   4800     1225      4807    3 из 42
--   Разработчик: разбор       1200      507      1226    6 из 50
--   QA: прогон проверок       1800      909      1880    8 из 29
--   Ответ JSON: отчёт         1200      239      1207    2 из 39
--   Разработчик: самопроверка 1200      369      1240    1 из 30
--
-- У QA на разборе изменений (1300, максимум 1238) и на проверке цели (2200, максимум
-- 531) стены не было — их поднимаем за компанию, ради одного правила на все шаги, а
-- не по уликам.
--
-- Новые лимиты — от среднего с запасом, а не «побольше на всякий случай». Шаговый
-- таймаут нужен: он ловит зависшую оболочку, не дожидаясь конца прогона. Но стоять
-- он должен там, где заведомо кончилась работа, а не там, где она в разгаре.
--
--   разбор            1200 -> 2400   при среднем 507
--   реализация        4800 -> 7200   при среднем 1225
--   самопроверка      1200 -> 2400   при среднем 369
--   JSON-шаги         1200 -> 1800   при среднем 239 и 53
--   QA: разбор        1300 -> 2400   при среднем 444
--   QA: прогон        1800 -> 3600   при среднем 909
--   QA: проверка цели 2200 -> 2400   при среднем 147
--   QA: JSON и вердикт      -> 1800  при среднем до 100
--
-- Худший круг разработчика теперь 2400 + 7200 + 1800 + 2400 + 1800 = 15600с, что
-- **больше** потолка 14400. Так и задумано: отсекает прогон целиком тот, кто считает
-- круги доработки, а не отдельный шаг посередине работы.
--
-- Менеджер и багфиксер идут следом за компанию: лимиты у них те же `_const_1200`, а
-- замеров пока мало — но упереться в ту же стену они могут ровно так же, и чинить это
-- второй миграцией через неделю смысла нет.
--
-- Идемпотентность: каждое условие проверяет прежнее значение — повторный прогон уже
-- поднятые лимиты не тронет.

-- Разработчик (WF56): разбор и самопроверка.
UPDATE `agent_workflow_step` SET `metadata` = REPLACE(`metadata`, '_const_1200', '_const_2400')
 WHERE `id` IN (434, 440) AND `metadata` LIKE '%_const_1200%';

-- Разработчик: реализация — самый дорогой шаг конвейера.
UPDATE `agent_workflow_step` SET `metadata` = REPLACE(`metadata`, '_const_4800', '_const_7200')
 WHERE `id` = 436 AND `metadata` LIKE '%_const_4800%';

