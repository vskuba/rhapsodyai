-- Промпты Developer и QA разобрались обратно: кавычки в JSON (шаги 433, 445).
--
-- Авария, найденная по стоящему конвейеру. Миграции `20260830170000` и
-- `20260830171000` вставили в промпты пример команды с двойными кавычками:
--
--     grep -ril "<имя того, что трогал>" .claude/docs/
--
-- Колонка `metadata` — это JSON, и внутри строки такие кавычки обязаны быть
-- экранированы. Неэкранированные оборвали строку: `json.loads` перестал разбирать
-- шаг целиком, движок не собрал промпт и слал агенту пустоту. В журнале это выглядело
-- как «Разработчик не ответил. Ошибка: prompt пустой» — про кавычки ни слова.
--
-- Цена: пять подзадач исчерпали по три попытки и легли в `blocked`, их задачи ушли в
-- `failed`. Работы агент при этом не делал вовсе — ему нечего было читать.
--
-- Чиним заменой на кавычки-ёлочки: экранирования они не требуют, и следующая правка
-- этого текста не наступит на те же грабли. Отдельной миграцией, а не правкой тех
-- двух: они применены и записаны в `_yoyo_migration`.
--
-- Урок, который стоит дороже самой правки: после правки промпта надо проверять, что
-- колонка осталась разбираемой (`json.loads`), а не только что текст встал на место.
-- Глазами такое не видно — текст выглядит правильным.

UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(`metadata`,
        CONCAT('grep -ril ', CHAR(34), '<имя того, что трогал>', CHAR(34)),
        'grep -ril «имя того, что трогал»')
 WHERE `id` = 433;

UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(`metadata`,
        CONCAT('grep -ril ', CHAR(34), '<имя того, что трогали>', CHAR(34)),
        'grep -ril «имя того, что трогали»')
 WHERE `id` = 445;
