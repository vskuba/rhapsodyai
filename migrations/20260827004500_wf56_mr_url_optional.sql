-- Пустой merge request больше не обязателен: промпты разработчика (workflow #56).
--
-- Что было. Три промпта требовали непустой `mr_url`: «пустым не оставляй» в отчёте,
-- «merge request в master открыт» в формальных требованиях самопроверки и «без него
-- работа считается недоделанной» в реализации.
--
-- Почему это ломалось. Подзадача, работа которой уже лежит в `master` — её сделала
-- соседняя подзадача, прошлый круг или человек руками, — выполнить требование не
-- может: коммитить нечего, дифф пуст, merge request открывать не из чего. Разработчик
-- упирался в формальность и жёг круг за кругом: #2038 сделала так три раза подряд,
-- около 66 минут, каждый раз доходя до отчёта и спотыкаясь на одном и том же.
--
-- Что делаем. Во всех трёх местах разрешаем пустой `mr_url`, когда коммитить было
-- нечего, и требуем сказать об этом в отчёте. Приёмка от этого не слабеет: гейта на
-- `mr_url` в коде нет и не было — `task_pipeline.py` только записывает его в
-- `metadata`, и никто его не читает для проверки. Вердикт QA выносится по целям.
--
-- Чего не трогаем. Шаг 618 «Работы не было» (переход из 620 по `work_has == no`)
-- остаётся: он ловит другое — агента, который ответил, не приступив к работе, — и по
-- журналу `project_task_attempt` не срабатывал ни разу.
--
-- Идемпотентность. `REPLACE` ищет исходную формулировку: повторный прогон её уже не
-- найдёт и ничего не изменит.
--
-- Парная правка инструкций ролей — в том же коммите: `.claude/docs/role_developer.md`,
-- `role_qa.md`, `role_bugfixer.md`, `project_task.md`. Их читает сам агент, и
-- расхождение промпта с инструкцией он разрешит не в ту сторону.

-- ─── Промпт: реализация (id 435) ────────────────────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    'Работа не закончена, пока её негде посмотреть. Проверив себя, доведи её до merge request:',
    'Проверив себя, доведи работу до merge request:')
WHERE `id` = 435;
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    '4. Запомни полный адрес merge request: по нему человек смотрит работу со страницы\\n   задач, и без него работа считается недоделанной.',
    '4. Запомни полный адрес merge request: по нему человек смотрит работу со страницы\\n   задач.\\n\\nКоммитить нечего — тоже законный итог. Если работа подзадачи уже лежит в master (её\\nсделала соседняя подзадача, прошлый круг или человек руками), дифф пуст: не коммить\\nпустоту и не заводи пустой merge request. Оставь mr_url пустым и скажи в отчёте, что\\nпроверил и почему изменений нет. Принимают по целям, а не по ссылке.')
WHERE `id` = 435;

-- ─── Промпт: самопроверка (id 439) ──────────────────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    'адрес попал в отчёт полем mr_url; ничего лишнего',
    'адрес попал в отчёт полем mr_url — либо, если коммитить было нечего и работа уже в\\nmaster, ветка пуста и это прямо сказано в отчёте; ничего лишнего')
WHERE `id` = 439;

-- ─── Промпт JSON: отчёт (id 506) ────────────────────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    '- mr_url — полный адрес открытого merge request, пустым не оставляй.',
    '- mr_url — полный адрес открытого merge request. Оставь пустым, если коммитить было\\n  нечего и merge request не открывался: пустое значение приёмку не роняет.')
WHERE `id` = 506;
