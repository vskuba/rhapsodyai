-- Менеджер больше не заводит подзадачу-приёмку (workflow #55, шаг «Промпт: разбиение»).
--
-- Что было. План заканчивался подзадачей с `final: true` — «проверить результат
-- остальных», «убедиться, что всё сошлось». Конвейер придерживал её, пока соседи не
-- закроются, и только потом отдавал в работу.
--
-- Почему она не могла работать в принципе. Приёмка проверяет **сумму** работы соседей,
-- а суммы этой не существует ни в одном дереве. Ветка каждой подзадачи режется от
-- главной (`task_worktree_base_branch`), а вливает их в главную человек — кнопкой,
-- после того как конвейер закончил (`task_worktree_merge` из роутера, конвейер его не
-- зовёт никогда). Приёмка же запускается по состоянию соседей, то есть **до** слияния:
-- её собственное дерево — это главная ветка без единой их правки.
--
-- Она проверяла то, чего ещё нет, и любой её круг кончался «не сошлось» — сколько бы
-- их ни было. Наблюдалось на #1631: три круга подряд, каждый упирался в то, что работа
-- шести закрытых соседей лежит в невлитых ветках (21 коммит, ~60 файлов). У #2040 то же
-- самое: две цели из трёх закрылись только потому, что нужные ветки влили руками.
--
-- Что делаем. Приёмки в плане больше нет: результат задачи целиком принимает человек,
-- когда сливает ветки. Поле `final` остаётся в контракте разбиения, но всегда `false` —
-- убирать его из схемы ответа рискованнее, чем оставить с явным запретом.
--
-- Механику ожидания соседей (`task_metadata_final_wait_sql`) не трогаем: она страхует
-- планы, составленные до этой правки, и на планах без `final` просто не срабатывает.
--
-- Идемпотентность. `REPLACE` ищет исходные формулировки: повторный прогон их уже не
-- найдёт и ничего не изменит.

-- ─── До: строка, которую тронем ───────────────────────────────────────────────
SELECT `id`, `workflow_id`, `position`, `title`
FROM `agent_workflow_step`
WHERE `id` = 424;

-- ─── Промпт: разбиение ────────────────────────────────────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    '- Разбивать нужно — 2-7 подзадач в порядке выполнения, последняя проверяет результат.',
    '- Разбивать нужно — 2-7 подзадач в порядке выполнения. Отдельной подзадачи-приёмки\\n  в конце не заводи: результат целиком принимает человек при слиянии веток.')
WHERE `id` = 424;

UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    'Разведка нашла, что поведение уже реализовано и делать нечего? Тогда подзадача ровно\\nодна и она **приёмка** — `final: true`: подтвердить поведение доказательствами и\\nзакрыть задачу. Не заводи под это работающую подзадачу: менять ей нечего.',
    'Разведка нашла, что поведение уже реализовано и делать нечего? Так и напиши в плане\\nразбиения, а подзадач не заводи вовсе: работы нет, и придумывать её под видом «проверить\\nи подтвердить» значит гонять круг впустую.')
WHERE `id` = 424;

UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    'Поле final — true только у подзадачи, которая проверяет результат остальных\\n(приёмка, финальная сверка, «убедиться, что всё сошлось»). У работающих\\nподзадач — false. Такую подзадачу конвейер не возьмёт в работу, пока соседи\\nне закрыты: раньше проверять нечего, и она впустую потратит свои попытки.\\nПриёмка в плане либо одна, либо её нет вовсе.',
    'Поле final — **всегда false**. Оно осталось от подзадач-приёмок, которых больше не\\nзаводят: такая подзадача проверяла сумму работы остальных, а суммы этой не существует\\nни в одном дереве. Ветки подзадач режутся от главной и вливаются в неё человеком —\\nпосле того, как конвейер закончил. Приёмка запускалась раньше слияния и проверяла то,\\nчего ещё нет: любой её круг кончался «не сошлось», сколько бы их ни было.\\n\\nРезультат задачи целиком принимает человек, когда сливает ветки.')
WHERE `id` = 424;

-- ─── После: приёмки в промпте не осталось ─────────────────────────────────────
SELECT `id`,
       `metadata` LIKE '%final: true%'                    AS `still_asks_final`,
       `metadata` LIKE '%последняя проверяет результат%'  AS `still_asks_last`,
       `metadata` LIKE '%всегда false%'                   AS `has_ban`
FROM `agent_workflow_step`
WHERE `id` = 424;

-- Ожидаемо: still_asks_final = 0, still_asks_last = 0, has_ban = 1.
