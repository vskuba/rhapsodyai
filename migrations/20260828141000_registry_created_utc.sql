-- Хвост переезда реестра в UTC: колонка `created_at`.
--
-- Соседняя миграция (`20260828140000_registry_time_utc`) сдвинула `last_seen_at` и
-- `closed_at`, считая, что `created_at` уже в UTC — его-де заполняет база своим
-- `DEFAULT CURRENT_TIMESTAMP`. Это неверно: регистрация пишет колонку **явно**, тем же
-- временем приложения, что и остальные две. Причина в самом коде и названа —
-- «`DEFAULT CURRENT_TIMESTAMP` взял бы часовой пояс MySQL, и в одной строке
-- `created_at` и `last_seen_at` оказались бы в разных поясах». Умолчание схемы
-- остаётся, но до него дело не доходит.
--
-- То есть таблица была согласована внутри себя и сдвинута целиком относительно UTC.
-- Сдвинув две колонки из трёх, первая миграция ровно то расхождение и создала, от
-- которого предостерегал комментарий: у шестидесяти строк `last_seen_at` оказался
-- раньше `created_at` — сессия пинговала до того, как её завели.
--
-- Здесь третья колонка догоняет. После этого таблица снова согласована — и уже в UTC,
-- как требует `docs-common/datetime_rules.md`.
--
-- **Сдвигаем все строки без условия по дате.** Явная запись `created_at` появилась в
-- коммите `964060f` 2026-08-11 16:36, а самая ранняя строка реестра — 16:42 того же
-- дня, шестью минутами позже. Строк, чей `created_at` поставила бы база, в таблице
-- нет ни одной, и отделять их не от чего.
--
-- Смещение читается из настройки тем же выражением, что и в соседней миграции:
-- значения писались тем поясом, который в ней стоял. `COALESCE` вокруг всего
-- подзапроса, а не внутри: без строки настройки подзапрос даёт NULL, а
-- `INTERVAL NULL HOUR` обнулил бы колонку целиком.

UPDATE `ai_claude_session_registry`
   SET `created_at` = `created_at` - INTERVAL COALESCE((
           SELECT CAST(REPLACE(REPLACE(value, 'UTC', ''), ' ', '') AS SIGNED)
             FROM `setting`
            WHERE `key` = 'timezone' AND user_id IS NULL AND node_id IS NULL
            LIMIT 1), 0) HOUR
 WHERE `created_at` IS NOT NULL;
