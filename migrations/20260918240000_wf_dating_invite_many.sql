-- `dating_invite_write`: текстов столько, сколько девушек в сети (2026-09-18)
--
-- ЧТО БЫЛО. Агент присылал ОДИН шаблон, и весь пул уходил от него: дюжина наших
-- анкет писала разным людям слово в слово одно и то же. Со стороны сайта это
-- примета агентства вернее любой другой — разные девушки, одна реплика, одна
-- минута.
--
-- Лечили это тем, что заход шёл от одной анкеты. Помогало, но упирало пул в одну
-- девушку за раз: остальные ждали следующего круга.
--
-- ЧТО СТАЛО. Панель говорит, сколько текстов ей нужно (`invite_count` — по числу
-- девушек в сети), и получает их **в одном вызове**. Дюжина вызовов вернула бы
-- цену, ради ухода от которой шаблон и заводили; дюжина текстов в одном вызове
-- стоит одного.
--
-- ⚠⚠ СУДЬЯ ТЕПЕРЬ СВЕРЯЕТ ТЕКСТЫ МЕЖДУ СОБОЙ. Это главное в правке, и без него
-- она бессмысленна: попроси модель «напиши двенадцать разных реплик» — получишь
-- двенадцать вариантов одной мысли. Проверено на этом же workflow трижды: «будь
-- разной» она понимает как «пиши похоже» (три шаблона из трёх начинались с
-- «you're trouble»).
--
-- Поэтому у судьи появилось правило: тексты, похожие ДРУГ НА ДРУГА — тот же заход,
-- тот же образ, те же ключевые слова, — это брак, и он идёт на правку целиком.
--
-- ⚠ ФОРМА ОТВЕТА. Тексты разделены строкой `---`. Не JSON-массивом: конверт
-- `VERDICT/WHY/TEXT` уже есть, и второй способ сказать «несколько» означал бы два
-- разборщика. Разделитель — строка целиком, потому что «—» внутри реплики
-- встречается постоянно.
--
-- ⚠ Просили один — отвечает одним текстом, без разделителей. Панель разбирает оба
-- вида (`mail_agent._invites`), и старый ответ остаётся законным.
--
-- Идемпотентность: промпты переписываются целиком, переменная заводится по
-- условию отсутствия.

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_invite_write');

SELECT 'ДО' AS этап, @wf AS workflow,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%invite_count%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 1) AS правка_есть;

-- ---------------------------------------------------------------- Переменная
INSERT INTO `agent_workflow_variable` (`name`, `type`, `description`)
SELECT 'invite_count', 'workflow',
       'Сколько разных реплик просим за раз — по числу девушек в сети. Считает DatingAi'
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow_variable` WHERE `name` = 'invite_count');

INSERT INTO `agent_workflow_variable_workflow` (`variable_id`, `workflow_id`)
SELECT v.`id`, @wf FROM `agent_workflow_variable` v
 WHERE v.`name` = 'invite_count'
   AND NOT EXISTS (SELECT 1 FROM `agent_workflow_variable_workflow` vw
                    WHERE vw.`variable_id` = v.`id` AND vw.`workflow_id` = @wf);

-- ------------------------------------------- Черновик: просим несколько текстов
--
-- ⚠ Правка точечная, заменой двух мест: в промпте живут секции приёма, длины,
-- времени, страны и списка «так уже было», заведённые соседними миграциями.
-- Перепиши мы его целиком — порядок применения решал бы, чей текст останется.
UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(
         `metadata`, '$.prompt_user',
         REPLACE(
           REPLACE(JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')),
                   CONCAT('Ты — девушка на сайте знакомств, пишешь первой мужчине, ',
                          'с которым ещё не знакома. Придумай ШАБЛОН такой первой ',
                          'реплики. Один и тот же текст уйдёт разным мужчинам — ',
                          'каждому по разу, друг друга они не видят.'),
                   CONCAT('Ты — девушка на сайте знакомств, пишешь первой мужчине, ',
                          'с которым ещё не знакома. Придумай ШАБЛОНЫ таких первых ',
                          'реплик — ровно %invite_count% штук.\n\n',
                          '⚠⚠ ГЛАВНОЕ: эти реплики должны быть РАЗНЫМИ МЕЖДУ СОБОЙ. ',
                          'Не вариантами одной мысли разными словами, а разными ',
                          'заходами: одна дразнит, другая признаётся, третья ',
                          'спрашивает, четвёртая предлагает игру. Разное начало, ',
                          'разный образ, разная длина внутри заданной вилки.\n\n',
                          'Каждая реплика уйдёт от СВОЕЙ девушки — их столько же, ',
                          'сколько текстов. Напиши две похожие, и два разных ',
                          'человека получат почти одно и то же в одну минуту: так ',
                          'выдаёт себя агентство, и это худшее, что может случиться ',
                          'с этими репликами.\n\n',
                          'Один текст уйдёт разным мужчинам — каждому по разу, друг ',
                          'друга они не видят.')),
           CONCAT('Верни строго JSON с одним ключом:\n',
                  '- "invite_draft": сам текст шаблона, одной строкой, без кавычек ',
                  'вокруг и без пояснений'),
           CONCAT('Верни строго JSON с одним ключом:\n',
                  '- "invite_draft": все %invite_count% реплик, разделённые строкой ',
                  'из трёх дефисов (---) на отдельной строке. Никаких номеров, ',
                  'заголовков, кавычек вокруг и пояснений — только сами тексты.\n\n',
                  '⚠ Разделитель — строка «---» целиком, отдельной строкой. Тире ',
                  'внутри реплики («скажи — ты из тех, кто…») разделителем не ',
                  'считается.')))
 WHERE `workflow_id` = @wf AND `position` = 1;

-- ------------------------------------------- Судья: похожие между собой — брак
UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(
         `metadata`, '$.prompt_user',
         REPLACE(
           REPLACE(JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')),
                   CONCAT('Ты — редактор. Проверь, годится ли этот текст как ПЕРВАЯ ',
                          'реплика девушки мужчине в чате сайта знакомств. Он уйдёт ',
                          'полусотне живых людей без правки, поэтому суди строго.'),
                   CONCAT('Ты — редактор. Перед тобой реплики девушек мужчинам в ',
                          'чате сайта знакомств — их может быть несколько, ',
                          'разделённых строкой «---». Каждая уйдёт от своей девушки ',
                          'десяткам живых людей без правки, поэтому суди строго.\n\n',
                          '⚠⚠ ПЕРВЫМ ДЕЛОМ сверь реплики МЕЖДУ СОБОЙ. Если две из ',
                          'них похожи — тот же заход, тот же образ, те же ключевые ',
                          'слова, одна мысль другими словами, — это брак (no). Их ',
                          'пишут разные девушки в одну минуту, и два человека ',
                          'получат почти одинаковое сообщение: так выдаёт себя ',
                          'агентство.\n\n',
                          'Дальше проверь каждую по отдельности.')),
           CONCAT('Забракуй (no), если верно ХОТЬ ОДНО:\n'),
           CONCAT('Забракуй (no), если верно ХОТЬ ОДНО — хотя бы для одной из ',
                  'реплик:\n',
                  '0. Две реплики похожи друг на друга (см. выше). Это самая частая ',
                  'и самая дорогая ошибка здесь.\n')))
 WHERE `workflow_id` = @wf AND `position` = 2;

-- ------------------------------------------- Правка: сохранить число и разность
UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(
         `metadata`, '$.prompt_user',
         REPLACE(JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')),
                 CONCAT('Требования те же: одна реплика в чат, один абзац, игривый ',
                        'дразнящий тон'),
                 CONCAT('Требования те же: ровно %invite_count% реплик, разделённых ',
                        'строкой «---», РАЗНЫХ между собой (разный заход, разный ',
                        'образ, разные слова), по одному абзацу каждая, игривый ',
                        'дразнящий тон')))
 WHERE `workflow_id` = @wf AND `position` = 3;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%invite_count%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 1) AS число_у_черновика,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%РАЗНЫМИ МЕЖДУ СОБОЙ%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 1) AS требование_разности,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%сверь реплики МЕЖДУ СОБОЙ%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 2) AS сверка_у_судьи,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%invite_count%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 3) AS число_у_правки,
       (SELECT COUNT(*) FROM `agent_workflow_variable_workflow`
         WHERE `workflow_id` = @wf) AS переменных;
