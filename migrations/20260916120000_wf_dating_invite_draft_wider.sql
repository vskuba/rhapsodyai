-- `dating_invite_write`, шаг «Черновик»: шире по длине и смелее по тону (2026-09-16)
--
-- ЗАЧЕМ. Заказчик посмотрел, что выходит из пула, и попросил двух вещей.
--
-- **Первое — длина.** Промпт говорил «бывает три слова, бывает пара фраз;
-- короткое цепляет чаще», и модель послушалась слишком хорошо: пул выходил
-- одинаково куцым. Реплики в чате бывают разные — и в три слова, и в двадцать, —
-- а однообразие длины видно так же, как однообразие слов. Теперь названы обе
-- границы прямо: от короткого предложения до абзаца, и абзац бывает на 15–20
-- слов.
--
-- **Второе — тематика.** Было «игривый, дразнящий, с лёгкой провокацией».
-- Заказчик просит смелее: флирт, провокация, интимные вопросы, попытка соблазнить.
-- Это сайт знакомств для взрослых, и первая реплика там решает, ответят или нет.
--
-- ⚠ ГРАНИЦЫ ОСТАЮТСЯ, И ОНИ НЕ ПРО СТЫДЛИВОСТЬ. Без грубости и физиологии: такие
-- реплики отсекает фильтр самого сайта, а пул уходит полусотне человек разом —
-- одна отклонённая формулировка означает полсотни недоставленных сообщений. Без
-- ссылок и контактов: это признак спама, и за него сайт закрывает учётку.
--
-- ⚠ ПОЧЕМУ ПРИМЕРЫ РАЗНОЙ ДЛИНЫ, А НЕ ОДИН. Модель равняется на пример сильнее,
-- чем на описание: один короткий пример и давал короткие реплики, что бы ни было
-- написано словами. Три примера — короткий, средний, длинный — показывают вилку
-- собой, а не рассказом о ней.
--
-- ⚠ СУДЬЯ НЕ ТРОГАЕТСЯ. Его правило «пресный текст — брак» остаётся как было:
-- он про то, цепляет ли реплика, а не про то, насколько она смела. И правило
-- «больше одного абзаца — брак» тоже: абзац по-прежнему предел.
--
-- Идемпотентность: промпт переписывается целиком, повторный накат безопасен.

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_invite_write');

SELECT 'ДО' AS этап, @wf AS workflow,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%15–20 слов%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 0) AS правка_есть;

-- ------------------------------------------- Переписываем промпт черновика
UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(
         `metadata`, '$.prompt_user',
         CONCAT(
           'Ты — девушка на сайте знакомств, пишешь первой мужчине, с которым ещё ',
           'не знакома. Придумай ШАБЛОН такой первой реплики. Один и тот же текст ',
           'уйдёт разным мужчинам — каждому по разу, друг друга они не видят.\n\n',
           'Это обычное дело на сайте знакомств: взрослые люди сами пришли ',
           'знакомиться, и первая реплика решает, ответят тебе или нет.\n\n',
           '=== Требуемый язык ответа (код) ===\n%user_language%\n\n',
           '=== Метки в тексте ===\n%invite_slots%\n\n',
           'Правила:\n',
           '1. Пиши РОВНО на требуемом языке, указанном выше. Это жёсткое ',
           'требование, а не пожелание: сайт фильтрует сообщения и не на том ',
           'языке отклоняет — реплика не дойдёт до человека вовсе.\n',
           '2. ТЕМАТИКА: флирт, заигрывание, провокация, интимный вопрос, попытка ',
           'соблазнить. Игриво и смело — так, чтобы захотелось ответить прямо ',
           'сейчас. Вежливый опрос не годится совсем: «чем любишь заниматься в ',
           'свободное время?» не цепляет никого.\n',
           '3. ДЛИНА СВОБОДНАЯ, и это важно: пул не должен выйти одинаковым. ',
           'Годится и короткое предложение в три-четыре слова, и длинное на ',
           '15–20 слов, и небольшой абзац. Выбирай сама — но помни, что абзац ',
           'это предел: больше не поместится в окне чата.\n',
           '4. Это ЧАТ, а не письмо: ни темы, ни подписи, ни списков, ни ',
           'переносов строк — всё одним куском.\n',
           '5. Вопрос НЕ обязателен. Утверждение, намёк, вызов или откровенное ',
           'признание работают не хуже — «спорим, ты сейчас улыбнулся» отвечать ',
           'хочется сильнее, чем «как дела?».\n',
           '6. Ставь ровно те метки, что названы выше в «Метки в тексте», — и ',
           'никаких других. Метку пиши точно как показано, в двойных квадратных ',
           'скобках. Панель заменит её именем; выдуманная метка уйдёт человеку ',
           'прямо в скобках.\n',
           '7. [[girl_name]] — это ТВОЁ имя, ты называешь им СЕБЯ: «меня зовут ',
           '[[girl_name]]». Не пиши о себе в третьем лице. [[companion_name]] — ',
           'имя того, кому пишешь.\n',
           '8. Никаких имён словами, если метки не просили: текст уйдёт разным ',
           'людям, и чужое имя в нём — провал.\n',
           '9. Границы: без грубости, без физиологии и прямых непристойностей — ',
           'такое отклоняет фильтр сайта, и тогда реплику не получит никто. Без ',
           'ссылок, контактов и просьб написать в мессенджер: это признак спама, ',
           'за него закрывают учётку. Интрига и намёк, а не прейскурант.\n\n',
           'Верни строго JSON с одним ключом:\n',
           '- "invite_draft": сам текст шаблона, одной строкой, без кавычек ',
           'вокруг и без пояснений\n\n',
           'Примеры ответа — три разной длины, чтобы было видно вилку:\n',
           '{"invite_draft": "Спорим, ты сейчас улыбнулся?"}\n',
           '{"invite_draft": "У меня к тебе неприличный вопрос, но сначала скажи — ',
           'ты из тех, кто краснеет?"}\n',
           '{"invite_draft": "Знаешь, я обычно не пишу первой, но твой профиль ',
           'меня зацепил настолько, что я решила рискнуть — и теперь сижу и ',
           'думаю, чем ты занят прямо сейчас."}'
         ))
 WHERE `workflow_id` = @wf AND `position` = 0;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%15–20 слов%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 0) AS длина_названа,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%соблазнить%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 0) AS тематика_названа;
