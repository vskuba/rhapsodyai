-- Метки реестра сессий переезжают в UTC — таблица `ai_claude_session_registry`.
--
-- Зачем. Правило проекта одно: хранение в UTC, показ в поясе настройки `timezone`
-- (`docs-common/datetime_rules.md`). Реестр его нарушал наполовину: `created_at`
-- заполняется базой (`DEFAULT CURRENT_TIMESTAMP`, то есть UTC), а `last_seen_at` и
-- `closed_at` писало приложение через `datetime_now()` — время в поясе настройки. При
-- `timezone = '+3'` две колонки одной строки расходились на три часа.
--
-- Работу это не ломало: свежесть пинга считается в Python, и обе стороны сравнения
-- брали время из одного источника. Ломало разбор. Любой запрос, сверяющий
-- `last_seen_at` с `NOW()` или `UTC_TIMESTAMP()`, давал ложный ответ: живые сессии
-- выглядели пришедшими из будущего (возраст пинга отрицательный), а мёртвые —
-- свежими. На этом уже споткнулись при разборе простоя пула: мёртвых оболочек в
-- реестре насчитали три вместо сорока трёх.
--
-- Код переведён на `datetime_utc_now()` в тех же шести местах, где раньше стоял
-- `datetime_now()` — и у писателей, и у читателей свежести. Здесь остаётся уже
-- записанное.
--
-- **Сдвиг берём из самой настройки, а не константой.** Значения писались тем
-- смещением, которое стояло в `timezone` на момент записи; хардкод «минус три часа»
-- сломал бы установку с другим поясом. Формат настройки — `'+3'`, `'UTC+3'`, `'-2'`:
-- убираем `UTC` и приводим к числу. Пустая или нечитаемая настройка даёт 0, и тогда
-- миграция не делает ничего — это верное поведение для установки, которая жила в UTC.
--
-- `COALESCE` обёрнут вокруг всего подзапроса, а не вокруг `CAST`. Внутри он не
-- спасает: строки настройки может не быть вовсе, тогда подзапрос вернёт NULL,
-- `INTERVAL NULL HOUR` даст NULL — и вместо сдвига колонка обнулилась бы целиком.
--
-- Живые строки поправились бы и сами: пинг приходит раз в две секунды и перезапишет
-- колонку уже в UTC. Но до первого пинга мёртвая сессия числилась бы живой ещё на
-- величину смещения — три часа тишины, принятые за работу. Ради этого окна сдвиг и
-- делается сразу.
--
-- Идемпотентность обеспечена отметкой самой миграции: повторный прогон yoyo не
-- запускает. Своей защиты у запроса нет намеренно — она потребовала бы признака
-- «уже сдвинуто», а его в данных нет: UTC и местное время неотличимы на глаз.

UPDATE `ai_claude_session_registry`
   SET `last_seen_at` = `last_seen_at` - INTERVAL COALESCE((
           SELECT CAST(REPLACE(REPLACE(value, 'UTC', ''), ' ', '') AS SIGNED)
             FROM `setting`
            WHERE `key` = 'timezone' AND user_id IS NULL AND node_id IS NULL
            LIMIT 1), 0) HOUR
 WHERE `last_seen_at` IS NOT NULL;

UPDATE `ai_claude_session_registry`
   SET `closed_at` = `closed_at` - INTERVAL COALESCE((
           SELECT CAST(REPLACE(REPLACE(value, 'UTC', ''), ' ', '') AS SIGNED)
             FROM `setting`
            WHERE `key` = 'timezone' AND user_id IS NULL AND node_id IS NULL
            LIMIT 1), 0) HOUR
 WHERE `closed_at` IS NOT NULL;
