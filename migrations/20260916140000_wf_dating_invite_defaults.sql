-- `dating_invite_write`: умолчания переменным разнообразия (2026-09-16)
--
-- ЧТО НЕ ТАК БЫЛО. Промпт черновика ссылается на `%invite_angle%` и
-- `%invite_length%`, а переменные заведены типом `workflow` **без умолчания**.
-- Тип `workflow` — это запись в реестре для редактора, а не требование: движок
-- проверяет обязательность только у `global` и `input` (`workflow.md`, §3).
--
-- Значит вызов, не передавший их, ничего не нарушает — и получает в промпте
-- **саму метку словами**. Проверено рендером:
--
--     === Приём на этот раз ===
--     %invite_angle%
--
-- Модель читает это как текст задания и отвечает наугад. DatingAi их передаёт
-- всегда, поэтому в работе не видно; а вот человек, пробующий агента из чата
-- админки, и любой будущий вызывающий получат мусор — молча.
--
-- ⚠ ПОЧЕМУ НЕ СДЕЛАТЬ ИХ `global`. Тогда движок потребует их при каждом запросе и
-- ответит `400` тому, кто не передал. Для рабочего пути это ничего не меняет
-- (DatingAi передаёт), а вот проверить агента руками из админки стало бы нельзя —
-- ровно там, где промпт и проверяют. Умолчание лучше запрета: оно не мешает
-- работе и делает одиночный вызов осмысленным.
--
-- ⚠ `invite_avoid` УМОЛЧАНИЯ НЕ ТРЕБУЕТ, и это не забывчивость. Он стоит внутри
-- `%if invite_avoid%…%endif%`, а отсутствующая переменная для условия — «ложь»:
-- секция просто не появится. Пустое умолчание дало бы то же самое.
--
-- ЧТО СТАВИМ. Не «пусто», а осмысленный текст: одиночный вызов без переменных
-- должен дать годную реплику, а не вырожденную. Умолчание говорит модели
-- «выбирай сама» — то самое, что в рабочем пути делает жребий панели.

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_invite_write');

SELECT 'ДО' AS этап,
       SUM(`default` IS NOT NULL) AS с_умолчанием, COUNT(*) AS всего
  FROM `agent_workflow_variable`
 WHERE `name` IN ('invite_angle', 'invite_length', 'invite_avoid');

-- ------------------------------------------- Умолчания
UPDATE `agent_workflow_variable`
   SET `default` = CONCAT('любой заход на твой выбор — вопрос, вызов, признание, ',
                          'игра или наблюдение. Не бери первое, что придёт в ',
                          'голову: избитое начало выдаёт рассылку')
 WHERE `name` = 'invite_angle' AND (`default` IS NULL OR `default` = '');

UPDATE `agent_workflow_variable`
   SET `default` = CONCAT('свободная — от короткой фразы в три-четыре слова до ',
                          'абзаца в 25–35 слов. Абзац — предел')
 WHERE `name` = 'invite_length' AND (`default` IS NULL OR `default` = '');

-- ⚠ `invite_avoid` оставляем пустым намеренно: он под `%if%`, и пустота для
-- условия — «нечего избегать». Ставим пустую строку вместо `NULL`, чтобы в
-- редакторе было видно, что умолчание обдумано, а не забыто.
UPDATE `agent_workflow_variable`
   SET `default` = ''
 WHERE `name` = 'invite_avoid' AND `default` IS NULL;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап, `name`, LEFT(IFNULL(`default`, '(нет)'), 60) AS умолчание
  FROM `agent_workflow_variable`
 WHERE `name` IN ('invite_angle', 'invite_length', 'invite_avoid')
 ORDER BY `name`;
