-- Своя запись справочника собеседников для DatingAi (2026-09-19)
--
-- ЗАЧЕМ. `/chat/ask` требует `companion_id` и берёт по нему **имя** из справочника
-- (`chat.py`: `companion_name=entity_companion.get('name')`). DatingAi слал туда
-- единицу, считая поле «типом собеседника» — а единица это конкретная персона,
-- «Vadim». Цена вышла в двух местах сразу.
--
-- ⚠⚠ ПЕРВОЕ: ИМЯ В ТЕКСТЕ. Промпты зовут собеседника `%companion_title%`, и агент
-- писал живым людям «ok vadim» — человеку по имени Gerard. Поймано на проде.
--
-- ⚠⚠ ВТОРОЕ, ХУЖЕ: ФАКТЫ. Шаг разбора кладёт факты в Qdrant по ключу
-- `document_id: '%companion_name%'`, а переписку — по `'%girl_id%_%companion_name%'`.
-- С одним именем на всех факты обо ВСЕХ мужчинах сайта валились в один документ
-- «Vadim», а разговоры девушки со всеми — в «yulia_77_Vadim». Ровно та беда, от
-- которой у девушек стоит `girl_id`.
--
-- ЧТО ДЕЛАЕМ. Заводим запись под dating, чтобы `agent_session.companion_id` вёл на
-- честную строку, а не на чужого человека: журнал сессий перестаёт утверждать, что
-- полсотни анкет переписываются с Вадимом.
--
-- ⚠ ИМЯ И НАЗВАНИЕ СОБЕСЕДНИКА ПРИ ЭТОМ ПРИХОДЯТ ПЕРЕМЕННЫМИ ВЫЗОВА, а не отсюда.
-- Иначе пришлось бы заводить строку на каждого мужчину сайта — их тысячи, а `name`
-- здесь `char(25)` и уникален. Переменные запроса перекрывают базовые
-- (`chat.py`: `json_request.variables` идут последними), и узел Dating в них не
-- вмешивается — среди его переменных `companion_*` нет.
--
-- ⚠ НОМЕР ЗАДАЁМ ЯВНО. Справочник маленький и служебный, а на той стороне номер
-- нужен константой: искать строку по имени перед каждым вызовом значило бы лишний
-- поход в чужую базу ради значения, которое не меняется.
--
-- Идемпотентность: `INSERT IGNORE` по уникальному `name`.

