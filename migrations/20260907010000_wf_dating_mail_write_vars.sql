-- `dating_mail_write` перестаёт писать имена словами (2026-09-07)
--
-- ЧТО БЫЛО. Первый живой прогон дал складное письмо — с вопросами про паруса и
-- саксофон, ровно как просили. Но начиналось оно так: «Привет, John. Я Diana из
-- Киева…» — то есть имена вписаны **словами**, а не переменными.
--
-- ЦЕНА. Такое письмо годится ровно одному адресату. Рассылка же берёт шаблон и
-- подставляет в него имя каждого получателя; письмо с зашитым «John» уйдёт сотне
-- человек, из которых John — один. Это не косметика: одинаковое письмо с чужим
-- именем выдаёт рассылку вернее, чем что-либо ещё.
--
-- ОТЧЕГО ТАК ВЫШЛО. Промпт давал карточки обоих участников и отдельно —список
-- переменных, с правилом «вставляй переменные». Модель прочла это как разрешение,
-- а не как требование: имена у неё уже были, и она их подставила.
--
-- ЧТО ВМЕСТО. Правило переписано в запрет: имена и город **не писать словами**,
-- только переменной. Плюс сказано, зачем: письмо уходит многим, и зашитое имя
-- уедет не тому. Модель, понимающая причину, держит правило лучше.
--
-- Заодно: просим не писать ничего, кроме письма, — на том же прогоне в текст
-- утёк хвост размышлений («…let's stop and write the final answer now.</think>»).
-- Вырезает его и вызывающая сторона (`dating_mail_agent._letter`), но чинить
-- надо в обоих местах: промпт — чтобы не появлялось, разбор — потому что
-- появится всё равно.
--
-- Идемпотентность: условие на то, что старая формулировка ещё на месте.

-- ---------------------------------------------------------------- До
SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_mail_write');

SELECT 'ДО' AS этап,
       @wf AS workflow_id,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND `metadata` LIKE '%Вставляй переменные%') AS правило_старое;

-- ------------------------------------------- Правило про переменные
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '3. Вставляй переменные в виде [[имя]] — ровно те, что в списке. Других не выдумывай: их нечем подставить, и письмо не уйдёт.\\n4. Обращайся к нему по имени через переменную, а не словом «привет».\\n',
        '3. ЗАПРЕЩЕНО писать имена и город словами. Имя девушки, имя собеседника, её город — только переменной [[имя]] из списка выше. Письмо уходит многим людям: зашитое в текст имя уедет не тому.\\n4. Переменные — ровно те, что в списке. Других не выдумывай: их нечем подставить, и письмо не уйдёт.\\n')
 WHERE `workflow_id` = @wf
   AND `metadata` LIKE '%Вставляй переменные%';

-- ------------------------------------------- Только письмо, без размышлений
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '6. Ответ — только текст письма. Без заголовков, пояснений и markdown.',
        '6. Ответ — только текст письма. Без заголовков, пояснений, markdown и размышлений: всё, что ты напишешь, уйдёт человеку как есть.')
 WHERE `workflow_id` = @wf
   AND `metadata` LIKE '%Без заголовков, пояснений и markdown.%';

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND `metadata` LIKE '%ЗАПРЕЩЕНО писать имена%') AS правило_новое,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND `metadata` LIKE '%и размышлений%') AS про_размышления;
