-- `dating_talk`: переменная `answer_anyway` — «здесь молчать нельзя» (2026-09-19)
--
-- ЗАЧЕМ. Молчание — законный ход: судья (шаг 109) нарочно выбирает его, когда
-- ответ выглядел бы автоматическим, и правило «сомневаешься — молчи» там стоит не
-- случайно. Менять это не надо.
--
-- Но есть место, где молчание стоит дорого: **первый ответ человека на инвайт**.
-- Мы позвали его сами, он ответил — и не услышал ничего. Разговор, который мы же
-- и начали, обрывается на первой реплике; следующего раза не будет.
--
-- ЧТО ДЕЛАЕМ. Переменная `answer_anyway`. Ноль (и отсутствие) — как было. Единица
-- означает «этот ответ обязателен»: путь молчания закрыт.
--
-- ⚠ ЕДИНИЦА НЕ ОТМЕНЯЕТ ПРОВЕРКУ, А МЕНЯЕТ ЕЁ ВОПРОС. Судья перестаёт спрашивать
-- «нужен ли ответ» и начинает спрашивать «годится ли этот». Язык, осмысленность,
-- соответствие сказанному — всё остаётся; не годится — судья пишет замену. Иначе
-- обязательный ответ превратился бы в обязательную отправку чего угодно, включая
-- пустую строку, а это хуже молчания.
--
-- ⚠⚠ ЗАМЕНА КЛАДЁТСЯ В ОТДЕЛЬНЫЙ КЛЮЧ (`girl_response_fixed`), А НЕ ПОВЕРХ
-- ЧЕРНОВИКА. Объяви мы судье выход `girl_response`, он писал бы его **всегда** —
-- и в обычном заходе пустой ответ судьи затирал бы готовый текст автора. Поломка
-- вышла бы тихой: workflow вернул бы пустоту там, где раньше возвращал реплику.
-- Поэтому ключ свой, а выбирает между ними шаг ответа (106) условием.
--
-- ⚠ ПРОВЕРКУ НА ПОВТОР (шаг 105) ЕДИНИЦА НЕ ТРОГАЕТ, и это осознанно. Она ловит
-- другую беду — отправку того же текста второй раз, — и «отвечать обязательно» не
-- значит «можно повторяться». Обязательность снимает молчание, а не защиту от
-- дубля.
--
-- ⚠ Значения по умолчанию заводить не нужно: у соседа `%if%` считает ложными и
-- пустое, и `'0'`, и отсутствующую переменную (`ai_workflow_variable_truthy`).
-- Не передали — ведём себя как раньше.
--
-- Идемпотентность: промпты переписываются целиком, ключ добавляется проверкой на
-- наличие.

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_talk');

SELECT 'ДО' AS этап, @wf AS workflow,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%answer_anyway%'
          FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 10)
       AS есть_у_автора,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%answer_anyway%'
          FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 11)
       AS есть_у_судьи;

-- ── Шаг 10: автор. Обязательный ответ не бывает пустым ──────────────────────
--
-- ⚠ Правило 4 («не поняла — верни пустую строку») остаётся для обычного захода:
-- это защита от ответа на невнятицу. Под `answer_anyway` оно заменяется, а не
-- дополняется: два правила про пустую строку — одно «верни», другое «не
-- возвращай» — модель читает как противоречие и выбирает произвольно.

UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(
         `metadata`, '$.prompt_user',
         REPLACE(
           JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')),
           '4. КРИТИЧЕСКОЕ ПРАВИЛО: Если сообщение %companion_title% — это неразборчивый набор букв, опечатка, случайные символы или у тебя нет четкого понимания, что ответить, ты ОБЯЗАНА вернуть абсолютно пустую строку (ни одного символа, пробела или знака препинания). Не пытайся отшучиваться или переспрашивать в таких случаях.',
           CONCAT(
             '%if answer_anyway%',
             '4. КРИТИЧЕСКОЕ ПРАВИЛО: ответ ОБЯЗАТЕЛЕН — пустую строку возвращать ',
             'нельзя. Это первый ответ человека на наше приглашение: промолчав, мы ',
             'обрываем разговор, который сами и начали. Если его сообщение ',
             'неразборчиво или непонятно, о чём оно, — не переспрашивай дословно и ',
             'не отшучивайся: ответь коротко и по-человечески на то, что ты всё же ',
             'поняла, или поддержи знакомство простым живым вопросом о нём.',
             '%else%',
             '4. КРИТИЧЕСКОЕ ПРАВИЛО: Если сообщение %companion_title% — это ',
             'неразборчивый набор букв, опечатка, случайные символы или у тебя нет ',
             'четкого понимания, что ответить, ты ОБЯЗАНА вернуть абсолютно пустую ',
             'строку (ни одного символа, пробела или знака препинания). Не пытайся ',
             'отшучиваться или переспрашивать в таких случаях.',
             '%endif%')))
 WHERE `workflow_id` = @wf AND `position` = 10;

-- ── Шаг 11: судья. Под единицей вопрос другой ───────────────────────────────
--
-- Переписывается целиком: правка кусками оставила бы в шапке «оцени, обязателен
-- ли ответ», и модель пошла бы за ней, а не за новым требованием — на этом уже
-- обжигались в `dating_invite_write`.

UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(
         `metadata`, '$.prompt_user',
         CONCAT(
           '=== Текущее время ===\n%datetime_current_get_45_result_str%\n\n',
           '%if session_messages_29_result_str%',
           '=== История переписки (время сообщений в квадратных скобках) ===\n',
           '%session_messages_29_result_str%\n\n%endif%',
           '=== %companion_title% пишет ===\n%prompt_user%\n\n',
           '=== Черновик ответа девушки ===\n%girl_response%\n\n',
           '=== Что нужно ===\n',
           '%if answer_anyway%',
           'Ты строгий редактор. Этот ответ ОБЯЗАТЕЛЕН: человек впервые ответил на ',
           'наше приглашение, и молчание оборвёт разговор, который мы сами начали. ',
           'Решать, нужен ли ответ, не требуется — он нужен.\n\n',
           'Твоя работа — проверить, годится ли черновик:\n',
           '- он написан на языке %user_language%;\n',
           '- он отвечает именно на то, что написал %companion_title%, а не на ',
           'что-то своё;\n',
           '- в нём есть содержание: это не пустая строка, не набор символов, не ',
           'одно междометие;\n',
           '- он звучит по-человечески и уместен по времени суток;\n',
           '- он не повторяет дословно то, что девушка уже говорила в истории.\n\n',
           'Годится — верни girl_response_skip: 0 и girl_response_fixed: "" ',
           '(пустую строку, править нечего).\n\n',
           'Не годится — верни girl_response_skip: 0 и напиши в girl_response_fixed ',
           'свой вариант: одно-два предложения, до 20 слов, строго на языке ',
           '%user_language%, по существу сказанного. ⚠ girl_response_skip остаётся ',
           '0 в ЛЮБОМ случае: пустой girl_response_fixed означает «черновик хорош», ',
           'а не «ответа не будет».\n',
           '%else%',
           'Ты строгий редактор реалистичности переписки. Реальная девушка не ',
           'отвечает на каждое сообщение: часть реплик она оставляет без ответа, ',
           'иногда просто молчит. Автоответ на все подряд выглядит фальшиво. ',
           'Критически оцени, обязателен ли этот ответ.\n\n',
           'girl_response_skip = 1 (пропустить ответ), если:\n',
           '- сообщение %companion_title% - реплика-реакция, не требующая ответа: ',
           'ок, ясно, понятно, ахах, круто, одиночный смайл\n',
           '- черновик не несет новой информации: поддакивание, повтор уже ',
           'сказанного, вежливое поддержание разговора ради разговора\n',
           '- на суть сообщения девушка уже ответила ранее в истории\n',
           '- черновик пустой или бессодержательный\n\n',
           'girl_response_skip = 0 (ответ нужен), если:\n',
           '- есть прямой вопрос к девушке или запрос информации\n',
           '- обсуждаются планы, договоренности, место или время встречи\n',
           '- новая тема или сообщение с новыми фактами, на которые естественно ',
           'отреагировать\n',
           '- если уже пропустила два или три обращения, то из вежливости можно ',
           'ответить, но только по делу, если запросы вежливые и не навязчивые\n',
           '- первое сообщение диалога или сообщение после долгой паузы (сравни ',
           'метки времени с текущим временем)\n',
           '- %companion_title% делится чем-то личным и молчание выглядело бы ',
           'грубо\n\n',
           'Если сомневаешься между 0 и 1 - выбирай 1: молчание реалистичнее ',
           'лишнего ответа.\n\n',
           '⚠ girl_response_fixed в этом заходе всегда пустая строка: править ',
           'черновик здесь не нужно.\n',
           '%endif%',
           '\n=== Important information about final response ===\n',
           'Please return your response in JSON format. The JSON response must ',
           'contain follow keys: \n',
           '- "girl_response_skip": 0 или 1, где 1 - ответ пропускаем (девушка ',
           'молчит), 0 - ответ отправляем\n',
           '- "girl_response_fixed": исправленный текст ответа или пустая строка, ',
           'если черновик годится\n\n',
           'Example of JSON response:\n',
           '{\n  "girl_response_skip": 1,\n  "girl_response_fixed": ""\n}\n\n',
           'Example of JSON response one more:\n',
           '{\n  "girl_response_skip": 0,\n',
           '  "girl_response_fixed": "sorry, my phone died - what did you say?"\n}'))
 WHERE `workflow_id` = @wf AND `position` = 11;

-- ⚠ Ключ надо ещё и **объявить**: без строки в `llm_to_json_variable` движок его
-- из ответа не возьмёт, и правка судьи потеряется молча.
UPDATE `agent_workflow_step`
   SET `metadata` = JSON_ARRAY_APPEND(
         `metadata`, '$.llm_to_json_variable',
         JSON_OBJECT('variable', 'girl_response_fixed',
                     'text', 'исправленный судьёй ответ; пусто — черновик годится'))
 WHERE `workflow_id` = @wf AND `position` = 11
   AND JSON_SEARCH(`metadata`, 'one', 'girl_response_fixed') IS NULL;

-- ── Шаг 13: что именно возвращаем ───────────────────────────────────────────
--
-- ⚠ Правка судьи имеет приоритет — но только когда она есть. Пустая строка здесь
-- означает «править было нечего», и подставлять её вместо ответа нельзя.

UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(`metadata`, '$.prompt_user',
         '%if girl_response_fixed%%girl_response_fixed%%else%%girl_response%%endif%')
 WHERE `workflow_id` = @wf AND `position` = 13;

SELECT 'ПОСЛЕ' AS этап,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%answer_anyway%'
          FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 10)
       AS у_автора,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%ОБЯЗАТЕЛЕН%'
          FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 11)
       AS у_судьи,
       (SELECT JSON_SEARCH(`metadata`, 'one', 'girl_response_fixed') IS NOT NULL
          FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 11)
       AS ключ_объявлен,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
          FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 13)
       AS что_возвращаем;
