-- `dating_invite_write`: обращаемся по имени без фамилии (2026-09-11)
--
-- ЗАЧЕМ. Сайт отдаёт имя одной строкой, и промпт получал её целиком. Отсюда
-- реплики вида «Hi Tall_Good_Man» и «Здравствуйте, JULIO RODRIGO ZAPATA OLIVA» —
-- по имени и фамилии разом не обращаются нигде, и первая же строка выдаёт
-- заполненную форму вместо человека.
--
-- ⚠ РЕШАЕТ ПРОМПТ, А НЕ ПАНЕЛЬ. Первое имя приходит **отдельной переменной**
-- (`invite_companion_first_name`), и оно бывает пустым: «Kevin» и
-- «Tall_Good_Man» — одно слово, делить нечего. Что делать с пустотой, знает тот,
-- кто пишет текст, — здесь это `%if%`: есть первое имя, зовём им; нет —
-- полным.
--
-- Подставить в панели «первое имя, иначе полное» было бы короче, но тогда промпт
-- перестал бы отвечать на вопрос «как модель узнаёт, чем звать»: ответ уехал бы в
-- чужой код, а видно его было бы только по результату.
--
-- ⚠ ПУСТОЕ ЗНАЧЕНИЕ ПЕРЕМЕННОЙ И ОТСУТСТВИЕ — ОДНО И ТО ЖЕ для `%if%`
-- (`ai_workflow_variable_truthy`), и на это мы и опираемся: панель шлёт переменную
-- всегда, а пустой она приходит у тех, у кого имя одно слово.
--
-- ⚠ ВЕТКА `%else%`, А НЕ ВТОРОЙ `%if%` С ОТРИЦАНИЕМ. Движок знает отрицание, но
-- пишется оно `%if !var%`, а не `%if not var%` (`WORKFLOW_IF_BLOCK_RE`): пробела
-- регулярка не ждёт, и «человеческое» написание осталось бы в промпте **текстом**
-- — молча, потому что модель проглотит что угодно. `%else%` не оставляет места
-- этой ошибке.

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_invite_write');

SELECT 'ДО' AS этап, @wf AS workflow,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%invite_companion_first_name%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 0) AS имя_отдельно;

-- ------------------------------------------- Переменная под первое имя
--
-- ⚠ Своя, как и `invite_companion_name`: `companion_name` в этой базе уже занято
-- дважды (#73 global, #81 input), и привязка по общему имени сделала бы
-- подстановку неоднозначной.
INSERT INTO `agent_workflow_variable` (`name`, `type`, `description`)
SELECT 'invite_companion_first_name', 'workflow',
       'Имя собеседника без фамилии — первое слово. Пусто, если делить нечего'
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow_variable`
                    WHERE `name` = 'invite_companion_first_name');

-- ------------------------------------------- Промпт
UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(
         `metadata`, '$.prompt_user',
         CONCAT(
           'Ты пишешь ПЕРВУЮ реплику в чате на сайте знакомств. Девушка пишет ',
           'мужчине, они не знакомы и до этого не говорили.\n\n',
           '=== Требуемый язык ответа (код) ===\n%user_language%\n\n',
           '=== Кому пишем ===\n',
           '%if invite_companion_first_name%',
           'Как звать: %invite_companion_first_name% (полное имя — ',
           '%invite_companion_name%; в реплике зови только по первому имени, ',
           'фамилию не пиши)\n',
           '%else%',
           'Как звать: %invite_companion_name%\n',
           '%endif%',
           '%companion_card%\n\n',
           '=== Кто пишет ===\n%girl_card%\n\n',
           'Правила:\n',
           '1. Пиши РОВНО на требуемом языке, указанном выше. Это жёсткое ',
           'требование, а не пожелание: сайт фильтрует сообщения и не на том ',
           'языке отклоняет — реплика не дойдёт до человека вовсе. Язык профиля ',
           'собеседника значения не имеет: он подсказывает, О ЧЁМ спросить, а не ',
           'на каком языке.\n',
           '2. Это ЧАТ, а не письмо. Одна реплика, одно-два предложения. Ни темы, ',
           'ни подписи, ни абзацев: текст всплывёт у него в окне чата как ',
           'сообщение от живого человека.\n',
           '3. Обратись к нему по имени — ровно один раз и внутри текста, тем ',
           'именем, которое указано выше в «Как звать». Место обращения выбирай ',
           'сам: «..., а вы...» и «Давно этим занимаетесь, ...?» звучат ',
           'по-разному, и одинаковая рамка у всех реплик выдаёт рассылку. Два ',
           'обращения в двух предложениях читаются как сбой подстановки.\n',
           '4. Заканчивай вопросом или предложением, на которое легко ответить. ',
           '«Привет, как дела?» отвечать нечем. Спроси про то, что есть в его ',
           'профиле, — так видно, что профиль прочли.\n',
           '5. О нём ничего не известно — задай живой общий вопрос про его ',
           'занятия. Промолчать нельзя: без текста инвайт не попадёт в пул вовсе, ',
           'и человек останется без приглашения.\n',
           '6. Без комплиментов внешности, без «я увидела твоё фото», без просьб ',
           'написать первым. Первая реплика — повод для разговора, а не признание.\n',
           '7. Ответ — только сам текст реплики. Без кавычек, пояснений, markdown ',
           'и размышлений: всё, что ты напишешь, уйдёт в чат как есть.'
         ))
 WHERE `workflow_id` = @wf AND `position` = 0;

INSERT INTO `agent_workflow_variable_workflow` (`variable_id`, `workflow_id`)
SELECT v.`id`, @wf FROM `agent_workflow_variable` v
 WHERE v.`name` = 'invite_companion_first_name'
   AND NOT EXISTS (SELECT 1 FROM `agent_workflow_variable_workflow` vw
                    WHERE vw.`variable_id` = v.`id` AND vw.`workflow_id` = @wf);

SELECT 'ПОСЛЕ' AS этап,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%invite_companion_first_name%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 0) AS имя_отдельно,
       (SELECT COUNT(*) FROM `agent_workflow_variable_workflow`
         WHERE `workflow_id` = @wf) AS переменных;
