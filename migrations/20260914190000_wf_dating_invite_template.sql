-- `dating_invite_write`: один шаблон на пул вместо реплики на человека (2026-09-14)
--
-- ЧТО МЕНЯЕТСЯ. Прежде панель звала этот workflow **на каждую пару**: пул в
-- полсотни карточек стоил полусотни вызовов LLM и минут ожидания. Теперь вызов
-- один на заход: агент присылает **шаблон** реплики, а панель раскладывает его по
-- парам, заменяя метки именами.
--
-- Отсюда три правки промпта, и каждая следует из этого одного:
--
-- 1. КАРТОЧЕК БОЛЬШЕ НЕТ. Ни `girl_card`, ни `companion_card`, ни имени
--    собеседника: шаблон общий, и подстраиваться ему не подо что. Просить у
--    модели персонализацию, а потом раздать её пятидесяти разным людям, значило
--    бы обманывать самих себя.
--
-- 2. ИМЕНА — МЕТКАМИ, И РЕШАЕТ ИХ ПАНЕЛЬ. Метку просит переменная
--    `%invite_slots%`: панель бросает жребий (имя девушки — 5%, имя мужчины —
--    30%) и говорит прямо, что поставить. ⚠ Так сделано потому, что «вставляй имя
--    изредка» модель понимает как «вставляй всегда»: вероятность у неё
--    стилистическая, а не считаемая.
--
-- 3. ТЕМАТИКА ДРУГАЯ. Было «приветственный вопрос по профилю» — вежливо и мимо:
--    профиля у большинства нет, и реплики выходили одинаково пресными («чем
--    любите заниматься в свободное время?»). Заказчик просит флирт, заигрывание,
--    провокацию — то, на что отвечают. Длина — от короткой до абзаца, но не
--    больше абзаца: это чат, а не письмо.
--
-- ⚠ ПОЧЕМУ WORKFLOW ТОТ ЖЕ, А НЕ НОВЫЙ. Занятие не изменилось — «первая реплика в
-- чат», — изменилось, как её просят. Новое имя означало бы, что у каждого сайта
-- заводится второй агент, а первый остаётся висеть; агенты привязаны к имени
-- workflow (`invite_<сайт>` у соседа), и переезд стоил бы ручной чистки.
--
-- ⚠ ЦЕНА РАЗМЕНА, НАЗВАННАЯ ПРЯМО. Все реплики пула одинаковы с точностью до
-- имён. Держится это тем, что каждый человек получает из пула ровно одну карточку
-- — панель следит за уникальностью собеседников (`dating_invite.py`).

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_invite_write');

SELECT 'ДО' AS этап, @wf AS workflow,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%invite_slots%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 0) AS шаблон_уже_просят,
       (SELECT COUNT(*) FROM `agent_workflow_variable`
         WHERE `name` = 'invite_slots') AS переменная_есть;

-- ------------------------------------------- Переменная под указание о метках
--
-- ⚠ Фразу собирает панель, а не промпт: шаблонизатор у соседа подставляет
-- значения и условий не понимает. Держи мы все четыре сочетания в промпте —
-- правка вероятностей означала бы правку этой базы.
INSERT INTO `agent_workflow_variable` (`name`, `type`, `description`)
SELECT 'invite_slots', 'workflow',
       'Какие метки поставить в шаблон инвайта: имя девушки, имя собеседника, '
       'обе или ни одной. Фразу целиком присылает DatingAi'
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow_variable`
                    WHERE `name` = 'invite_slots');

-- ------------------------------------------- Переписываем промпт
UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(
         `metadata`, '$.prompt_user',
         CONCAT(
           'Ты придумываешь ШАБЛОН первой реплики в чате на сайте знакомств. ',
           'Девушка пишет мужчине, они не знакомы и до этого не говорили. Один и ',
           'тот же текст уйдёт разным мужчинам — каждому по разу, друг друга они ',
           'не видят.\n\n',
           '=== Требуемый язык ответа (код) ===\n%user_language%\n\n',
           '=== Метки в тексте ===\n%invite_slots%\n\n',
           'Правила:\n',
           '1. Пиши РОВНО на требуемом языке, указанном выше. Это жёсткое ',
           'требование, а не пожелание: сайт фильтрует сообщения и не на том ',
           'языке отклоняет — реплика не дойдёт до человека вовсе.\n',
           '2. ТЕМАТИКА: флирт, заигрывание, лёгкая провокация, подкат. Нужно ',
           'зацепить — так, чтобы захотелось ответить. Не вежливый опрос: ',
           '«чем любишь заниматься в свободное время?» не цепляет никого.\n',
           '3. Это ЧАТ, а не письмо. Один абзац — и не больше: ни темы, ни ',
           'подписи, ни списков, ни переносов строк. Длина свободная: бывает ',
           'три слова, бывает пара фраз. Короткое цепляет чаще.\n',
           '4. Вопрос НЕ обязателен. Утверждение, намёк или вызов работают не ',
           'хуже — «спорим, ты сейчас улыбнулся» отвечать хочется сильнее, чем ',
           '«как дела?».\n',
           '5. Ставь ровно те метки, что названы выше в «Метки в тексте», — и ',
           'никаких других. Метку пиши точно как показано, в двойных квадратных ',
           'скобках. Панель заменит её именем; выдуманная метка уйдёт человеку ',
           'прямо в скобках.\n',
           '6. Никаких имён словами, если метки не просили: текст уйдёт разным ',
           'людям, и чужое имя в нём — провал.\n',
           '7. Без комплиментов внешности, без «я увидела твоё фото», без просьб ',
           'написать первым, без ссылок и контактов. Флирт — это интрига, а не ',
           'признание и не реклама.\n',
           '8. Ответ — только сам текст шаблона. Без кавычек, пояснений, ',
           'markdown и размышлений: всё, что ты напишешь, уйдёт в чат как есть.'
         ))
 WHERE `workflow_id` = @wf AND `position` = 0;

-- ------------------------------------------- Привязка переменной
INSERT INTO `agent_workflow_variable_workflow` (`variable_id`, `workflow_id`)
SELECT v.`id`, @wf FROM `agent_workflow_variable` v
 WHERE v.`name` = 'invite_slots'
   AND NOT EXISTS (SELECT 1 FROM `agent_workflow_variable_workflow` vw
                    WHERE vw.`variable_id` = v.`id` AND vw.`workflow_id` = @wf);

-- ------------------------------------------- Отвязка того, чего больше не шлют
--
-- ⚠ Переменные `girl_card`, `companion_card`, `invite_companion_name` и
-- `invite_companion_first_name` остаются в базе — их зовут соседние workflow (а
-- `invite_companion_*` заводились под это занятие и пригодятся, если решим
-- вернуть персонализацию). Здесь снимается только привязка: неподставленная
-- переменная в промпте — это `%girl_card%` словами в тексте у живого человека.
DELETE vw FROM `agent_workflow_variable_workflow` vw
  JOIN `agent_workflow_variable` v ON v.`id` = vw.`variable_id`
 WHERE vw.`workflow_id` = @wf
   AND v.`name` IN ('girl_card', 'companion_card', 'invite_companion_name',
                    'invite_companion_first_name');

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%invite_slots%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 0) AS шаблон_просят,
       (SELECT COUNT(*) FROM `agent_workflow_variable_workflow`
         WHERE `workflow_id` = @wf) AS переменных_привязано;
