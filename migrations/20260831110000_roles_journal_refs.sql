-- Журнал подзадачи — всем ролям, и никакого пересказа его в промпт.
--
-- Разбор после того, как QA получал в промпте собственный разбор пересказом
-- (`20260831100000`). Обход остальных ролей нашёл два пробела.
--
-- **Первый: багфиксер не знал про журнал.** Все прочие роли начинают круг с чтения
-- `.task-state.md` и `.task-log.md` — там итог прошлого круга, коммиты ветки и
-- хронология шагов. У багфиксера каталог такой же (`task_work_dir`), журнал в нём
-- лежит, а промпт о нём молчал: круг после обрыва начинался с чистого листа, хотя
-- рядом лежала запись о том, что уже сделано.
--
-- **Второй: обещание, которое перестало быть правдой.** Три шага разбора говорили
-- агенту «этот ответ целиком уходит в следующий промпт». У QA так и было — и это
-- чинилось отдельно; у Manager, Developer и багфиксера ответ никуда не вклеивался
-- уже давно. Обещание не безобидно: агент пишет пересказ для воображаемого читателя
-- вместо того, чтобы назвать сделанное.
--
-- Правда же в том, что ответ попадает **в журнал круга** — `.task-log.md` строкой
-- вида `23:16:06 сделал Разработчик: разбор [15 мин]: ...`, и читают его следующие
-- круги и человек на вкладке «Журналы». Так и пишем: требование «коротко и по делу»
-- сохраняется, но обосновано тем, что происходит на самом деле.
--
-- Почему не убрали из промптов данные, которые «и так есть в журнале» (отчёт
-- разработчика, итог прошлого круга). Журнал у живой подзадачи разрастается: у #5219
-- `.task-log.md` — 120 КБ против 4 КБ у `.task-state.md`. Данные в промпте приходят
-- даром, а чтение файла стоит вызова инструмента и токенов на весь его объём.
-- Дублирование здесь дешевле обращения к источнику — в отличие от пересказа агенту
-- его же слов в той же сессии, который не давал ничего вовсе.
--
-- Идемпотентность: каждое условие проверяет, что заменяемый текст ещё на месте.

-- 1. Багфиксер: журнал перед разбором. Формулировка та же, что у разработчика
--    (шаг 433), — роли разные, а причина читать журнал одна.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '%endif%Что сделать:\\n1. Пойми, о чём баг:',
        '%endif%%if task_work_dir%=== СНАЧАЛА ПОСМОТРИ ЖУРНАЛ ===\\n'
        'Прогон мог оборваться по таймауту: оболочку тогда перезапускают, и ты не помнишь\\n'
        'ничего, — а работа и записи о ней остались в каталоге бага. Поэтому первым делом,\\n'
        'до чтения кода проекта:\\n'
        '  cat .task-state.md   — итог последнего круга и что уже лежит в ветке\\n'
        '  cat .task-log.md     — хронология по кругам, шаг за шагом\\n'
        '  git log master..HEAD и git status --porcelain — что из этого в коммитах\\n\\n'
        'Журнал ведётся сам, дописывать его не нужно. Файлов нет и коммитов нет — это\\n'
        'первый круг, разбирай с нуля.\\n\\n'
        '%endif%Что сделать:\\n1. Пойми, о чём баг:')
 WHERE `id` = 555
   AND `metadata` LIKE '%Что сделать:\\\\n1. Пойми, о чём баг:%'
   AND `metadata` NOT LIKE '%task-state.md%';

-- 2. Обещание про следующий промпт — в трёх шагах разбора. Ответ уходит в журнал,
--    и это единственное, что с ним происходит.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'Без заголовков и\\nтаблиц — этот ответ целиком уходит в следующий промпт.',
        'Без заголовков и\\nтаблиц — этот ответ уходит строкой в журнал круга (.task-log.md), его читают\\n'
        'следующие круги и человек.')
 WHERE `id` IN (433, 555)
   AND `metadata` LIKE '%уходит в следующий промпт%';

UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'Без заголовков,\\nтаблиц и значков — этот ответ целиком уходит в следующий промпт.',
        'Без заголовков,\\nтаблиц и значков — этот ответ уходит строкой в журнал круга (.task-log.md),\\n'
        'его читают следующие круги и человек.')
 WHERE `id` = 445
   AND `metadata` LIKE '%уходит в следующий промпт%';
