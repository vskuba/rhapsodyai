-- Тип шага «Тема и действие» — рядом с `branch`, а не вместо (2026-10-10)
--
-- ЗАЧЕМ. Движок берёт имя типа шага из базы (`agent_workflow_step_type.name` →
-- `step_type_name` → `elif step_type == …`), и новому приёму — отсев по меткам
-- в тексте плюс вопросы в подпотоке — нужна своя строка.
--
-- ⚠⚠ СТРОКА `branch` ОСТАЁТСЯ ЖИВОЙ, и это не осторожность впрок. Таблицу в
-- соседней миграции удалось подменить представлением, а строку подменить нечем:
-- переименуй `branch` в `topic_action` — и старый контейнер, который в окне
-- выкладки ещё держит трафик, не найдёт свою ветку `elif` и уронит шаг на
-- каждом ответе в чат (`deploy.md`).
--
-- ⚠⚠ Поэтому переход РУЧНОЙ и обратимый: тип заводится рядом, движок понимает
-- оба имени, а человек переводит шаг на новый тип на странице Workflow, когда
-- форма готова и вопросы заведены. До перевода всё работает по-старому; после —
-- старый тип и его ветка в движке уходят следующей выкладкой, вместе с
-- представлениями-подпорками.
--
-- ⚠ Номер строки не назначается: `branch` занял 8, и жёсткое число здесь
-- разошлось бы между установками, где типы заводились в своём порядке.
--
-- Устройство слоя — `.claude/docs/workflow_branch.md`.

-- ── 0. Что было до ──────────────────────────────────────────────────────────

SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step_type`
         WHERE `name` = 'branch') AS тип_branch,
       (SELECT COUNT(*) FROM `agent_workflow_step_type`
         WHERE `name` = 'topic_action') AS тип_topic_action;

-- ── 1. Новый тип шага ───────────────────────────────────────────────────────
--
-- ⚠ Значок тот же, что у ветки: предмет у шага не изменился — он по-прежнему
-- про тему разговора, — а два разных значка на время перехода читались бы как
-- два разных дела.

INSERT INTO `agent_workflow_step_type` (`name`, `icon`, `description`, `description_full`)
SELECT 'topic_action', '🌿', 'Тема и действие',
       'Ищет метки тем в тексте истории — словом целиком, считая только разные метки. '
       'Тема, набравшая свой минимум, уходит в subflow со своими вопросами; тот '
       'спрашивает модель и, если ответов «yes» хватило, отдаёт инструкцию темы. '
       'Тем может подняться несколько: инструкции накапливаются через карты вызова.'
 WHERE NOT EXISTS (SELECT 1 FROM (
           SELECT 1 FROM `agent_workflow_step_type` WHERE `name` = 'topic_action'
       ) AS уже_есть);

-- ── 2. Что стало ────────────────────────────────────────────────────────────

SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step_type`
         WHERE `name` = 'branch') AS тип_branch,
       (SELECT COUNT(*) FROM `agent_workflow_step_type`
         WHERE `name` = 'topic_action') AS тип_topic_action,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `metadata` LIKE '%"branch":%') AS шагов_на_старом_типе;
