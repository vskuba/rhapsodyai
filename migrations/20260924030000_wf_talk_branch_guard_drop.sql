-- Сторож на входе ветки снят: он гасил сочинение (2026-09-24)
--
-- ## ⚠⚠ ЧТО СЛОМАЛОСЬ
--
-- Прошлая миграция поставила каждой ветке сторож на входе:
-- `girl_response exists` → «Валидация», с мыслью «ответ уже написан — значит
-- сюда попали ошибочно».
--
-- Мысль неверна. `girl_response` объявлена переменной **workflow**, и
-- `ai_workflow_variables_defaults_apply` кладёт её в область видимости **на
-- старте прогона** — пустой строкой (умолчание `NULL` → `''`). Оператор
-- `exists` смотрит на наличие ключа, а не на значение, и потому истинен с
-- первой секунды.
--
-- Итог на живом прогоне 39117: развилка сработала верно и увела на «Письмо
-- первым», а там сторож тут же увёл на «Валидацию».
--
--     шаг              токенов  мс
--     Ответ в чат          0     2   ← ушёл по развилке, это верно
--     Письмо первым        0     0   ← ушёл по сторожу, письма НЕ БЫЛО
--     Валидация ответа   693  1709   ← судья проверял пустоту
--
-- Ноль токенов — письмо не сочинялось вовсе. Так же молчали бы и ответы в чат.
--
-- ## ⚠ Почему сторож не нужен вовсе
--
-- От провала ветки друг в друга защищает **выход**, а не вход: у каждой ветки
-- стоит `transitions_after` с тем же `girl_response exists` → «Валидация». И
-- вот там истинность с первой секунды не мешает, а помогает — переход
-- срабатывает всегда, то есть ветка гарантированно уходит на проверку и ни при
-- каких условиях не падает в соседнюю.
--
-- Порядок шагов доделывает остальное: ветки стоят вплотную за шагом чата, а
-- «Влить придуманные факты» снова последний.
--
-- ⚠⚠ Урок не про `exists`, а про **область видимости**: переменная, объявленная
-- у workflow, существует до того, как её кто-либо заполнил. Условие «уже
-- посчитано» на таких переменных надо писать по **значению**, а не по наличию.
--
-- Идемпотентность: снимает список, которого может уже не быть.

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_talk');

SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND `title` IN ('Письмо первым', 'Ответ на письмо', 'Инициатива')
           AND JSON_LENGTH(JSON_EXTRACT(`metadata`, '$.transitions_before')) > 0)
         AS веток_со_сторожем;

UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(`metadata`, '$.transitions_before', JSON_ARRAY())
 WHERE `workflow_id` = @wf
   AND `title` IN ('Письмо первым', 'Ответ на письмо', 'Инициатива');

SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND `title` IN ('Письмо первым', 'Ответ на письмо', 'Инициатива')
           AND JSON_LENGTH(JSON_EXTRACT(`metadata`, '$.transitions_before')) > 0)
         AS веток_со_сторожем,
       -- ⚠ Выход обязан остаться у всех четырёх: он и держит ветки врозь.
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND `title` IN ('Ответ в чат', 'Письмо первым', 'Ответ на письмо',
                           'Инициатива')
           AND JSON_LENGTH(JSON_EXTRACT(`metadata`, '$.transitions_after')) = 1)
         AS веток_с_выходом,
       -- ⚠ И развилка у шага чата — три правила, её сторож не трогал.
       (SELECT JSON_LENGTH(JSON_EXTRACT(`metadata`, '$.transitions_before'))
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `title` = 'Ответ в чат') AS правил_развилки;
