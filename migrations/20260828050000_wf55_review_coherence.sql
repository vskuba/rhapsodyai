-- Судья проверяет связность плана — шаг 409 (WF55).
--
-- Зачем. С появлением зависимостей и спецификаций у плана возник новый способ быть
-- неверным: каждый кусок хорош по отдельности, а вместе они не сходятся. Подзадача
-- проверяет поведение, которого не создаёт ни одна предыдущая. Цель задачи не закрыта
-- никем. Две подзадачи правят одно место — при слиянии веток это конфликт, и круг
-- уйдёт в `blocked`. Прежние разделы судьи такого не ловят: они смотрят на план, цели
-- и разбиение по отдельности.
--
-- Почему в судью, а не отдельным шагом. Шаг — это ещё один поход в LLM, а круг
-- планирования и так идёт 15–25 минут. Судья же читает ровно те данные, по которым
-- собирается спецификация (план, цели, разбиение, `depends_on`), и у него уже есть всё
-- нужное: вердикт `review_ok`, адрес возврата `review_target` и ветки доработки
-- (411 → план, 418 → цели, 430 → разбиение). Разрывы связности чинятся переразбиением,
-- то есть `review_target: split` — путь, который уже работает.
--
-- Правило «называй, а не переписывай» действует и здесь: судья возвращает работу на
-- доработку, а не переписывает план сам — иначе он разошёлся бы с тем, что менеджер
-- уже выдал на предыдущих шагах.
--
-- Идемпотентность: `REPLACE` по точной подстроке; текст, уже содержащий «СВЯЗНОСТЬ»,
-- второй раз не дополнится.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'Замечания давай находками и заданиями на доработку',
        'СВЯЗНОСТЬ: план обязан сходиться как целое, а не только каждым куском.\\n'
        'Проверь пять вещей:\\n'
        '- Каждая цель задачи закрыта хотя бы одной подзадачей. Не закрыта — работа\\n'
        '  заявлена, а делать её некому.\\n'
        '- Подзадача не проверяет поведение, которого не создаёт ни одна из идущих\\n'
        '  раньше. Проверяет — она обязана назвать ту в своём `depends_on`.\\n'
        '- Две подзадачи не правят одно и то же место: их ветки сольются с конфликтом,\\n'
        '  и работа встанет.\\n'
        '- `depends_on` ссылается только назад, на подзадачи выше по списку. Ссылка\\n'
        '  вперёд или по кольцу означает порядок, который не выполнить никогда.\\n'
        '- Подзадача, которой нужен чужой код, стоит после той, что его пишет, —\\n'
        '  и назвала её в зависимостях, а не просто идёт следом по списку.\\n'
        '\\n'
        'Нашёл разрыв связности — `review_target: split`: чинится переразбиением.\\n'
        '\\n'
        'Замечания давай находками и заданиями на доработку')
 WHERE `id` = 409
   AND `metadata` LIKE '%Замечания давай находками%'
   AND `metadata` NOT LIKE '%СВЯЗНОСТЬ%';
