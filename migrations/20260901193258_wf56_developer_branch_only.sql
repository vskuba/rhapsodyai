-- не на цели подзадачи.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '  не мержишь.\\n',
        '  не мержишь. Merge request, конфликты с master и вообще GitHub — вне проверки:\\n'
        '  их не смотришь и время на них не тратишь.\\n')
 WHERE `id` = 447
   AND `metadata` LIKE '%не мержишь.%'
   AND `metadata` NOT LIKE '%вне проверки%';
