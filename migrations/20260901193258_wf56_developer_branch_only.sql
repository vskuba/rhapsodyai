        'проверил и почему изменений нет. Принимают по целям, а не по ссылке.',
        'Коммитить нечего — тоже законный итог. Если работа подзадачи уже сделана (её закрыла\\n'
        'соседняя подзадача, прошлый круг или человек), дифф пуст: не коммить пустоту.\\n'
        'Скажи в отчёте, что проверил и почему изменений нет. Принимают по целям.')
 WHERE `id` = 435
   AND `metadata` LIKE '%не заводи пустой merge request%';

