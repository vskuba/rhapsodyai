-- Ветки, слияния и GitHub уходят из промптов ролей: это вне их подзадачи.
--
-- Правило. У подзадачи есть ветка, и она — единственное, с чем роль имеет дело.
-- Разработчик коммитит и пушит в неё, QA её проверяет. Master, слияния, конфликты и
-- merge request не относятся ни к тому, ни к другому: ветку сводит с главной система
-- после приёмки, а расхождения разбирает человек.
--
-- Почему это правится в промптах, а не объясняется ролям на словах. Требование
-- «merge request открыт» стояло в формальных требованиях самопроверки, и агент дочитывал
-- его как «открыт и сходится с master»: шёл в `gh pr view --json mergeable` и заворачивал
-- собственную работу за конфликт в файлах, которых не трогал. У #6438 так ушли все три
-- круга самопроверки из трёх — на состояние чужого кода, а не на задачу. Пока в промпте
-- есть предмет, о нём будут судить; поэтому предмет убирается целиком.
--
-- Почему merge request вообще не нужен роли. Он давно никому не служил. Ссылку на MR со
-- страницы задач убрали ещё раньше и по причине, записанной прямо в шаблоне: MR на
-- сервере сравнивает ветку с `origin/master`, а конвейер режет её от локальной главной,
-- которая бывает на десятки коммитов впереди, — вся эта чужая работа попадает в MR как
-- изменения задачи (на двух строках правки выходило 113 файлов). Ревью идёт по ссылке
-- diff на странице, слияние — кнопкой там же. То есть за MR платили `gh pr create` в
-- каждом круге и полем `mr_url` в контракте отчёта, а читать его было незачем.
--
-- Слияние остаётся, но становится операцией системы, а не работой роли:
--   - код подзадач-предшественников вливает в ветку `task_depend_merge_upstream` —
--     перед каждым кругом разработчика и только из тех, что прошли QA;
--   - сведение готовой работы с главной делает человек кнопкой на странице задач, а на
--     стороне GitHub — инструменты `src/tool/github/github_merge.py`.
-- Конфликт в обоих случаях не разрешается агентом: он возвращается человеку.
--
-- `mr_url` остаётся в коде (`task_agent_developer`, `TASK_METADATA_KEY_MR`) намеренно:
-- поле читается терпимо и теперь всегда пустое, а в metadata уже закрытых подзадач
-- лежат настоящие адреса — стирать их незачем.
--
-- Кавычек в добавляемом тексте нет намеренно: промпт лежит строкой внутри JSON в
-- `metadata`, и двойная кавычка рвёт разбор шага целиком (см.
-- `tests/test_agent_workflow_steps.py`). В вырезаемом фрагменте они есть — потому он и
-- вырезается по границам через SUBSTRING, а не сопоставлением текста с экранированием.
--
-- Идемпотентность: условия проверяют, что заменяемый текст ещё на месте.

-- 1. Шаг 435 (реализация): своя ветка — и на этом круг замыкается.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '  подзадач свои каталоги, а общий чекаут держит человек. В master не коммитишь и\\n'
        '  master не мержишь: слияние делает человек, приняв merge request.',
        '  подзадач свои каталоги, а общий чекаут держит человек.\\n'
        '- Работаешь только в своей ветке. Master, слияния, конфликты, merge request и\\n'
        '  вообще GitHub — вне твоей подзадачи: ветку сводит с главной система после\\n'
        '  приёмки, расхождения разбирает человек. Не смотри туда и не трать на это круг.\\n'
        '  Код подзадач, от которых твоя зависит, конвейер вливает в твою ветку сам, до\\n'
        '  начала круга — руками этого делать не нужно.')
 WHERE `id` = 435
   AND `metadata` LIKE '%master не мержишь: слияние делает человек%';

-- 2. Шаг 435: заголовок блока сдачи больше не ведёт к merge request.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'Проверив себя, доведи работу до merge request:',
        'Проверив себя, закрой круг:')
 WHERE `id` = 435
   AND `metadata` LIKE '%доведи работу до merge request%';

-- 3. Шаг 435: пункты 3 и 4 (gh pr create и запоминание адреса) вырезаются целиком.
--
-- По границам, а не заменой текста: в вырезаемом фрагменте есть двойные кавычки
-- (`--title "..."`), в JSON они экранированы, и сопоставлять их в SQL значит ставить
-- правку в зависимость от того, как именно они экранированы сегодня.
UPDATE `agent_workflow_step`
   SET `metadata` = CONCAT(
        SUBSTRING(`metadata`, 1, LOCATE('3. Открой merge request в master:', `metadata`) - 1),
        '3. На этом всё. Работу человек смотрит по ссылке diff на странице задач.\\n',
        SUBSTRING(`metadata`, LOCATE('\\nПравку данных или схемы', `metadata`)))
 WHERE `id` = 435
   AND `metadata` LIKE '%gh pr create%'
   AND LOCATE('3. Открой merge request в master:', `metadata`) > 0
   AND LOCATE('\\nПравку данных или схемы', `metadata`)
       > LOCATE('3. Открой merge request в master:', `metadata`);

