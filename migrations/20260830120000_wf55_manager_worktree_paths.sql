-- Менеджер планирует в своей выкладке и пишет пути от корня репозитория.
--
-- Разбор аварии с подзадачей #4799. Исполнитель создал файл в основном чекауте и
-- закоммитил в master — но не по недосмотру: в плане стоял абсолютный путь
-- `/home/vasyl/PycharmProjects/RhapsodyAi/src/project/team/team_session_cleanup.py`,
-- и он выполнил ровно написанное. Инструкция разработчика («работай в выкладке»)
-- проиграла плану: общее правило против конкретного пути под конкретный шаг.
--
-- Откуда путь взялся. Менеджер вёл разведку в основном чекауте — других каталогов
-- ему не давали, — а промпт требовал «указывай конкретные пути к файлам». Он и указал
-- те, что видел. Про выкладки его workflow не знает вовсе: ни одного вхождения слов
-- `worktree`, `выкладка`, `feature_task` во всех шагах WF55.
--
-- Здесь три правки, закрывающие это с двух сторон.
--
-- **1. Разведка переезжает в выкладку задачи.** Каталог у менеджера уже есть и
-- создаётся до планирования (`task_pipeline.py`, `_subtask_dir` в круге менеджера) —
-- он лежал без дела, под журнал и состояние. Теперь в нём же читается код.
--
-- Дело не только в путях. Основной чекаут — рабочий стол человека, и в нём лежат его
-- незакоммиченные правки. Разведка по такому дереву даёт план по коду, которого в
-- master нет, и заметить это невозможно: отчёт выглядит обычным. Живьём при разборе
-- этой самой аварии чекаут был занят правкой `role_developer.md` и `role_manager.md` —
-- то есть тех самых инструкций, по которым конвейер и работает. Выкладка режется от
-- master, и планирование по ней воспроизводимо.
--
-- **2. Пути в плане — только от корня репозитория.** Это главное: сам по себе переезд
-- разведки путей не чинит. Останься требование «конкретный путь» без формы, менеджер
-- писал бы `/home/.../worktrees/feature_task_4798/src/…` — свою выкладку, которой у
-- разработчика нет и которая снимается при закрытии задачи. Абсолютный путь неверен
-- всегда, потому что исполнитель работает в другом каталоге по замыслу.
--
-- Требование конкретности при этом сохраняется полностью — меняется только запись.
--
-- **3. То же правило в шаге разбиения (424).** Абсолютный путь в #4799 пришёл именно
-- оттуда: там сказано «какие файлы и функции трогать», и там же он и появился.
-- Поправить только разведку значило бы оставить открытой ту дверь, через которую
-- ошибка и вошла.
--
-- Идемпотентность: условие `NOT LIKE '%от корня репозитория%'` — повторный прогон и
-- уже дополненный текст не тронет.

-- 1. Разведка ведётся в выкладке задачи.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '=== ЧЕМ РАБОТАТЬ В ЭТОМ ПРОЕКТЕ ===',
        '=== ГДЕ РАБОТАТЬ ===\\n'
        'Код читай в каталоге задачи (`%task_work_dir%`), а не в основном чекауте\\n'
        'проекта. Это отдельная выкладка репозитория, срезанная от главной ветки: в\\n'
        'основном чекауте лежат незакоммиченные правки человека, и план по ним оказался\\n'
        'бы планом по коду, которого в главной ветке нет.\\n\\n'
        '=== ЧЕМ РАБОТАТЬ В ЭТОМ ПРОЕКТЕ ===')
 WHERE `id` = 422
   AND `metadata` LIKE '%=== ЧЕМ РАБОТАТЬ В ЭТОМ ПРОЕКТЕ ===%'
   AND `metadata` NOT LIKE '%=== ГДЕ РАБОТАТЬ ===%';

-- 2. Пути в разведке — от корня репозитория.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'Указывай конкретные пути к файлам, а не общие слова.',
        'Указывай конкретные пути к файлам, а не общие слова.\\n'
        '   Путь пиши **от корня репозитория** — `src/project/team/team_session_cleanup.py`,\\n'
        '   а не `/home/…/src/…`. Подзадачу делают в отдельной выкладке, и абсолютный\\n'
        '   путь уводит исполнителя мимо неё — в чужой каталог, где его работа не\\n'
        '   попадёт ни в ветку, ни в merge request.')
 WHERE `id` = 422
   AND `metadata` LIKE '%Указывай конкретные пути к файлам, а не общие слова.%'
   AND `metadata` NOT LIKE '%от корня репозитория%';

-- 3. То же в шаге разбиения на подзадачи.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'Пиши конкретику этой подзадачи: какие файлы и функции трогать,',
        'Пиши конкретику этой подзадачи: какие файлы и функции трогать,\\n'
        '  путями **от корня репозитория** (`src/project/team/…`, не `/home/…`):\\n'
        '  подзадачу делают в отдельной выкладке, и абсолютный путь уведёт исполнителя\\n'
        '  мимо неё,')
 WHERE `id` = 424
   AND `metadata` LIKE '%Пиши конкретику этой подзадачи: какие файлы и функции трогать,%'
   AND `metadata` NOT LIKE '%от корня репозитория%';
