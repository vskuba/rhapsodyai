-- Документация — обязанность разработчика и предмет проверки QA (шаги 433, 445).
--
-- Разбор по следам #4799. В отчёте по той подзадаче стояло «документация не обновлена»
-- как нарушение — а нарушать было нечего: требования не существовало ни в одной
-- инструкции. `docs_rules.md` описывает, **как** писать документацию, но не говорит,
-- **когда** её обновлять, и ни разработчик, ни QA к ней не обращались вовсе.
--
-- Цена не в аккуратности. Менеджер планирует по коду и по `.claude/docs/`, и
-- разошедшееся описание хуже отсутствующего: по нему разведка выдаёт план на то, чего
-- в коде уже нет, а исполнитель ищет функцию, которой не осталось. Отсутствующее
-- описание хотя бы честно отправляет читать исходники.
--
-- Поэтому требование в двух местах, и они несимметричны. Разработчик **приводит
-- описание в соответствие**: не «пишет про свою работу», а правит то, что стало
-- неверным. QA **сверяет** — вердикт даёт он, и без его проверки требование осталось
-- бы пожеланием.
--
-- Что требует правки, а что нет — названо списком. Без границы роль либо не тронет
-- ничего («вроде и так понятно»), либо припишет абзац к каждой опечатке, и diff
-- подзадачи перестанет читаться.
--
-- Идемпотентность: условие `NOT LIKE '%документац%'` — повторный прогон и уже
-- дополненный текст не тронет.

-- Разработчик: привести описание в соответствие с кодом.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'Сейчас только разбор:',
        'Поведение изменилось — приведи описание в соответствие. Описание подсистемы\\n'
        'живёт в `.claude/docs/`, и разошедшееся хуже отсутствующего: по нему планируют\\n'
        'следующие задачи. Нужный файл ищется так:\\n'
        '  grep -ril "<имя того, что трогал>" .claude/docs/\\n'
        'Требует правки: новая точка API, новая таблица или колонка, новое поведение\\n'
        'существующего, изменившийся контракт. Не требует: правка внутри функции, тест,\\n'
        'опечатка, ускорение без смены поведения. Файла нет и подсистема новая — заведи\\n'
        'по образцу соседей и добавь строку в индекс CLAUDE.md.\\n\\n'
        'Сейчас только разбор:')
 WHERE `id` = 433
   AND `metadata` LIKE '%Сейчас только разбор:%'
   AND `metadata` NOT LIKE '%документац%';

-- QA: сверить описание с кодом. Отдельным пунктом приёмки, а не пожеланием.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'Цели из неё — критерии приёмки: по ним работу примет QA, и добавлять к ним',
        'Отдельно сверь документацию с кодом. Поведение изменилось — описание в\\n'
        '`.claude/docs/` обязано было измениться вместе с ним. Смотри, есть ли в\\n'
        '`git diff master...HEAD --stat` файлы `.claude/docs/`; нет — проверь, была ли\\n'
        'правка нужна: grep -ril "<имя того, что трогали>" .claude/docs/\\n'
        'Описание разошлось с кодом или подсистема новая и не описана — это `qa_ok: no`\\n'
        'наравне с незакрытой целью. Правка внутри функции, тест или опечатка описания\\n'
        'не требуют. Проверяй соответствие, а не объём: абзац, пересказывающий код\\n'
        'своими словами, ничего не улучшил.\\n\\n'
        'Цели из неё — критерии приёмки: по ним работу примет QA, и добавлять к ним')
 WHERE `id` = 445
   AND `metadata` LIKE '%Цели из неё — критерии приёмки%'
   AND `metadata` NOT LIKE '%документац%';
