-- Срок ожидания в очереди агента — настройкой, а не константой (2026-09-23)
--
-- ## ЗАЧЕМ
--
-- Срок был прибит в общем слое: `AI_FRAMEWORK_QUEUE_TTL = 60.0` в
-- `py_modules/ai/ai_thread.py`. Одно число мерило два разных случая:
--
--   * **чат с человеком** — дольше минуты ждать вправду незачем: HTTP-запрос уже
--     отвалился по 504, а запоздалый ответ собеседнику выдаёт бота;
--   * **пакетный прогон** — шаблон инвайтов просит несколько реплик ОДНИМ вызовом
--     и внутри крутит цикл «черновик → судья» на каждую. При одном слоте на агента
--     (`node.llm_parallel_per_agent_max` = 1 у ноды Dating) второй такой вызов
--     встаёт в очередь целиком и минуты не дожидается никогда.
--
-- Живой случай, с которого это началось: прогон `dating_invite_write` упал через
-- 60,1 с — «Агент 'invite_ladadate' занят: запрос отброшен по TTL очереди»
-- (трасса #37291).
--
-- ## ⚠⚠ Настройка ОБЩАЯ, а не на ноду
--
-- Соседний предел — слоты — живёт колонкой `node.llm_parallel_per_agent_max`, и
-- соблазн положить срок туда же велик. Но это разные вопросы: слоты про
-- **мощность узла**, срок про **терпение очереди**. Узел с двумя слотами и узел с
-- одним ждут одинаково — ждёт не узел, а заявка.
--
-- ## Что меняется в коде (уже сделано, миграция лишь заводит значение)
--
--   1. `py_modules/ai/framework/ai_framework_model.py` — поле
--      `llm_workflow_queue_ttl` у заявки, умолчание прежние 60 с;
--   2. `py_modules/ai/ai_thread.py` — диспетчер берёт срок **из заявки**;
--   3. `src/ai/ai_llm.py` — `ai_llm_queue_ttl_get()` читает настройку;
--   4. `src/ai/framework/agent/ai_framework_manager.py` — заполняет поле при
--      сборке модели.
--
-- ⚠ Читается **один раз на заявку**, а не диспетчером: тот крутится каждые 0,1 с,
-- и поход в базу на каждом обороте стоил бы дороже самой очереди.
--
-- ## Почему 180, а не 60
--
-- Три минуты покрывают цикл из нескольких вызовов к одному агенту: замерено, что
-- заход инвайтов с двумя репликами идёт около 40 секунд, а прогон целиком — до
-- десяти минут на папку. При этом чат человека столько не ждёт: его обрывает
-- **свой** таймаут (`chat_timeout`, 60 с по умолчанию), и до этого срока дело не
-- доходит.
--
-- ⚠ Ноль и отрицательное значение код считает опиской и берёт умолчание: «ждать
-- вечно» и «не ждать вовсе» настройкой не выражаются.
--
-- Идемпотентность: строка заводится только если её ещё нет — человек мог уже
-- поправить значение на странице, и перезатирать его миграция не вправе.

SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM `setting`
         WHERE `key` = 'llm_workflow_queue_ttl') AS есть_настройка;

INSERT INTO `setting` (`key`, `value`, `user_id`, `node_id`, `dynamic`)
SELECT 'llm_workflow_queue_ttl', '180', NULL, NULL, 0
 WHERE NOT EXISTS (SELECT 1 FROM `setting`
                    WHERE `key` = 'llm_workflow_queue_ttl'
                      AND `user_id` IS NULL AND `node_id` IS NULL);

SELECT 'ПОСЛЕ' AS этап,
       (SELECT `value` FROM `setting`
         WHERE `key` = 'llm_workflow_queue_ttl'
           AND `user_id` IS NULL AND `node_id` IS NULL) AS значение;
