-- Подпоток ветки переезжает на ШАГ (2026-10-07)
--
-- ЗАЧЕМ. Настройка была разорвана пополам, и половины жили на разных страницах:
-- карты вызова (`inputs_map`, `outputs_map`) правятся на шаге, а сам подпоток
-- выбирался на вкладке Branch, у ветки. Человек настраивал аргументы вызова, не
-- видя, кого вызывает, и чтобы сменить дорогу — уходил на другую вкладку.
--
-- ⚠⚠ Это не только про удобство. Карты принадлежат ПАРЕ «шаг + подпоток»: имена
-- в них — переменные конкретного подпотока. Храня подпоток у ветки, мы позволяли
-- сменить его из другого места и оставить карты от прежнего — молча, без единой
-- ошибки: движок на карту в никуда ругается в лог, которого никто не читает.
-- Отсюда же уходит правило «первый привязанный подпоток задаёт контракт, подмена
-- требует совпадения» — оно было подпоркой ровно под этот разрыв.
--
-- УСТРОЙСТВО. `branch.workflow_id` в метаданных шага; у ветки остаются имя,
-- порог и темы — то, что общее для всех её шагов.
--
-- ⚠⚠ Колонка `agent_workflow_branch.workflow_id` ЗДЕСЬ НЕ СНОСИТСЯ. Миграции
-- накатывает новый контейнер uvicorn до переключения слота, а трафик в этот
-- момент держит ещё старый код — он колонку читает. Снос едет второй выкладкой
-- (`deploy.md`, «Удаление из схемы едет ДВУМЯ выкладками»).
--
-- ⚠⚠ И значения в ней НЕ ЗАНУЛЯЮТСЯ — это не забывчивость. Пока снос не уехал,
-- колонка остаётся единственным местом, откуда дорогу можно вернуть при откате:
-- занули её сейчас, и откат на прежний код застал бы ветки без подпотоков, то
-- есть ответ агента молча стал бы общей генерацией вместо своей дороги.
-- Читателей у колонки с этой выкладки нет; она лежит мёртвым грузом ровно до
-- второй, где уйдёт вместе со своими значениями.

SET @type_branch = (SELECT `id` FROM `agent_workflow_step_type` WHERE `name` = 'branch');

-- Сколько шагов отдадут дорогу — до переноса, чтобы отчёт внизу было с чем
-- сравнить.
SET @before = (
    SELECT COUNT(*)
      FROM `agent_workflow_step` s
      JOIN `agent_workflow_branch` b
        ON b.`id` = CAST(JSON_UNQUOTE(JSON_EXTRACT(s.`metadata`, '$.branch.branch_id')) AS UNSIGNED)
     WHERE s.`type_id` = @type_branch
       AND b.`workflow_id` IS NOT NULL
);

-- ⚠ Перенос по ЛЮБОМУ шагу, который смотрит на ветку с дорогой, а не по
-- известному одному: на установке такой шаг сегодня один (#5235 → ветка 155 →
-- подпоток 74), но запрос обязан пережить вторую установку с другими номерами.
--
-- ⚠ `JSON_SET`, а не сборка строки: `metadata` — это JSON в `longtext`, и
-- склейка потеряла бы остальные ключи шага (переходы, `to_next_step`).
UPDATE `agent_workflow_step` s
  JOIN `agent_workflow_branch` b
    ON b.`id` = CAST(JSON_UNQUOTE(JSON_EXTRACT(s.`metadata`, '$.branch.branch_id')) AS UNSIGNED)
   SET s.`metadata` = JSON_SET(s.`metadata`, '$.branch.workflow_id', b.`workflow_id`)
 WHERE s.`type_id` = @type_branch
   AND b.`workflow_id` IS NOT NULL
   AND JSON_EXTRACT(s.`metadata`, '$.branch.branch_id') IS NOT NULL;

-- Шаг, смотрящий на ветку БЕЗ дороги, остаётся без ключа вовсе — это и значит
-- «ветка сужает общий ответ». Писать туда `null` незачем: движок читает
-- `branch_meta.get('workflow_id')`, и отсутствие ключа отвечает тем же.

SELECT 'ГОТОВО' AS этап,
       @before AS шагов_ждало_переноса,
       (SELECT COUNT(*)
          FROM `agent_workflow_step`
         WHERE `type_id` = @type_branch
           AND JSON_EXTRACT(`metadata`, '$.branch.workflow_id') IS NOT NULL) AS шагов_с_дорогой,
       (SELECT COUNT(*) FROM `agent_workflow_branch` WHERE `workflow_id` IS NOT NULL)
           AS веток_с_колонкой_пока_живой;
