-- Галочка «to next step» снята там, где путь по номеру ведёт в чужую ветку
--
-- ## ⚠⚠ ЗАЧЕМ
--
-- Движок идёт по позициям: шаг, чей переход не сработал, утекает в следующий.
-- Для прямой цепочки это верно, а у `dating_talk` шаги стоят так:
--
--     12 Ответ в чат      → Валидация
--     13 Письмо первым    → Валидация
--     14 Ответ на письмо  → Валидация
--     15 Инициатива       → Валидация
--     16 Валидация ответа → Проверка повтора
--     17 Проверка повтора → Ответ / Тишина
--
-- Следующий по номеру у каждой ветки — **соседняя ветка**, и граф рисует туда
-- стрелку: `graph.js` ставит её каждому нетерминальному шагу, о переходах не
-- спрашивая. Человек читает «после письма идёт ответ на письмо», хотя поток
-- туда не идёт никогда.
--
-- Галочка снимает и стрелку на графе, и сам путь: не сработал ни один переход —
-- шаг отвечает `no more step available` вместо тихого ухода в чужую ветку.
--
-- ## ⚠ Кому снимаем, а кому нет
--
-- | шаг | галочка | почему |
-- |-----|---------|--------|
-- | 12–15, ветки сочинения | снята | следующий по номеру — соседняя ветка |
-- | 16 Валидация | **оставлена** | её путь по номеру — «Проверка повтора», и это обычный ход |
-- | 17 Проверка повтора | **оставлена** | её путь по номеру — «Ответ», и это законный исход |
-- | 18–19, 21 (`return_response_*`) | не трогаем | они и так заканчивают прогон |
-- | 20 «Ветка: письма и фото» | снята | следующий — «Ответ ветки», но попасть туда можно только её переходом |
-- | 22 `girl_fact_create` | **оставлена** | это прямая цепочка: дальше «Влить придуманные факты» |
--
-- ⚠⚠ У «Валидации» галочку **не трогаем**, и это главное решение здесь. Её
-- `transitions_after` уводит на «Тишину» при `girl_response_skip = 1`; во всех
-- прочих случаях поток обязан идти дальше по номеру — на «Проверку повтора».
-- Снять галочку значило бы оборвать обычный ход: ответ, который агент написал,
-- не дошёл бы до отправки вовсе.
--
-- Итог: снимаем у 12, 13, 14, 15 и 20. Остальные живут как жили.
--
-- ## ⚠ Идемпотентность
--
-- `JSON_SET` кладёт `false` поверх любого прежнего значения; повторный прогон
-- ничего не меняет. Умолчание (ключа нет) значит «включена», и шаги, которых
-- здесь нет, его сохраняют.

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_talk');

SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND JSON_EXTRACT(`metadata`, '$.to_next_step') IS NOT NULL)
         AS шагов_с_галочкой;

UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(COALESCE(`metadata`, '{}'), '$.to_next_step', FALSE)
 WHERE `workflow_id` = @wf
   AND `title` IN ('Ответ в чат', 'Письмо первым', 'Ответ на письмо',
                   'Инициатива', 'Ветка: письма и фото')
   AND `metadata` IS NOT NULL AND `metadata` <> '' AND JSON_VALID(`metadata`);

SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND JSON_EXTRACT(`metadata`, '$.to_next_step') = FALSE)
         AS путь_по_номеру_закрыт,
       -- ⚠ Проверка обратной стороны: у прямых шагов галочка НЕ появилась.
       -- Сними её у «Проверки повтора» — и обычный ответ перестал бы доходить.
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND `title` IN ('Валидация ответа', 'Проверка повтора',
                           'girl_fact_create', 'Влить придуманные факты')
           AND JSON_EXTRACT(`metadata`, '$.to_next_step') IS NOT NULL)
         AS прямые_тронуты_ошибочно;
