-- Workflow `dating_favorite_mail_write`: письмо, возобновляющее разговор (2026-09-11)
--
-- ЗАЧЕМ. У панели замкнулась цепочка почты: разослали → он ответил → мы ответили
-- → ждём. Он не пишет. Разговор затихает, и сам собой не оживает: все наши поводы
-- написать были реакцией на его письмо.
--
-- Этот workflow даёт повод. Письмо пишется **первым** тому, кто уже отвечал (он в
-- избранных у девушки), и это не знакомство, а продолжение прерванного разговора.
--
-- ⚠ ПОЧЕМУ НЕ `dating_mail_reply`. Тот отвечает на ПОСЛЕДНЕЕ письмо мужчины — его
-- первое правило так и написано. Здесь отвечать не на что: последнее слово наше,
-- и письмо, притворяющееся ответом, спрашивало бы о том, чего он не говорил.
-- Задача обратная — заметить, что ответа нет, и дать разговору новый повод, не
-- упрекая молчанием.
--
-- ⚠ ПОЧЕМУ НЕ `dating_mail_write`. Тот пишет ШАБЛОН — заготовку для всех, без
-- имён и без конкретики, и нарочно не получает ни анкеты, ни собеседника. Здесь
-- конкретика и есть суть: письмо одному человеку, с которым уже говорили, и
-- ссылка на сказанное — единственное, что отличает его от рассылки.
--
-- ЧЕМУ УЧИТ ПРОМПТ.
--
-- 1. **Разговор был, и он прервался.** Поводом служит то, о чём уже говорили, —
--    вопрос, оставшийся без ответа, рассказ, который можно продолжить.
-- 2. **Без упрёка.** «Ты пропал», «почему не отвечаешь» — это претензия, и она
--    закрывает разговор надёжнее молчания.
-- 3. **Не повторять уже написанное.** Переписка перед глазами целиком, включая
--    прошлые возобновления: второе письмо теми же словами выдаёт робота.
-- 4. **Язык — заданный переменной**, как у ответа: фильтр сайта отклоняет
--    кириллицу, и русское письмо не дойдёт вовсе.
-- 5. **Никаких переменных в скобках**: это готовый текст, а не шаблон.
--
-- Идемпотентность: всё вставляется по условию отсутствия.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow`
         WHERE `name` = 'dating_favorite_mail_write') AS workflow_есть;

-- ------------------------------------------- Сам workflow
INSERT INTO `agent_workflow` (`node_id`, `name`, `title`, `description`, `position`, `subflow`)
SELECT 2, 'dating_favorite_mail_write', 'Возобновление разговора',
       'Пишет письмо тому, кто уже отвечал, но замолчал: повод продолжить '
       'прерванный разговор. Для пула «Переписка» на вкладке «Фавориты»',
       0, 0
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow`
                    WHERE `name` = 'dating_favorite_mail_write');

SET @wf = (SELECT `id` FROM `agent_workflow`
            WHERE `name` = 'dating_favorite_mail_write');

-- ------------------------------------------- Единственный шаг
--
-- ⚠ Один шаг и обычный текст, а не JSON в два шага, как у `dating_mail_reply`.
-- Там второй шаг нужен проверке черновика (`reply_hint`); здесь проверять нечем —
-- требований к тексту, выразимых регуляркой, у письма нет. Разбор ответа делает
-- панель (`dating_mail_agent._letter`): снимает размышления модели и markdown.
INSERT INTO `agent_workflow_step` (`workflow_id`, `type_id`, `title`, `position`, `metadata`)
SELECT @wf, 1, 'Письмо', 0,
       JSON_OBJECT(
         'transitions_after', JSON_ARRAY(),
         'prompt_user',
         CONCAT(
           'Ты пишешь письмо мужчине на сайте знакомств от имени девушки. Они ',
           'уже переписывались, но разговор прервался: последнее слово осталось ',
           'за ней, и он не ответил.\n\n',
           '=== Требуемый язык ответа (код) ===\n%user_language%\n\n',
           '=== Переписка (старые сверху, последнее — внизу) ===\n',
           '%mail_history%\n\n',
           '=== Кто пишет ===\n%girl_card%\n\n',
           '=== Кому пишет ===\n%companion_card%\n\n',
           'Правила:\n',
           '1. Это НЕ ответ на его письмо — отвечать не на что, последним писала ',
           'она. Задача другая: дать разговору новый повод. Оттолкнись от того, о ',
           'чём уже говорили: вопрос, оставшийся без ответа, тема, которую он ',
           'поднимал, рассказ, который можно продолжить.\n',
           '2. НИ СЛОВА УПРЁКА. «Ты пропал», «почему не отвечаешь», «я ждала» — ',
           'это претензия, и она закрывает разговор надёжнее молчания. Пиши так, ',
           'будто пауза — обычное дело, и ты просто вспомнила о нём.\n',
           '3. Не повторяй того, что уже написано выше. Переписка перед тобой ',
           'целиком, включая прежние письма с её стороны: второе письмо теми же ',
           'словами выдаёт робота.\n',
           '4. Пиши РОВНО на требуемом языке, указанном выше. Это жёсткое ',
           'требование, а не пожелание: сайт фильтрует письма и не на том языке ',
           'отклоняет — письмо не дойдёт до человека вовсе.\n',
           '5. Два-три коротких абзаца. Длинное письмо после молчания читается ',
           'как заготовка, которую разослали всем.\n',
           '6. Один вопрос в конце — чтобы ответить было чем и легко. Не три: ',
           'анкета вместо письма.\n',
           '7. Никаких переменных в квадратных скобках и никаких плейсхолдеров: ',
           'это готовый текст, а не шаблон. Имена бери из карточек выше.\n',
           '8. Не обещай встреч, не проси денег, не давай контактов вне сайта.\n',
           '9. Ответ — только сам текст письма. Без темы, без пояснений, без ',
           'markdown и размышлений: всё, что ты напишешь, уйдёт человеку как есть.'
         ))
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow_step`
                    WHERE `workflow_id` = @wf AND `position` = 0);

-- ------------------------------------------- Привязка переменных
--
-- Все четыре уже заведены соседними workflow: переменные в этой базе общие, и
-- вторая с тем же именем сделала бы подстановку неоднозначной.
INSERT INTO `agent_workflow_variable_workflow` (`variable_id`, `workflow_id`)
SELECT v.`id`, @wf FROM `agent_workflow_variable` v
 WHERE v.`name` IN ('mail_history', 'girl_card', 'companion_card', 'user_language')
   AND v.`type` = 'workflow'
   AND NOT EXISTS (SELECT 1 FROM `agent_workflow_variable_workflow` vw
                    WHERE vw.`variable_id` = v.`id` AND vw.`workflow_id` = @wf);

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT `id` FROM `agent_workflow`
         WHERE `name` = 'dating_favorite_mail_write') AS workflow_id,
       (SELECT COUNT(*) FROM `agent_workflow_step` WHERE `workflow_id` = @wf) AS шагов,
       (SELECT COUNT(*) FROM `agent_workflow_variable_workflow`
         WHERE `workflow_id` = @wf) AS переменных;
