-- `dating_talk`: переменная `make_initiative` — заговорить первой (2026-09-19)
--
-- ЗАЧЕМ. Workflow отвечает на сказанное: есть реплика собеседника — есть ответ. У
-- инициативы реплики нет вовсе, поводом служит **тишина**, и «ответь на пустоту»
-- даёт вежливое ничто: «как дела?» в третий раз подряд.
--
-- Переменная `make_initiative` меняет задачу шага сочинения: не «ответь», а
-- «заговори». Пустая или `0` — всё как было.
--
-- ⚠⚠ ПРИЁМ ВЫБИРАЕМ МЫ, А НЕ МОДЕЛЬ, и это главное решение этой миграции.
--
-- Соблазн написать «будь разной, придумай что-нибудь» велик и уже проверен на
-- инвайтах: три шаблона из трёх начинались с «you're trouble». Модель не умеет
-- быть разной по требованию — она держит один тон и возвращается к нему всегда.
--
-- Поэтому приём приходит **готовым**, переменной `initiative_kind`: жребий бросает
-- панель (`initiative.py`), и разнообразие обеспечивает она же. Шаг получает одну
-- задачу и выполняет одну задачу.
--
-- ⚠ ИСТОРИЯ И ФАКТЫ ЗДЕСЬ УЖЕ СОБРАНЫ предыдущими шагами — отдельной ветки под
-- инициативу не нужно. Меняем **одну** секцию «Что нужно»: всё, что до неё,
-- работает одинаково для обоих случаев.
--
-- ⚠ СУДЬЯ ПРИ ИНИЦИАТИВЕ НЕ МОЛЧИТ: панель зовёт её с `answer_anyway=1`, и путь
-- молчания закрыт (`wf_dating_talk_answer_anyway`). Инициатива, на которую агент
-- промолчал, — это заход, потраченный впустую: пара останется затихшей, а счётчик
-- повторов не сдвинется.
--
-- Идемпотентность: шаг переписывается целиком.

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_talk');

SELECT 'ДО' AS этап, @wf AS workflow,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%make_initiative%'
          FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 10)
       AS уже_есть;

UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(
         `metadata`, '$.prompt_user',
         REPLACE(
           JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')),
           '=== Что нужно ===\n1. Вернуть короткий ответ:',
           CONCAT(
             '%if make_initiative%',
             '=== Что нужно ===\n',
             '⚠⚠ ЭТО НЕ ОТВЕТ. Собеседник молчит — ты пишешь ему САМА, первой, '
             'после паузы. Отвечать не на что: последнее слово в разговоре твоё.\n\n',
             'Приём на этот раз: %initiative_kind%\n\n',
             '⚠ Приём выбран за тебя — исполни именно его, не подменяй другим и не '
             'смешивай несколько в одной реплике. Одна мысль, один ход.\n\n',
             '1. Одно-два предложения, до 25 слов, как в мессенджере.\n',
             '2. Не спрашивай, почему он молчит, не упрекай и не извиняйся за '
             'сообщение — это читается как «мне нужно внимание».\n',
             '3. Не повторяй того, что уже говорила в истории переписки: посмотри '
             'её и зайди с другого.\n',
             '4. Не начинай с «привет» и не здоровайся заново — разговор уже идёт, '
             'просто в нём была пауза.\n',
             '5. Тон живой и приземлённый: работа, быт, кафе, сериалы, спорт, '
             'поездки, планы. Без поэзии и высокопарности.\n',
             '6. Соответствуй времени суток и тому, о чём говорили раньше.\n',
             '7. Отвечай строго на языке: %user_language%.\n',
             '8. ⚠ Пустую строку возвращать НЕЛЬЗЯ: это заход инициативы, и '
             'молчание тратит его впустую.\n\n',
             '=== Important information about final response ===\n',
             'Please return your response in JSON format. The JSON response must '
             'contain follow keys: \n',
             '- "girl_response": твоя реплика\n\n',
             'Example of JSON response:\n',
             '{\n  "girl_response": "у нас тут дождь третий день, я уже забыла как '
             'выглядит солнце"\n}\n',
             '%else%',
             '=== Что нужно ===\n1. Вернуть короткий ответ:',
             '%endif%')))
 WHERE `workflow_id` = @wf AND `position` = 10;

-- ⚠ Хвост обычной ветки (пункты 2-5 и формат ответа) остаётся за `%endif%` — он
-- уже в промпте и нужен обоим случаям... нет: под инициативой он не нужен, и
-- закрывающий `%endif%` стоит ДО него нарочно. Ветка инициативы возвращает свой
-- формат ответа целиком и заканчивается сама; обычная — как была.
--
-- ⚠⚠ Здесь легко ошибиться местом `%endif%`, и ошибка тихая: обе ветки
-- склеиваются, модель читает два противоречивых списка требований и выбирает
-- произвольно. Проверка ниже смотрит, что ветка инициативы **заканчивается**
-- своим примером ответа.

SELECT 'ПОСЛЕ' AS этап,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%make_initiative%'
          FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 10)
       AS ветка_есть,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%initiative_kind%'
          FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 10)
       AS приём_приходит_извне,
       (SELECT (LENGTH(JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')))
                - LENGTH(REPLACE(JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')),
                                 '%endif%', '')))
               / LENGTH('%endif%')
          FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 10)
       AS сколько_endif;
