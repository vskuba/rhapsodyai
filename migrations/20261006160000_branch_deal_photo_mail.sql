-- Первая ветка и первая тема: «Договориться» и письма с фотографиями (2026-10-06)
--
-- ЗАЧЕМ. Слой веток заведён пустым, и проверить его не на чем. Здесь он
-- наполняется тем, что уже работает в проде: тема `photo_mail` переезжает из
-- промптов `dating_talk_about_photo` в запись реестра.
--
-- ⚠ Тексты перенесены, а не придуманы: `acceptance` и `restriction` — это те же
-- четыре случая и тот же список запретов, что стоят в промпте подпотока с
-- 21.09.2026. Разойдись они, ветка начала бы отвечать иначе, чем отвечала.
--
-- ⚠⚠ Поле `direction` в прежнем промпте отсутствовало вовсе: там была только
-- реакция («соглашайся»), а направления не было. Оно и есть то, ради чего слой
-- заводился, — и здесь оно появляется впервые.
--
-- Метки: из двух слов и больше. Односложные не различают близкие темы — слово
-- «письмо» ровно так же стоит в рассказе про письмо от деда.

SET @node_dating = (SELECT `id` FROM `node` WHERE `name` = 'Dating');
SET @wf_photo = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_talk_about_photo');

INSERT INTO `agent_workflow_branch`
       (`node_id`, `name`, `title`, `description`, `workflow_id`, `match_min`, `position`)
SELECT @node_dating, 'deal', 'Договориться',
       'Разговор, где нужно не поддержать беседу, а договориться: письма, фотографии, встреча',
       @wf_photo, 1, 0
 WHERE @node_dating IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM (SELECT * FROM `agent_workflow_branch`) x
                    WHERE x.`node_id` = @node_dating AND x.`name` = 'deal');

SET @branch_deal = (SELECT `id` FROM `agent_workflow_branch`
                     WHERE `node_id` = @node_dating AND `name` = 'deal');

INSERT INTO `agent_workflow_branch_topic`
       (`branch_id`, `name`, `title`, `tags`, `acceptance`, `direction`, `restriction`, `position`)
SELECT @branch_deal, 'photo_mail', 'Письма и фотографии',
       'обмен письмами, пришли письмо, интимное письмо, перейти в письма, прислать фотографии, покажи фото, скинь фотку, почему не отвечаешь письмом',

       CONCAT(
         'Разговор зашёл про письма и фотографии. Здесь нужно договориться, а не поддержать беседу.\n\n',
         'Сперва пойми, о чём именно речь, и ответь по своему случаю:\n',
         '1. Он предлагает прислать СВОИ фотографии — соглашайся охотно и скажи, что ждёшь его письмо. Покажи интерес: ему важно, что его хотят увидеть.\n',
         '2. Он просит ТВОИ фотографии — соглашайся и скажи, что пришлёшь письмом. Не обещай конкретного часа: «сегодня вечером» превращается в упрёк, если письмо придёт завтра.\n',
         '3. Он зовёт перейти в письма без упоминания фотографий — соглашайся: в письмах спокойнее и можно написать длиннее.\n',
         '4. Он спрашивает, почему не отвечаешь письмом — скажи, что напишешь.'),

       CONCAT(
         'Веди разговор в письма: там спокойнее, можно написать длиннее и показать себя. ',
         'Если он ещё не звал в письма — дай понять, что тебе там будет удобнее ответить подробно.'),

       CONCAT(
         'Не описывай, что именно на фотографиях, и не обещай ничего откровенного: обещание, которого не выполнить, хуже отказа.\n',
         'Не проси денег, не упоминай оплату писем и не жалуйся на неё.\n',
         'Не давай почту, телефон и никаких контактов вне сайта.\n',
         'Не отказывайся и не уходи от темы: он спросил прямо, и уклончивость читается как «нет».'),
       0
 WHERE @branch_deal IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM (SELECT * FROM `agent_workflow_branch_topic`) x
                    WHERE x.`branch_id` = @branch_deal AND x.`name` = 'photo_mail');

SELECT 'ГОТОВО' AS этап,
       @branch_deal AS ветка,
       @wf_photo AS её_подпоток,
       (SELECT COUNT(*) FROM `agent_workflow_branch_topic`
         WHERE `branch_id` = @branch_deal) AS тем;
