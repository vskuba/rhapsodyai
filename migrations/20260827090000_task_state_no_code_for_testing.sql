-- `project_task`.`pipeline_state` — новое значение `no_code_for_testing`.
--
-- Что это. Терминальное и успешное состояние подзадачи: перед кругом QA конвейер
-- смотрит каталог подзадачи, и если в ветке нет ни коммитов, ни незакоммиченных
-- правок — проверять нечего. Такое бывает, когда работа подзадачи уже лежит в
-- `master`: её сделала соседняя подзадача, прошлый круг или человек руками.
--
-- Почему отдельное значение, а не `done`. «Проверено и принято» и «проверять было
-- нечего» — разные факты, и склеив их, мы потеряли бы второй: по журналу нельзя
-- было бы отличить подзадачу, которую QA разобрал по целям, от той, где он не
-- запускался вовсе. И не `failed`: это не сбой, работа сделана — просто не здесь.
--
-- Почему это обязательно, а не «желательно». Колонка — ENUM, и MySQL в нестрогом
-- режиме на неизвестное значение не ругается, а молча пишет пустую строку. Подзадача
-- тогда залипает навсегда: финализация ищет `done`/`blocked`/`failed`, реклейм —
-- свои состояния, и пустую строку не видит ни один из них.
--
-- Порядок значений менять нельзя: ENUM хранится числом, и перестановка переписала бы
-- состояния уже существующих строк. Новое значение только в конец.
--
-- Идемпотентность. `MODIFY COLUMN` с тем же определением безвреден: на базе, где
-- значение уже есть, файл ничего не меняет.
--
-- Имени базы здесь нет намеренно: `USE` в миграции однажды увёл прогон «в песочницу»
-- на рабочую базу. Имя задаёт подключение.
ALTER TABLE `project_task`
    MODIFY COLUMN `pipeline_state` ENUM('new','planning','plan_approval','reviewing','approved',
                                        'processing','testing','planned','developing','qa_pending',
                                        'failed_qa','blocked','done','failed','bugfixing',
                                        'no_code_for_testing')
        DEFAULT NULL;
