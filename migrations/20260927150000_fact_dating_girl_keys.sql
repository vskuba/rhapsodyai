-- Факты девушек: ключи под номер сайта (2026-09-27)
--
-- ## ЗАЧЕМ
--
-- Ключ документа фактов собирается у соседа как `%girl_id%_%girl_name%`, и обе его
-- части в DatingAi только что сменились:
--
--     girl_id    цифры логина  →  номер анкеты НА САЙТЕ
--     girl_name  «Elena»       →  «elena» (латиница строчными)
--
-- Накопленные документы остались под прежними ключами. Агент их не найдёт: он
-- ищет фильтром по новому `document_id`, а факты лежат под старым. Молча — ответы
-- останутся осмысленными, просто девушка перестанет помнить о себе.
--
-- ## Что переименовывается
--
--     120998_Diana   →  418024_diana     анкета 41, цифры логина 120998
--     8511_Oksana    →  413636_oksana    анкета 48, цифры логина 8511
--     89_Elena       →  599939_elena     анкета 43, цифры логина 89
--
-- ⚠ `643694_diana` (23 факта, самый большой документ) **не трогается**: он и был
-- собран правильно — из номера сайта и имени строчными. Это и есть довод, что новая
-- схема не выдумана, а восстановлена.
--
-- ## ⚠⚠ Почему пары записаны буквами, а не выведены запросом
--
-- Соответствие «старый ключ → новый» живёт в **другой базе**: номер сайта и имя
-- лежат в `profile` у DatingAi, на своём сервере MySQL. Соединить их запросом
-- нельзя, а повторять правило сборки ключа здесь значило бы завести его вторую
-- копию — ту самую, что разойдётся с первой.
--
-- Поэтому пары сняты с живых данных обеих баз 27.09.2026 и записаны как есть.
-- Проверка совпадения: у каждой старый ключ = «цифры логина + имя», новый = «номер
-- сайта + имя строчными», имя у обеих частей одно.
--
-- ⚠ Локально этих ключей нет вовсе (там свои тестовые), и миграция там — пустая
-- работа с честным отчётом «переименовано 0». Это не повод не применять: базы
-- расходятся данными, а не схемой.
--
-- ## ⚠⚠ QDRANT ПОЧИНИТСЯ САМ, И ЧИСТИТЬ ЕГО НЕ НАДО
--
-- Факты в Qdrant — проекция этой таблицы, и напрашивается мысль, что переименование
-- оставит там сирот под прежним ключом. **Не оставит**, и вот почему: точка
-- адресуется не ключом документа, а **номером строки MySQL** —
--
--     point_id = uuid5(NAMESPACE_DNS, 'fact_id_<fact.id>')      qdrant_save()
--
-- Номер строки переименование не трогает. Значит `qdrant_synced = 0` ниже заставит
-- крон `fact_qdrant_sync` переписать **те же самые шесть точек** новым содержимым
-- payload. Ни дублей, ни сирот: было 29 точек — останется 29.
--
-- ⚠ Проверено на проде, а не выведено из кода: все шесть точек нашлись ровно по
-- `uuid5('fact_id_117')`…`uuid5('fact_id_122')` со старым `document_id` в payload, и
-- всего в коллекции 29 точек при 29 строках в таблице — одна на строку.
--
-- ⚠⚠ Поэтому `qdrant_remove_by` по старому ключу звать **не нужно**, и до пересинка
-- прямо вредно: удалённые точки крон восстановит, но в промежутке девушка окажется
-- без фактов на ровном месте.
--
-- ## ⚠⚠⚠ ЕДИНСТВЕННОЕ, ЧТО ДЕЙСТВИТЕЛЬНО ТРЕБУЕТ ПОРЯДКА
--
-- Ключ фактов собирает **сам сосед**, шагом «Переменные» из `%girl_id%_%girl_name%`.
-- То есть ключ сменится в ту секунду, когда DatingAi начнёт слать новые значения, —
-- и к этой секунде в Qdrant уже должны лежать точки с новым ключом.
--
--     1. эта миграция                 MySQL: новые ключи, `synced = 0`
--     2. крон `fact_qdrant_sync`      Qdrant: те же точки, новый payload
--     3. выкладка DatingAi            панель начинает слать новые значения
--
-- Между 1 и 2 панель шлёт ещё **старые** ключи, а в Qdrant лежат старые точки — то
-- есть находит. После 2 и до 3 — то же самое. Разрыва нет ни на одном шаге.
--
-- ⚠ А вот выложи DatingAi раньше шага 2 — и девушки отвечали бы без своих фактов
-- всё время до ближайшего прогона крона. Молча: пустая выборка не ошибка.

SELECT 'ДО' AS этап, f.document_id AS ключ, COUNT(*) AS фактов,
       SUM(f.qdrant_synced = 0) AS не_синхронизировано
  FROM fact f JOIN fact_collection fc ON fc.id = f.collection_id
 WHERE fc.name = 'dating_girl'
 GROUP BY f.document_id ORDER BY f.document_id;

SET @was_total = (SELECT COUNT(*) FROM fact f
                    JOIN fact_collection fc ON fc.id = f.collection_id
                   WHERE fc.name = 'dating_girl');

-- ⚠ Коллекция ищется **по имени**: её номер у баз свой, как и у всего остального.
--
-- ⚠⚠ `qdrant_synced = 0` — половина работы: без него переименование осталось бы
-- только в MySQL, а поиск у агента идёт по Qdrant, где ключ прежний.
UPDATE `fact` f
  JOIN `fact_collection` fc ON fc.id = f.collection_id
  JOIN (
            SELECT '120998_Diana' AS was_key, '418024_diana' AS new_key
  UNION ALL SELECT '8511_Oksana',             '413636_oksana'
  UNION ALL SELECT '89_Elena',                '599939_elena'
  ) pairs ON pairs.was_key = f.document_id
   SET f.document_id = pairs.new_key,
       f.qdrant_synced = 0
 WHERE fc.name = 'dating_girl';

SELECT 'ПОСЛЕ' AS этап, f.document_id AS ключ, COUNT(*) AS фактов,
       SUM(f.qdrant_synced = 0) AS не_синхронизировано
  FROM fact f JOIN fact_collection fc ON fc.id = f.collection_id
 WHERE fc.name = 'dating_girl'
 GROUP BY f.document_id ORDER BY f.document_id;

-- ⚠⚠ Сверка по существу, а не по числу строк. «Столько же фактов» верно и тогда,
-- когда переименование не сработало вовсе.
SELECT 'старых ключей осталось' AS проверка, COUNT(*) AS сколько
  FROM fact f JOIN fact_collection fc ON fc.id = f.collection_id
 WHERE fc.name = 'dating_girl'
   AND f.document_id IN ('120998_Diana', '8511_Oksana', '89_Elena');

-- ⚠ Ни один факт не должен потеряться: `UPDATE` не удаляет, но проверить дешевле,
-- чем однажды искать пропажу.
SELECT 'фактов было / стало' AS проверка, @was_total AS было,
       (SELECT COUNT(*) FROM fact f JOIN fact_collection fc ON fc.id = f.collection_id
         WHERE fc.name = 'dating_girl') AS стало;

-- ⚠ Сколько ждёт досыла: это и есть работа для крона `fact_qdrant_sync` — он
-- перепишет те же точки, а не заведёт новые (см. ⚠⚠ выше).
SELECT 'ждут досыла в Qdrant' AS проверка, COUNT(*) AS сколько
  FROM fact f JOIN fact_collection fc ON fc.id = f.collection_id
 WHERE fc.name = 'dating_girl' AND f.qdrant_synced = 0;
