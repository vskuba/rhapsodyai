-- Три круга доработки разработчику и потолок прогона в четыре часа.
--
-- Разбор: почему круги повторяются прогон за прогоном. У подзадачи #5219 семь из
-- десяти последних попыток кончились «Разработчик не ответил за 4800с» — прогон
-- обрывался по таймауту, конвейер ставил его заново, и так по кругу. Каждый такой
-- заход стоил восьмидесяти минут работы агента и не давал ничего.
--
-- Замеры по 41 прогону разработчика (`project_task_metric`, секунды):
--
--   разбор       481   (худший 1226)
--   реализация  1169   (худший 4807)
--   отчёт JSON   240   (худший 1207)
--   самопроверка 355   (худший 1240)
--   ответ JSON    53   (худший  106)
--
-- Первый круг до самопроверки — 38 минут. Каждая доработка добавляет 30: разбор не
-- повторяется, замечания приходят готовыми (`dev_critique` в промпте реализации).
-- Три круга по среднему — 99 минут, при прежнем потолке 7000с (117 минут) третий
-- уже впритык, а по худшим замерам не хватало и на первый.
--
-- Отсюда две правки.
--
-- **`max_dev_iterations` 2 -> 3.** Разработчик получает право трижды вернуть себе
-- работу на доработку по собственным замечаниям; на четвёртый круг замечания больше
-- не принимаются и работа уходит к QA как есть. Это не бесконечность: механизм
-- ограничен сверху, а каждый круг обязан прибавлять код (`task_metric_lines_advanced`),
-- иначе попытка сгорает.
--
-- **`timeout_developer_run` 7000 -> 14400 (четыре часа).** Потолок на весь прогон, а
-- не на шаг: три круга по среднему укладываются вдвое, а патологический случай
-- обрывается, не заняв оболочку на полсуток. Шесть часов (три круга по худшим
-- замерам) не берём намеренно — оболочка и модель в проекте пока в одном экземпляре,
-- и висящая подзадача останавливает всю очередь.
--
-- Лестница таймаутов обязана сохраниться: прогон агента < job воркера < блокировка
-- строки (`task_setting_timeout_ladder_problem`). Иначе воркера убьют раньше, чем
-- прогон сорвётся сам, либо соседний тик заберёт строку, над которой ещё работают.
-- Поэтому `timeout_worker_job` и `timeout_task_lock` поднимаются следом, с шагом в
-- десять минут: этого хватает на постановку в очередь и уборку.
--
-- `timeout_qa_run` (7400) не трогаем: у QA кругов доработки нет, он выносит вердикт
-- за один заход. Лестницу он не ломает — потолок в ней берётся максимальный из
-- ролей, а это теперь разработчик.
--
-- Идемпотентность: каждое условие проверяет прежнее значение — повторный прогон и
-- уже поднятые настройки не тронет.

-- Три круга доработки.
UPDATE `agent_workflow_variable`
   SET `default` = '3',
       `description` = 'Максимум кругов самопроверки разработчика (workflow task_developer). '
                       'Три круга доработки по своим же замечаниям; на четвёртый работа '
                       'уходит к QA как есть'
 WHERE `name` = 'max_dev_iterations'
   AND `default` = '2';

-- Потолок прогона разработчика: четыре часа.
UPDATE `setting` SET `value` = '14400'
 WHERE `key` = 'timeout_developer_run' AND `value` = '7000';

-- Лестница: job воркера и блокировка строки идут следом за самым долгим агентом.
UPDATE `setting` SET `value` = '15000'
 WHERE `key` = 'timeout_worker_job' AND CAST(`value` AS UNSIGNED) < 15000;

UPDATE `setting` SET `value` = '15600'
 WHERE `key` = 'timeout_task_lock' AND CAST(`value` AS UNSIGNED) < 15600;
