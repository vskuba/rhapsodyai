-- Ссылки на шаги в ветках — по номеру этой базы, а не прода (2026-09-24)
--
-- ## ⚠⚠ ЧТО СЛОМАНО И ЧЕМ
--
-- Миграция `20260924010000_wf_talk_branches` завела четыре ветки сочинения,
-- вписав тексты промптов **литералами, снятыми с прода**. А в промпте живут
-- ссылки на результаты соседних шагов, и имя такой переменной содержит **номер
-- шага**, а не его позицию:
--
--     %qdrant_fact_search_676_result_str%
--
-- Номер 676 — это `qdrant_fact_search_girl_tags` **на проде**. В любой другой
-- базе у того же шага номер свой: в рабочей это 1529. То есть на проде промпт
-- верен, а везде ещё ссылается в пустоту, и поиск фактов по меткам девушки
-- молча не попадает в ответ.
--
-- ⚠ Беда тихая вдвойне. Переменная без значения не оставляет метку в тексте
-- (`workflow.md`, §3.1) — секция просто исчезает, и ответ выглядит обычным.
--
-- ## ⚠ Почему так вышло и как не повторить
--
-- Правило записано в `workflow.md`, §8 п.1: «Имя результата шага содержит его
-- `id`, а не позицию. Копируя шаг из другого workflow, ссылку надо перецелить».
-- Я скопировала промпты между **базами**, и правило действует там же.
--
-- Поэтому чинится не подстановкой числа, а **поиском по названию**: миграция
-- находит настоящий номер шага в этой базе и переписывает ссылку. На проде она
-- не меняет ничего — номер там уже верный.
--
-- ## ⚠ Сличения у баз разные — их нельзя поминать
--
-- `metadata` в рабочей базе `utf8mb4_general_ci`, на проде `utf8mb4_0900_ai_ci`.
-- Сравнение столбца с `CONCAT(…, @переменная, …)` роняет запрос: у
-- пользовательской переменной та же «весомость» сличения, что у столбца, и
-- MySQL отказывается выбирать между ними (`Illegal mix of collations` — поймано
-- этой же миграцией на первом прогоне). Прописать `COLLATE` было бы проще и
-- неверно: имя подошло бы ровно одной из двух баз.
--
-- Поэтому `@tags` участвует только в **сборке** строки замены, а сравнения идут
-- с литералом.

-- ## ⚠⚠ Заменяем ТОЛЬКО номер прода, а не «любой номер по шаблону»
--
-- Первая попытка правила гласила «найти `qdrant_fact_search_<любое>_result` и
-- поставить свой номер». Она сломала то, что чинила: в промпте **две** разные
-- ссылки подряд —
--
--     %qdrant_fact_search_25_result_str%%qdrant_fact_search_676_result_str%
--
-- поиск фактов о девушке и поиск по её меткам, — и замена по шаблону сделала
-- обе одинаковыми. Поймано сверкой с продом после прогона.
--
-- Поэтому заменяется ровно `676`: это литерал, попавший в промпты из миграции
-- `…_wf_talk_branches`, и он один и тот же в любой базе, куда та миграция
-- доехала. На проде замена ничего не меняет — там 676 и есть верный номер.

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_talk');
SET @tags = (SELECT `id` FROM `agent_workflow_step`
              WHERE `workflow_id` = @wf
                AND `title` = 'qdrant_fact_search_girl_tags' LIMIT 1);

SELECT 'ДО' AS этап, @tags AS настоящий_номер,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND `metadata` LIKE '%qdrant\_fact\_search\_676\_result%')
         AS шагов_с_номером_прода;

UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(`metadata`, 'qdrant_fact_search_676_result',
         CONCAT('qdrant_fact_search_', @tags, '_result'))
 WHERE `workflow_id` = @wf
   AND `title` IN ('Ответ в чат', 'Письмо первым', 'Ответ на письмо', 'Инициатива')
   AND @tags <> 676
   AND `metadata` LIKE '%qdrant\_fact\_search\_676\_result%';

SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND `metadata` LIKE '%qdrant\_fact\_search\_676\_result%')
         AS осталось_с_номером_прода,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND `title` IN ('Ответ в чат', 'Письмо первым', 'Ответ на письмо',
                           'Инициатива')
           AND `metadata` REGEXP 'qdrant_fact_search_[0-9]+_result')
         AS веток_со_ссылками;
