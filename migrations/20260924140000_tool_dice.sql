-- Инструмент «жребий»: разнообразие, которое модель сама себе не даёт (2026-09-24)
--
-- ## ⚠⚠ ЗАЧЕМ
--
-- «Будь разной» модель не исполняет — это измеренный закон проекта, а не
-- осторожность. Три шаблона инвайтов из трёх начинались с «you're trouble».
-- Вилка «от абзаца до трёх» дала девять писем из двенадцати ровно в три абзаца.
-- Единственный пример в конце промпта работает выкройкой: пять писем прода из
-- восьми открывались его оборотом.
--
-- Вывод один и тот же: выбирать должен кто-то снаружи модели. Раньше выбирала
-- панель — и каждая новая грань разнообразия стоила четырёх мест: настройка в
-- реестре DatingAi, код панели, объявление переменной, правка промпта. Этот
-- инструмент сводит их к одному: жребий лежит рядом с промптом, который им и
-- пользуется.
--
-- ## Как выглядит
--
--     вход   {"mail_opening": {"вспомнила о тебе": 40, "новость про себя": 60}}
--     выход  {"mail_opening": "вспомнила о тебе"}
--
-- Переменных сколько угодно, но хотя бы одна; вариантов у каждой сколько угодно,
-- но хотя бы два — один вариант это не жребий, а постоянное значение.
--
-- ⚠ Доля может быть меткой (`"%favorite_mail_name_percent%"`): метаданные шага
-- проходят подстановку **до** вызова инструмента, так что шанс вправе приходить
-- из настройки сайта или входящей переменной workflow.
--
-- ## ⚠⚠ Почему миграцией, а не синхронизацией
--
-- Инструменты умеет собирать `ai_tool_sync`, но ручка зовёт его с `force=True`,
-- то есть перетряхивает **весь** реестр разом — сто с лишним строк ради одной
-- новой. Здесь заводится ровно одна запись, и её видно в diff.
--
-- ⚠ Значения `args` и `description` — те же, что вывел бы сканер из сигнатуры и
-- докстринга (проверено вызовом `inspect`): случись когда-нибудь общий пересбор,
-- он ничего не изменит.

-- ── Группа: имя даёт папка инструмента с большой буквы (`ai_tool_sync`) ─────
INSERT INTO `tool_group` (`name`)
SELECT 'Dice'
 WHERE NOT EXISTS (SELECT 1 FROM (SELECT 1) AS x
                    WHERE EXISTS (SELECT 1 FROM `tool_group` WHERE `name` = 'Dice'));

SET @grp = (SELECT `id` FROM `tool_group` WHERE `name` = 'Dice' LIMIT 1);

-- ── Сам инструмент ──────────────────────────────────────────────────────────
--
-- ⚠ `name` обязан совпадать с именем **функции**: движок достаёт её из модуля
-- через `getattr(module, tool_name)`. Разойдись они — шаг упадёт «не удалось
-- подготовить функцию к запуску», и виновата будет эта строка, а не код.
INSERT INTO `tool` (`name`, `group_id`, `path`, `description`, `args`)
SELECT 'dice', @grp, '/app/src/tool/dice/dice.py',
       'Бросить жребий по каждой переменной и вернуть выпавшие значения.',
       JSON_OBJECT('input', JSON_OBJECT('spec', JSON_OBJECT(
                       'type', 'dict', 'default', 'Required')),
                   'output', JSON_OBJECT('type', 'dict'))
 WHERE NOT EXISTS (SELECT 1 FROM (SELECT 1) AS x
                    WHERE EXISTS (SELECT 1 FROM `tool` WHERE `name` = 'dice'));

UPDATE `tool`
   SET `group_id` = @grp,
       `path` = '/app/src/tool/dice/dice.py',
       `args` = JSON_OBJECT('input', JSON_OBJECT('spec', JSON_OBJECT(
                       'type', 'dict', 'default', 'Required')),
                            'output', JSON_OBJECT('type', 'dict'))
 WHERE `name` = 'dice';

SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `tool_group` WHERE `name` = 'Dice') AS группа,
       (SELECT COUNT(*) FROM `tool` WHERE `name` = 'dice') AS инструмент,
       (SELECT JSON_TYPE(JSON_EXTRACT(`args`, '$.input.spec'))
          FROM `tool` WHERE `name` = 'dice') AS довод_описан;
