-- `dating_favorite_mail_write`: письмо без переписки перед глазами (2026-09-13)
--
-- ЧТО СЛУЧИЛОСЬ. У панели изменилось правило отбора: письмо избранному пишут по
-- звёздочке, а не по наличию переписки в её базе. Звезду ставят тому, кто отвечал,
-- — значит разговор был; но шёл он на сайте, возможно задолго до панели, и в
-- `dating_message` мог не приехать вовсе. У одной анкеты в списке избранных
-- восемнадцать человек, переписка нашлась у одного.
--
-- Промпт же написан в уверенности, что переписка есть: «Они уже переписывались»,
-- «оттолкнись от того, о чём уже говорили». Получив пустой блок, модель честно
-- выполняла инструкцию — и **сочиняла общее прошлое**. Живые черновики с прода:
--
--     «I was cleaning out the old photo archive today and stumbled upon a
--      snapshot from that coffee shop we mentioned a while back…»
--     «…we left off mid-conversation…»
--
-- Ни кофейни, ни прерванного разговора не было: модель не видела ни строчки.
-- Человеку такое письмо выдаёт робота вернее молчания — он-то помнит, о чём
-- говорил, а чаще помнит, что не говорил вовсе.
--
-- ⚠ ПОЧЕМУ ПРАВКА ЗДЕСЬ, А НЕ В ПАНЕЛИ. Панель пробовала своё: вместо истории
-- отправляла указание «переписки нет, не выдумывай». Инструкция в переменной
-- данных — место неверное (переменная обещает текст переписки) и работает плохо:
-- модель читала её как часть разговора. У промпта для этого есть ветвление, и
-- пустая строка для шаблонизатора ложна.
--
-- ЧТО МЕНЯЕТСЯ:
--
-- 1. Блок переписки ветвится: `%if mail_history%` — как было, `%else%` — прямой
--    запрет ссылаться на прошлое и указание, на что опереться вместо него.
-- 2. Вступление больше не утверждает, что переписка есть: «они знакомы» — правда
--    в обоих случаях, «они уже переписывались, и вот их слова» — только в первом.
-- 3. Правило 1 раздвоено по тому же признаку.
-- 4. Добавлено правило про выдумку: она названа прямо и с примером.
--
-- ⚠ ЧЕГО ЗДЕСЬ НЕТ. Борьбы с «размышлениями»: модель подтекает хвостом
-- `…</think>` вопреки прямому запрету в правиле 9, и просить её ещё раз — ничего
-- не менять. Срезает их панель (`dating_mail_agent._letter`) — там это надёжно.
--
-- Идемпотентность: `UPDATE` по имени workflow; накат дважды даёт тот же текст.

SET @wf = (SELECT `id` FROM `agent_workflow`
            WHERE `name` = 'dating_favorite_mail_write');

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап, @wf AS workflow,
       (SELECT LOCATE('%if mail_history%',
                      JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))) > 0
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 0) AS ветвление_есть;

-- ------------------------------------------- Промпт
UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(
         `metadata`, '$.prompt_user',
         CONCAT(
           'Ты пишешь письмо мужчине на сайте знакомств от имени девушки. Они ',
           'знакомы: он у неё в избранных, а туда попадают те, кто отвечал. ',
           'Последнее слово осталось за ней, и он молчит.\n\n',
           '=== Требуемый язык ответа (код) ===\n%user_language%\n\n',
           '%if mail_history%',
           '=== Переписка (старые сверху, последнее — внизу) ===\n',
           '%mail_history%\n\n',
           '%else%',
           '=== Переписки перед тобой нет ===\n',
           'Разговор был раньше — на сайте, до панели, — и его текст нам ',
           'недоступен. Ты не знаешь о нём НИЧЕГО: ни тем, ни слов, ни ',
           'обстоятельств.\n\n',
           '%endif%',
           '=== Кто пишет ===\n%girl_card%\n\n',
           '=== Кому пишет ===\n%companion_card%\n\n',
           'Правила:\n',
           '1. Это НЕ ответ на его письмо — отвечать не на что, последним писала ',
           'она. Задача другая: дать разговору новый повод.\n',
           '   • Если переписка выше есть — оттолкнись от неё: вопрос, оставшийся ',
           'без ответа, тема, которую он поднимал, рассказ, который можно ',
           'продолжить.\n',
           '   • Если переписки нет — опирайся ТОЛЬКО на карточку собеседника: ',
           'город, возраст, занятие, интересы. Этого достаточно для одного ',
           'открытого вопроса.\n',
           '2. НИКОГДА НЕ ВЫДУМЫВАЙ ОБЩЕЕ ПРОШЛОЕ. Без переписки перед глазами ',
           'запрещено писать «мы говорили о…», «помнишь, ты рассказывал…», «мы ',
           'остановились на полуслове», «та кофейня, которую мы обсуждали». Он ',
           'помнит, чего не говорил, и выдуманная подробность выдаёт робота ',
           'вернее молчания. Не помнишь — не вспоминай: пиши так, как пишут ',
           'доброму знакомому, с которым давно не общались.\n',
           '3. НИ СЛОВА УПРЁКА. «Ты пропал», «почему не отвечаешь», «я ждала» — ',
           'это претензия, и она закрывает разговор надёжнее молчания. Пиши так, ',
           'будто пауза — обычное дело, и ты просто вспомнила о нём.\n',
           '4. Не повторяй того, что уже написано выше. Переписка перед тобой ',
           'целиком, включая прежние письма с её стороны: второе письмо теми же ',
           'словами выдаёт робота.\n',
           '5. Пиши РОВНО на требуемом языке, указанном выше. Это жёсткое ',
           'требование, а не пожелание: сайт фильтрует письма и не на том языке ',
           'отклоняет — письмо не дойдёт до человека вовсе.\n',
           '6. Два-три коротких абзаца. Длинное письмо после молчания читается ',
           'как заготовка, которую разослали всем. Без переписки — короче: два ',
           'абзаца, и лучше один.\n',
           '7. Один вопрос в конце — чтобы ответить было чем и легко. Не три: ',
           'анкета вместо письма.\n',
           '8. Никаких переменных в квадратных скобках и никаких плейсхолдеров: ',
           'это готовый текст, а не шаблон. Имена бери из карточек выше.\n',
           '9. Не обещай встреч, не проси денег, не давай контактов вне сайта.\n',
           '10. Ответ — только сам текст письма. Без темы, без пояснений, без ',
           'markdown и размышлений: всё, что ты напишешь, уйдёт человеку как есть.'
         ))
 WHERE `workflow_id` = @wf AND `position` = 0;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT LOCATE('%if mail_history%',
                      JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))) > 0
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 0) AS ветвление_есть,
       (SELECT LOCATE('НЕ ВЫДУМЫВАЙ ОБЩЕЕ ПРОШЛОЕ',
                      JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))) > 0
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 0) AS запрет_есть;
