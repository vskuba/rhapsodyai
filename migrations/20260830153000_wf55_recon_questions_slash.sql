-- Лишний слеш у `questions` в шаге 419 (WF55).
--
-- Хвост к `20260830152000`. Обратный слеш там собирался `CHAR(92)` дважды — по числу
-- слешей, которые показывал клиент mysql. Клиент их удваивает при выводе: в колонке
-- перед `"plan` лежит один слеш (`7B 5C 22`), а на экране он выглядит как два. Сверив
-- по виду, я поставил два — и `questions` получил вдвое больше экранирования, чем
-- соседи (`20 5C 5C 22`).
--
-- На глаз такое не различить, поэтому проверять надо `HEX`, а не выводом клиента.
--
-- Приводим к одному слешу, как у `plan`, `subtasks` и `goals`. Слеши по-прежнему
-- собираем `CHAR(92)`, чтобы правка не зависела от правил экранирования по дороге.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        CONCAT(CHAR(92), CHAR(92), '"questions', CHAR(92), CHAR(92), '"'),
        CONCAT(CHAR(92), '"questions', CHAR(92), '"'))
 WHERE `id` = 419
   AND LOCATE(CONCAT(CHAR(92), CHAR(92), '"questions'), `metadata`) > 0;
