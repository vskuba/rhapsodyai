-- `dating_invite_write`: шаг правки тоже возвращает ВСЕ реплики (2026-09-18)
--
-- ЧТО ПОКАЗАЛ ЖИВОЙ ПРОГОН. Просили двенадцать реплик, черновик их и прислал,
-- судья честно забраковал повторы («рельефные семантические и структурные повторы
-- в 7-9 репликах») — а шаг правки вернул ОДНУ. В пул легли двенадцать анкет с
-- одним текстом на всех: ровно то, от чего уходили.
--
-- ПОЧЕМУ. Требование «ровно %invite_count% реплик» в этот шаг соседняя миграция
-- дописала, но **шапка осталась прежней**: «Напиши вместо него новый», «=== Забра-
-- кованный текст ===» — всё в единственном числе. Модель читает шапку первой и
-- слушается её; требование в середине проигрывает.
--
-- ⚠⚠ ЭТО ОБЩЕЕ ПРАВИЛО, А НЕ ЧАСТНЫЙ СЛУЧАЙ. Правя промпт кусками, легко оставить
-- согласование в числе или роде в тех местах, которые не трогал, — и модель пойдёт
-- за ними, а не за новым требованием. Здесь шаг переписывается целиком.
--
-- Идемпотентность: промпт переписывается целиком.

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_invite_write');

SELECT 'ДО' AS этап, @wf AS workflow,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%Напиши вместо него новый%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 3) AS шапка_в_единственном;

UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(
         `metadata`, '$.prompt_user',
         CONCAT(
           'Редактор забраковал черновик. Напиши вместо него новый набор реплик — ',
           'так, чтобы замечание было снято.\n\n',
           '⚠⚠ Реплик должно быть РОВНО %invite_count% штук, разделённых строкой ',
           'из трёх дефисов (---) на отдельной строке. Столько же, сколько просили ',
           'у автора: каждая уйдёт от своей девушки, и недостающих взять неоткуда.\n\n',
           '=== Забракованный набор ===\n%invite_draft%\n\n',
           '=== Замечание редактора ===\n%invite_why%\n\n',
           '=== Что требуется ===\n',
           '⚠ Замечание редактора выше — служебный текст, он написан по-русски для ',
           'человека. Язык замечания к репликам отношения не имеет: пиши РОВНО на ',
           'языке с кодом ниже. Сайт фильтрует сообщения и не на том языке ',
           'отклоняет — реплика не дойдёт до человека вовсе.\n',
           'Язык (код): %user_language%\n',
           'Метки: %invite_slots%\n',
           'Сколько реплик: %invite_count%\n\n',
           '⚠⚠ ГЛАВНОЕ, если замечание про похожесть: реплики должны отличаться ',
           'ДРУГ ОТ ДРУГА по существу. Не синонимами и не перестановкой слов, а ',
           'заходом: одна дразнит, другая признаётся, третья спрашивает, четвёртая ',
           'предлагает игру, пятая жалуется на скуку. Две реплики про «докажи» или ',
           'две про «я почти пролистала» — это повтор, сколько бы разных слов в них ',
           'ни было.\n\n',
           'Требования те же: по одному абзацу каждая, игривый дразнящий тон, ровно ',
           'запрошенные метки и никаких других (во всём проекте их две: ',
           '[[girl_name]] и [[companion_name]]), никаких имён словами, ссылок и ',
           'контактов. [[girl_name]] — твоё собственное имя, говори о себе в первом ',
           'лице.\n\n',
           'Не объясняй правку и не извиняйся: нужны только новые тексты.\n\n',
           'Верни строго JSON с ключами:\n',
           '- "invite_draft": все %invite_count% реплик, разделённые строкой «---»\n',
           '- "invite_ok": строка "fixed"\n\n',
           'Пример ответа для трёх реплик:\n',
           '{"invite_draft": "Спорим, ты сейчас улыбнулся?\n---\nУ меня к тебе ',
           'неприличный вопрос, но сначала скажи — ты из тех, кто краснеет?\n---\n',
           'Знаешь, я обычно не пишу первой, но сегодня мне скучно настолько, что я ',
           'решила рискнуть.", "invite_ok": "fixed"}'))
 WHERE `workflow_id` = @wf AND `position` = 3;

SELECT 'ПОСЛЕ' AS этап,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%новый набор реплик%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 3) AS шапка_во_множественном,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%РОВНО %invite_count%%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 3) AS число_в_шапке,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%ДРУГ ОТ ДРУГА%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 3) AS правило_разности;
