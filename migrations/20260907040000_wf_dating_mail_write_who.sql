-- `dating_mail_write` перестаёт путать отправительницу с получателем (2026-09-07)
--
-- ЧТО БЫЛО. Письмо начиналось так: «[[girl_name]], it is such a pleasure to read
-- your profile!» — то есть обращение к получателю подставляло имя **девушки**, от
-- которой письмо. Дальше по тексту `[[companion_name]]` встречалась к месту, так
-- что переменные агент понимал, — а кто из них кто, нет.
--
-- ЦЕНА. Письмо, начинающееся с собственного имени отправительницы, выглядит
-- ровно тем, чем является: машинной подстановкой. Это первое, что видит человек,
-- открыв письмо.
--
-- ОТЧЕГО ТАК ВЫШЛО. Правило «обращайся к нему по имени через переменную»
-- потерялось при прошлой правке (`20260907010000`): туда дописали запрет писать
-- имена словами, и старый пункт заменили целиком, вместе с указанием, к кому
-- письмо обращено. Осталось «вставляй переменные», без «какую куда».
--
-- ЧТО ВМЕСТО. Правило вернулось и стало точнее: **имена переменных придумывает
-- человек**, и `girl_name` завтра может называться `sender`. Поэтому промпт учит
-- не именам, а способу: рядом с каждой переменной в списке стоит подпись —
-- «Имя девушки, от которой письмо», «Имя получателя письма», — и её надо
-- прочитать, а не угадывать по имени переменной.
--
-- Идемпотентность: условие на то, что правила про обращение ещё нет.

-- ---------------------------------------------------------------- До
SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_mail_write');

SELECT 'ДО' AS этап,
       @wf AS workflow_id,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND `metadata` LIKE '%Обращение — к получателю%') AS правило_есть;

-- ------------------------------------------- Кто есть кто
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '4. Переменные — ровно те, что в списке. Других не выдумывай: их нечем подставить, и письмо не уйдёт.\\n',
        '4. Переменные — ровно те, что в списке. Других не выдумывай: их нечем подставить, и письмо не уйдёт.\\n'
        '5. Обращение — к получателю, а не к себе. У каждой переменной в списке есть подпись: она говорит, чьё это имя. Прочитай её, а не угадывай по имени переменной: письмо, начинающееся с имени отправительницы, читается как машинная подстановка.\\n')
 WHERE `workflow_id` = @wf
   AND `metadata` LIKE '%Других не выдумывай%'
   AND `metadata` NOT LIKE '%Обращение — к получателю%';

-- ------------------------------------------- Перенумеровать хвост
--
-- Пункты после вставленного сдвигаются: список с двумя «пятыми» читается как
-- недосмотр, а промпт — тоже текст, который читают.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '5. Пиши живо и просто',
        '6. Пиши живо и просто')
 WHERE `workflow_id` = @wf
   AND `metadata` LIKE '%5. Пиши живо и просто%'
   AND `metadata` LIKE '%Обращение — к получателю%';

UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '6. Ответ — только текст письма.',
        '7. Ответ — только текст письма.')
 WHERE `workflow_id` = @wf
   AND `metadata` LIKE '%6. Ответ — только текст письма.%'
   AND `metadata` LIKE '%Обращение — к получателю%';

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND `metadata` LIKE '%Обращение — к получателю%') AS правило_новое,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND `metadata` LIKE '%7. Ответ — только текст%') AS хвост_перенумерован;
