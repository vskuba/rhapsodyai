-- Вернуть время строкам реестра, которые и так были в UTC.
--
-- Две предыдущие миграции (`..140000_registry_time_utc`, `..141000_registry_created_utc`)
-- сдвинули все строки `ai_claude_session_registry` на смещение из настройки `timezone`,
-- считая, что все они записаны местным временем. Для установки, заведённой недавно, это
-- верно. Для установки постарше — нет.
--
-- **Часы у регистрации менялись.** До коммита `964060f` (2026-08-11 16:36 +03) она писала
-- `now = datetime.now()` — время контейнера, а контейнер живёт по UTC. После — `datetime_now()`,
-- то есть время в поясе настройки. `created_at` до того коммита ставила база своим
-- `DEFAULT CURRENT_TIMESTAMP`, тоже UTC. Значит строки, заведённые раньше, уже лежали в UTC
-- и сдвигать их не следовало: их пометки уехали бы на три часа в прошлое.
--
-- Обе колонки в паре менялись вместе, поэтому по данным этого не видно: у сессии, которая
-- зарегистрировалась и сразу умолкла, `created_at` и `last_seen_at` отличаются на секунду и
-- до, и после коммита. Различает только дата.
--
-- **Граница — 2026-08-11 16:00 по записанным значениям, до сдвига.** Установка, обновившаяся
-- на этот коммит, пишет местное время, и первая её строка будет не раньше 16:36 местных.
-- Установка, ещё не обновившаяся, пишет UTC, и её строки того дня меньше 16:00, пока
-- обновление не случилось позже 19:00 местных. На известных установках разрыв надёжный:
-- на рабочей самая ранняя строка — 16:42 того же дня, на боевой последняя дококоммитная —
-- 12:17, а следующая только 17 августа.
--
-- Сравниваем с уже сдвинутым значением, поэтому от границы отнимается то же смещение:
-- строка, лежавшая как `12:17`, после двух миграций стала `09:17`, и порог `16:00` для неё
-- превращается в `13:00`.
--
-- Почему отдельной миграцией, а не правкой тех двух. Они уже применены на рабочей
-- установке и записаны в `_yoyo_migration`; правка файла ничего бы там не переиграла, зато
-- разошлась бы с тем, что на самом деле выполнено. Возврат отдельным шагом честнее: на
-- боевой все три пройдут подряд и дадут верный итог, на рабочей третья не найдёт ни одной
-- строки и не сделает ничего.

-- Смещение читается подзапросом трижды, а не через пользовательскую переменную: порядок
-- её вычисления внутри одного запроса MySQL не определяет, и `SET` мог бы прочитать её
-- раньше, чем `WHERE` присвоит. NULL в `last_seen_at` и `closed_at` переживает сложение
-- сам — `NULL + INTERVAL` даёт NULL, и отдельная проверка не нужна.
--
-- `WHERE` сверяется с исходными значениями строки, а не с теми, что кладёт `SET`: MySQL
-- вычисляет условие до записи, поэтому `created_at` в условии — ещё сдвинутый, как и
-- рассчитано.

UPDATE `ai_claude_session_registry`
   SET `created_at`   = `created_at`   + INTERVAL COALESCE((SELECT CAST(REPLACE(REPLACE(value, 'UTC', ''), ' ', '') AS SIGNED)
            FROM `setting`
           WHERE `key` = 'timezone' AND user_id IS NULL AND node_id IS NULL
           LIMIT 1), 0) HOUR,
       `last_seen_at` = `last_seen_at` + INTERVAL COALESCE((SELECT CAST(REPLACE(REPLACE(value, 'UTC', ''), ' ', '') AS SIGNED)
            FROM `setting`
           WHERE `key` = 'timezone' AND user_id IS NULL AND node_id IS NULL
           LIMIT 1), 0) HOUR,
       `closed_at`    = `closed_at`    + INTERVAL COALESCE((SELECT CAST(REPLACE(REPLACE(value, 'UTC', ''), ' ', '') AS SIGNED)
            FROM `setting`
           WHERE `key` = 'timezone' AND user_id IS NULL AND node_id IS NULL
           LIMIT 1), 0) HOUR
 WHERE `created_at` < TIMESTAMP('2026-08-11 16:00:00') - INTERVAL COALESCE((SELECT CAST(REPLACE(REPLACE(value, 'UTC', ''), ' ', '') AS SIGNED)
            FROM `setting`
           WHERE `key` = 'timezone' AND user_id IS NULL AND node_id IS NULL
           LIMIT 1), 0) HOUR;
