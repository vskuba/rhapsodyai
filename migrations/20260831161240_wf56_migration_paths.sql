-- Промпт разработчика перестаёт врать про миграции (шаг 435, WF56).
--
-- Две правки, обе из разбора подзадачи #5219.
--
-- **Первая: метка времени с секундами.** Правило `YYYYMMDDHHMMSS` записано в
-- `database_rules.md` давно, но в проекте все 42 метки «круглые» (`...150000`,
-- `...140500`) — их писали руками, округляя. Роль копирует то, что видит, и две
-- работы одного часа берут один номер. Живьём: #5219 собиралась завести
-- `20260831150000_wf57_qa_mode.sql`, а такой номер за четверть часа до неё занял
-- соседний файл. Два файла на одну метку yoyo применит в неопределённом порядке, а
-- при слиянии веток это конфликт.
--
-- Лечится не правилом, а командой: `date +%Y%m%d%H%M%S` не оставляет выбора.
--
-- **Вторая: промпт ссылается на то, чего нет.** В нём стояло «схема БД меняется
-- только в `migrations/0001.sql`, данные — через Seed UI или скрипт в
-- `data/migration_manual/`». Ни файла, ни папки в проекте нет: начальная схема
-- заморожена под именем `20260101000000_initial_schema.sql`, а `migration_manual`
-- упразднена (см. `.claude/docs/migration.md`, CLAUDE.md).
--
-- Разработчик читает промпт как указание и идёт искать несуществующий путь — это
-- прямо объясняет, почему у #5219 шестнадцать минут круга ушло на «сверку якорей»
-- вместо работы. Устаревшее указание хуже отсутствующего: отсутствующее отправляет
-- читать документацию, а это ведёт в тупик с видом уверенности.
--
-- Идемпотентность: каждое условие проверяет, что заменяемый текст ещё на месте.

-- 1. Пути: и схема, и данные — обычной миграцией с меткой времени.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '- Схема БД меняется только в migrations/0001.sql. Данные — через Seed UI или\\n  скрипт в data/migration_manual/. Прод и общие системы не трогаешь.',
        '- Схема и данные меняются одинаково — файлом в migrations/ с меткой времени.\\n'
        '  Имя берёшь командой: date +%Y%m%d%H%M%S — секунды обязательны, иначе две\\n'
        '  работы одного часа возьмут один номер и столкнутся при слиянии.\\n'
        '  Прод и общие системы не трогаешь.')
 WHERE `id` = 435
   AND `metadata` LIKE '%migrations/0001.sql%';

-- 2. Там же, где правило про миграции: назвать команду, а не оставлять на догадку.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'Файл —\\n`migrations/<метка времени>_<что делаешь>.sql`; применит его yoyo при старте\\n',
        'Файл — migrations/<метка>_<что делаешь>.sql, где метка это date +%Y%m%d%H%M%S\\n'
        'целиком, с секундами. Применит его yoyo при старте\\n')
 WHERE `id` = 435
   AND `metadata` LIKE '%migrations/<метка времени>_<что делаешь>.sql%';
