-- QA не пересказывают ему же его разбор — шаг 447 (WF57).
--
-- Что было. Промпт прогона проверок открывался блоком:
--
--     === ЧТО ТЫ РАЗОБРАЛ И НАМЕТИЛ ПРОВЕРИТЬ ===
--     %qa_recon%
--
-- `qa_recon` — это `response` предыдущего шага, то есть **весь** вывод агента на
-- разборе. Промпт разбора просит короткий итог («не длиннее 15 строк, строка на файл
-- и строка на проверку»), но в переменную попадает не итог, а всё, что агент сказал
-- по дороге, включая реплики между вызовами инструментов.
--
-- Живьём в блок уезжало вот это, дословно и по-английски:
--
--     The log is large with many failed runs. Let me read the later successful rounds
--     and get the full diff. Now let me examine the QA agent file... Let me examine
--     `_taskFlagSave`, the `json_from_string` behavior...
--
-- Заголовок обещает разобранное и намеченное, а под ним лежит поток намерений.
--
-- Почему блок не нужен вовсе, а не «нужен, но почище». Все шаги QA идут в **одну
-- живую сессию** Claude Code (`session: task_shell_session`): разбор и прогон — это
-- две реплики одному и тому же процессу, у которого контекст не прерывался. Агент
-- помнит свой разбор без напоминания; вклеивать его обратно — платить токенами за
-- пересказ самому себе. А то, что стоит помнить между кругами, лежит в журнале
-- подзадачи (`.task-state.md`, `.task-log.md`), и промпт разбора уже велит его читать.
--
-- Ни одна другая роль так не делает: Manager, Developer и Bugfixer пишут свой разбор
-- в переменную и обратно не подставляют. QA был единственным.
--
-- Переменную `qa_recon` не трогаем. Она остаётся в `outputs_map` шага 446 и работает
-- признаком «агент вообще ответил»: переход `empty -> 456` уводит круг в «QA
-- недоступен». Уберём её оттуда — и молчание оболочки станет неотличимо от разбора.
--
-- Идемпотентность: условие `LIKE '%qa_recon%'` — повторный прогон уже почищенный
-- текст не тронет.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '%endif%=== ЧТО ТЫ РАЗОБРАЛ И НАМЕТИЛ ПРОВЕРИТЬ ===\\n%qa_recon%\\n\\n',
        '%endif%Разбор ты только что сделал сам, в этой же сессии — он у тебя перед\\n'
        'глазами, пересказывать его себе не нужно. Забыл, что уже проверено в прошлых\\n'
        'кругах, — смотри журнал подзадачи (.task-state.md, .task-log.md).\\n\\n')
 WHERE `id` = 447
   AND `metadata` LIKE '%qa_recon%';
