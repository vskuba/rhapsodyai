-- Требование к документации у разработчика — шаг 433 (WF56).
--
-- Хвост к `20260830170000`. Там правка шага 433 не прошла и промолчала: условие
-- идемпотентности стояло `NOT LIKE '%документац%'`, а слово в промпте уже было — в
-- отсылке к правилам проекта («.claude/docs/ и .claude/docs-common/ — именование,
-- размещение кода, схема БД, документация»). Условие сработало как «уже добавлено»,
-- `UPDATE` затронул ноль строк, отказа при этом нет.
--
-- Урок общий: признаком «уже применено» должна быть фраза из самой правки, а не слово,
-- которое могло встретиться в тексте по любому другому поводу. Здесь такой признак —
-- «приведи описание в соответствие».
--
-- Смысл правки — в соседней миграции: разошедшееся описание хуже отсутствующего, по
-- нему менеджер планирует следующие задачи.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'Сейчас только разбор:',
        'Поведение изменилось — приведи описание в соответствие. Описание подсистемы\n'
        'живёт в `.claude/docs/`, и разошедшееся хуже отсутствующего: по нему планируют\n'
        'следующие задачи. Нужный файл ищется так:\n'
        '  grep -ril "<имя того, что трогал>" .claude/docs/\n'
        'Требует правки: новая точка API, новая таблица или колонка, новое поведение\n'
        'существующего, изменившийся контракт. Не требует: правка внутри функции, тест,\n'
        'опечатка, ускорение без смены поведения. Файла нет и подсистема новая — заведи\n'
        'по образцу соседей и добавь строку в индекс CLAUDE.md.\n\n'
        'Сейчас только разбор:')
 WHERE `id` = 433
   AND `metadata` LIKE '%Сейчас только разбор:%'
   AND `metadata` NOT LIKE '%приведи описание в соответствие%';
