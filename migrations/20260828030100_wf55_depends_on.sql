-- Менеджер называет зависимости между подзадачами — шаги 424 и 502 (WF55).
--
-- Зачем. План был плоским списком, и конвейер брал подзадачи в работу разом. Но они
-- не равноправны: «написать тесты вкладки» не начать раньше, чем вкладка есть, а
-- «проверить на стенде» — раньше обеих. Живой повод: #2438 разложилась на три
-- подзадачи, третья опиралась на первую, и все три ушли в работу одновременно.
--
-- Кто ещё, если не менеджер. Зависимости видны только тому, кто разбивал: он решал,
-- где провести границы, и знает, какая половина без какой не работает. Вывести их
-- потом из текста плана — гадание.
--
-- Номера позиционные (1, 2, 3…), а не id: строк на момент планирования ещё нет.
-- В id их переводит `task_depend_apply` сразу после создания подзадач.
--
-- Ссылки только назад. `depends_on` описывает порядок работы, и ссылка на подзадачу,
-- идущую позже, означает, что менеджер сам не решил, что за чем, — принять её
-- значит завести цикл на ровном месте. Такие связи отсеивает `task_depend_plan_links`,
-- но сказать об этом в промпте дешевле, чем молча выбрасывать.
--
-- Здесь же усилено требование целей. Разбиение #2438 пришло с планами, но без целей
-- у всех трёх подзадач — конвейер принял его молча, а QA потом нечем было доказывать
-- работу: он принимает подзадачу по её целям. Пустой список целей теперь назван
-- недопустимым прямо в контракте JSON, рядом с таким же требованием к массиву.
--
-- Идемпотентность: `REPLACE` по точной подстроке. Повторный прогон ничего не найдёт
-- и ничего не изменит; текст, уже содержащий `depends_on`, второй раз не дополнится.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '- goals — 1-4 проверяемые цели именно этой подзадачи',
        '- depends_on — номера подзадач из этого же списка, без которых эту не начать.\\n'
        '  Считай по порядку с единицы. Зависимость это про код, а не про смысл:\\n'
        '  ставь её, когда исполнителю нужен файл или функция, которых до соседней\\n'
        '  подзадачи не существует. Ссылайся только назад — на подзадачи выше по\\n'
        '  списку. Ни от кого не зависит — пустой массив, и это обычный случай:\\n'
        '  чем меньше связей, тем больше подзадач идёт параллельно.\\n'
        '- goals — 1-4 проверяемые цели именно этой подзадачи')
 WHERE `id` = 424
   AND `metadata` LIKE '%- goals — 1-4 проверяемые цели именно этой подзадачи%'
   AND `metadata` NOT LIKE '%depends_on%';

UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '\\"plan\\": \\"- шаг\\\\n- шаг\\", \\"goals\\": [\\"проверяемая цель\\"]}]}',
        '\\"plan\\": \\"- шаг\\\\n- шаг\\", \\"goals\\": [\\"проверяемая цель\\"], \\"depends_on\\": [1]}]}')
 WHERE `id` = 502
   AND `metadata` NOT LIKE '%depends_on%';

UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '- У каждого объекта ровно четыре поля: title, description, plan, goals.',
        '- У каждого объекта ровно пять полей: title, description, plan, goals, depends_on.\\n'
        '- depends_on — массив номеров подзадач из этого же ответа, считая с единицы:\\n'
        '  тех, без которых эту не начать. Ни от кого не зависит — пустой массив [].\\n'
        '  Ссылки только назад: номер меньше собственного.')
 WHERE `id` = 502
   AND `metadata` LIKE '%ровно четыре поля%';

UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '- goals — массив строк, не объект и не одна строка через запятую.',
        '- goals — массив строк, не объект и не одна строка через запятую.\\n'
        '- goals пустым быть не может: по целям QA принимает работу, и подзадача без\\n'
        '  них уходит на проверку, которой нечего доказывать. Минимум одна цель.')
 WHERE `id` = 502
   AND `metadata` NOT LIKE '%goals пустым быть не может%';
