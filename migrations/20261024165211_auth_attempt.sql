-- Заслон от подбора пароля: счёт неудачных попыток входа.
--
-- Схема перенесена из эталона общего скелета — `dashboard/src/panel/schema/
-- auth_attempt.sql`; читает её `panel_auth_throttle.py`. Правя одно, сверься
-- со вторым: разойдутся — общий код не найдёт колонки.
--
-- Зачем: вход отвечал `401` на любую попытку и больше ничего не делал. Замер
-- на живой установке — двенадцать неверных паролей подряд, двенадцать `401`,
-- время ответа не росло. Теперь каждая неудача удваивает паузу до следующей
-- попытки: 1с, 2с, 4с … 15 минут потолок.

-- ⚠⚠ Строка на СУБЪЕКТА, а не на попытку. Журнал попыток рос бы ровно так
-- быстро, как идёт перебор, — то есть атака наполняла бы диск, и заслон сам
-- становился бы уязвимостью. Здесь перебор в миллион попыток оставляет две
-- строки.
CREATE TABLE IF NOT EXISTS `auth_attempt`
(
    -- Кого считаем: `login` — имя, под которым пробуют войти, `ip` — адрес.
    -- ⚠ Два счёта про разное: логин ловит подбор пароля к аккаунту, адрес —
    -- перебор логинов с одной точки. Держит тот, у кого срок больше.
    `kind`       ENUM ('login', 'ip') NOT NULL,

    -- ⚠ 190 — ровно столько знаков utf8mb4 индексируется в одном ключе.
    `subject`    VARCHAR(190)         NOT NULL,

    `fails`      INT UNSIGNED         NOT NULL DEFAULT 0,

    -- ⚠⚠ Время в UTC, как и везде: заслон сравнивает сроки, и смешай мы
    -- пояса, пауза оказалась бы то нулевой, то трёхчасовой.
    `last_fail`  DATETIME             NOT NULL,

    -- Раньше этого мгновения пробовать нельзя. ⚠ Хранится СРОК, а не
    -- длительность: иначе правка констант задним числом меняла бы запрет тем,
    -- кто уже его отбыл.
    `allowed_at` DATETIME             NOT NULL,

    PRIMARY KEY (`kind`, `subject`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

-- Выключатели. ⚠ Оба по умолчанию включены: заслон, который молчит, пока его
-- не включили, защищает ровно до первой установки, где об этом забыли. Код и
-- без этих строк считает умолчанием «включено» — строки нужны, чтобы человек
-- увидел переключатель на `/admin/setting`, а не догадывался о нём.
--
-- ⚠⚠ `auth_throttle_ip_enabled` выключают там, где сервер запущен БЕЗ
-- `--proxy-headers`: туда приходит адрес обратного прокси — один и тот же у
-- всех, — и счёт по адресу запер бы вход всем сразу.
--
-- ⚠⚠⚠ Не `INSERT IGNORE`, и это не придирка. Уникальный ключ здесь —
-- `(key, user_id, node_id)`, а у общей настройки два последних NULL; в MySQL
-- `NULL <> NULL`, поэтому уникальность на такие строки НЕ действует и
-- `INSERT IGNORE` молча положил бы второй экземпляр при повторном прогоне.
-- `setting_get` взял бы из двух строк любую.
INSERT INTO `setting` (`key`, `value`)
SELECT 'auth_throttle_enabled', '1'
WHERE NOT EXISTS (SELECT 1 FROM `setting`
                  WHERE `key` = 'auth_throttle_enabled'
                    AND `user_id` IS NULL AND `node_id` IS NULL);

INSERT INTO `setting` (`key`, `value`)
SELECT 'auth_throttle_ip_enabled', '1'
WHERE NOT EXISTS (SELECT 1 FROM `setting`
                  WHERE `key` = 'auth_throttle_ip_enabled'
                    AND `user_id` IS NULL AND `node_id` IS NULL);
