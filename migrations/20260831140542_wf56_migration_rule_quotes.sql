-- Починка кавычек в промпте разработчика (шаг 435, WF56).
--
-- Предыдущая миграция (`20260831140000`) вставила в промпт пример тела запроса с
-- двойными кавычками: `{"name": "<имя файла>", "dry": true}`. Колонка `metadata` —
-- это JSON-строка, и незакрытая кавычка обрывает её: `json.loads` перестаёт
-- разбирать шаг целиком, движок отдаёт агенту пустой промпт, а в журнале это
-- выглядит как «Разработчик не ответил».
--
-- Ровно этот дефект уже случался — пять подзадач легли в `blocked`, четыре задачи
-- ушли в `failed`, — и от него написан `tests/test_agent_workflow_steps.py`. Здесь он
-- повторился при вставке безобидного на вид примера.
--
-- Кавычки убираем совсем: пример пишем словами, а не JSON-литералом. Экранировать их
-- в SQL-строке, которая сама лежит внутри JSON, — три уровня экранирования, и правка
-- такого текста ломает его снова при первом же прикосновении.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'и откатывает — POST /api/task/%subtask_id%/migration/apply с телом\\n{"name": "<имя файла>", "dry": true}. Идемпотентность проверяй условиями в самом\\n',
        'и откатывает — POST /api/task/%subtask_id%/migration/apply, в теле имя файла\\n'
        'полем name и признак сухого прогона полем dry со значением истина.\\n'
        'Идемпотентность проверяй условиями в самом\\n')
 WHERE `id` = 435
   AND `metadata` LIKE '%migration/apply с телом%';
