-- Карточка роли гаснет через 45 секунд без пинга вместо 90.
--
-- Порог отвечает на вопрос «жива ли оболочка» и служит сразу двум местам: показу
-- карточек на `/admin/team` и отбору работы (`task_role_shell_sessions_by_project` —
-- протухшая оболочка круга не получает). Число одно на оба ответа намеренно: разойдись
-- они, страница показывала бы живой роль, которой конвейер работы уже не даёт.
--
-- Почему 90 было много. Оболочка пингует раз в две секунды, то есть на 90 секундах
-- запас — сорок пять пропущенных пингов подряд. Всё это время закрытый терминал
-- числится живым: карточка горит, а отбор считает роль рабочей и держит для неё место
-- в пределе параллельности. На 45 секундах запас остаётся в двадцать два пинга — с
-- сетевой заминкой это по-прежнему несравнимо, а мёртвая оболочка отваливается вдвое
-- быстрее.
--
-- Ниже опускать не стоит: в подсказке к настройке записано, что до 30 секунд карточки
-- начинают мигать на обычной сетевой заминке. Нижняя граница поля (5 с) оставлена как
-- была — она про свободу правки, а не про разумное значение.
--
-- Правится и умолчание в коде (`task_setting_timeout.py`), и строка настройки: у
-- установки, где строка уже есть, умолчание ни на что не влияет — читается строка.
--
-- Идемпотентность: условие на прежнее значение. Выставленное человеком вручную число
-- не трогаем — своя настройка старше нашего умолчания.
UPDATE `setting`
   SET `value` = '45'
 WHERE `key` = 'timeout_ping_stale'
   AND `value` = '90';
