-- Письма и вопросы пишутся на языке ноды, а не на языке промпта (2026-09-07)
--
-- ЧТО БЫЛО. Нода Dating объявляет `languages = en`, а письма приходили на
-- русском. Выглядело как поломка настройки — на деле настройка тут ни при чём.
--
-- ⚠ ЯЗЫК НОДЫ НИЧЕГО НЕ НАВЯЗЫВАЕТ, И ЭТО ЗАДУМАНО. В `chat.py` сказано прямо:
-- `node_languages` — «только справочный список для UI/промптов», а «решение,
-- укладывается ли в него выбор пользователя, принимает **сам workflow**». Движок
-- публикует `%node_languages%` и `%user_language%` переменными и на этом
-- останавливается: он не знает, обязан ли конкретный workflow им подчиняться.
--
-- Наши три промпта этих переменных не читали вовсе. Отсюда и русский: промпт
-- написан по-русски, и модель отвечает на языке промпта — это её обычное
-- поведение, а не сбой.
--
-- Хуже того, в `dating_mail_question` стояло прямо противоположное правило:
-- «Пиши на том же языке, на котором написан профиль получателя». Профиль на
-- русском — вопрос на русском, и никакая настройка ноды этого не отменяла.
--
-- ЧТО ВМЕСТО. Каждому из трёх промптов добавлено правило языка, и оно ссылается
-- на `%user_language%` — активный язык, который движок уже вычислил с учётом
-- ноды. Зашивать «English» нельзя: нода сменит язык, а промпты останутся со
-- старым и разъедутся с настройкой молча.
--
-- ⚠ ПОЧЕМУ ПРАВИЛО ПЕРВЫМ ПУНКТОМ. Язык — свойство всего ответа, а не одна из
-- деталей: модель, дочитавшая до шестого пункта, уже выбрала язык по первым
-- пяти. Ставим впереди остальных.
--
-- Идемпотентность: условие на то, что правила ещё нет.

-- ---------------------------------------------------------------- До
SET @nl = CONCAT(CHAR(92), 'n');

SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step` s
          JOIN `agent_workflow` w ON w.id = s.workflow_id
         WHERE w.`name` IN ('dating_mail_write', 'dating_mail_question', 'dating_mail_vars')
           AND s.`metadata` LIKE '%user_language%') AS правило_есть;

-- ------------------------------------------- Письмо
SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_mail_write');

UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        CONCAT('Правила:', @nl, '1. Не больше четырёх абзацев.'),
        CONCAT('Правила:', @nl,
               '0. ЯЗЫК ПИСЬМА — %user_language% (код языка). Пиши только на нём, ',
               'даже если профили участников и эти правила написаны на другом. ',
               'Письмо читает человек на сайте знакомств, и язык там один.', @nl,
               '1. Не больше четырёх абзацев.'))
 WHERE `workflow_id` = @wf
   AND `metadata` NOT LIKE '%user_language%';

-- ------------------------------------------- Вопрос
--
-- ⚠ Здесь не добавление, а **замена**: правило про язык профиля получателя прямо
-- противоречило языку ноды и было причиной русских вопросов.
SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_mail_question');

UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '5. Пиши на том же языке, на котором написан профиль получателя.',
        '5. ЯЗЫК ВОПРОСА — %user_language% (код языка). Пиши только на нём, даже если профиль получателя и эти правила написаны на другом: вопрос встанет внутрь письма, а письмо на одном языке.')
 WHERE `workflow_id` = @wf
   AND `metadata` LIKE '%на том же языке%';

-- ------------------------------------------- Переменные анкеты
--
-- Тут язык тоже значим: `girl_city` = «Киев» и «Kyiv» — разные строки, и в
-- английском письме первая читается как сбой.
SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_mail_vars');

UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        CONCAT('Правила:', @nl, '1. Верни JSON-объект:'),
        CONCAT('Правила:', @nl,
               '0. ЗНАЧЕНИЯ — на языке %user_language% (код языка): имена и ',
               'города пиши на нём, даже если в анкете они записаны иначе. Эти ',
               'значения подставятся в письмо, а письмо на одном языке.', @nl,
               '1. Верни JSON-объект:'))
 WHERE `workflow_id` = @wf
   AND `metadata` NOT LIKE '%user_language%';

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step` s
          JOIN `agent_workflow` w ON w.id = s.workflow_id
         WHERE w.`name` IN ('dating_mail_write', 'dating_mail_question', 'dating_mail_vars')
           AND s.`metadata` LIKE '%user_language%') AS промптов_с_языком,
       (SELECT COUNT(*) FROM `agent_workflow_step` s
          JOIN `agent_workflow` w ON w.id = s.workflow_id
         WHERE w.`name` = 'dating_mail_question'
           AND s.`metadata` LIKE '%на том же языке%') AS старое_правило_осталось;
