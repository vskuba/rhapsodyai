-- Закладка-стенд для сюиты DatingAi (2026-09-11)
--
-- ЗАЧЕМ. Сюита соседа заводит анкеты **по HTTP в живую панель**, а та сверяет
-- сайт здесь (`GET /api/browser/site/{id}`): выдуманный номер она отвергает —
-- «нет сайта с номером 999777». Поэтому тесты писем и рассылки заводили свои
-- анкеты на **настоящем** сайте 343 (Ladadate), рядом с рабочими.
--
-- ⚠ ЧЕМ ЭТО ПЛОХО, СТАЛО ВИДНО НЕ СРАЗУ. Пока у сайта не было кругов, соседство
-- ничего не стоило. Теперь у 343 включены круги избранных и инвайтов, а они
-- берут **все включённые анкеты сайта** — то есть и тестовую, с фальшивым
-- паролем. Ценой были бы вызовы LLM, занятая вкладка Chromium и строки отказов в
-- журнале под анкетой, которой через секунду не станет.
--
-- Прогоны это и показали: два полных прогона из четырёх дали сбои в разных
-- файлах, а по отдельности те же файлы зелёные.
--
-- ⚠ БЕЗ МЕТКИ `dating`, И ЭТО ГЛАВНОЕ. Список сайтов панель спрашивает с
-- `?tag=dating` — стенд в селект не попадёт, и человек его не увидит. А вот
-- `GET /api/browser/site/{id}` отвечает по номеру и метку не смотрит: заведение
-- анкеты пройдёт. Ровно то, что нужно сюите, и ровно то, чего не нужно человеку.
--
-- ⚠ НОМЕР ЗАДАН ЯВНО, А НЕ ОТДАН АВТОИНКРЕМЕНТУ. Тест сослаться на стенд может
-- только числом — спросить «сайт по имени» у соседа нечем, а метки у стенда нет,
-- так что и в списке его не найти. Автоинкремент дал бы на каждой установке свой
-- номер, и сюита падала бы у всех, кроме первого. `999343` выбран далеко от
-- настоящих (те в сотнях) и читается как «стенд при 343».
--
-- `presence` пуст намеренно: стенд не сайт знакомств, ходить по нему некуда.
-- Сценариев у него тоже нет — тестам они и не нужны, весь разговор с сайтом идёт
-- через заглушку на стороне сюиты (`site_api_fake.py`).

SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM `browser_site` WHERE `id` = 999343) AS стенд_есть,
       (SELECT COUNT(*) FROM `browser_site` WHERE `tags` LIKE '%dating%') AS сайтов_знакомств;

INSERT INTO `browser_site` (`id`, `name`, `url`, `tags`)
SELECT 999343, 'Стенд DatingAi: сюита', 'http://stand.invalid', ''
 WHERE NOT EXISTS (SELECT 1 FROM `browser_site` WHERE `id` = 999343);

-- ⚠ Адрес — `.invalid`: зарезервированный домен, который не резолвится нигде
-- (RFC 2606). Если когда-нибудь по стенду попробуют сходить браузером, это
-- кончится внятным отказом DNS, а не походом на чужой живой сайт.

SELECT 'ПОСЛЕ' AS этап,
       (SELECT `name` FROM `browser_site` WHERE `id` = 999343) AS стенд,
       (SELECT `tags` = '' FROM `browser_site` WHERE `id` = 999343) AS без_метки,
       (SELECT COUNT(*) FROM `browser_site` WHERE `tags` LIKE '%dating%') AS сайтов_знакомств;
