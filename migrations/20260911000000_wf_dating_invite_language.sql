-- `dating_invite_write`: язык реплики задаётся явно (2026-09-11)
--
-- ЧТО ПОКАЗАЛ ПЕРВЫЙ ЖЕ ПРОГОН. Пул набрался, и все четыре реплики вышли
-- **по-русски** — мужчинам на англоязычном сайте:
--
--     «Ahmet ust., как Вы обычно проводите свободное время?»
--     «Frank, а чем вы любите заниматься в свободное время?»
--
-- ⚠ ЭТО НЕ ВКУСОВЩИНА, А НЕДОСТАВКА. Фильтр LadaDate отклоняет кириллицу —
-- «Message not delivered. Unacceptable words: …», — и такая реплика до собеседника
-- не дойдёт вовсе (записано в DatingAi, `dating_answer.py`, у константы
-- `DATING_ANSWER_LANGUAGE`). То есть пул из двадцати инвайтов был бы пулом из
-- двадцати сообщений, которые сайт не пропустит.
--
-- ⚠ ПРИЧИНА — В ПРОМПТЕ, А НЕ В МОДЕЛИ. Правило стояло такое: «пиши на том же
-- языке, на котором написан его профиль». У этих людей профиля нет вовсе
-- (`about` не собран), сравнивать было не с чем — и модель ушла в язык, на котором
-- написан сам промпт.
--
-- ⚠ ПОЧЕМУ У ПИСЕМ ЭТОГО НЕ БЫЛО. У них язык задан явно: `dating_mail_write`
-- получает `%user_language%` отдельным шагом («Требуемый язык (код)»), а ответ на
-- письмо пишется поверх английской переписки и продолжает её сам. У инвайта нет ни
-- того, ни другого: это **первая** реплика, и опереться ей не на что.
--
-- Отсюда правка: язык называется в промпте по имени, переменной `%user_language%`
-- — той же, что у писем и автоответа. Значение передаёт DatingAi из настройки
-- сайта (`presence.answer_language`, умолчание `en`).
--
-- ⚠ ПРОФИЛЬ БОЛЬШЕ НЕ РЕШАЕТ ЯЗЫК. Он остался подсказкой о том, **о чём**
-- спросить; на «каком языке» отвечает настройка сайта. Иначе один и тот же сайт
-- получал бы реплики на трёх языках — по языку, которым каждый мужчина заполнил
-- свою анкету.

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_invite_write');

SELECT 'ДО' AS этап, @wf AS workflow,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%user_language%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 0) AS язык_задан;

-- ------------------------------------------- Переписываем промпт
UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(
         `metadata`, '$.prompt_user',
         CONCAT(
           'Ты пишешь ПЕРВУЮ реплику в чате на сайте знакомств. Девушка пишет ',
           'мужчине, они не знакомы и до этого не говорили.\n\n',
           '=== Требуемый язык ответа (код) ===\n%user_language%\n\n',
           '=== Кому пишем ===\n',
           'Имя: %invite_companion_name%\n%companion_card%\n\n',
           '=== Кто пишет ===\n%girl_card%\n\n',
           'Правила:\n',
           '1. Пиши РОВНО на требуемом языке, указанном выше. Это жёсткое ',
           'требование, а не пожелание: сайт фильтрует сообщения и не на том ',
           'языке отклоняет — реплика не дойдёт до человека вовсе. Язык профиля ',
           'собеседника значения не имеет: он подсказывает, О ЧЁМ спросить, а не ',
           'на каком языке.\n',
           '2. Это ЧАТ, а не письмо. Одна реплика, одно-два предложения. Ни темы, ',
           'ни подписи, ни абзацев: текст всплывёт у него в окне чата как ',
           'сообщение от живого человека.\n',
           '3. Обратись к нему по имени — ровно один раз и внутри текста. Место ',
           'обращения выбирай сам: «%invite_companion_name%, а вы...» и «Давно этим ',
           'занимаетесь, %invite_companion_name%?» звучат по-разному, и одинаковая ',
           'рамка у всех реплик выдаёт рассылку. Два обращения в двух предложениях ',
           'читаются как сбой подстановки.\n',
           '4. Заканчивай вопросом или предложением, на которое легко ответить. ',
           '«Привет, как дела?» отвечать нечем. Спроси про то, что есть в его ',
           'профиле, — так видно, что профиль прочли.\n',
           '5. О нём ничего не известно — задай живой общий вопрос про его ',
           'занятия. Промолчать нельзя: без текста инвайт не попадёт в пул вовсе, ',
           'и человек останется без приглашения.\n',
           '6. Без комплиментов внешности, без «я увидела твоё фото», без просьб ',
           'написать первым. Первая реплика — повод для разговора, а не признание.\n',
           '7. Ответ — только сам текст реплики. Без кавычек, пояснений, markdown ',
           'и размышлений: всё, что ты напишешь, уйдёт в чат как есть.'
         ))
 WHERE `workflow_id` = @wf AND `position` = 0;

-- ------------------------------------------- Привязка переменной языка
--
-- `user_language` — глобальная переменная соседа (#120: «активный язык диалога»),
-- ту же передают автоответ и письма. Своей не заводим: две переменные одного
-- смысла разошлись бы в первый же день.
INSERT INTO `agent_workflow_variable_workflow` (`variable_id`, `workflow_id`)
SELECT v.`id`, @wf FROM `agent_workflow_variable` v
 WHERE v.`name` = 'user_language'
   AND NOT EXISTS (SELECT 1 FROM `agent_workflow_variable_workflow` vw
                    WHERE vw.`variable_id` = v.`id` AND vw.`workflow_id` = @wf);

SELECT 'ПОСЛЕ' AS этап,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%user_language%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 0) AS язык_задан,
       (SELECT COUNT(*) FROM `agent_workflow_variable_workflow`
         WHERE `workflow_id` = @wf) AS переменных;
