-- Модель в замерах работы ролей — колонка `project_task_metric`.`llm_name`.
--
-- Зачем. Замеры отвечали на вопрос «сколько стоит круг этой роли», и этого хватало,
-- пока модель у проекта была одна. С пулом их несколько, и круги идут на разных:
-- вопрос сменился на «какая модель для нас лучше» — а ответить на него нечем, в
-- строке замера модели нет.
--
-- Что это даёт. Скорость (`tokens_per_sec`), время круга и доля сорванных прогонов —
-- всё уже пишется; не хватало только измерения, к которому их отнести. С колонкой
-- те же строки читаются в разрезе моделей: локальная против облачной, дешёвая против
-- быстрой, — и выбор пула перестаёт быть делом вкуса.
--
-- Пустая строка у старых замеров — честнее выдумки: те круги шли до появления пула,
-- и приписать им модель задним числом нельзя. Сводка по моделям такие строки
-- показывает отдельной группой «модель не записана», а не растворяет в чужих средних.
--
-- Идемпотентность: колонку добавляем только если её ещё нет. `ADD COLUMN IF NOT
-- EXISTS` MySQL не поддерживает, поэтому через information_schema и подготовленный
-- запрос — тем же приёмом, что и соседние миграции над существующими таблицами.
SET @exists := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
     WHERE TABLE_SCHEMA = DATABASE()
       AND TABLE_NAME = 'project_task_metric'
       AND COLUMN_NAME = 'llm_name'
);

SET @sql := IF(@exists = 0,
    'ALTER TABLE `project_task_metric`
        ADD COLUMN `llm_name` VARCHAR(100) NOT NULL DEFAULT ''''
            COMMENT ''Модель круга из пула проекта; пусто — замер до появления пула''
            AFTER `role`,
        ADD INDEX `idx_metric_llm` (`llm_name`)',
    'SELECT 1');

PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
