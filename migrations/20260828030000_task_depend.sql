-- Зависимости между задачами — таблица `project_task_depend`.
--
-- Зачем. План менеджера — плоский список подзадач, и конвейер берёт их в работу
-- разом, как только план разложен. Но подзадачи планом не равноправны: «написать
-- тесты вкладки» не начать раньше, чем вкладка существует, а «проверить на стенде» —
-- раньше обеих. Живой повод: задача #2438 разложилась на три подзадачи, где третья
-- явно опиралась на первую, и все три ушли в работу одновременно.
--
-- Что даёт таблица. Подзадача ждёт, пока не закрыты те, от кого зависит; всё
-- остальное по-прежнему идёт параллельно — ровно настолько, насколько хватает
-- оболочек и моделей. Параллельность не отменяется, из неё вычитаются связи.
--
-- Почему отдельная таблица, а не поле в `metadata`. Зависимостей у подзадачи бывает
-- несколько, и отбор работы обязан спрашивать «все ли предшественники закрыты» одним
-- условием — на JSON это `JSON_CONTAINS` по каждой строке, то есть перебор. Здесь же
-- `NOT EXISTS` по индексу, и FK не даёт остаться связи с удалённой строкой.
--
-- Связь направленная: `task_id` ждёт `depends_on_id`. Обратное направление читается
-- тем же индексом с другой стороны (`idx_depend_on`) — по нему страница рисует,
-- кого разблокирует закрытие подзадачи.
--
-- Циклы таблица не запрещает: SQL этого не умеет, а проверять на каждой вставке
-- триггером — прятать логику в базе. Ловит их запись плана (`task_depend_set`), и
-- ловит по делу: план с циклом не выполнить в принципе, о нём нужно сказать
-- человеку, а не тихо развернуть.
--
-- `ON DELETE CASCADE` с обеих сторон: удалили подзадачу — её связи не значат ничего.
-- Пара уникальна: одна и та же зависимость, записанная дважды, — это та же
-- зависимость, а не две.
--
-- Идемпотентность: `CREATE TABLE IF NOT EXISTS`.
CREATE TABLE IF NOT EXISTS `project_task_depend` (
    `task_id` INT NOT NULL COMMENT 'Кто ждёт',
    `depends_on_id` INT NOT NULL COMMENT 'Кого ждёт: пока он не закрыт, работы нет',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`task_id`, `depends_on_id`),
    INDEX `idx_depend_on` (`depends_on_id`),
    CONSTRAINT `fk_depend_task` FOREIGN KEY (`task_id`)
        REFERENCES `project_task` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_depend_on` FOREIGN KEY (`depends_on_id`)
        REFERENCES `project_task` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
