-- Намерения разговора: что агент пометил словом и когда (2026-10-11)
--
-- ЗАЧЕМ. Намерение («она обещала прислать фото») находится по тексту истории, а
-- история накапливается: реплика «can you send me your photos» остаётся в окне
-- двадцати обменов, и тема поднимается на каждом следующем ответе. Одно и то же
-- намерение уезжало бы вызывающему двадцать раз подряд.
--
-- ⚠⚠ Запомнить «такое намерение уже было» и больше не отдавать — НЕЛЬЗЯ.
-- Обещание, повторённое через две реплики, — **новое** намерение, и его ждут.
-- Строка при этом та же самая (`instructions` темы — константа), так что по
-- самому намерению первое от второго не отличить.
--
-- Отличает их **время**: намерение №2 возникло из реплик, пришедших ПОСЛЕ
-- намерения №1. Поэтому таблица хранит не «было/не было», а отметку времени —
-- по ней история режется надвое («до намерений» и «свежая»), и модель ищет
-- новое только в свежей половине, видя при этом всю переписку целиком.
--
-- ⚠ Строка на каждое намерение, а не одна на пару: два обещания фото — две
-- записи, и это верно. По ним же видно историю обещаний в разговоре.
--
-- ⚠ Идемпотентна: повторный прогон не заводит второй таблицы.

CREATE TABLE IF NOT EXISTS `companion_intention` (
    `id`           INT AUTO_INCREMENT PRIMARY KEY,
    -- Пара разговора — теми же ключами, что у `companion_session`: намерение
    -- принадлежит разговору, а не одной из сторон.
    `owner_id`     INT          NOT NULL COMMENT 'наша сторона (companion.id)',
    `companion_id` INT          NOT NULL COMMENT 'та сторона (companion.id)',
    -- Метка словом: `she_promised_send_photo`. Длина — как у инструмента
    -- (`CHAT_INTENTION_LENGTH_MAX`): метка, а не пересказ разговора.
    `intention`    VARCHAR(100) NOT NULL COMMENT 'намерение меткой-словом',
    -- ⚠⚠ Главное поле. По нему история режется на «до» и «свежую»: следующий
    -- прогон ищет намерения только в том, что пришло позже этой отметки.
    `created_at`   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP
                                COMMENT 'когда намерение найдено — граница свежести',

    -- Отбор всегда один: «последнее намерение этой пары». Ключ накрывает его
    -- целиком, без похода в строки.
    KEY `companion_intention_pair_at` (`owner_id`, `companion_id`, `created_at`),

    CONSTRAINT `companion_intention_owner`
        FOREIGN KEY (`owner_id`) REFERENCES `companion` (`id`) ON DELETE CASCADE,
    CONSTRAINT `companion_intention_companion`
        FOREIGN KEY (`companion_id`) REFERENCES `companion` (`id`) ON DELETE CASCADE
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_general_ci
  COMMENT = 'намерения разговора пары: метка и время находки';
