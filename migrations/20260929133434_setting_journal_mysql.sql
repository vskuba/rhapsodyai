-- Счёт запросов к базе — настройкой, а не переменной окружения (2026-09-29)
--
-- ## ЗАЧЕМ
--
-- Выключатель подвкладки «MySQL» страницы «Журнал» заводился как
-- `MYSQL_WATCH_ENABLED` в `.env`. Это дороже, чем предмет того стоит: на проде
-- переменную надо класть через secret `ENV_FILE` (иначе её сотрёт деплой), а
-- чтобы погасить счёт — править конфиг и перезапускать контейнеры.
--
-- Настройка снимает и то и другое: строка правится на `/admin/setting`, живая
-- установка подхватывает её сама. Соседние выключатели того же рода живут там
-- же — `llm_workflow_queue_ttl`, `gx10_autocompact_limit`, таймауты конвейера.
--
-- ## ⚠ Настройка ОБЩАЯ, а не на ноду
--
-- Скоуп ноды здесь бессмыслен: запросы к базе шлёт процесс, а не узел LLM.
-- Строка заводится с `node_id = NULL` и `user_id = NULL`.
--
-- ## Что значит значение
--
-- `0`, `false`, `no`, `off` и пустое — не считаем; всё остальное — считаем.
-- Умолчание `1`: журнал заводят затем, чтобы он был, а цена счёта — словарь в
-- памяти процесса и одна запись в полминуты.
--
-- ⚠ Правка действует **через полминуты и без перезапуска**: такт сброса
-- (`journal_mysql_flush_forever`) перечитывает настройку на каждом обороте.
-- Ради этого её и предпочли переменной окружения. Короткие процессы — воркеры и
-- кронджобы — читают её на старте своего захода, то есть тоже свежую.
--
-- ⚠ Строка заводится только если её ещё нет: человек мог уже поправить значение
-- на странице, и перезатирать его миграция не вправе.

SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM `setting`
         WHERE `key` = 'journal_mysql_enabled') AS есть_настройка;

INSERT INTO `setting` (`key`, `value`, `user_id`, `node_id`, `dynamic`)
SELECT 'journal_mysql_enabled', '1', NULL, NULL, 0
 WHERE NOT EXISTS (SELECT 1 FROM `setting`
                    WHERE `key` = 'journal_mysql_enabled'
                      AND `user_id` IS NULL AND `node_id` IS NULL);

SELECT 'ПОСЛЕ' AS этап,
       (SELECT `value` FROM `setting`
         WHERE `key` = 'journal_mysql_enabled'
           AND `user_id` IS NULL AND `node_id` IS NULL) AS значение;
