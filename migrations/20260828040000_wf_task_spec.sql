-- Роли читают спецификацию подзадачи — шаги 433 (Developer), 445 (QA), 422 (Manager).
--
-- Зачем. План говорит порядок шагов («поправить роутер, потом шаблон») — этого хватает
-- тому, кто уже знает проект. Исполнителю не хватает: план не отвечает, какой контракт
-- у точки API, что считается ошибкой, чем работа будет доказана. Каждый агент
-- достраивал недостающее сам, и достраивал по-своему — оттого разработчик и QA
-- расходились в понимании одной и той же подзадачи.
--
-- Спецификация (`.task-spec.md`, `src/project/task/task_spec.py`) закрывает разрыв:
-- один документ на обоих, и в нём написано не «что поправить», а «как это должно себя
-- вести». Кладёт её конвейер в каталог подзадачи, рядом с журналом, и перезаписывает
-- на каждом круге — план и зависимости меняются пересмотром.
--
-- **Якорь взят по первой строке роли, а не по блоку журнала.** Промпты в базе правят
-- и через `/admin/workflow`, поэтому установки расходятся: на проде эти шаги вдвое
-- короче локальных, и блока «СНАЧАЛА ПОСМОТРИ ЖУРНАЛ» в них нет вовсе. Миграция,
-- написанная по нему, на проде молча не сработала бы — файл писался бы, а промпт о
-- нём не говорил. Строка «Сейчас только разбор» (у ролей) и «Перед планированием
-- проведи разведку» (у менеджера) есть в обеих установках: это начало задания, и
-- переживает оно любые правки середины.
--
-- Вставляем сразу после неё — до всего остального: спецификация отвечает «что вообще
-- требуется», журнал и код — «что из этого уже сделано». В обратном порядке агент
-- читает отчёт о работе, не зная, к чему она была.
--
-- Багфиксера здесь нет намеренно: у бага не бывает подзадач и разбиения, и его
-- спецификация свелась бы к описанию с целями — тому, что и так лежит в его промпте.
--
-- Идемпотентность: условие `NOT LIKE '%task-spec.md%'` — повторный прогон и уже
-- дополненный текст не тронет.

-- Developer и QA: своя спецификация подзадачи.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'Сейчас только разбор:',
        'Сначала прочти `.task-spec.md` в каталоге подзадачи — что требуется сделать и\\n'
        'чем это считается сделанным. Документ собран из плана, целей и зависимостей\\n'
        'подзадачи; цели в нём — критерии приёмки, по ним работу примет QA. Файла нет —\\n'
        'работай по плану из этого промпта.\\n\\n'
        'Сейчас только разбор:')
 WHERE `id` IN (433, 445)
   AND `metadata` LIKE '%Сейчас только разбор:%'
   AND `metadata` NOT LIKE '%task-spec.md%';

-- Менеджер: сводная по всей задаче. Он её не исполняет, а проверяет — по ней видно,
-- сходится ли план как целое.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'Перед планированием проведи разведку задачи.',
        'Перед планированием проведи разведку задачи.\\n'
        'Если задачу уже разбивали, в её каталоге лежит `.task-spec.md` — сводный\\n'
        'документ по всем подзадачам: их цели, порядок выполнения и зависимости.\\n'
        'По нему видно, закрыта ли каждая цель задачи хоть одной подзадачей и нет ли\\n'
        'подзадач, ждущих друг друга по кольцу.')
 WHERE `id` = 422
   AND `metadata` LIKE '%Перед планированием проведи разведку задачи.%'
   AND `metadata` NOT LIKE '%task-spec.md%';
