-- Роли читают спецификацию подзадачи — шаги 433 (Developer) и 445 (QA).
--
-- Зачем. План говорит порядок шагов («поправить роутер, потом шаблон») — этого хватает
-- тому, кто уже знает проект. Исполнителю не хватает: план не отвечает, какой контракт
-- у точки API, что считается ошибкой, чем работа будет доказана. Каждый агент
-- достраивал недостающее сам, и достраивал по-своему — оттого разработчик и QA
-- расходились в понимании одной и той же подзадачи.
--
-- Спецификация (`.task-spec.md`, `src/project/task/task_spec.py`) закрывает разрыв:
-- один документ на обоих, и в нём написано не «что поправить», а «как это должно себя
-- вести». Кладёт её конвейер в каталог подзадачи, рядом с журналом, и перезаписывает
-- на каждом круге — план и зависимости меняются пересмотром.
--
-- Порядок чтения: спецификация первой, журнал следом. Спецификация отвечает «что
-- вообще требуется», журнал — «что из этого уже сделано»; в обратном порядке агент
-- читает отчёт о работе, не зная, к чему она была.
--
-- Идемпотентность: `REPLACE` по точной подстроке. Повторный прогон ничего не найдёт;
-- текст, уже содержащий `.task-spec.md`, второй раз не дополнится.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '=== СНАЧАЛА ПОСМОТРИ ЖУРНАЛ ПОДЗАДАЧИ ===',
        '=== СНАЧАЛА ПРОЧТИ СПЕЦИФИКАЦИЮ ===\\n'
        'В каталоге подзадачи лежит `.task-spec.md` — что требуется сделать и чем это\\n'
        'считается сделанным. Она собрана из плана, целей и зависимостей подзадачи:\\n'
        '  cat .task-spec.md\\n'
        'Цели из неё — критерии приёмки: по ним работу примет QA, и добавлять к ним\\n'
        'своё понимание задачи не нужно. Файла нет — работай по плану из промпта.\\n\\n'
        '=== СНАЧАЛА ПОСМОТРИ ЖУРНАЛ ПОДЗАДАЧИ ===')
 WHERE `id` IN (433, 445)
   AND `metadata` LIKE '%СНАЧАЛА ПОСМОТРИ ЖУРНАЛ ПОДЗАДАЧИ%'
   AND `metadata` NOT LIKE '%task-spec.md%';

-- Багфиксера здесь нет намеренно: у бага не бывает подзадач и разбиения, и его
-- спецификация свелась бы к описанию с целями — тому, что и так лежит в его промпте.
--
-- У менеджера свой блок и свой смысл: он спецификацию не исполняет, а проверяет —
-- сводная по всей задаче лежит в каталоге родителя и показывает, сходится ли план как
-- целое (все ли цели закрыты подзадачами, нет ли колец в зависимостях).
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '=== СНАЧАЛА ПОСМОТРИ ЖУРНАЛ ЗАДАЧИ ===',
        '=== СВОДНАЯ СПЕЦИФИКАЦИЯ ===\\n'
        'Если задачу уже разбивали, в её каталоге лежит `.task-spec.md` — сводный\\n'
        'документ по всем подзадачам: их цели, порядок выполнения и зависимости:\\n'
        '  cat .task-spec.md\\n'
        'По нему видно, сходится ли план как целое: закрыта ли каждая цель задачи\\n'
        'хоть одной подзадачей и нет ли подзадач, ждущих друг друга по кольцу.\\n\\n'
        '=== СНАЧАЛА ПОСМОТРИ ЖУРНАЛ ЗАДАЧИ ===')
 WHERE `id` = 422
   AND `metadata` LIKE '%СНАЧАЛА ПОСМОТРИ ЖУРНАЛ ЗАДАЧИ%'
   AND `metadata` NOT LIKE '%task-spec.md%';
