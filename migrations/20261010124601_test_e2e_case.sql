-- Выключатель отдельного E2E-случая: что гонять, а что пока не трогать (2026-10-10)
--
-- ЗАЧЕМ. Случай может шуметь: страница перестраивается, селектор ещё не
-- поправлен, а прогон каждую ночь красит отчёт красным. Красный тест, который
-- никто не чинит, вреднее отсутствующего — на него перестают смотреть, и
-- вместе с ним перестают смотреть на соседние.
--
-- ⚠⚠ Признак живёт В БАЗЕ, а не в самом YAML, и это выбор, а не удобство.
-- Файлы случаев одни на все установки: выключив случай в YAML, его выключаешь
-- и на проде, и на машине разработчика разом. А гасят их как раз порознь —
-- на проде шумит, локально чинят. Плюс выключение в файле требует выкладки,
-- то есть погасить ночной шум в три часа ночи нечем.
--
-- ⚠ Ключ — ИМЯ ФАЙЛА случая, а не его человеческое название. Название правят
-- ради формулировки («Трассы — нет ошибок» → «Трассы: ошибок за сутки»), и
-- выключатель при этом терял бы свою привязку молча.
--
-- ⚠ Строки нет — случай ВКЛЮЧЁН. Заводится она только переключателем, поэтому
-- новый случай работает сразу, без строки и без миграции.
--
-- Устройство — `.claude/docs/e2e.md`.

CREATE TABLE IF NOT EXISTS `test_e2e_case`
(
    -- Имя файла случая без каталога: «workflow_trace_error_today.yaml».
    `case_file`  VARCHAR(190) NOT NULL,

    `enabled`    TINYINT(1)   NOT NULL DEFAULT 1,

    -- Название на момент переключения — КОПИЕЙ, как `name` в `test_e2e`.
    -- Нужно одному: показать в отчёте, что именно выключено, если файл случая
    -- тем временем переименовали или унесли.
    `name`       VARCHAR(190) NOT NULL DEFAULT '',

    -- UTC, как всё время в проекте.
    `updated_at` DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP
                              ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (`case_file`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_general_ci;
