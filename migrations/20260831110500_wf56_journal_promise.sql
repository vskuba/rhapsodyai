-- Разработчику — та же правда про его ответ, что и соседям (шаг 433, WF56).
--
-- Продолжение `20260831110000`: там обещание «этот ответ целиком уходит в следующий
-- промпт» поправили у QA и багфиксера, а у разработчика формулировка оказалась своя —
-- с хвостом «и каждая лишняя строка там читается заново», — и замена мимо неё прошла.
--
-- Обещание неверно: `dev_recon` заполняется ответом шага разбора и никуда больше не
-- подставляется. Ответ уходит строкой в журнал круга, и оттуда его читают следующие
-- круги и человек на вкладке «Журналы».
--
-- Довод «каждая лишняя строка читается заново» при этом остаётся верным и нужным:
-- журнал у живой подзадачи разрастается (у #5219 — 120 КБ), и каждый следующий круг
-- платит за его чтение. Поэтому меняем только обоснование, а требование краткости
-- сохраняем вместе с ним.
--
-- Идемпотентность: условие `LIKE '%следующий промпт%'` — уже поправленный текст не
-- тронет.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'этот ответ целиком уходит в следующий промпт, и каждая лишняя строка там читается\\nзаново.',
        'этот ответ уходит строкой в журнал круга (.task-log.md), и каждая лишняя строка\\n'
        'там читается заново каждым следующим кругом.')
 WHERE `id` = 433
   AND `metadata` LIKE '%следующий промпт%';
