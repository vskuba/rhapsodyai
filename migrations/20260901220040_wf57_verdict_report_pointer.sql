-- Вердикт QA перестаёт пересказывать агенту его же отчёт о прогоне.
--
-- Что было. Промпт вердикта (шаг 451) начинался с блока `=== ОТЧЁТ О ПРОГОНЕ ===` и
-- целиком вкладывал в него `%qa_report_json%` — тот самый JSON, который агент написал
-- сам несколькими ходами выше, на шаге 511 той же сессии. Оболочка у круга одна, и все
-- шаги workflow идут в один и тот же Claude Code: его контекст этот ответ уже содержит.
--
-- Цена. Отчёт о прогоне — это `summary`, список проверок и замечания; на живом круге
-- #6500 он занимал единицы килобайт, а весь промпт вердикта — 7054 символа. То есть
-- изрядная часть промпта уходила на пересказ агенту его собственных слов, и так на
-- каждом круге проверки.
--
-- Что вместо. Короткая отсылка: отчёт ты писал сам, перечитай его выше. Плюс запасной
-- ответ на случай, когда перечитывать нечего.
--
-- **Про запасной ответ отдельно.** Соблазн был сослаться на `.task-log.md`, как это
-- сделано у разработчика («не помнишь — разбор записан в журнале»). Здесь так нельзя:
-- журнал круга дописывается по его завершении (`task_log_write_run` из `_log_run`), а
-- вердикт выносится внутри того же круга — своего отчёта в файле ещё нет, и агент
-- прочитал бы там прошлый круг, приняв его за текущий. Поэтому отсылка ведёт не в файл,
-- а на список целей, который в промпте остаётся: он собран из проверок самого агента,
-- по одной записи на цель, и первые два вопроса вердикта опираются именно на него.
--
-- Сам `qa_report_json` никуда не девается: он по-прежнему заполняется шагом 511 и уходит
-- в отчёт задачи. Убрана только его подстановка в промпт вердикта.
--
-- Кавычек в добавляемом тексте нет намеренно: промпт лежит строкой внутри JSON в
-- `metadata`, и двойная кавычка рвёт разбор шага целиком (см.
-- `tests/test_agent_workflow_steps.py`).
--
-- Идемпотентность: условие на то, что подстановка ещё на месте.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '=== ОТЧЁТ О ПРОГОНЕ ===\\n%qa_report_json%\\n\\n',
        'Отчёт о прогоне ты написал сам, несколькими ходами выше в этой сессии, —\\n'
        'перечитай его там, а не пересказывай заново. Не помнишь (контекст мог\\n'
        'сжаться) — суди по списку целей ниже: он собран из твоих же проверок,\\n'
        'по одной записи на цель.\\n\\n')
 WHERE `id` = 451
   AND `metadata` LIKE '%=== ОТЧЁТ О ПРОГОНЕ ===%';
