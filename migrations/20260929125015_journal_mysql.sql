-- Журнал запросов к базе: подвкладка «MySQL» страницы «Журнал» (2026-09-29)
--
-- ## Зачем
--
-- Страница «Журнал» отвечает на вопрос «что происходило на установке». Первая её
-- подвкладка, «Ошибки», отвечает про сломавшееся. Эта — про то, что не ломается,
-- а просто стоит дорого: запросы к базе.
--
-- Повод прямой. Разбор на проде показал, что 1.53 млрд из 1.55 млрд прочитанных
-- строк приходятся на две таблицы, и нашли это не по коду, а по счётчикам
-- `performance_schema` — то есть постфактум и вручную. Смотреть туда каждый раз
-- незачем: числа про свои же запросы установка может собирать сама.
--
-- ## ⚠ Строка одна на вид запроса, а не на его прогон
--
-- Тот же приём, что у соседней подвкладки, и по той же причине — только резче.
-- Замерено на живом сервере: воркер шлёт **6832 запроса в минуту**. Строка на
-- каждый — это десять миллионов строк в сутки и удвоенная нагрузка на ту самую
-- базу, которую этим журналом и собирались чинить.
--
-- Поэтому считает счётчик в памяти процесса (`py_modules/mysql_/mysql_watch.py`),
-- а сюда пачкой сбрасывает `src/journal/journal_mysql.py` раз в полминуты. Строка
-- одна на отпечаток вида запроса, повторы — в счётчики.
--
-- ## Что в строке
--
--   hits, total_ms   — сколько раз и сколько на это ушло всего. Главная пара:
--                      дешёвый запрос, заданный тысячу раз, стоит дороже
--                      дорогого, заданного однажды, и видно это только так.
--   max_ms           — худший случай.
--   total_rows, max_rows — сколько строк вернулось. Отвечает на вопрос «запрос
--                      долгий потому, что много ищет, или потому, что много
--                      отдаёт».
--   slow_*           — самый долгий прогон целиком: его время, его строки и его
--                      **значения**. Аргументы последнего прогона к вопросу
--                      «почему иногда медленно» отношения не имеют.
--
-- ⚠ Ответы базы здесь **не хранятся** — ни одной строки данных. Только сам
-- запрос, его значения и числа. Значения при этом чистятся от секретов тем же
-- кодом, что и журнал запросов (`mysql_log_args`, `docs-common/observability_rules.md`, §10).
--
-- ## Ключ — отпечаток вместе с процессом
--
-- Один и тот же запрос из uvicorn и из воркера — две строки, и это осознанно:
-- «кто спрашивает» — половина ответа на вопрос «зачем так часто». Отбор по
-- процессу на странице уже есть, он общий с подвкладкой ошибок.

CREATE TABLE IF NOT EXISTS `journal_mysql` (
    `id` INT NOT NULL AUTO_INCREMENT,
    -- Отпечаток вида запроса: md5 текста, сведённого к одному виду (пробелы,
    -- длина списков `IN (%s, %s, ...)`). Считает `mysql_watch_fingerprint`;
    -- значение здесь, а не в коде страницы, потому что по нему стоит UNIQUE.
    `fingerprint` CHAR(32) NOT NULL COMMENT 'md5 вида запроса — по нему повтор находит свою строку',
    `source` VARCHAR(32) NOT NULL DEFAULT '' COMMENT 'Процесс: uvicorn, worker, telegram, cronjob',
    `query` MEDIUMTEXT NOT NULL COMMENT 'Сам запрос с плейсхолдерами, как он написан в коде',

    `hits` BIGINT NOT NULL DEFAULT 0 COMMENT 'Сколько раз выполнялся',
    `total_ms` DOUBLE NOT NULL DEFAULT 0 COMMENT 'Сколько времени ушло всего, мс',
    `max_ms` DOUBLE NOT NULL DEFAULT 0 COMMENT 'Самый долгий прогон, мс',
    `total_rows` BIGINT NOT NULL DEFAULT 0 COMMENT 'Сколько строк вернул всего',
    `max_rows` INT NOT NULL DEFAULT 0 COMMENT 'Больше всего строк за один прогон',

    `slow_ms` DOUBLE NOT NULL DEFAULT 0 COMMENT 'Время самого долгого прогона, мс',
    `slow_rows` INT NOT NULL DEFAULT 0 COMMENT 'Сколько строк вернул самый долгий прогон',
    `slow_args` MEDIUMTEXT NULL COMMENT 'Значения самого долгого прогона; секреты вырезаны',
    `slow_at` DATETIME(3) NULL COMMENT 'Когда случился самый долгий прогон',

    `first_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
        COMMENT 'Когда запрос увидели впервые',
    `last_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
        COMMENT 'Последний раз; по нему видно, живой запрос или остался от старого кода',

    PRIMARY KEY (`id`),
    -- Одна строка на вид запроса в одном процессе: повтор бьётся в счётчики.
    UNIQUE KEY `uniq_journal_mysql_shape` (`fingerprint`, `source`),
    -- Лента по умолчанию — самое дорогое сверху.
    INDEX `idx_journal_mysql_total` (`total_ms`),
    -- Чистка по сроку и отбор «что работало на днях».
    INDEX `idx_journal_mysql_last` (`last_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
