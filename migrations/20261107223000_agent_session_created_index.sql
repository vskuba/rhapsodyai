-- Индекс под уборку журнала вызовов LLM (`ai_session_trim`).
--
-- У `agent_session` срока хранения не было вовсе: таблица росла с 19 июля и к
-- 2026-11-07 набрала 2.29 млн строк на 7.3 ГБ — 80% базы в 9.2 ГБ при буферном
-- пуле в 1 ГБ. Мёртвый хвост вытеснял из кэша живые страницы: 568 млн
-- физических чтений с диска и 6408 ожиданий свободной страницы в пуле за 39
-- суток аптайма базы.
--
-- Уборка сносит пачками по `created_at` с `ORDER BY created_at`, и без индекса
-- каждая пачка была бы полным проходом по таблице в 7.3 ГБ — ровно та беда, от
-- которой уборку заводили. В начальной схеме индексы есть на `session_uuid`,
-- `llm_id`, `agent_id`, `user_id`, а на `created_at` — нет.
--
-- ⚠ ALTER идёт INPLACE: добавление индекса перестройки таблицы не требует,
-- запись живых вызовов на это время не останавливается.
--
-- ⚠⚠ **Этот индекс заводится руками ДО выкладки, а не выкладкой.** Миграции
-- накатывает новый контейнер uvicorn при старте, а `bluegreen.sh` ждёт его
-- ответа 90 секунд (`HEALTH_TIMEOUT`). Построение индекса по таблице в 7.3 ГБ в
-- это окно не влезает: выкладка покраснеет, не дождавшись слота. Замер для
-- сравнения — 34 с на индекс при таблице 1 328 МБ (session.md, §«Индексы»),
-- отсюда и правило про две выкладки на этой же таблице.
--
-- Порядок такой: сперва тот же ALTER руками в тихий час, потом выкладка — и
-- миграция на ней станет пустым `SELECT 1` благодаря проверке ниже. Проверка
-- стоит здесь именно ради этого, а не для красоты идемпотентности.

SET @index_exists = (
    SELECT COUNT(*) FROM information_schema.STATISTICS
     WHERE TABLE_SCHEMA = DATABASE()
       AND TABLE_NAME = 'agent_session'
       AND INDEX_NAME = 'idx_agent_session_created');
SET @sql = IF(@index_exists = 0,
    'ALTER TABLE `agent_session`
       ADD INDEX `idx_agent_session_created` (`created_at`),
       ALGORITHM=INPLACE',
    'SELECT 1');
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
