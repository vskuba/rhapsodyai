-- Адрес оболочки в шагах `claude_shell_call`: `inputs_map.session = task_shell_session`.
--
-- Зачем. У роли бывает несколько живых оболочек — по одной на открытый терминал, — и
-- круг конвейера захватывает себе одну на всё время работы (`team_shell_pool`). Чтобы
-- шаги ходили именно в неё, адрес нужно передать инструменту: он приезжает в прогон
-- переменной `task_shell_session`, а связывает её с аргументом инструмента вот эта
-- запись в `inputs_map`.
--
-- Без неё захват был бы бесполезен: `claude_shell_call` продолжил бы выбирать самую
-- свежую по пингу оболочку роли, и два круга одной роли попали бы в одну и ту же —
-- второй промпт прилетел бы агенту посреди чужого хода.
--
-- Правим все шаги с этим инструментом разом, а не перечисляем их номерами: шаги
-- добавляют и переносят между workflow, и список id устарел бы к следующей правке.
-- Условие отбора — сам `tool_name`, он и есть признак «этот шаг ходит в оболочку».
--
-- Идемпотентность: `JSON_SET` перезаписывает ключ тем же значением, повторный прогон
-- ничего не меняет. Пустая переменная в прогоне (старый вызов агента, ручной запуск
-- workflow) инструменту не мешает — он тогда выбирает оболочку сам, как раньше.
UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(`metadata`,
                             '$.tool_invoke.inputs_map.session',
                             'task_shell_session')
 WHERE JSON_VALID(`metadata`)
   AND JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.tool_invoke.tool_name')) = 'claude_shell_call';
