-- Цепочки сценариев браузера убраны: `browser_workflow`, `browser_workflow_step`.
--
-- Что это было. Цепочка гнала несколько сценариев подряд в одной сессии, копила
-- их `extract` в общий словарь и вставала на первом упавшем звене.
--
-- Почему убираем. Единственный, кому это могло пригодиться, — DatingAi, — ведёт
-- последовательность у себя: держит `session_id` и передаёт его в каждый прогон
-- сценария. Иначе он не может, потому что между шагами принимает решения — кому
-- отвечать, что писать, пора ли перелогиниться. Цепочка же гонит шаги вслепую от
-- начала до конца, и вставить решение в середину ей некуда.
--
-- В итоге запуск звали из одного места — кнопки на `/admin/browser`, — а в базе за
-- всё время завелась одна цепочка `wf_test` из двух звеньев, тестовая.
--
-- Сценарии остаются: ими и работает и админка, и DatingAi
-- (`POST /api/browser/scenario/{id}/run`).
--
-- Порядок удаления обратен порядку создания: звенья ссылаются на цепочку внешним
-- ключом, и снести её первой нельзя.
DROP TABLE IF EXISTS `browser_workflow_step`;
DROP TABLE IF EXISTS `browser_workflow`;
