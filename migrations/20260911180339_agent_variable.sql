-- Переменные агента: `agent.agent_variable`.
--
-- ЧТО БЫЛО. Агенты одного вида отличаются друг от друга не логикой, а одной
-- строкой внутри системного промпта. Живой пример — знакомства: `dating_talk`
-- один на всех, текст промпта у всех анкет совпадает до буквы, и разнится в нём
-- ровно имя: «You are a girl Diana» против «You are a girl Renata». Каждой
-- анкете приходилось заводить своего агента — сотни записей с одинаковым
-- текстом. Правка формулировки в промпте означала правку в каждой из них, а
-- заведение анкеты — лишний прогон workflow только ради копии текста.
--
-- ЧТО ДЕЛАЕМ. Колонка `agent_variable` — JSON-словарь `{"girl_name": "Natalia"}`.
-- Значения подставляются в `%плейсхолдеры%` системного промпта и приветствия
-- перед отправкой в модель. Запись агента становится одна, а различие между
-- собеседницами переезжает в переменную; конкретный разговор может прислать
-- своё значение в `variables` запроса `POST /chat/ask` — оно перекрывает
-- умолчание записи.
--
-- ⚠ ПОЧЕМУ ОТДЕЛЬНАЯ КОЛОНКА, А НЕ `workflow_variable`. Соседняя колонка уже
-- хранит JSON переменных, и соблазн сложить туда же велик. Но у них разные
-- владельцы: `workflow_variable` — вход workflow, его читает движок шагов;
-- `agent_variable` — то, чем агент отличается от соседа, и это видно в форме
-- отдельным блоком. Смешав их, мы бы объяснили человеку, что «переменные
-- workflow» — это ещё и про имя собеседницы.
--
-- NULL для существующих записей: переменных у них нет, и выдумывать их нечем.
-- Пустой словарь `'{}'` в колонку не пишем — «переменных нет» и «переменные
-- есть, но пустые» в чтении неразличимы.
--
-- Идемпотентность: `ADD COLUMN IF NOT EXISTS` MySQL не поддерживает, поэтому
-- через `information_schema` и `PREPARE` — тем же приёмом, что в
-- `20260903100320_agent_site.sql`.

SET @exists := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
     WHERE TABLE_SCHEMA = DATABASE()
       AND TABLE_NAME = 'agent'
       AND COLUMN_NAME = 'agent_variable'
);

SET @sql := IF(@exists = 0,
    'ALTER TABLE `agent`
        ADD COLUMN `agent_variable` LONGTEXT DEFAULT NULL
            COMMENT ''Переменные агента JSON: подставляются в %плейсхолдеры% промпта и приветствия''
            AFTER `workflow_variable`',
    'SELECT 1');

PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
