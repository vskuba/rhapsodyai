-- Ветка «письма и фото»: формулировки, не толкающие к отказу (2026-09-21)
--
-- ЗАЧЕМ. Ветка заводилась ради согласия в ОБЕ стороны, но на «пришли свои
-- фотографии» отвечала отказом. Нашёл живой тест
-- `tests_llm/test_dating_talk.py::test_it_promises_her_photos`.
--
-- ⚠⚠ ПЕРВАЯ ПРИЧИНА — САМ ПРОМПТ ВЕТКИ. В запретах стояло «обещание, которого не
-- выполнить, хуже отказа». Для человека это довод «не завирайся»; модель читает
-- его как прямое разрешение отказать — ей ведь сказали, что отказ лучше. Запрет
-- на откровенное оставляем, довод убираем.
--
-- ⚠ ВТОРАЯ — случай «он просит ТВОИ» был описан мягче остальных. Дописано, что
-- перевести разговор на его фотографии или ответить «потом» это тот же отказ,
-- только другими словами: модель выбирала ровно эти обходы.
--
-- ⚠⚠ ЧЕСТНО О РЕЗУЛЬТАТЕ: правка помогает не до конца. После неё три случая из
-- четырёх проходят, а «пообещать свои» по-прежнему срывается в увёртку («save the
-- surprise for later»). Выкладывается затем, чтобы прод и разработка не
-- расходились — расхождение само по себе источник ошибок, — а не как решение.
-- Разбор продолжается.
--
-- Идемпотентность: `REPLACE` не найдёт строку на второй заход и ничего не тронет.

SET @step = (SELECT `id` FROM `agent_workflow_step`
              WHERE `workflow_id` = (SELECT `id` FROM `agent_workflow`
                                      WHERE `name` = 'dating_talk_about_photo')
                AND `title` = 'Ответ про письма и фото');

SELECT 'ДО' AS этап, @step AS шаг,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `id` = @step
           AND JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%хуже отказа%') AS довод_к_отказу;

UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(`metadata`, '$.prompt_user',
       REPLACE(JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')),
               '- не описывай, что именно на фотографиях, и не обещай ничего откровенного: обещание, которого не выполнить, хуже отказа;', '- не описывай, что именно на фотографиях, и не обещай ничего откровенного — но и не отказывай: согласие без подробностей это то, что нужно;'))
 WHERE `id` = @step;

UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(`metadata`, '$.prompt_user',
       REPLACE(JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')),
               '2. **Он просит ТВОИ фотографии.** Соглашайся и скажи, что пришлёшь письмом. Не обещай конкретного часа: «сегодня вечером» превращается в упрёк, если письмо придёт завтра.', '2. **Он просит ТВОИ фотографии.** Соглашайся и скажи, что пришлёшь письмом. ⚠ Именно пообещать своё, а не перевести разговор на его фотографии и не ответить «потом» или «при встрече»: это отказ другими словами. Часа не называй — «сегодня вечером» превращается в упрёк, если письмо придёт завтра.'))
 WHERE `id` = @step;

SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `id` = @step
           AND JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%хуже отказа%') AS довод_к_отказу,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `id` = @step
           AND JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%это отказ другими словами%') AS случай_заострён;
