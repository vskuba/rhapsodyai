-- `favorite_mail_write`: письмо избранному собирается ШАБЛОНОМ, как инвайт (2026-09-18)
--
-- ЧТО БЫЛО. Агент писал письмо **на каждую пару**: видел карточку девушки,
-- карточку мужчины и их переписку, и отвечал одним текстом одному человеку. Пул
-- в полсотни писем стоил полусотни вызовов LLM и минут ожидания у нажатой кнопки.
--
-- ЧТО СТАЛО. Один вызов на весь заход: агент присылает ШАБЛОН с меткой
-- `[[companion_name]]`, а панель раскладывает его по парам подстановкой. Тот же
-- размен, что у `dating_invite_write`, и цена та же: все письма захода одинаковы
-- с точностью до имени.
--
-- ⚠⚠ ЦЕНА ЗДЕСЬ ВЫШЕ, ЧЕМ У ИНВАЙТОВ, И ЭТО НАДО ЗНАТЬ. Инвайт уходит
-- незнакомому — терять нечего. Письмо уходит тому, кто УЖЕ ОТВЕЧАЛ: прежняя
-- версия отталкивалась от переписки пары, шаблон не видит её вовсе. Разговор
-- возобновляется не «с того места», а заново.
--
-- Держится это тем, что письмо и не притворяется продолжением: правило «не
-- выдумывай общее прошлое» было здесь и раньше — оно включалось на пустой
-- истории (`…_wf_dating_favorite_mail_no_history.sql`). Теперь история пуста
-- всегда, и правило стало безусловным. Живому человеку такое письмо читается как
-- «вспомнила о тебе», а не как ответ на реплику, которой он не помнит.
--
-- ЧЕМ ПИСЬМО ОТЛИЧАЕТСЯ ОТ ИНВАЙТА — ровно тем, ради чего занятие и заводили:
--
--   втрое больше текста     `fav_length` — от абзаца до трёх, по 40–60 слов;
--   рассказ девушки о себе  `fav_story` — день, случай, желание, опыт общения
--                           с мужчинами. По жребию, доля 40%;
--   вопрос НЕ всегда        `fav_question` — доля 25%. Вопрос в каждом письме
--                           превращает переписку в анкету;
--   имя изредка             `fav_slots` — доля 10%, и только первое слово.
--
-- ⚠⚠ ВСЕ ЧЕТЫРЕ ДОЛИ БРОСАЕТ ПАНЕЛЬ, А НЕ МОДЕЛЬ. Это уже проверено на инвайтах:
-- «вставляй имя изредка» модель понимает как «вставляй всегда», а «будь разной» —
-- как «пиши одинаково» (три шаблона из трёх начинались с «you're trouble»).
-- Вероятность у неё не считается, она стилистическая. Поэтому сюда приходит не
-- вероятность, а решение: метка нужна или нет, рассказ нужен или нет.
--
-- ⚠ ВРЕМЯ ПРОСЯТ ТОЛЬКО ПОД РАССКАЗ. Дай модели время — она помянет его почти
-- везде (на живом пуле инвайтов: 94 из 202 за сутки). Но «как прошёл день» без
-- часа выходит про несуществующий день, поэтому `fav_time` поднимается ровно
-- тогда, когда выпал рассказ о себе.
--
-- ЦЕПОЧКА — та же, что у инвайта, и по той же причине: шаблон уходит десяткам
-- живых людей без человеческого взгляда, и брак портит весь пул.
--
--   0 время → 1 черновик → 2 судья → 3 правка → 4 ответ конвертом
--
-- Судья, сказавший «yes», перескакивает правку переходом на шаг ответа.
--
-- ⚠ `step_id` перехода — это ID ШАГА В БАЗЕ, строкой, а не позиция. Он разный в
-- каждой инсталляции, поэтому переход и метка результата инструмента
-- проставляются отдельными запросами — по ID, известным только после вставки.
--
-- Идемпотентность: промпты переписываются целиком, шаги и переменные заводятся по
-- условию отсутствия.

-- ⚠ Имя в базе соседа — с приставкой `dating_`, хотя в константе панели её нет
