-- ---------------------------------------------------------------- Шаг времени
--
-- Прежний единственный шаг стоял нулевым. Освобождаем ему место: письмо
-- становится шагом 1, а нулевым встаёт вызов часов.
-- ⚠⚠ `type_id <> 3` здесь **обязательно**, и это не перестраховка. Без него
-- повторный прогон сдвигает на позицию 1 уже сам шаг времени — тот, что встал
-- нулевым в первый раз, — и следующий `UPDATE … position = 1` превращает часы во
-- второй черновик. Поймано на втором прогоне живьём: два шага на одной позиции и
-- `Subquery returns more than 1 row` строкой ниже.
UPDATE `agent_workflow_step` SET `position` = 1
 WHERE `workflow_id` = @wf AND `position` = 0 AND `type_id` <> 3;

