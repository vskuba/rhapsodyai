-- Чинит переносы строк, задвоенные прошлой правкой промпта (2026-09-07)
--
-- ЧТО БЫЛО. Прошлая миграция (`20260907040000`) вставила в промпт пятое правило и
-- перенумеровала хвост. Правила встали верно, а вот переносы строк вокруг них
-- записались как `\\n` вместо `\n`.
--
-- ⚠ ПОЧЕМУ ТАК ВЫШЛО. `metadata` — это **текст JSON**, и перенос строки внутри
-- него записан двумя символами: `\` и `n`. В SQL-литерале `'...\\n'` ожидалось,
-- что MySQL свернёт `\\` в один `\` — так работает его разбор строк по
-- умолчанию. Не свернул: yoyo подаёт файл драйверу, и обратный слэш доехал парой.
--
-- ЦЕНА. При разборе JSON `\\n` даёт не перенос строки, а видимый текст «\n»
-- посреди промпта: «…не уйдёт.\n5. Обращение…» одной строкой. Смысла это не
-- меняет, но промпт читает и человек, и модель — а лишний мусор в тексте учит её,
-- что мусор здесь допустим.
--
-- ЧТО ВМЕСТО. Правим тем же приёмом, но без экранирования: ищем и заменяем
-- **двусимвольную** последовательность, собранную `CONCAT` из `CHAR(92)`
-- (обратный слэш) и буквы `n`. Так строка не проходит через разбор экранирования
-- вовсе, и гадать, сколько слэшей доедет, не приходится.
--
-- Идемпотентность: замена ищет только задвоенный вид; повторный накат не найдёт
-- ничего.

-- ---------------------------------------------------------------- До
SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_mail_write');

-- `\n` и `\\n` — как последовательности символов, без участия разбора строк.
SET @nl = CONCAT(CHAR(92), 'n');
SET @nl2 = CONCAT(CHAR(92), CHAR(92), 'n');

SELECT 'ДО' AS этап,
       @wf AS workflow_id,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND LOCATE(@nl2, `metadata`) > 0) AS задвоенных_есть;

-- ------------------------------------------- Замена
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(`metadata`, @nl2, @nl)
 WHERE `workflow_id` = @wf
   AND LOCATE(@nl2, `metadata`) > 0;

-- ---------------------------------------------------------------- После
--
-- ⚠ Проверяем **и то, что переносы на месте**: замена, снёсшая их вместе с
-- задвоением, оставила бы промпт одной строкой — и это заметили бы не сразу.
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND LOCATE(@nl2, `metadata`) > 0) AS задвоенных_осталось,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND LOCATE(@nl, `metadata`) > 0) AS переносы_на_месте;
