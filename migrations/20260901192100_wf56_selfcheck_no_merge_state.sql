-- Самопроверка разработчика перестаёт судить о слиянии с master.
--
-- Разбор случая #6438, круг самопроверки в 19:09. Ответ: dev_ok=no, и первым
-- замечанием — блокирующим — стоит вот это:
--
--   ЗАМЕЧАНИЕ 1, блокирующее. PR не мержится: gh pr view 43 даёт
--   mergeable=CONFLICTING, mergeStateStatus=DIRTY. Ветка отстаёт от origin/master на
--   14 коммитов <...> ЗАДАНИЕ: влить origin/master в feature/task_6438 и разрулить эти
--   два места самому <...> неразрешённый конфликт в собственную ветку есть недотык
--   своей работы, а не чужая вина.
--
-- Разработчик прав в фактах и неправ в выводе. Конфликтуют `.claude/docs/testing.md` и
-- `.claude/docs/project_task_roles.md` — файлы, которые за эти 14 коммитов правил не он,
-- а соседние работы и человек. Ни свитчера Light/Full, ни `qa_mode` в конфликте нет.
--
-- Почему вывод неверен по устройству конвейера. Ветку подзадачи режут от master один
-- раз, и дальше она работает со своего среза — это не оплошность, а решение: работа
-- привязана к состоянию, на котором её планировали, и подтягивать master в неё
-- запрещено ровно затем, чтобы код не менялся под ногами у идущего круга (см.
-- `task_pipeline._manager_plan_write`, где к master подтягивается **каталог менеджера**
-- и оговорено, что для подзадачи так делать нельзя). Master за время работы уезжает
-- всегда: подзадача идёт часами, а рядом идут другие.
--
-- Отсюда цена ошибки. Слияние делает человек, глядя на diff, — и конфликт разбирает он
-- же. Разработчик не может ни предотвратить чужой коммит, ни решить за человека, чья
-- версия строки верна. Оставь мы это замечание в силе — подзадача не сдаётся не потому,
-- что работа не сделана, а потому, что кто-то поправил соседний файл в master. Живьём
-- это стоило #6438 круга: единственная задача на круг была не про код задачи.
--
-- Случай не первый, и в этом главное. Тот же дрейф ветки заворачивал самопроверку
-- дважды до того: в 13:20 — критично мержить строго после PR #35, необходимо
-- переоткрытие PR на свежий master; в 18:21 — сюита красная, нужно либо смержить
-- origin/master. Три круга из трёх израсходованы на состояние чужого кода.
--
-- Поэтому правится не список замечаний, а сама формулировка требования. Слово открыт в
-- формальных требованиях агент дочитывал как открыт и сходится с master — отсюда
-- `gh pr view --json mergeable`. Теперь граница названа прямо: открыт, и только.
--
-- Заодно запрещено лечение, которое агент себе прописал: влить master в свою ветку. Оно
-- хуже болезни — меняет срез, на котором QA будет проверять работу, и переносит разбор
-- чужих конфликтов на агента, то есть ровно туда, откуда его убирают.
--
-- Кавычек в тексте нет намеренно: промпт лежит строкой внутри JSON в `metadata`, и
-- двойная кавычка рвёт разбор шага целиком (см. `tests/test_agent_workflow_steps.py`).
--
-- Идемпотентность: условия проверяют, что заменяемый текст ещё на месте.

-- 1. Формальное требование: merge request нужен открытый, а не сошедшийся с master.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'merge request в master открыт и его\\nадрес попал в отчёт полем mr_url',
        'merge request в master открыт и его\\nадрес попал в отчёт полем mr_url '
        '(открыт — и только: сойдётся ли он с master, здесь не спрашивают)')
 WHERE `id` = 439
   AND `metadata` LIKE '%адрес попал в отчёт полем mr_url%'
   AND `metadata` NOT LIKE '%здесь не спрашивают%';

-- 2. Состояние слияния — в списке того, что замечанием не является.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '  - улучшения соседнего кода, замеченные попутно;\\n',
        '  - улучшения соседнего кода, замеченные попутно;\\n'
        '  - состояние слияния с master: отставание ветки, конфликты, mergeable у PR.\\n'
        '    Ветку режут от master один раз, и работает она со своего среза; master за\\n'
        '    это время уезжает — так устроено, это не твой недосмотр. Конфликты\\n'
        '    разбирает человек при слиянии, он же его и делает. Master в свою ветку не\\n'
        '    вливай: что входит в ветку, решает конвейер, а не круг самопроверки.\\n'
        '    Нужна чужая правка, чтобы твоя работа вообще шла, — это вопрос человеку\\n'
        '    полем question, а не слияние своей рукой;\\n')
 WHERE `id` = 439
   AND `metadata` LIKE '%улучшения соседнего кода, замеченные попутно%'
   AND `metadata` NOT LIKE '%состояние слияния с master%';
