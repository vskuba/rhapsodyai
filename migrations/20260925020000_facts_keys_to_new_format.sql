-- Ключи фактов переводятся на новый образец (2026-09-25)
--
-- ## ⚠⚠ ЗАЧЕМ: иначе выкладка отнимет у агентов память
--
-- Факты девушек лежат под старыми ключами, а новый поиск ходит за другими:
--
--     лежит   renata_1430354     ищем   1430354_renata
--     лежит   diana_9021         ищем   643694_diana
--
-- Ключ теперь собирает шаг «Ключи» (`…_wf_talk_girl_key`) из **номера анкеты на
-- сайте** и её имени строчными. Разойдись запись и поиск — беда будет совершенно
-- тихой: ошибки нет, поиск честно вернёт пусто, и Renata просто «забудет» о себе
-- всё, что о ней записано.
--
-- ## ⚠⚠ Устройство: `UPDATE`, а не замена
--
-- Соседний файл (`migrations/local/…_facts_from_prod`) сносил таблицу целиком и
-- заливал снимок — там это было уместно, потому что база локальная и в ней лежал
-- мусор сюиты. **Здесь так нельзя**: это боевые данные, единственный экземпляр.
--
-- Поэтому: ничего не удаляем, ключи переводим по одному, неизвестные оставляем
-- как есть и показываем в отчёте.
--
-- ## Что переводится
--
--     renata_1430354  32 факта  → 1430354_renata   профиль 2, логин 1430354
--     diana_9021      23 факта  → 643694_diana     профиль 40, site_uid 643694
--
-- ⚠⚠ У Diana меняется **не только регистр**: `9021` — это обрывок почтового
-- адреса `bogiladiana9021@bigmir.net`, а настоящий номер на сайте `643694`
-- (`profile.site_uid`). Прежний ключ не значил ничего.
--
-- ⚠ У Renata `site_uid` нет — она заведена до того, как его начали снимать; её
-- номер лежит в `profile.id` и равен логину.
--
-- ## ⚠⚠ Что НЕ переводится, и это решение
--
--     masha                  31 факт   владелец admin
--     elena                  28 фактов владелец admin
--     dating_girl_universal   2 факта  имя агента, а не девушки
--
-- Первые два числятся за `admin`, а не за `dating_service` — то есть заведены
-- руками до того, как у DatingAi появилась своя учётка. Анкеты `masha` нет нигде,
-- Elena две (профили 43 и 44), и какая из них — не говорит ничто.
--
-- Отдать их одной из двух живых анкет значило бы приписать человеку чужие слова.
-- Они **остаются как есть**: новым поиском недостижимы, но и не потеряны. Кто
-- захочет — разберётся по текстам.
--
-- ⚠ Третий — `dating_girl_universal` — сироты подпрогона выдумывания: он помечал
-- факты именем агента, одним на всех (починено `…_wf_invent_facts_key`). Чьи они,
-- не знает никто.
--
-- ## ⚠⚠ Qdrant правится не здесь
--
-- `document_id` лежит копией в payload точки, и `UPDATE` в MySQL её не трогает.
-- Поэтому переведённые факты помечаются `qdrant_synced = 0`, а после выкладки
-- надо снести их точки и позвать `qdrant_fact_sync` — иначе в Qdrant окажутся
-- **обе** версии: старая под прежним ключом и новая под новым.

SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM `fact`) AS фактов_всего,
       (SELECT GROUP_CONCAT(DISTINCT `document_id` ORDER BY `document_id`
                            SEPARATOR ', ') FROM `fact`) AS ключи;

-- ── Перевод ─────────────────────────────────────────────────────────────────
--
-- ⚠ По имени ключа, а не по номеру анкеты: номера у баз разные, а ключ — это то
-- самое, что мы и чиним. Условие «старый ключ» заодно делает прогон повторяемым:
-- второй раз под него не попадёт никто.
UPDATE `fact` SET `document_id` = '1430354_renata', `qdrant_synced` = 0
 WHERE `document_id` = 'renata_1430354';

UPDATE `fact` SET `document_id` = '643694_diana', `qdrant_synced` = 0
 WHERE `document_id` = 'diana_9021';

-- ── Записи девушек в справочнике ────────────────────────────────────────────
--
-- ⚠ Девушки живут в том же справочнике, что и собеседники (`…_wf_talk_girl_key`),
-- и записи им нужны **заранее**: иначе workflow заведёт их сам при первом заходе,
-- но с другим номером — а факты уже лежат под этим ключом.
INSERT INTO `companion` (`unique_id`, `title`)
SELECT one.`key`, one.`title` FROM (
        SELECT '1430354_renata' AS `key`, 'Renata' AS `title`
  UNION SELECT '643694_diana', 'Diana') AS one
 WHERE NOT EXISTS (SELECT 1 FROM (SELECT * FROM `companion`) x
                    WHERE x.`unique_id` = one.`key`);

SELECT 'ПОСЛЕ' AS этап,
       -- ⚠⚠ Главная проверка: фактов столько же, сколько было. Эта миграция
       -- **ничего не удаляет** — разойдись счёт, значит удалила.
       (SELECT COUNT(*) FROM `fact`) AS фактов_всего,
       (SELECT COUNT(*) FROM `fact`
         WHERE `document_id` IN ('1430354_renata', '643694_diana')) AS переведено,
       (SELECT COUNT(*) FROM `fact`
         WHERE `document_id` IN ('renata_1430354', 'diana_9021')) AS осталось_старых,
       -- ⚠ Непереводимые обязаны уцелеть: они не мусор, а память, чьего хозяина
       -- мы не знаем.
       (SELECT COUNT(*) FROM `fact`
         WHERE `document_id` IN ('masha', 'elena',
                                 'dating_girl_universal')) AS оставлено_как_есть,
       (SELECT COUNT(*) FROM `companion`
         WHERE `unique_id` IN ('1430354_renata', '643694_diana')) AS записей_девушек,
       -- ⚠⚠ Ждут пересинхронизации: без неё в Qdrant останется старый ключ, и
       -- поиск не найдёт ничего, хотя в базе всё верно.
       (SELECT COUNT(*) FROM `fact` WHERE `qdrant_synced` = 0) AS ждут_синка;
