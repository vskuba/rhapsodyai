-- Условные блоки переходят на `[<if var>]` (2026-09-25)
--
-- ## ⚠⚠ ЗАЧЕМ (указание человека, не почин модели)
--
--     было:  %if var%…%else%…%endif%              отрицание %if !var%
--     стало: [<if var>]…[<else>]…[<endif>]        отрицание [<if !var>]
--
-- Прежний синтаксис делил проценты с метками переменных, и от этого страдали обе
-- стороны: имя внутри условия писалось **без** процентов (не как везде), а
-- `%endif%` выглядел меткой, меткой не будучи. Разборщику приходилось держать
-- список «слова разметки, которые выглядят переменной» и вычитать его из улова
-- меток — и то же самое повторяла подсветка в редакторе. Два места, знающих один
-- список, расходятся.
--
-- Теперь разметка и метки не пересекаются: `[<…>]` — управление, `%…%` —
-- подстановка. ⚠ Имя внутри условия — **без процентов**: проценты значат
-- «сюда встанет значение», а условие значение проверяет, а не вставляет.
--
-- ## ⚠⚠ Почему `[<…>]`, а не `[[…]]`
--
-- Двойные квадратные скобки были взяты первыми и прожили полдня. Они **уже заняты**,
-- причём дважды, и оба места живые:
--
--     [[Создать проект]]   чипса чата — кнопка под ответом агента (chat.html)
--     [[firstName]]        метка переменной письма (DatingAi/src/dating/mail.py)
--
-- ⚠⚠⚠ Первое опаснее. `MESSAGE_TOKEN_REGEX` ловит **любое** `[[…]]`, и
-- неразвёрнутый блок показался бы человеку **кнопкой**: `[[if var]]` — кнопкой
-- «if var», по щелчку отправляющей эти слова агенту как реплику, а отрицание
-- `[[!var]]` попадает в ветку `[[!текст]]` — «опасное действие», то есть в
-- **красную** кнопку.
--
-- Второе — тот же вид записи с двумя смыслами в одном тексте: промпт шага «Что не
-- так» одновременно содержал условие блока и просьбу к модели «вставь метку
-- `[[имя]]`».
--
-- Различать их по содержимому нельзя: `endif` — законное имя переменной письма.
-- Поэтому скобки разведены **видом**, а не списком исключений.
--
-- ## ⚠ Миграция принимает ДВА прежних вида, и это не перестраховка
--
-- Локальная база успела получить `[[…]]` первой версией этого файла. На проде их
-- нет — там ещё проценты. Один файл обязан приводить к цели из обоих состояний,
-- иначе понадобилась бы вторая миграция ради промежуточного вида, которого в
-- истории проекта не было ни дня.
--
-- ## Объём
--
--     53 шага, 163 блока, из них 2 с отрицанием — всё в `agent_workflow_step.metadata`
--
-- ⚠ Прочие места чисты, проверено запросом: `agent.prompt_system`, `agent.greeting`,
-- `node_variable.default`, `agent_workflow_variable.default` — ни одного блока.
--
-- ## ⚠⚠ Порядок замен обязателен, иначе съедим лишнее
--
--     1. %endif%  → [<endif>]       закрытия — они однозначны
--     2. %else%   → [<else>]        то же
--     3. %if !x%  → [<if !x>]       отрицание ПЕРЕД обычным…
--     4. %if x%   → [<if x>]        …иначе шаг 4 съест «!» в имя
--
-- ⚠ Шаги 3 и 4 идут `REGEXP_REPLACE` по одному имени: `%if ` и `%` вокруг имени
-- не парны, и простой `REPLACE` тут не выразим.
--
-- ## ⚠⚠⚠ Обратная ссылка в MySQL — `$1`, а НЕ `\1`
--
-- Стоило репетиции на копии прода: с `'\\1'` замена вставляет **букву «1»** вместо
-- имени, и все 163 блока получают `[<if 1>]`. Переменной `1` не существует —
-- значит каждый блок считался бы ложным, и **все условные секции промптов исчезли
-- бы разом**, беззвучно: ошибки нет, промпт собран, просто беднее.
--
-- ⚠⚠ Первая версия проверки «после» этого **не поймала**: она считала блоки,
-- открытия, закрытия и отрицания — все счётчики сошлись (163 = 163), а данные были
-- испорчены. Отсюда добавленный ниже счёт **имён-неидентификаторов**: сверять надо
-- не только число блоков, но и то, что внутри них осталось настоящее имя.
--
-- ## ⚠⚠ Проверка «до» и «после» считает БЛОКИ, а не строки
--
-- Строка может нести десяток блоков. Сойдись счёт строк, а не блоков — половина
-- условий осталась бы прежним синтаксисом при зелёном отчёте.

SELECT 'ДО' AS этап,
       SUM(ROUND((LENGTH(`metadata`) - LENGTH(REPLACE(`metadata`, '%endif%', '')))
                 / LENGTH('%endif%'))) AS блоков_процентных,
       SUM(ROUND((LENGTH(`metadata`) - LENGTH(REPLACE(`metadata`, '[[endif]]', '')))
                 / LENGTH('[[endif]]'))) AS блоков_двойных,
       SUM(ROUND((LENGTH(`metadata`) - LENGTH(REPLACE(`metadata`, '[<endif>]', '')))
                 / LENGTH('[<endif>]'))) AS блоков_целевых,
       SUM(`metadata` LIKE '%\%if !%') + SUM(`metadata` LIKE '%[[if !%')
           AS строк_с_отрицанием
  FROM `agent_workflow_step`;

-- ── 1. Закрытия и «иначе» ───────────────────────────────────────────────────
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(REPLACE(`metadata`, '%endif%', '[<endif>]'),
                            '[[endif]]', '[<endif>]')
 WHERE `metadata` LIKE '%\%endif\%%' OR `metadata` LIKE '%[[endif]]%';

UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(REPLACE(`metadata`, '%else%', '[<else>]'),
                            '[[else]]', '[<else>]')
 WHERE `metadata` LIKE '%\%else\%%' OR `metadata` LIKE '%[[else]]%';

-- ── 2. Отрицание — ПЕРЕД обычным условием ───────────────────────────────────
--
-- ⚠⚠ Порядок не переставлять: обычное условие `%if (\w+)%` не совпадёт с
-- `%if !var%` (восклицательный знак — не `\w`), но стоило бы шаблону стать
-- терпимее — и «!» уехал бы внутрь имени, дав `[<if !var>]` со «!» внутри имени.
-- Блок с таким именем не развернётся никогда, и молча: сторож увидит остаток
-- разметки, но причину («съеденное отрицание») не назовёт.
UPDATE `agent_workflow_step`
   SET `metadata` = REGEXP_REPLACE(`metadata`, '%if !([[:alnum:]_]+)%',
                                   '[<if !$1>]')
 WHERE `metadata` REGEXP '%if !';

UPDATE `agent_workflow_step`
   SET `metadata` = REGEXP_REPLACE(`metadata`, '\\[\\[if !([[:alnum:]_]+)\\]\\]',
                                   '[<if !$1>]')
 WHERE `metadata` LIKE '%[[if !%';

-- ── 3. Обычное условие ──────────────────────────────────────────────────────
UPDATE `agent_workflow_step`
   SET `metadata` = REGEXP_REPLACE(`metadata`, '%if ([[:alnum:]_]+)%',
                                   '[<if $1>]')
 WHERE `metadata` REGEXP '%if ';

-- ⚠ Здесь `[[if ` и `[[firstName]]` различает **слово `if`**: метки письма
-- (`[[girl_name]]`) шаблон не задевает и задеть не должен.
UPDATE `agent_workflow_step`
   SET `metadata` = REGEXP_REPLACE(`metadata`, '\\[\\[if ([[:alnum:]_]+)\\]\\]',
                                   '[<if $1>]')
 WHERE `metadata` LIKE '%[[if %';

SELECT 'ПОСЛЕ' AS этап,
       -- ⚠⚠ Прежних блоков не остаётся ни одного — это и есть цель.
       SUM(ROUND((LENGTH(`metadata`) - LENGTH(REPLACE(`metadata`, '%endif%', '')))
                 / LENGTH('%endif%'))) AS блоков_процентных,
       SUM(ROUND((LENGTH(`metadata`) - LENGTH(REPLACE(`metadata`, '[[endif]]', '')))
                 / LENGTH('[[endif]]'))) AS блоков_двойных,
       -- ⚠ Целевых столько же, сколько было прежних: потеряйся блок — условие
       -- исчезло бы вместе с секцией промпта, и заметили бы это по ответу модели.
       SUM(ROUND((LENGTH(`metadata`) - LENGTH(REPLACE(`metadata`, '[<endif>]', '')))
                 / LENGTH('[<endif>]'))) AS блоков_целевых,
       -- ⚠⚠ Открытий должно быть ровно столько же, сколько закрытий: разойдись
       -- они — блок не развернётся, и промпт уедет с разметкой внутри.
       SUM(ROUND((LENGTH(`metadata`) - LENGTH(REPLACE(`metadata`, '[<if ', '')))
                 / LENGTH('[<if '))) AS открытий,
       -- ⚠ Отрицание уцелело и не съелось в имя.
       SUM(`metadata` LIKE '%[<if !%') AS строк_с_отрицанием,
       -- ⚠⚠ Имя обязано остаться ИМЕНЕМ. Первая версия считала блоки и
       -- отрицания — счёт сошёлся (163 = 163) при `[<if 1>]` во всех.
       SUM(`metadata` REGEXP '\\[<if !?[0-9]') AS имён_из_цифр,
       -- ⚠ Проценты внутри скобок: `LIKE '%[<if %\%%'` тут негоден — он ловит
       -- любой процент дальше по тексту, а их в шаге десятки. Нужен REGEXP,
       -- ограниченный самими скобками.
       SUM(`metadata` REGEXP '\\[<if [^>]*%') AS процент_в_скобках,
       -- ⚠⚠ Остатков прежнего синтаксиса быть не должно вовсе.
       SUM(`metadata` LIKE '%\%if %') + SUM(`metadata` LIKE '%[[if %')
           AS осталось_старых_if,
       -- ⚠ А вот метки письма `[[имя]]` уцелеть ОБЯЗАНЫ: промпт, просящий модель
       -- их поставить, — законный текст. Счётчик стоит здесь, чтобы правка,
       -- ловящая разметку по скобкам, а не по слову, сразу дала ноль.
       SUM(`metadata` LIKE '%[[%') AS строк_с_метками_письма
  FROM `agent_workflow_step`;
