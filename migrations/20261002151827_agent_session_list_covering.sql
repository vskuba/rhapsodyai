-- Список сессий перестаёт ходить в таблицу: покрывающий индекс (2026-10-02)
--
-- ## ⚠⚠ ЗАЧЕМ
--
-- Страница «Сессии», вкладка «Агенты» открывалась на проде **семь секунд**.
-- Половина — перевоз и отрисовка полного списка, её сняла постраничная выдача
-- (`SESSION_PAGE`). Вторая половина в базе, и постраничность её не трогает:
-- чтобы отдать пятьдесят свежих сессий, надо сгруппировать все 443 371 строку.
--
-- Группировка идёт по `session_uuid` (есть `idx_session`), но в выборке ещё
-- `created_at`, `agent_id`, `user_id`, `kind_type`, `role` — их в индексе нет,
-- и база лезет за ними в таблицу. Таблица весит **1 328 МБ**: в ней лежит
-- `content`, то есть промпты и ответы модели.
--
-- Замерено на боевой базе (MySQL 8.0.46):
--
--     запрос                                     сейчас   план
--     список без фильтра                          3.9 с   temporary + filesort, в таблицу
--     DISTINCT kind_type                          1.1 с   полный перебор, индекса нет
--     та же группировка из одного индекса         0.4 с   Using index
--
-- Разница девятикратная, и она целиком в походах за строками.
--
-- ## Что делает индекс
--
-- `idx_session_list` — под выборку без фильтра: группировка по `session_uuid`,
-- остальные столбцы следом, чтобы в таблицу не ходить вовсе. Он же накрывает
-- `DISTINCT kind_type` — отдельного индекса под это не нужно. Проверено
-- переписью планов на копии боевых данных (443 371 строка).
--
-- ## ⚠⚠ Это ПЕРВАЯ из двух выкладок, и делятся они не из осторожности
--
-- Выборке с фильтром по агенту нужен второй индекс: `idx_agent_user`
-- расширяется с трёх столбцов до шести. Вместе два индекса строятся
-- **60–80 секунд** (замерено: 34 с на индекс на копии из 443 тысяч строк), а
-- `bluegreen.sh` ждёт ответа нового слота 90 секунд. Запас в десять секунд —
-- не запас, поэтому индексы едут по одному.
--
-- Вторая миграция **не должна** лежать в этом же коммите: yoyo применяет всё,
-- что есть в папке, и порядок имён от этого не спасает (deploy.md).
--
-- ## ⚠⚠ Цена: +56 МБ индексов, и она измерена, а не прикинута
--
-- Индекс собран на копии боевых столбцов: было 58 МБ на всю таблицу, стало
-- 114 МБ при таблице в 1 328 МБ. Платится этим и запись: `agent_session`
-- пишется на каждый вызов модели, и теперь каждая вставка обновляет на один
-- широкий индекс больше. Принято сознательно: читают страницу люди и часто, а
-- вставку делает машина и по одной строке.
--
-- ## ⚠ ALGORITHM=INPLACE, LOCK=NONE — чтобы прод продолжал писать
--
-- Сборка вторичного индекса в MySQL 8 умеет идти без блокировки записи.
-- Указано явно: умолчание выбрала бы сама база, а молчаливый откат к
-- `LOCK=SHARED` на боевой таблице — это остановка всех вызовов модели на
-- время сборки.
--
-- ## ⚠ Если выкладка всё же не уложится в healthcheck
--
-- Трафик держит **старый** слот, прод работает. Индекс к тому моменту уже
-- построен, а миграция идемпотентна — повтор (`gh run rerun <id> --failed`)
-- пройдёт мимо неё за миллисекунды. Худший исход — красная выкладка и повтор,
-- не простой.
--
-- Идемпотентность проверена: файл прогнан через yoyo дважды со снятой
-- отметкой, второй прогон не сделал ничего.

SELECT 'ДО' AS этап,
       (SELECT COUNT(DISTINCT INDEX_NAME) FROM information_schema.STATISTICS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'agent_session') AS индексов,
       (SELECT ROUND(INDEX_LENGTH/1024/1024) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'agent_session') AS индексы_мб;

SET @sql = IF(
    (SELECT COUNT(*) FROM information_schema.STATISTICS
      WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'agent_session'
        AND INDEX_NAME = 'idx_session_list') = 0,
    'ALTER TABLE `agent_session`
        ADD INDEX `idx_session_list`
            (`session_uuid`, `created_at`, `agent_id`, `user_id`, `kind_type`, `role`),
        ALGORITHM=INPLACE, LOCK=NONE',
    'SELECT ''idx_session_list уже есть'' AS пропуск');
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM information_schema.STATISTICS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'agent_session'
           AND INDEX_NAME = 'idx_session_list') AS столбцов_в_индексе,
       (SELECT ROUND(INDEX_LENGTH/1024/1024) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'agent_session') AS индексы_мб;
