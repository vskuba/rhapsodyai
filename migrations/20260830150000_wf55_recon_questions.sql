-- Вопросы разведки доезжают до человека — шаг 526 (WF55).
--
-- Разбор вместе с аварией #4799. Шаг разведки просит менеджера сформулировать до пяти
-- вопросов и ответить на них по коду — это и есть работа разведки. Но перевод разведки
-- в машинный вид (`Промпт JSON: разведка`) забирал ровно два поля, `task_done` и
-- `task_size`. Вопросы никуда не записывались: они оставались текстом в контексте
-- агента, и человек их не видел никогда.
--
-- Часть из них агент закрывает сам — на то и разведка. Но не все: развилку «чего хочет
-- заказчик» по коду не решить, и такой вопрос обязан дойти до человека. Раньше
-- единственной дверью был ключ `question` в плане — ровно один вопрос и только если
-- менеджер о нём вспомнит. Пачка в эту дверь не проходила.
--
-- Теперь просим их отдельным ключом. Просим **только те, что он не смог закрыть сам**:
-- пять вопросов, на которые он и так ответил по коду, человеку читать незачем, а
-- пачка, где половина отвечена автором, обесценивает остальные.
--
-- Задачу вопросы не держат — тем же правилом, что и одиночный вопрос в плане: план
-- пишется по разумному допущению, допущение называется вслух, ответ приходит к
-- пересмотру. Останавливать планирование до ответа значило бы менять минуты работы на
-- часы ожидания там, где допущение чаще всего верно.
--
-- Идемпотентность: условие `NOT LIKE '%questions%'` — повторный прогон и уже
-- дополненный текст не тронет.

UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '{\\"task_done\\": \\"no\\", \\"task_size\\": \\"small\\"}',
        '{\\"task_done\\": \\"no\\", \\"task_size\\": \\"small\\", \\"questions\\": []}')
 WHERE `id` = 526
   AND `metadata` LIKE '%task_size%'
   AND `metadata` NOT LIKE '%questions%';

UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '- task_size — small при правке в одном-трёх файлах без изменений схемы БД и',
        '- questions — развилки, которые ты **не смог** закрыть по коду: чего хочет\\n'
        '  заказчик, что важнее при выборе, каким объёмом ограничиться. До пяти, каждая\\n'
        '  объектом {\\"text\\": \\"вопрос одной фразой\\", \\"options\\": [\\"вариант\\", \\"вариант\\"]}.\\n'
        '  Вопрос, на который ты ответил сам, сюда не пиши — разведка на то и разведка.\\n'
        '  Развилок нет — пустой массив, это обычный исход.\\n'
        '  Кавычки внутри text и options запрещены.\\n'
        '- task_size — small при правке в одном-трёх файлах без изменений схемы БД и')
 WHERE `id` = 526
   AND `metadata` LIKE '%task_size — small при правке%'
   AND `metadata` NOT LIKE '%questions — развилки%';

-- Ключ из ответа агента становится переменной круга. Без этой строки JSON пришёл бы
-- с вопросами, а движок их не разобрал бы: `outputs_map` перечисляет, что забирать.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '\"task_size\": \"task_size\"',
        '\"task_size\": \"task_size\", \"questions\": \"task_questions_json\"')
 WHERE `id` = 527
   AND `metadata` LIKE '%\"task_size\": \"task_size\"%'
   AND `metadata` NOT LIKE '%task_questions_json%';

-- И наружу, в ответ круга: конвейер читает его и кладёт вопросы человеку.
-- `%if%` обязателен: без вопросов переменная пуста, и голая подстановка дала бы
-- `"questions": ` — сломанный JSON, на котором развалился бы весь ответ прогона.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '\"goals\": %task_goals_json%}',
        '\"goals\": %task_goals_json%%if task_questions_json%, \"questions\": %task_questions_json%%endif%}')
 WHERE `id` = 419
   AND `metadata` LIKE '%task_goals_json%'
   AND `metadata` NOT LIKE '%task_questions_json%';
