-- Вопросы разведки в ответе круга — шаг 419 (WF55). Третий заход.
--
-- Два предыдущих (`..150000`, `..151000`) эту правку не сделали и прошли молча: в
-- колонке лежит JSON внутри JSON, кавычка экранирована двумя слешами, и подобрать
-- совпадающий якорь через слеши не удалось — `REPLACE` не находил, `UPDATE` трогал
-- ноль строк, а отказа при этом нет, миграция отмечалась выполненной.
--
-- Здесь слешей нет вовсе. Якорь взят по куску без экранирования (`%task_goals_json%}`),
-- а обратный слеш в подставляемом тексте собирается `CHAR(92)`: он не зависит ни от
-- правил экранирования MySQL, ни от того, через что файл прошёл по дороге.
--
-- `LOCATE` вместо `LIKE`: в якоре есть `%`, и в `LIKE` он был бы подстановочным знаком,
-- то есть условие совпадало бы с чем угодно.
--
-- `%if%` обязателен: без вопросов переменная пуста, и голая подстановка дала бы
-- `"questions": ` — сломанный JSON, на котором развалился бы весь ответ прогона.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '%task_goals_json%}',
        CONCAT('%task_goals_json%%if task_questions_json%, ',
               CHAR(92), CHAR(92), '"questions', CHAR(92), CHAR(92), '": ',
               '%task_questions_json%%endif%}'))
 WHERE `id` = 419
   AND LOCATE('%task_goals_json%}', `metadata`) > 0
   AND LOCATE('task_questions_json', `metadata`) = 0;
