-- Анкета собеседника: ею можно пользоваться, а не только не ссылаться (2026-09-22)
--
-- ЗАЧЕМ. Миграция `20260922180000_wf_dating_talk_companion_bio` завела блок
-- анкеты с оговоркой:
--
--     ⚠ Это он написал о себе сам при регистрации, а не сказал тебе в
--     разговоре. Ссылаться на это словами «ты же говорил» нельзя — он тебе
--     этого не говорил.
--
-- Оговорка написана про **способ ссылки**, а прочиталась как запрет на само
-- знание. Замер на живых прогонах, прямой вопрос «Do you know what my job is?»:
--
--     «sounds mysterious! i guess i'll never know then. tell me, what do you
--      actually do?»
--     «hmm, let me guess... you're a chef? or maybe a detective? :)»
--     «no idea lol. you in europe?»
--
-- Анкета в промпте лежала — это проверено отдельно, по трассе. Девушка её
-- видела и **не воспользовалась**: три ответа из трёх «не знаю».
--
-- ⚠⚠ ЦЕНА ЭТОГО ВЫШЕ, ЧЕМ КАЖЕТСЯ. Занятие заводилось ровно ради начала
-- разговора — там, где фактов ещё нет. Промолчав про анкету, агент ведёт себя
-- точно так, как до правки: пишет незнакомцу, не зная о нём ничего. То есть
-- работа была сделана и не работала.
--
-- ЧТО ДЕЛАЕМ. Говорим оба правила раздельно и в нужном порядке: сперва
-- **можно**, потом узкое **нельзя**. Запрет остаётся тот же — не выдавать
-- прочитанное за сказанное в разговоре.
--
-- ⚠ Порядок не случаен. «Нельзя ссылаться» первым задаёт рамку запрета, и
-- разрешение читается как оговорка к нему. Наоборот — рамка разрешения, а
-- запрет сужает её до одного оборота речи, что и требуется.
--
-- Идемпотентность: `REPLACE` не найдёт старой строки, если её уже заменили.

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_talk');

SELECT 'ДО' AS этап,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%ты её видела%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 12) AS уже_правлено;

UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(
         `metadata`, '$.prompt_user',
         REPLACE(
           JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')),
           '⚠ Это он написал о себе сам при регистрации, а не сказал тебе в разговоре. Ссылаться на это словами «ты же говорил» нельзя — он тебе этого не говорил.',
           CONCAT(
             '⚠ Это его анкета на сайте знакомств: ты её видела, как видит любой. ',
             'Знать это тебе можно — отвечай на вопросы о нём, опираясь на анкету, ',
             'а не отговаривайся «не знаю».\n',
             '⚠ Нельзя только выдавать прочитанное за сказанное: он тебе этого ',
             'в разговоре не рассказывал, поэтому без «ты же говорил» и «ты ',
             'упоминал». Достаточно сказать прямо — ты смотрела его анкету.')))
 WHERE `workflow_id` = @wf AND `position` = 12
   AND JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
       NOT LIKE '%ты её видела%';

SELECT 'ПОСЛЕ' AS этап,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%ты её видела%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 12) AS разрешение_есть,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%ты же говорил%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 12) AS запрет_на_месте;
