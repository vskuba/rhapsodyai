-- Девушка знает свою анкету, и зовут её по имени, а не именем агента (2026-09-24)
--
-- ## ⚠⚠ ЗАЧЕМ: две дыры на одном месте
--
-- Панель шлёт в каждый вызов имя девушки (`girl_name`) и её анкету (`girl_bio`).
-- Обе переменные объявлены входящими, обе приходят — и **ни одна не читается
-- ни одним промптом**. Проверено на проде и локально: 4444 прогона с `girl_bio`
-- в переменных, ноль упоминаний в шагах `dating_talk`.
--
-- **Первая дыра — имя.** В заголовке блока фактов стоит `%agent_name%`, а это
-- имя **агента**, которое кладёт движок (`ai_workflow.py`). На проде выходит:
--
--     === Информация о fav_mail_ladadate в базе данных ===
--
-- Под заголовком лежат факты о девушке, а названы они системным именем. Ошибка
-- тихая: модель берёт содержимое блока, ответ выходит складным, и увидеть это
-- можно только в отрисованном промпте.
--
-- ⚠ Раньше агент был **свой у каждой девушки** (`dating_girl_<имя>`), и
-- подстановка была осмысленной. Смысл она потеряла при переезде на одного
-- универсального агента (`dating_girl_universal`), а промпт остался прежним.
--
-- **Вторая дыра — анкета.** У собеседника запасной путь есть и работает:
--
--     %if qdrant_fact_search_38_result_str%   факты о нём
--     %else%%if companion_bio%                иначе — его анкета с сайта
--
-- У девушки такого пути нет вовсе: нашлись факты — блок есть, не нашлись —
-- пусто. То есть на первом же разговоре, пока фактов ещё не накопилось, девушка
-- «не знает» о себе того, что написано в её же анкете.
--
-- ## Как теперь
--
-- Заголовок зовёт `%girl_name%`, а `%else%` подставляет анкету — ровно тем же
-- устройством, что у собеседника. Правка одна на четыре ветки: блок у них
-- совпадает до знака (проверено сравнением).
--
-- ⚠ Текст оговорки у девушки **свой**, а не скопированный: собеседнику пишут
-- «ты смотрела его анкету, но не выдавай прочитанное за сказанное», а здесь
-- анкета своя собственная — предупреждать не о чем, но и пересказывать её
-- дословно незачем.
--
-- ## ⚠ Идемпотентность
--
-- Выражение ищет **старый** вид блока — с `%agent_name%` в заголовке. После
-- первого прогона такого текста нет, и второй прогон не находит ничего: замена
-- вхолостую оставляет строку как есть.

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_talk');

SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%Информация о \%agent\_name\% в базе%') AS с_именем_агента,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%girl\_bio%') AS с_анкетой_девушки;

-- ── Имя девушки вместо имени агента, и анкета запасным путём ────────────────
--
-- ⚠⚠ Заменяем **блок целиком**, а не одно `%agent_name%`: правка должна и
-- переименовать заголовок, и добавить `%else%`. Две отдельные замены оставили бы
-- окно, в котором промпт уже переименован, но ещё без запасного пути, — а
-- миграции применяют и по одной.
--
-- ⚠⚠ **Выражением, а не `REPLACE` по тексту**, и это обязательно: внутри блока
-- стоит `%qdrant_fact_search_<номер>_result_str%`, где номер — **шаг этой базы**.
-- Локально он 1529, на проде 676. Дословная замена сработала бы ровно в той
-- базе, с которой её списали, а в остальных прошла бы молча вхолостую — миграция
-- «удалась», промпт прежний. Ровно эта ловушка описана в `db_sync.md`, §2.
--
-- ⚠⚠ Обратная ссылка на группу в MySQL — **`$1`, а не `\\1`**. С `\\1` замена
-- проходит без ошибки и подставляет **литеральную единицу**: номер шага из
-- промпта пропадает, а `%qdrant_fact_search_25_result_str%1` выглядит почти как
-- прежний текст. Поймано репетицией на копии — на живой базе это стоило бы
-- потерянной ссылки на поиск фактов по тегам.
--
-- ⚠ Номер сохраняем как есть: он верен для своей базы, и трогать его здесь
-- нечем — правка про имя и анкету, а не про ссылки.
UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(`metadata`, '$.prompt_user',
         REGEXP_REPLACE(JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')),
             '=== Информация о %agent_name% в базе данных ===\n%qdrant_fact_search_25_result_str%(%qdrant_fact_search_[0-9]+_result_str%)?\n%endif%',
             '=== Информация о %girl_name% в базе данных ===\n%qdrant_fact_search_25_result_str%$1\n%else%%if girl_bio%\n=== Твоя анкета на сайте знакомств ===\n⚠ Это то, что написано в твоей анкете: собеседник её видит. Отвечай о себе, опираясь на неё, а не выдумывай заново — иначе завтра скажешь другое.\n%girl_bio%\n%endif%%endif%'))
 WHERE `workflow_id` = @wf
   AND `title` IN ('Ответ в чат', 'Письмо первым', 'Ответ на письмо',
                   'Инициатива');

SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%Информация о \%girl\_name\% в базе%') AS зовут_по_имени,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%girl\_bio%') AS анкета_запасным_путём,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
               LIKE '%Информация о \%agent\_name\%%') AS осталось_с_агентом;
