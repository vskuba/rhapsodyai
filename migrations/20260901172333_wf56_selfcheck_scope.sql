-- Самопроверка разработчика получает границу: своя работа этого круга, и только она.
--
-- Разбор случая #6438. Задача про свитчер Light/Full и сохранение режима в metadata.
-- Круг самопроверки вернул dev_ok=no с тремя замечаниями, из которых по целям было
-- одно. Остальные два:
--
--   1. Тон документации нарушен, править. Абзац написан от первого лица и пересказом
--      истории, docs_rules.md параграф 3.2 требует утвердительно и в настоящем времени.
--   2. Место правила под вопросом. Вынести суть в docs-common/testing_rules.md, а в
--      проектном testing.md оставить местные specifics.
--
-- Ни свитчера, ни metadata тут нет вовсе. Разработчик открыл документацию, сверил её
-- с правилами оформления и завернул собственную работу на доработку тона.
--
-- Тонкость, из-за которой это не ловится глазами: критикуемый абзац **написал он сам**
-- в предыдущем круге (коммит 87563eb, `.claude/docs/testing.md`). То есть формально
-- правило «не трогай чужое» не нарушено — работа своя. Нарушено другое: замечание не
-- служит целям подзадачи.
--
-- Отсюда граница вводится по двум признакам сразу, а не по одному:
--   - строка изменена этой веткой (git diff master...HEAD);
--   - без замечания цели подзадачи не закрыты.
--
-- Одного первого мало — под него подходит и этот случай. Одного второго мало — под него
-- не подходит регрессия в соседнем коде, которую ловить надо.
--
-- Отдельно назван выход для замеченного мимоходом: строка в отчёт, а не круг. Без него
-- агент выбирает между «промолчать» и «крутить круг», и выбирает второе — он же
-- рецензент, ему велено искать. И отдельно сказано, что делать со своей же правкой вне
-- целей: убрать из ветки, а не улучшать кругами. Иначе получается вечный двигатель —
-- написал побочный абзац, забраковал его тон, переписал, забраковал снова.
--
-- Цена промедления видна в замерах: круг доработки это 30 минут работы агента, оболочка
-- в проекте одна, и потолок прогона общий на все круги (`timeout_developer_run`).
--
-- Правится и пункт 3 списка ракурсов: «размещение файлов» без границы прямо звало
-- пересматривать, где что лежит в проекте, — второе замечание #6438 ровно оттуда.
--
-- Кавычек в тексте нет намеренно: промпт лежит строкой внутри JSON в `metadata`, и
-- двойная кавычка рвёт разбор шага целиком (см. `tests/test_agent_workflow_steps.py`).
--
-- Идемпотентность: условия проверяют, что заменяемый текст ещё на месте.

-- 1. Граница охвата — перед списком ракурсов, до того как агент начнёт искать.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'Дальше посмотри на изменение с другого ракурса:',
        'ОХВАТ САМОПРОВЕРКИ — твоя работа этого круга, и только она.\\n'
        'Граница видна командой: git diff master...HEAD. Что лежало в master до тебя,\\n'
        'писал не ты; хорошо оно сделано или плохо, сейчас тебя не касается.\\n\\n'
        'Замечание годится, когда верно и то, и другое:\\n'
        '  - оно про строку, которую ты добавил или изменил в этой ветке;\\n'
        '  - без него не закрыты цели подзадачи.\\n\\n'
        'Это не замечания, и dev_ok=no они не дают:\\n'
        '  - тон, стиль и устройство того, что существовало до задачи;\\n'
        '  - перенос правила или файла в другое место, если цели того не требуют;\\n'
        '  - улучшения соседнего кода, замеченные попутно;\\n'
        '  - твоя же правка, которая целям не служит: такую убери из ветки,\\n'
        '    улучшать её кругами незачем.\\n\\n'
        'Заметил стоящее, но вне охвата — пиши строкой в отчёт, а не заворачивай круг.\\n'
        'Круг доработки стоит получаса работы, оболочка в проекте одна, и потолок\\n'
        'прогона общий на все круги.\\n\\n'
        'Дальше посмотри на изменение с другого ракурса:')
 WHERE `id` = 439
   AND `metadata` LIKE '%Дальше посмотри на изменение с другого ракурса:%'
   AND `metadata` NOT LIKE '%ОХВАТ САМОПРОВЕРКИ%';

-- 2. Пункт 3 без границы звал пересматривать устройство проекта целиком.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '3. Правила проекта: именование, размещение файлов, схема БД, контракт API,\\n   фронтенд — что нарушено?',
        '3. Правила проекта в том, что ты изменил: именование, размещение новых\\n'
        '   файлов, схема БД, контракт API, фронтенд — что нарушено?')
 WHERE `id` = 439
   AND `metadata` LIKE '%3. Правила проекта: именование, размещение файлов%';
