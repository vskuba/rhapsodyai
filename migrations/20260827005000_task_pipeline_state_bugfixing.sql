-- `project_task`.`pipeline_state` — догнать значение `bugfixing` на живой базе.
--
-- Зачем отдельным файлом. В начальной схеме значение уже описано, но
-- `20260101000000_initial_schema.sql` — это схема для чистой установки: на заполненной
-- базе `CREATE TABLE` не перевыполняется, и накопленную БД он не догоняет. Раньше это
-- догонял ручной скрипт `data/migration_manual/2026-08-18_task_pipeline_state_bugfixing.sql`;
-- папку упразднили, и правка переезжает сюда, чтобы не потеряться вместе с ней.
--
-- Зачем значение. Багфиксер (роль `bugfixer`, агент `task_bug_fixer`) держит в нём
-- захваченный баг, пока чинит его. Своё состояние, а не `developing`: то бывает только
-- у подзадач плана, и карты возврата брошенной блокировки у корневых строк и подзадач
-- разные (`TASK_CLAIM_STATE_RECLAIM` против `TASK_CLAIM_SUBTASK_STATE_RECLAIM`).
--
-- Почему это обязательно, а не «желательно». Колонка — ENUM, и MySQL в нестрогом режиме
-- на неизвестное значение не ругается, а молча пишет пустую строку. Захват при этом
-- отрабатывает как удачный (rowcount = 1, человеческий статус меняется), но строка
-- залипает навсегда: реклейм ищет `bugfixing`, следующий тик — NULL или `new`, и ни один
-- из них пустую строку не видит. Баг остаётся в работе, которой никто не делает, и
-- вернуть его может только человек руками.
--
-- Идемпотентность. `MODIFY COLUMN` с тем же определением безвреден: на базе, где значение
-- уже есть, файл ничего не меняет. Отдельная сверка с `information_schema` не нужна и
-- потребовала бы процедуры с `DELIMITER`, а это директива клиента mysql — yoyo применяет
-- файл драйвером, и до сервера она не доходит.
--
-- Порядок значений менять нельзя: ENUM хранится числом, и перестановка переписала бы
-- состояния уже существующих строк. Новое значение только в конец.
--
-- Имени базы здесь нет намеренно: `USE` в миграции однажды увёл прогон «в песочницу» на
-- рабочую базу. Имя задаёт подключение.
ALTER TABLE `project_task`
    MODIFY COLUMN `pipeline_state` ENUM('new','planning','plan_approval','reviewing','approved',
                                        'processing','testing','planned','developing','qa_pending',
                                        'failed_qa','blocked','done','failed','bugfixing')
        DEFAULT NULL;
