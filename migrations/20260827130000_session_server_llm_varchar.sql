-- `ai_claude_session_registry`.`server_llm` — из ENUM в VARCHAR.
--
-- Что было. Колонка перечисляла ровно два значения: `anthropic` и `gx10`. Пока у
-- оболочки был булев флаг `--gx10`, этого хватало — бэкенда и правда было два.
--
-- Почему больше не хватает. Оболочка выбирает модель флагом `--llm
-- <провайдер>/<модель>`, и в реестр уходит полное имя: по нему видно не только
-- провайдера, но и чем именно эта сессия отвечает. У маршрутизатора вроде OpenRouter
-- моделей десятки, и каждая новая требовала бы миграции ENUM — то есть простоя ради
-- строки в справочнике.
--
-- Чем это проявлялось. Роутер регистрации приводил всё, кроме двух известных значений,
-- обратно к `anthropic` (белый список в `telegram_app_claude_session`). Оболочка,
-- поднятая на `openrouter/deepseek/deepseek-v4-flash-0731`, показывалась на карточке
-- команды как `anthropic` — карточка врала о том, чем работает роль.
--
-- Длина 100: имена двухуровневые (`openrouter/anthropic/claude-sonnet-4.5` — 38
-- символов), запас взят с расчётом на длинные имена вроде дат сборки в хвосте.
--
-- Данные не пострадают: ENUM хранится числом, но при переводе в VARCHAR MySQL
-- подставляет сами подписи — `anthropic` и `gx10` останутся строками.
--
-- Идемпотентность. `MODIFY COLUMN` с тем же определением безвреден.
ALTER TABLE `ai_claude_session_registry`
    MODIFY COLUMN `server_llm` VARCHAR(100) NOT NULL DEFAULT 'anthropic';
