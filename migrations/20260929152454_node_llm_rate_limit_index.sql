-- `node_llm`: индекс по `rate_limit_at` — чтобы сброс ошибок не запирал таблицу
-- (2026-09-29)
--
-- ## ЧТО СЛУЧИЛОСЬ
--
-- Ручка `/llm/status` сбрасывает просроченные ошибки моделей:
--
--   UPDATE node_llm SET rate_limit_at = NULL, code_error = NULL
--    WHERE rate_limit_at IS NOT NULL AND rate_limit_at < NOW() - INTERVAL ? SECOND
--
-- Индекса по `rate_limit_at` не было, и `EXPLAIN` на этот `UPDATE` отвечал
-- `type: index, key: PRIMARY, rows: 41` — просматривались **все** строки. При
-- `REPEATABLE-READ` просмотренное запирается next-key-замками, то есть замок
-- брался на всю таблицу, даже когда обновлять нечего.
--
-- Страница `/admin/llm` опрашивает эту ручку **раз в секунду**. 2026-09-29
-- запросы наложились друг на друга и встали в очередь за замком
-- (`innodb_lock_wait_timeout` — 50 с). Десять таких запросов заняли весь пул
-- соединений приложения, и вместе с ними встало всё, что ходит в базу: вход в
-- панель, вызовы LLM, работа соседнего проекта. Ошибок в логах не было ни одной:
-- исчерпанный пул не роняет запрос, а ждёт.
--
-- ## ЧТО ДЕЛАЕТСЯ
--
-- Правок две, и они разного рода:
--
--   1. **В коде** (`src/uvicorn/routers/llm/llm.py`) — сначала `SELECT COUNT(*)`,
--      и `UPDATE` только если есть что сбрасывать. `SELECT` замков не берёт, а
--      сбрасывать почти всегда нечего: модель в ошибке — исключение.
--   2. **Здесь** — индекс, чтобы и настоящий `UPDATE` трогал свои строки, а не
--      всю таблицу.
--
-- Одной первой правки мало: она убирает холостой замок, но не замок по делу.
-- Одного индекса тоже мало: `UPDATE`, не нашедший строк, всё равно открывает
-- транзакцию и идёт в базу на каждый тик опроса.
--
-- ⚠ Таблица крошечная (41 строка), и выигрыш здесь не в скорости чтения — она и
-- так мгновенная. Выигрыш в **объёме замка**: по индексу запираются только
-- строки с непустым `rate_limit_at`, а не все подряд.
--
-- Идемпотентность — через `information_schema` и `PREPARE`, как в `20260902125514`.

SET @exists := (
    SELECT COUNT(*) FROM information_schema.STATISTICS
     WHERE TABLE_SCHEMA = DATABASE()
       AND TABLE_NAME = 'node_llm'
       AND INDEX_NAME = 'idx_node_llm_rate_limit'
);

SET @sql := IF(@exists = 0,
    'ALTER TABLE `node_llm` ADD INDEX `idx_node_llm_rate_limit` (`rate_limit_at`)',
    'SELECT 1');

PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
