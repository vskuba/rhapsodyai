-- Два главных условия письма — в начало промпта (2026-09-07)
--
-- ЧТО БЫЛО. После добавления правила про язык (`20260907090000`) агент стал
-- терять переменные: три прогона подряд дали `['companion_name',
-- 'question_to_companion']`, `['girl_name']` и `[]` — в последнем имена написаны
-- словами («Hi John!»).
--
-- ЦЕНА. Письмо с зашитым именем годится ровно одному адресату; рассылка отправит
-- его сотне, из которых John — один.
--
-- ОТЧЕГО ТАК ВЫШЛО. Правил в промпте стало восемь, и запрет писать имена словами
-- оказался пятым по счёту. Модель держит первые пункты лучше последних — это её
-- обычное свойство, и бороться с ним надо порядком, а не силой формулировок:
-- прошлая правка уже переписала это правило в запрет с объяснением причины, и
-- одного этого не хватило.
--
-- ЧТО ВМЕСТО. Два условия, которые делают письмо пригодным для рассылки вообще,
-- стоят перед списком правил отдельным блоком: язык и переменные. Остальное —
-- про то, каким письмо выйдет; эти два — про то, годится ли оно совсем.
--
-- ⚠ ЭТО НЕ ГАРАНТИЯ. LLM не обещает соблюдать инструкции, и порядок лишь
-- повышает вероятность. Поэтому на стороне DatingAi добавлена проверка: письмо
-- без единой переменной помечается человеку прямо в панели — там, где он его
-- читает, до сохранения.
--
-- Идемпотентность: условие на то, что блока ещё нет.

-- ---------------------------------------------------------------- До
SET @nl = CONCAT(CHAR(92), 'n');
SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_mail_write');

SELECT 'ДО' AS этап,
       @wf AS workflow_id,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND `metadata` LIKE '%ДВА УСЛОВИЯ%') AS блок_есть;

-- ------------------------------------------- Блок перед правилами
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        CONCAT('Правила:', @nl,
               '0. ЯЗЫК ПИСЬМА — %user_language% (код языка). Пиши только на нём, ',
               'даже если профили участников и эти правила написаны на другом. ',
               'Письмо читает человек на сайте знакомств, и язык там один.', @nl),
        CONCAT('ДВА УСЛОВИЯ, без которых письмо не годится вовсе:', @nl,
               '— ЯЗЫК: пиши на %user_language% (код языка), даже если профили ',
               'участников и эти правила написаны на другом. Письмо читает человек ',
               'на сайте знакомств, и язык там один.', @nl,
               '— ИМЕНА: не пиши их словами. Имя девушки, имя получателя, её город ',
               '— только переменной [[имя]] из списка ниже. Письмо уходит многим ',
               'людям, и зашитое в текст имя уедет не тому.', @nl, @nl,
               'Остальные правила:', @nl))
 WHERE `workflow_id` = @wf
   AND `metadata` NOT LIKE '%ДВА УСЛОВИЯ%';

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `metadata` LIKE '%ДВА УСЛОВИЯ%') AS блок_новый,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `metadata` LIKE '%user_language%') AS язык_на_месте,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND LOCATE(CONCAT(CHAR(92), CHAR(92), 'n'), `metadata`) > 0) AS задвоенных;
