-- Вопросы разведки в ответе круга — шаг 419 (WF55).
--
-- Хвост к `20260830150000`. Там правка шага 419 не сработала и прошла молча: в колонке
-- строка хранится как JSON внутри JSON, и кавычка в ней экранирована **двумя** слешами
-- (`\\"goals\\"`), а якорь искал один. `REPLACE` не нашёл совпадения, `UPDATE` затронул
-- ноль строк, отказа при этом нет — миграция отметилась выполненной.
--
-- Отдельной миграцией, а не правкой той: она уже применена и записана в
-- `_yoyo_migration`, и правка файла ничего бы не переиграла, зато разошлась бы с тем,
-- что на самом деле выполнено.
--
-- `%if%` обязателен: без вопросов переменная пуста, и голая подстановка дала бы
-- `"questions": ` — сломанный JSON, на котором развалился бы весь ответ прогона.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '\\\\"goals\\\\": %task_goals_json%}',
        '\\\\"goals\\\\": %task_goals_json%%if task_questions_json%, \\\\"questions\\\\": %task_questions_json%%endif%}')
 WHERE `id` = 419
   AND `metadata` LIKE '%\\\\"goals\\\\": %task_goals_json%}%'
   AND `metadata` NOT LIKE '%task_questions_json%';
