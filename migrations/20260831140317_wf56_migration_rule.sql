-- Разработчик знает правило про базу из промпта, а не из чужой памяти (шаг 435, WF56).
--
-- Разбор по вопросу «с какой базой работает разработчик». Ответ: с рабочей. `.env` в
-- каталоге подзадачи — симлинк на общий (`MYSQL_DATABASE=project`), и сервер ветки
-- на :8013 поднимается тем же `env_file`. Своей базы у ветки нет: `UPDATE` из
-- worktree немедленно видят соседние подзадачи и живой конвейер, а откатить его, в
-- отличие от кода, нельзя.
--
-- Правило про это давно записано — `role_toolbox.md`, раздел «Изменения в базе», и
-- `role_developer.md`, «Не применяй SQL к базе». Но в промпт реализации оно не
-- попадало: там есть шаги до коммита и merge request, а про базу ни слова, и ссылки
-- на toolbox тоже нет (она стоит только в промпте разбора, шаг 433).
--
-- Держаться на том, что агент прочитал документ на прошлом шаге, здесь нельзя. Шаг
-- реализации — самый длинный в круге, к его концу разбор вытеснен из внимания
-- работой; а цена ошибки невосстановима: сломанные данные стенда правит человек
-- руками, и заметить это можно много позже.
--
-- API применение уже запрещает (`/api/task/{id}/migration/apply` принимает только
-- `dry: true`), но агент работает оболочкой с полным доступом и ходит в базу
-- напрямую — запрет на ручке его не касается. Отсюда правило словами.
--
-- Ставим перед абзацем про «коммитить нечего»: это конец списка действий, там же,
-- где сказано про коммит и merge request, — то есть в том месте, где разработчик
-- решает, что делать с результатом.
--
-- Идемпотентность: условие `NOT LIKE '%миграц%'` — повторный прогон и уже
-- дополненный текст не тронет.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'Коммитить нечего — тоже законный итог.',
        'Правку данных или схемы кладёшь файлом, но **не применяешь**. База одна на весь\\n'
        'стенд: твой SQL немедленно видят соседние подзадачи и живой конвейер, а\\n'
        'откатить его, в отличие от ветки, нельзя. Файл —\\n'
        '`migrations/<метка времени>_<что делаешь>.sql`; применит его yoyo при старте\\n'
        'приложения, уже после слияния ветки. Это касается и шагов workflow, и настроек,\\n'
        'и справочников — всего, что живёт в таблицах.\\n\\n'
        'Проверить миграцию можно, не применяя: сухой прогон выполняет её в транзакции\\n'
        'и откатывает — POST /api/task/%subtask_id%/migration/apply с телом\\n'
        '{"name": "<имя файла>", "dry": true}. Идемпотентность проверяй условиями в самом\\n'
        'SQL (`IF NOT EXISTS`, `NOT LIKE` по уже вставленному тексту): миграция обязана\\n'
        'пережить повторный прогон.\\n\\n'
        'Коммитить нечего — тоже законный итог.')
 WHERE `id` = 435
   AND `metadata` LIKE '%Коммитить нечего — тоже законный итог%'
   AND `metadata` NOT LIKE '%миграц%';
