-- Когда модель последний раз выдавали задаче — колонка `team_llm_lock.used_at`.
--
-- Зачем. Прилипание задачи к модели («на следующем круге вернуть ту же, чтобы не
-- перезапускать агента и не терять его контекст») искало модель так:
--
--     SELECT llm_name FROM team_llm_lock WHERE task_id = %s LIMIT 1
--
-- Без сортировки. А строк на задачу бывает несколько: строка заводится на модель и
-- живёт дальше, `task_id` в ней остаётся после освобождения — это и есть память о
-- прошлом круге. Отработала задача на двух моделях подряд, и обе строки помнят её
-- номер; какую вернёт `LIMIT 1`, решает MySQL, а не мы.
--
-- Поймано на живых данных: задача #4915 числилась разом за `gx10/qwen-large` (шёл
-- круг) и за `qwen/qwen3.7-flash` (след прошлого). Прилипание срабатывало через раз,
-- и цена ошибки — перезапуск агента с потерей накопленного контекста.
--
-- Почему не хватило `locked_at`. Он гасится при освобождении: у свободной строки там
-- NULL, и отличить «работала час назад» от «работала вчера» по нему нельзя — а
-- прилипание спрашивает именно про последнюю.
--
-- `used_at` не гасится никогда: он про факт выдачи, а не про удержание. Освобождение
-- (`team_llm_pool_release`) его не трогает.
--
-- Идемпотентность: колонка добавляется только когда её нет — повторный прогон
-- миграции и уже обновлённая база не пострадают.
SET @column_exists = (
    SELECT COUNT(*) FROM information_schema.COLUMNS
     WHERE TABLE_SCHEMA = DATABASE()
       AND TABLE_NAME = 'team_llm_lock'
       AND COLUMN_NAME = 'used_at');

SET @sql = IF(@column_exists = 0,
    'ALTER TABLE `team_llm_lock` ADD COLUMN `used_at` DATETIME NULL '
    'COMMENT ''Когда модель последний раз выдавали задаче; не гасится освобождением''',
    'SELECT 1');

PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- Существующим строкам проставляем то, что о них известно: занятая помнит своё
-- `locked_at`. У свободных времени не осталось вовсе — там NULL, и прилипание просто
-- не сработает до следующего круга. Выдумывать им время нельзя: подставь мы «сейчас»,
-- давняя строка выглядела бы самой свежей и перебила бы настоящую.
UPDATE `team_llm_lock` SET `used_at` = `locked_at`
 WHERE `used_at` IS NULL AND `locked_at` IS NOT NULL;
