-- Переменные сайта — таблица `browser_site_variable`.
--
-- Зачем. Сценарии ссылаются на `{{переменные}}`, а значения до сих пор жили только в
-- самом сценарии (`browser_scenario.variables`) либо приходили на прогон снаружи.
-- Логин от стенда, адрес личного кабинета, номер тарифа — всё это про сайт, а не про
-- один его сценарий: у сайта сценариев несколько, и одно и то же значение
-- переписывалось в каждом. Здесь оно заводится один раз на сайт.
--
-- **Секретные значения лежат зашифрованными, а не хэшем.** Хэш односторонний: из него
-- исходное значение не достать в принципе, а пароль нужен целиком — его подставляют в
-- поле формы и показывают человеку в кабинете. Поэтому обратимое шифрование, ключ в
-- окружении (`BROWSER_SECRET_KEY`), в базе — шифротекст с меткой `enc:v1:`. Дамп
-- базы, файл бэкапа, открытый phpMyAdmin и SQL-инъекция отдают набор байт, из
-- которого без ключа ничего не следует. Подробности и границы защиты —
-- `src/browser/browser_secret.py`.
--
-- Открытые и закрытые значения делят одну колонку: у переменной одна и та же роль
-- независимо от того, секретная она или нет, и раздельные колонки означали бы
-- «значение лежит то там, то тут» в каждом запросе. Различает их `is_secret`, а
-- зашифровано ли содержимое, видно по метке в самом значении.
--
-- `value` — TEXT, а не VARCHAR: шифротекст Fernet длиннее исходного примерно вдвое
-- плюс сотня байт заголовка, и короткий пароль после шифрования уже не влезал бы в
-- разумный VARCHAR вместе с длинными открытыми значениями вроде адреса с параметрами.
--
-- Удаление сайта уносит его переменные каскадом: без сайта они бессмысленны — это не
-- сценарий, который может быть общим (`fk_bs_site` там намеренно `SET NULL`).
--
-- Идемпотентность: `CREATE TABLE IF NOT EXISTS`.
CREATE TABLE IF NOT EXISTS `browser_site_variable` (
    `id` INT NOT NULL AUTO_INCREMENT,
    `site_id` INT NOT NULL COMMENT 'Чей сайт; без него переменная бессмысленна',
    -- Имя, каким переменная встречается в шагах: `{{login}}` — это `login`. Фигурные
    -- скобки в базе не храним, их ставит подстановка: иначе одно и то же имя лежало
    -- бы в двух видах и сравнивалось бы по-разному.
    `name` VARCHAR(100) NOT NULL COMMENT 'Имя без скобок: login, а не {{login}}',
    `value` TEXT NOT NULL COMMENT 'Значение; секретное — шифротекст с меткой enc:v1:',
    -- Секретность — свойство переменной, а не её текущего значения: по ней страница
    -- прячет значение под звёздочки, а журнал прогона замазывает его в тексте ошибок
    -- (`browser_scenario_mask`). Снятие пометки не расшифровывает запись само —
    -- значение переписывается при сохранении, целиком.
    `is_secret` TINYINT(1) NOT NULL DEFAULT 0 COMMENT 'Прятать в интерфейсе и в журнале',
    -- Зачем эта переменная нужна — словами. Имён вроде `p2` через месяц не помнит
    -- никто, а список переменных читают, чтобы понять, что сайту требуется для входа.
    `description` VARCHAR(255) NOT NULL DEFAULT '',
    `position` INT NOT NULL DEFAULT 0 COMMENT 'Порядок в списке; задаёт человек',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    -- Имя уникально внутри сайта, а не глобально: `login` есть у каждого сайта, и это
    -- разные логины. Уникальность нужна, потому что подстановка ищет по имени и при
    -- двойнике брала бы произвольный из двух.
    UNIQUE KEY `uk_bsv_site_name` (`site_id`, `name`),
    INDEX `idx_bsv_site_position` (`site_id`, `position`),
    CONSTRAINT `fk_bsv_site` FOREIGN KEY (`site_id`) REFERENCES `browser_site` (`id`)
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
