-- Вердикт QA получает ту же границу охвата, что и самопроверка разработчика.
--
-- Продолжение разбора #6438. Починив самопроверку (`20260901172333`), обошёл остальные
-- шаги ролей: где ещё сказано искать недостатки и не сказано, где искать перестать.
--
-- Разбор по шагам.
--
--   435 реализация     — граница есть: делаешь только свою подзадачу, соседние не
--                        трогаешь; ничего из описанного не задето — не трогаешь ничего.
--   445 разбор QA      — граница есть: git diff относительно origin/master, сопоставь
--                        изменения с описанием подзадачи.
--   447 прогон QA      — граница есть, и лучшая в проекте: сверь документацию с тем,
--                        что изменила подзадача; работа ничего из описанного не меняла —
--                        пункт не применим, и придираться не к чему.
--   516 проверка цели  — ограничен одной целью явно.
--   559 багфиксер      — вердикта не выносит, круга доработки не заворачивает.
--   451 вердикт QA     — ГРАНИЦЫ НЕТ.
--
-- Дыра именно здесь и хуже, чем выглядит. Вердикт спрашивает:
--
--   3. Ничего рядом не сломано и правила проекта не нарушены?
--   4. Документация не противоречит сделанному?
--
-- Ни в третьем, ни в четвёртом нет слов «в том, что изменила подзадача». А вердикт —
-- последнее слово круга: он перекрывает шаг 447, который тремя минутами раньше честно
-- объявил пункт неприменимым. Ответ «нет» на любой из четырёх даёт `qa_ok=no`.
--
-- И цена выше, чем у самопроверки. Самокритика крутит круги внутри прогона
-- разработчика; `qa_ok=no` заворачивает работу назад и **сжигает попытку из трёх**
-- (`timeout_attempt_max`). Исчерпаются — подзадача уходит в `blocked` и ждёт человека.
-- То есть плохо написанный чужой код в master мог заблокировать чужую подзадачу.
--
-- Границу вводим по той же паре признаков, что у разработчика: строка изменена этой
-- подзадачей И без замечания не закрыты её цели. Плюс третий запрет, своего у QA:
-- долги соседних подзадач плана. Их принимают в своих кругах, и заворачивать за них
-- эту работу значит наказывать за чужой охват.
--
-- Выход для замеченного вне охвата назван отдельно — строка в отчёт. Без выхода
-- проверяющий выбирает между «промолчать» и «завернуть», а молчать ему не велено.
--
-- Кавычек в тексте нет намеренно: промпт лежит строкой внутри JSON в `metadata`, и
-- двойная кавычка рвёт разбор шага целиком.
--
-- Идемпотентность: условия проверяют, что заменяемый текст ещё на месте.

-- 1. Граница охвата — перед списком вопросов, до того как проверяющий начнёт решать.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        'Решай по четырём вопросам:',
        'ОХВАТ ВЕРДИКТА — работа этой подзадачи, и только она.\\n'
        'Граница видна командой: git diff origin/master...HEAD в каталоге подзадачи.\\n'
        'Что лежало в master до неё, писал не этот разработчик; заворачивать за это\\n'
        'круг нельзя, как бы плохо оно ни было сделано.\\n\\n'
        'Замечание годится, когда верно и то, и другое:\\n'
        '  - оно про строку, которую изменила эта подзадача;\\n'
        '  - без него не закрыты цели подзадачи.\\n\\n'
        'Это не повод для qa_ok=no:\\n'
        '  - тон, стиль и устройство того, что существовало до подзадачи;\\n'
        '  - долги соседних подзадач плана: их примут в своих кругах;\\n'
        '  - улучшения, от которых стало бы лучше, но цели закрыты и без них.\\n\\n'
        'Заметил стоящее, но вне охвата — назови отдельной строкой в отчёте и круг не\\n'
        'заворачивай. Круг проверки стоит подзадаче попытки из трёх: исчерпаются —\\n'
        'она встанет и будет ждать человека.\\n\\n'
        'Решай по четырём вопросам:')
 WHERE `id` = 451
   AND `metadata` LIKE '%Решай по четырём вопросам:%'
   AND `metadata` NOT LIKE '%ОХВАТ ВЕРДИКТА%';

-- 2. Третий вопрос без границы звал судить правила проекта во всём, что видно.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '3. Ничего рядом не сломано и правила проекта не нарушены?',
        '3. Ничего рядом не сломано, а правила проекта не нарушены в том, что\\n'
        '   изменила эта подзадача?')
 WHERE `id` = 451
   AND `metadata` LIKE '%3. Ничего рядом не сломано и правила проекта не нарушены?%';

-- 3. Четвёртый вопрос — то же ограничение, что уже стоит в шаге 447: неизменённого
--    документация касаться не обязана.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        '4. Документация не противоречит сделанному: описанное в `CLAUDE.md` и `.claude/docs/`\\n   совпадает с новым устройством, а не с прежним?',
        '4. Документация не противоречит сделанному: описанное в `CLAUDE.md` и `.claude/docs/`\\n'
        '   совпадает с новым устройством, а не с прежним? Работа ничего из описанного\\n'
        '   не меняла — пункт не применим, и придираться не к чему.')
-- Условие «добавки ещё нет», а не «якорь на месте»: якорь целиком входит в новый
-- текст, и проверка по нему пропустила бы повторный прогон — добавка легла бы дважды.
 WHERE `id` = 451
   AND `metadata` LIKE '%совпадает с новым устройством, а не с прежним?%'
   AND `metadata` NOT LIKE '%пункт не применим, и придираться не к чему.%';
