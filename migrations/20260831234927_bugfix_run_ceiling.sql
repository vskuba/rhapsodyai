-- Потолок прогона багфиксера: 3600 -> 7400, вслед за поднятыми шагами.
--
-- Хвост правки `20260831234042`. Подняв шаговые лимиты ролей, я развёл потолок
-- багфиксера с его же шагами: четыре обращения к оболочке (разбор 2400, починка 2400,
-- самопроверка 2400, вердикт JSON 1800) дают до 9000с при потолке 3600.
--
-- Расхождение было и раньше — 4 x 1200 = 4800 против тех же 3600, — но правка его
-- расширила, а такая пара ведёт себя ровно как та, что чинилась вчера у разработчика:
-- роли разрешают работу, которую потолок не даёт довести до конца, прогон рвётся на
-- середине и ставится заново.
--
-- Замеров по багфиксеру нет вовсе (`project_task_metric` по роли пуст — живых багов
-- через него ещё не проходило), поэтому берём не «из данных», а по родству: скелет
-- workflow #59 повторяет разработчика без круга самопроверки, а один заход без кругов
-- доработки — это ровно случай QA. Отсюда и значение: `timeout_qa_run` = 7400.
--
-- Лестницу это не трогает: максимум потолков по-прежнему даёт разработчик (14400),
-- а `timeout_worker_job` = 15000 и `timeout_task_lock` = 15600 стоят выше него
-- (`task_setting_timeout_ladder_problem`).
--
-- Строки в таблице нет — значение всё это время бралось умолчанием из кода
-- (`task_setting_timeout.py`, `default: 3600`). Поэтому не UPDATE, а вставка; она
-- через NOT EXISTS, а не ON DUPLICATE KEY, потому что уникальный индекс
-- (`key`, `user_id`, `node_id`) с NULL в двух колонках дубликаты пропускает.

INSERT INTO `setting` (`key`, `user_id`, `node_id`, `value`, `dynamic`)
SELECT 'timeout_bugfix_run', NULL, NULL, '7400', 0
 WHERE NOT EXISTS (
       SELECT 1 FROM `setting`
        WHERE `key` = 'timeout_bugfix_run' AND `user_id` IS NULL AND `node_id` IS NULL);

UPDATE `setting` SET `value` = '7400'
 WHERE `key` = 'timeout_bugfix_run' AND `user_id` IS NULL AND `node_id` IS NULL
   AND CAST(`value` AS UNSIGNED) < 7400;
