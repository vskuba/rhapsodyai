-- «анкета мужчины: карточка»: фото не снимаем (2026-09-08)
--
-- ⚠ ФОТО УЖЕ ЕСТЬ. Аватарка приходит из ленты «Все онлайн» и ложится в карточку
-- при первом же щелчке по человеку. Снимать её второй раз со страницы анкеты
-- значит грузить то же самое дважды — и разбираться с ленивой загрузкой, из-за
-- которой в `src` попадает `/images/placeholder-loading.svg`.
--
-- Шаги `фото_главное` и `фото_галерея` убраны. Имя снимать остаёмся: карточку
-- заводят и под сбор описания, а тогда ленты за спиной нет.
SET @id = (SELECT `id` FROM `browser_scenario` WHERE `name` = 'анкета мужчины: карточка');

UPDATE `browser_scenario`
   SET `steps` = JSON_REMOVE(`steps`, '$[17]', '$[16]')
 WHERE `id` = @id;

SELECT JSON_LENGTH(`steps`) AS шагов,
       JSON_UNQUOTE(JSON_EXTRACT(`steps`, '$[*].name')) AS имена
  FROM `browser_scenario` WHERE `id` = @id;
