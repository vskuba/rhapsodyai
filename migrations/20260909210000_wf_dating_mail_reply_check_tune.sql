-- `dating_mail_reply`: проверка судит по делу, а не придирается (2026-09-09)
--
-- ЧТО ПОКАЗАЛ ПЕРВЫЙ ЖЕ ЖИВОЙ ПРОГОН. Шаг «Проверка» заработал: вердикт, переход,
-- счётчик, замечание — всё сработало. Но судил он неверно.
--
-- Ответ на «Moto is my life» начинался словами «Wow, "Moto is my life" says a lot…»
-- и продолжался вопросом про любимые маршруты — то есть был ровно по существу. Три
-- захода подряд получили `reply_topic_ok: 0`, три раза переписывались, и заход занял
-- 32 секунды вместо четырёх.
--
-- ⚠ ЦЕНА ЛОЖНОЙ ТРЕВОГИ ЗДЕСЬ ВЫШЕ, ЧЕМ ЦЕНА ПРОПУСКА. Пропущенный слабый ответ
-- лежит в пуле и ждёт человека — тот прочтёт и уберёт. Ложная тревога стоит трёх
-- лишних вызовов LLM на каждое письмо, и при пятидесяти письмах это два часа
-- впустую. Судья, который бракует хорошее, дороже того, кто изредка пропускает
-- посредственное.
--
-- ЧТО МЕНЯЕМ, и почему именно это:
--
--   1. **Планка названа явно.** «По существу» модель толкует как «идеально по
--      существу» и находит изъян в любом тексте. Ставим низкий порог: годится, если
--      подхватывает тему письма. Не «раскрывает», не «отвечает исчерпывающе».
--
--   2. **Пример того, что считать негодным.** Абстрактное правило каждый понимает
--      по-своему; «ответ про погоду на письмо про мотоциклы» не толкуется никак.
--
--   3. **Сомнение — в пользу ответа.** Прямое указание: не уверен — ставь 1. Без
--      него модель по умолчанию придирается, потому что найти изъян всегда легче,
--      чем убедиться в его отсутствии.
--
--   4. **Просьба не размышлять.** В журнале видно `exceeded, let's stop and write
--      the final answer now.</think>` — модель выжигала бюджет размышлений на
--      простом вопросе и отвечала уже второпях. Четыре вопроса «да/нет» этого не
--      требуют.
--
-- ⚠ Прочие три проверки не трогаем: язык, скобки и безопасность — вопросы
-- фактические, и на них модель отвечала верно (`1`, `1`, `1` во всех прогонах).

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_mail_reply');
SET @check = (SELECT `id` FROM `agent_workflow_step`
               WHERE `workflow_id` = @wf AND `title` = 'Проверка');

SELECT 'ДО' AS этап, @check AS шаг,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
          FROM `agent_workflow_step` WHERE `id` = @check) LIKE '%в пользу ответа%'
       AS уже_смягчён;

UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(`metadata`, '$.prompt_user', CONCAT(
       'Проверь ЧУЖОЙ ответ перед отправкой. Отвечает девушка мужчине на сайте знакомств.',
       CHAR(10 USING utf8mb4), CHAR(10 USING utf8mb4),
       '=== Переписка ===', CHAR(10 USING utf8mb4),
       '%mail_history%', CHAR(10 USING utf8mb4), CHAR(10 USING utf8mb4),
       '=== Ответ на проверку ===', CHAR(10 USING utf8mb4),
       '%reply%', CHAR(10 USING utf8mb4), CHAR(10 USING utf8mb4),
       'Ты ищешь ГРУБЫЕ нарушения, а не изъяны. Ответ уже написан и всё равно попадёт '
       'к человеку на проверку — твоё дело поймать то, что отправлять нельзя.',
       CHAR(10 USING utf8mb4), CHAR(10 USING utf8mb4),
       'Ответь 1 (годится) или 0 (нет):', CHAR(10 USING utf8mb4),
       'reply_lang_ok — ответ целиком на языке %user_language%? Имена и города не в счёт.',
       CHAR(10 USING utf8mb4),
       'reply_clean_ok — в ответе НЕТ переменных в квадратных скобках вида [[имя]]?',
       CHAR(10 USING utf8mb4),
       'reply_topic_ok — ответ хоть как-то подхватывает тему последнего письма? '
       'Достаточно упоминания того, о чём человек написал. Ноль ставь, только если '
       'ответ вообще про другое: он написал про мотоциклы, а ответ про погоду и книги. '
       'Короткий, простой или неглубокий ответ — это 1.',
       CHAR(10 USING utf8mb4),
       'reply_safe_ok — в ответе НЕТ обещаний встречи, просьб о деньгах, ссылок и '
       'контактов вне сайта (почта, мессенджеры, телефон)?',
       CHAR(10 USING utf8mb4), CHAR(10 USING utf8mb4),
       '⚠ Сомневаешься — ставь 1. Ложная тревога дороже пропуска: она заставляет '
       'переписывать хороший ответ, а слабый всё равно прочтёт человек.',
       CHAR(10 USING utf8mb4),
       '⚠ Не рассуждай. Это четыре вопроса «да/нет» — ответь сразу.',
       CHAR(10 USING utf8mb4), CHAR(10 USING utf8mb4),
       'Верни JSON: {"reply_lang_ok": 1, "reply_clean_ok": 1, "reply_topic_ok": 1, "reply_safe_ok": 1}'))
 WHERE `id` = @check;

SELECT 'ПОСЛЕ' AS этап,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
          FROM `agent_workflow_step` WHERE `id` = @check) LIKE '%в пользу%'
       AS смягчён,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user'))
          FROM `agent_workflow_step` WHERE `id` = @check) LIKE '%про погоду и книги%'
       AS есть_пример,
       (SELECT JSON_LENGTH(JSON_EXTRACT(`metadata`, '$.transitions_after'))
          FROM `agent_workflow_step` WHERE `id` = @check) AS переходов;
