-- Признак «этой модели размышления не давать» — колонка `llm.reasoning_disable`.
--
-- Зачем. Размышления (reasoning / thinking) модель тратит на внутренний
-- монолог до ответа. Где они уместны — там их и оставляют, а где нет — они
-- обходятся дважды: временем и токенами. У локальной модели это видно прямо:
-- с включёнными размышлениями она молча съедает бюджет ответа и возвращает
-- пустой `content` (см. `~/.claude/bin/gx10`, `enable_thinking: false`).
--
-- Почему запрет, а не разрешение. Поле называется `reasoning_disable`, а не
-- `reasoning_enable`, чтобы умолчание было нулём. Ноль — это «ведём себя как
-- раньше»: ни одна из уже заведённых моделей поведения не меняет, и колонку
-- можно добавить на живой базе, ничего не перенастраивая. Флаг-разрешение
-- потребовал бы обратного — проставить единицу всем существующим строкам,
-- и любая пропущенная означала бы молча замолчавшую модель.
--
-- Свойство модели, а не ноды. Размышления умеет или не умеет сама модель, и
-- запрет едет с ней в любую ноду, куда её подключили (`node_llm`). Положи мы
-- флаг на связку — одну и ту же модель пришлось бы настраивать в каждой ноде
-- заново, а разошедшиеся настройки давали бы разное поведение при одинаковом
-- имени в журнале запросов.
ALTER TABLE `llm`
    ADD COLUMN `reasoning_disable` TINYINT(1) NOT NULL DEFAULT 0
    COMMENT 'Не передавать модели размышления: 0 — как умеет сама модель, 1 — запрещено'
    AFTER `output_type`;
