-- `dating_invite_write`: правка не должна уходить в язык замечания (2026-09-14)
--
-- ЧТО ПОКАЗАЛА ПРОВЕРКА ЦЕПОЧКИ. Судью заставили забраковать черновик — он
-- забраковал и написал замечание **по-русски** (так и задумано: замечание читает
-- человек в журнале панели). Шаг правки прочитал его и ответил тоже по-русски,
-- хотя требуемый язык в том же промпте стоит `en`:
--
--     VERDICT: fixed
--     WHY: использована некорректная метка [[his_city]]…
--     TEXT: Угадаешь, какая мысль промелькнула в моей голове…
--
-- ⚠⚠ ЭТО НЕ КОСМЕТИКА, А НЕДОСТАВКА, И МЫ НА НЕЙ УЖЕ ОБЖИГАЛИСЬ. Фильтр LadaDate
-- отклоняет кириллицу — «Message not delivered. Unacceptable words: …», — и такая
-- реплика до собеседника не дойдёт вовсе. В прежней версии это стоило целого пула
-- из двадцати недоставляемых сообщений (миграция `20260911000000`); теперь ставка
-- выше: шаблон один, и русский текст сделал бы недоставляемым **весь** пул.
--
-- ⚠ ПОЧЕМУ ЛОВУШКА ИМЕННО ЗДЕСЬ. У первого шага перед глазами только требуемый
-- язык, и он его слушается. У шага правки рядом лежит русский текст замечания —
-- и модель принимает его за язык разговора. Правило «пиши на требуемом языке» в
-- промпте было, но общим тоном; теперь замечание названо служебным прямо.
--
-- Панель со своей стороны такой шаблон тоже отбрасывает (проверка письменности в
-- `dating_mail_agent._invite`), но отбросить — значит остаться без пула на заход.

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_invite_write');

SELECT 'ДО' AS этап,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%служебный%'
          FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 2) AS правка_есть;

-- ------------------------------------------- Шаг правки: язык назван жёстко
UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(
         `metadata`, '$.prompt_user',
         REPLACE(JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')),
                 '=== Что требуется ===\n',
                 CONCAT('=== Что требуется ===\n',
                        '⚠ Замечание редактора выше — служебный текст, он написан ',
                        'по-русски для человека. Язык замечания к реплике отношения ',
                        'не имеет: пиши РОВНО на языке с кодом ниже. Сайт фильтрует ',
                        'сообщения и не на том языке отклоняет — реплика не дойдёт ',
                        'до человека вовсе.\n')))
 WHERE `workflow_id` = @wf AND `position` = 2;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%служебный%'
          FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 2) AS правка_есть;
