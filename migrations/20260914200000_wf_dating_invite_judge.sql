-- `dating_invite_write`: судья в цепочке — шаблон проверяется до выдачи (2026-09-14)
--
-- ЗАЧЕМ СУДЬЯ. Шаблон теперь **один на весь пул**: он уйдёт полусотне живых людей
-- без единого человеческого взгляда между «модель написала» и «сайт отправил».
-- Прежде такой риск гасился сам собой — реплика сочинялась каждому, и негодная
-- портила одну карточку из двадцати; теперь негодная портит **всё**.
--
-- И это не теория. Первый же живой прогон нового промпта дал два брака из трёх:
--
--   1. ОТКАЗ ВМЕСТО ТЕКСТА:
--      «I can't help with crafting flirt or pickup messages, but here's a neutral
--       opener: Hi there, hope your day's going well…»
--      Отказ выглядит текстом и уехал бы в чат вместе с извинением — всем разом.
--
--   2. МЕТКА ИМЕНИ ПОНЯТА КАК ТРЕТЬЕ ЛИЦО:
--      «[[girl_name]] thinks you look like trouble, so I'm here to investigate…»
--      После подстановки: «Diana думает, что ты опасен, и я пришла проверить» —
--      от самой Diana.
--
-- Панель отбрасывает такое по приметам (`DATING_INVITE_REFUSAL_MARKS`, проверка
-- меток и абзаца в `dating_mail_agent._invite`), но её проверки — про форму:
-- «есть ли чужая метка», «не начинается ли с извинения». Вопрос «это вообще
-- годная первая реплика?» решается смыслом, и решать его должна модель.
--
-- ЦЕПОЧКА ШАГОВ. Четыре, и ветвление ровно одно:
--
--   0. Черновик      (llm_to_json → invite_draft)
--   1. Судья         (llm_to_json → invite_ok, invite_why); «yes» → сразу к шагу 3
--   2. Правка        (llm_to_json → invite_draft, invite_ok='fixed') — только если «no»
--   3. Ответ         (return_response_text: VERDICT / WHY / TEXT)
--
-- ⚠ ПОЧЕМУ ПРАВКА, А НЕ ПРОСТО ОТКАЗ. Отказ означал бы пустой пул до следующего
-- захода — а он раз в полчаса. Правка получает **конкретное замечание судьи**, и
-- это несравнимо лучше слепого повтора. Цена: на плохом пути три вызова LLM
-- вместо одного. Прежняя версия тратила пятьдесят на тот же пул.
--
-- ⚠ ПОЧЕМУ НЕТ ВТОРОГО СУДЬИ ПОСЛЕ ПРАВКИ. Возврат на шаг судьи — это петля, а
-- движок от петель не защищён (`workflow.md`, §8): плохая правка крутила бы её,
-- пока не кончится таймаут запроса, сжигая токены. Правка сама помечает результат
-- как `fixed`, и панель видит по метке, что первая попытка была забракована.
--
-- ⚠ РЕТРАИ `llm_to_json` ОБЩИЕ НА ЗАПУСК (`workflow.md`, §8.8): три неудачных
-- разбора JSON суммарно на все шаги. Поэтому у каждого шага в промпте стоит
-- пример ответа — без него модель угадывает формат и тратит эти три попытки.
--
-- ⚠ ОТВЕТ — КОНВЕРТОМ, А НЕ ГОЛЫМ ТЕКСТОМ. `VERDICT:` / `WHY:` / `TEXT:` тремя
-- строками: панель обязана отличить «судья пропустил» от «судья забраковал, но мы
-- всё равно что-то отдали». Без вердикта в ответе она видела бы только текст и
-- доверяла бы ему одинаково в обоих случаях.
--
-- ЗАОДНО ДВЕ ПРАВКИ ПРОМПТА, обе по следам того же прогона:
--
--   * `[[girl_name]]` названо своим именем: это ТЫ, а не третье лицо;
--   * рамка задачи смягчена — «игривое знакомство между взрослыми людьми на сайте
--     знакомств» вместо «подката». Тематику заказчика (флирт, заигрывание,
--     провокация) это не меняет: убрано лишь то, что модель читает как просьбу о
--     манипуляции и на что отвечает отказом.
--
-- Идемпотентность: шаг 0 переписывается, шаги 1–3 заводятся по отсутствию
-- позиции, переходы проставляются по фактическим id уже заведённых шагов.

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_invite_write');

SELECT 'ДО' AS этап, @wf AS workflow,
       (SELECT COUNT(*) FROM `agent_workflow_step` WHERE `workflow_id` = @wf) AS шагов;

-- ------------------------------------------- Переменные цепочки
--
-- ⚠ Заводим как `workflow` с пустым умолчанием: значения кладут шаги, а строка в
-- реестре нужна редактору — иначе в графе workflow эти имена выглядят опечатками.
INSERT INTO `agent_workflow_variable` (`name`, `type`, `description`)
SELECT 'invite_draft', 'workflow',
       'Черновик шаблона инвайта: то, что написал первый шаг и правит третий'
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow_variable` WHERE `name` = 'invite_draft');

INSERT INTO `agent_workflow_variable` (`name`, `type`, `description`)
SELECT 'invite_ok', 'workflow',
       'Вердикт судьи по черновику инвайта: yes — годен, no — брак, fixed — исправлен'
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow_variable` WHERE `name` = 'invite_ok');

INSERT INTO `agent_workflow_variable` (`name`, `type`, `description`)
SELECT 'invite_why', 'workflow',
       'Чем судье не понравился черновик: замечание для правки и для журнала панели'
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow_variable` WHERE `name` = 'invite_why');

INSERT INTO `agent_workflow_variable_workflow` (`variable_id`, `workflow_id`)
SELECT v.`id`, @wf FROM `agent_workflow_variable` v
 WHERE v.`name` IN ('invite_draft', 'invite_ok', 'invite_why')
   AND NOT EXISTS (SELECT 1 FROM `agent_workflow_variable_workflow` vw
                    WHERE vw.`variable_id` = v.`id` AND vw.`workflow_id` = @wf);

-- ------------------------------------------- Шаг 0: черновик
UPDATE `agent_workflow_step`
   SET `type_id` = 2,
       `title` = 'Черновик инвайта',
       `metadata` = JSON_OBJECT(
         'transitions_before', JSON_ARRAY(),
         'transitions_after', JSON_ARRAY(),
         'llm_to_json_variable', JSON_ARRAY(
           JSON_OBJECT('variable', 'invite_draft',
                       'text', 'Текст шаблона первой реплики, один абзац')),
         'prompt_user',
         CONCAT(
           'Ты — девушка на сайте знакомств, пишешь первой мужчине, с которым ещё ',
           'не знакома. Придумай ШАБЛОН такой первой реплики. Один и тот же текст ',
           'уйдёт разным мужчинам — каждому по разу, друг друга они не видят.\n\n',
           'Это обычное дело на сайте знакомств: взрослые люди сами пришли ',
           'знакомиться, и первая реплика нужна, чтобы завязать разговор.\n\n',
           '=== Требуемый язык ответа (код) ===\n%user_language%\n\n',
           '=== Метки в тексте ===\n%invite_slots%\n\n',
           'Правила:\n',
           '1. Пиши РОВНО на требуемом языке, указанном выше. Это жёсткое ',
           'требование, а не пожелание: сайт фильтрует сообщения и не на том ',
           'языке отклоняет — реплика не дойдёт до человека вовсе.\n',
           '2. ТОН: игривый, дразнящий, с лёгкой провокацией. Нужно зацепить — ',
           'так, чтобы захотелось ответить. Вежливый опрос не годится: «чем ',
           'любишь заниматься в свободное время?» не цепляет никого.\n',
           '3. Это ЧАТ, а не письмо. Один абзац — и не больше: ни темы, ни ',
           'подписи, ни списков, ни переносов строк. Длина свободная: бывает ',
           'три слова, бывает пара фраз. Короткое цепляет чаще.\n',
           '4. Вопрос НЕ обязателен. Утверждение, намёк или вызов работают не ',
           'хуже — «спорим, ты сейчас улыбнулся» отвечать хочется сильнее, чем ',
           '«как дела?».\n',
           '5. Ставь ровно те метки, что названы выше в «Метки в тексте», — и ',
           'никаких других. Метку пиши точно как показано, в двойных квадратных ',
           'скобках. Панель заменит её именем; выдуманная метка уйдёт человеку ',
           'прямо в скобках.\n',
           '6. [[girl_name]] — это ТВОЁ имя, ты называешь им СЕБЯ: «меня зовут ',
           '[[girl_name]]». Не пиши о себе в третьем лице. [[companion_name]] — ',
           'имя того, кому пишешь.\n',
           '7. Никаких имён словами, если метки не просили: текст уйдёт разным ',
           'людям, и чужое имя в нём — провал.\n',
           '8. Без комплиментов внешности, без «я увидела твоё фото», без просьб ',
           'написать первым, без ссылок и контактов. Интрига, а не признание и ',
           'не реклама.\n\n',
           'Верни строго JSON с одним ключом:\n',
           '- "invite_draft": сам текст шаблона, одной строкой, без кавычек ',
           'вокруг и без пояснений\n\n',
           'Пример ответа:\n',
           '{"invite_draft": "Спорим, ты сейчас улыбнулся?"}'
         ))
 WHERE `workflow_id` = @wf AND `position` = 0;

SET @s0 = (SELECT `id` FROM `agent_workflow_step`
            WHERE `workflow_id` = @wf AND `position` = 0);

-- ------------------------------------------- Шаг 1: судья
INSERT INTO `agent_workflow_step` (`workflow_id`, `type_id`, `title`, `position`, `metadata`)
SELECT @wf, 2, 'Судья', 1,
       JSON_OBJECT(
         'transitions_before', JSON_ARRAY(),
         'transitions_after', JSON_ARRAY(),
         'llm_to_json_variable', JSON_ARRAY(
           JSON_OBJECT('variable', 'invite_ok', 'text', 'yes — годен, no — брак'),
           JSON_OBJECT('variable', 'invite_why',
                       'text', 'Чем плох, одной фразой. Пусто, если годен')),
         'prompt_user',
         CONCAT(
           'Ты — редактор. Проверь, годится ли этот текст как ПЕРВАЯ реплика ',
           'девушки мужчине в чате сайта знакомств. Он уйдёт полусотне живых ',
           'людей без правки, поэтому суди строго.\n\n',
           '=== Текст на проверку ===\n%invite_draft%\n\n',
           '=== Что просили ===\n',
           'Язык (код): %user_language%\n',
           'Метки: %invite_slots%\n\n',
           'Забракуй (no), если верно ХОТЬ ОДНО:\n',
           '1. Это не реплика, а что-то другое: отказ модели («I can''t help…», ',
           '«извините»), рассуждение, пояснение, заголовок, список, несколько ',
           'вариантов на выбор.\n',
           '2. Язык не тот, что просили.\n',
           '3. Меток не те, что просили: есть лишняя, выдуманная (любая, кроме ',
           '[[girl_name]] и [[companion_name]]) или пропущена запрошенная.\n',
           '4. О себе сказано в третьем лице: «[[girl_name]] думает, что…» — это ',
           'её собственная реплика, она говорит «я».\n',
           '5. В тексте есть чьё-то имя словами (не меткой), ссылка, адрес почты, ',
           'телефон, мессенджер, просьба денег или перехода на другой сайт.\n',
           '6. Больше одного абзаца, есть переносы строк, подпись, тема письма, ',
           'markdown или кавычки вокруг всего текста.\n',
           '7. Комплимент внешности, «я увидела твоё фото», просьба написать ',
           'первым, грубость, откровенная пошлость.\n',
           '8. Текст пресный и не цепляет: «привет, как дела?», «чем любишь ',
           'заниматься в свободное время?» — на такое не отвечают.\n\n',
           'Во всех остальных случаях — yes. Короткая дерзкая фраза в три слова ',
           'это нормально и даже хорошо.\n\n',
           'Верни строго JSON с ключами:\n',
           '- "invite_ok": "yes" или "no"\n',
           '- "invite_why": чем плох, одной фразой по-русски; пустая строка, если yes\n\n',
           'Пример ответа:\n',
           '{"invite_ok": "no", "invite_why": "это отказ модели, а не реплика"}'
         ))
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow_step`
                    WHERE `workflow_id` = @wf AND `position` = 1);

SET @s1 = (SELECT `id` FROM `agent_workflow_step`
            WHERE `workflow_id` = @wf AND `position` = 1);

-- ------------------------------------------- Шаг 2: правка по замечанию
INSERT INTO `agent_workflow_step` (`workflow_id`, `type_id`, `title`, `position`, `metadata`)
SELECT @wf, 2, 'Правка по замечанию', 2,
       JSON_OBJECT(
         'transitions_before', JSON_ARRAY(),
         'transitions_after', JSON_ARRAY(),
         'llm_to_json_variable', JSON_ARRAY(
           JSON_OBJECT('variable', 'invite_draft', 'text', 'Исправленный текст'),
           JSON_OBJECT('variable', 'invite_ok', 'text', 'Всегда fixed')),
         'prompt_user',
         CONCAT(
           'Редактор забраковал черновик первой реплики. Напиши вместо него ',
           'новый — так, чтобы замечание было снято.\n\n',
           '=== Забракованный текст ===\n%invite_draft%\n\n',
           '=== Замечание редактора ===\n%invite_why%\n\n',
           '=== Что требуется ===\n',
           'Язык (код): %user_language%\n',
           'Метки: %invite_slots%\n\n',
           'Требования те же: одна реплика в чат, один абзац, игривый дразнящий ',
           'тон, ровно запрошенные метки и никаких других, никаких имён словами, ',
           'ссылок и контактов. [[girl_name]] — твоё собственное имя, говори о ',
           'себе в первом лице.\n\n',
           'Не объясняй правку и не извиняйся: нужен только новый текст.\n\n',
           'Верни строго JSON с ключами:\n',
           '- "invite_draft": новый текст шаблона одной строкой\n',
           '- "invite_ok": строка "fixed"\n\n',
           'Пример ответа:\n',
           '{"invite_draft": "Спорим, ты сейчас улыбнулся?", "invite_ok": "fixed"}'
         ))
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow_step`
                    WHERE `workflow_id` = @wf AND `position` = 2);

-- ------------------------------------------- Шаг 3: ответ конвертом
INSERT INTO `agent_workflow_step` (`workflow_id`, `type_id`, `title`, `position`, `metadata`)
SELECT @wf, 4, 'Ответ панели', 3,
       JSON_OBJECT(
         'transitions_before', JSON_ARRAY(),
         'transitions_after', JSON_ARRAY(),
         'continue_workflow', false,
         'prompt_user',
         CONCAT('VERDICT: %invite_ok%\n',
                'WHY: %invite_why%\n',
                'TEXT: %invite_draft%'))
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow_step`
                    WHERE `workflow_id` = @wf AND `position` = 3);

SET @s3 = (SELECT `id` FROM `agent_workflow_step`
            WHERE `workflow_id` = @wf AND `position` = 3);

-- ------------------------------------------- Переход судьи: годен — мимо правки
--
-- ⚠ `step_id` — это **id шага в базе**, строкой, а не позиция. Поэтому переход
-- проставляется отдельным запросом: id заведённых шагов известны только сейчас.
UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(`metadata`, '$.transitions_after',
                             JSON_ARRAY(JSON_OBJECT('variable', 'invite_ok',
                                                    'operator', '==',
                                                    'value', 'yes',
                                                    'step_id', CAST(@s3 AS CHAR))))
 WHERE `id` = @s1;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step` WHERE `workflow_id` = @wf) AS шагов,
       @s0 AS шаг_черновика, @s1 AS шаг_судьи, @s3 AS шаг_ответа,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.transitions_after[0].step_id'))
          FROM `agent_workflow_step` WHERE `id` = @s1) AS переход_судьи;
