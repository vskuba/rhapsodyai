-- Убранный ответ помечается, а не стирается — колонка
-- `companion_session.answer_deleted_at` (2026-10-03).
--
-- ## Зачем
--
-- На вкладке «Чат» страницы `/admin/session` появился чип «удалить»: он убирает
-- из обмена **наш** ответ, доставленный по ошибке. Пока такой ответ лежит в
-- таблице, он уезжает в промпт лентой `companion_session_history` наравне с
-- настоящими, и каждый следующий ответ модели опирается и на него.
--
-- Первая версия чистила поля (`answer = ''`), то есть стирала текст насовсем.
-- Это неверно по двум причинам: решение «лишний» принимает человек и может
-- ошибиться, а разбирать потом «что же там было написано» будет не по чему.
-- Отметка времени отвечает на оба вопроса: текст цел, читатели его не берут.
--
-- ## ⚠⚠ Помечается ПОЛОВИНА строки, поэтому имя не `deleted_at`
--
-- Строка здесь — это **обмен**: его реплика и наш ответ лежат в колонках одной
-- записи. Убирают только нашу половину — его слова настоящие, и `deleted_at` на
-- такой строке врал бы: запись-то жива и показывается дальше, просто без
-- ответа. Отсюда имя: отметка про `answer`, рядом с `answer_at`.
--
-- Понадобится когда-нибудь убирать обмен целиком — заводить **вторую** колонку
-- (`deleted_at`), а не переосмысливать эту: два разных действия с одним полем
-- расходятся на первой же правке.
--
-- ## Кто обязан смотреть на колонку
--
--   companion_session_rows        лента в промпт агента (через неё и history)
--   session_companion_messages    лента вкладки «Чат»
--   session_companion_list        счётчики разговоров и сам список
--
-- Условие одно на всех: `answer_deleted_at IS NULL`. Забыть его в одном месте —
-- это «на странице ответа нет, а модель его помнит», то есть ровно та беда, от
-- которой чип и заводили.
--
-- Идемпотентность: колонка добавляется только когда её нет — повторный прогон и
-- уже обновлённая база не пострадают (`ADD COLUMN IF NOT EXISTS` MySQL не умеет).
SET @column_exists = (
    SELECT COUNT(*) FROM information_schema.COLUMNS
     WHERE TABLE_SCHEMA = DATABASE()
       AND TABLE_NAME = 'companion_session'
       AND COLUMN_NAME = 'answer_deleted_at');

SET @sql = IF(@column_exists = 0,
    'ALTER TABLE `companion_session` ADD COLUMN `answer_deleted_at` DATETIME NULL '
    'DEFAULT NULL COMMENT ''Когда наш ответ убрали со страницы; текст остаётся'' '
    'AFTER `answer_at`',
    'SELECT 1');

PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- Существующим строкам ничего не проставляем: `NULL` и значит «не убирали».
-- Индекса тоже нет намеренно — колонка идёт довеском к отбору, который уже сужен
-- парой и каналом (`owner_id`, `companion_id`, `kind`), а строк в таблице сотни,
-- не миллионы. Появятся тысячи убранных ответов — тогда и мерить.
