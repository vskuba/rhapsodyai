-- Номер оболочки внутри роли — колонка `ai_claude_session_registry`.`role_index`.
--
-- Зачем. Оболочек у роли теперь столько, сколько терминалов открыл человек, и все
-- они называются одинаково: три окна «Developer», три карточки «Developer». Понять,
-- какое окно соответствует какой карточке — а значит, в каком терминале идёт та
-- задача, которую видно на странице, — нельзя ни по чему.
--
-- Номер это чинит: заголовок терминала становится «Developer 2», карточка — тоже.
-- Первая оболочка роли остаётся без номера: пока она одна, номер только шумит, а
-- именно так выглядит обычная установка.
--
-- Почему номер хранится, а не считается на лету. Порядковый номер по времени
-- регистрации «плавает»: закрыли первый терминал — второй молча станет первым, и
-- заголовок открытого окна разойдётся с карточкой. Записанный при регистрации номер
-- живёт со своей сессией до её конца.
--
-- Номера переиспользуются: при регистрации берётся наименьший свободный среди живых
-- оболочек роли. Иначе после десятка перезапусков человек читал бы «Developer 14»
-- при двух открытых окнах.
--
-- Ноль — номер не назначен: сессия зарегистрирована до появления колонки либо роли
-- у неё нет вовсе (безролевая рабочая оболочка).
--
-- Идемпотентность: колонку добавляем только если её ещё нет — `ADD COLUMN IF NOT
-- EXISTS` MySQL не поддерживает, поэтому через information_schema.
SET @exists := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
     WHERE TABLE_SCHEMA = DATABASE()
       AND TABLE_NAME = 'ai_claude_session_registry'
       AND COLUMN_NAME = 'role_index'
);

SET @sql := IF(@exists = 0,
    'ALTER TABLE `ai_claude_session_registry`
        ADD COLUMN `role_index` INT NOT NULL DEFAULT 0
            COMMENT ''Номер оболочки внутри роли: 1 — основная, 0 — не назначен''
            AFTER `role`',
    'SELECT 1');

PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
