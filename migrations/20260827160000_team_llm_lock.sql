-- Захват модели ролью на круг работы — таблица `team_llm_lock`.
--
-- Зачем. Оболочки перестают быть привязанными к одной модели: у проекта есть пул, и
-- роль берёт из него первую свободную, когда начинает круг. Двум оболочкам одна и та
-- же модель достаться не должна — иначе они делят один прокси и мешают друг другу.
--
-- Почему таблица, а не колонка в `project_team` или в реестре сессий. Строка на модель
-- одна (первичный ключ — её имя), а захват это `UPDATE ... WHERE свободна`: InnoDB
-- держит строку под замком, и `rowcount` честно говорит, досталась ли она. В колонке
-- пришлось бы читать-проверять-писать, а это три шага, между которыми успевает чужой.
--
-- Захват живёт круг, а не задачу: между кругами модель свободна и её берёт другая
-- работа. `task_id` держит привязку — на следующем круге той же задаче стараются
-- вернуть ту же модель, и тогда агента можно не перезапускать, его контекст цел.
--
-- `locked_at` — срок протухания: оболочка падает, круг обрывается по таймауту, и без
-- срока пул опустел бы от мёртвых захватов.
--
-- Идемпотентность: `CREATE TABLE IF NOT EXISTS`.
CREATE TABLE IF NOT EXISTS `team_llm_lock` (
    `llm_name` VARCHAR(100) NOT NULL COMMENT 'Имя модели из каталога оболочки',
    `project_id` INT NOT NULL DEFAULT '0' COMMENT 'Чей пул; 0 — «Без проекта»',
    `task_id` INT DEFAULT NULL COMMENT 'Задача, для которой взяли — по ней прилипание',
    `role` VARCHAR(50) NOT NULL DEFAULT '' COMMENT 'Роль, которая держит',
    `session_uuid` CHAR(36) NOT NULL DEFAULT '' COMMENT 'Оболочка, которой отдали',
    `locked_at` DATETIME DEFAULT NULL COMMENT 'Когда взяли; NULL — свободна',
    PRIMARY KEY (`llm_name`),
    INDEX `idx_tll_task` (`task_id`),
    INDEX `idx_tll_project` (`project_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
