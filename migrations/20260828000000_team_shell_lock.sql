-- Захват оболочки ролью на круг работы — таблица `team_shell_lock`.
--
-- Зачем. У роли бывает несколько живых оболочек: их поднимают одной и той же командой
-- запуска в новых терминалах, и каждая — свой процесс Claude Code со своим контекстом.
-- До этой таблицы конвейер их не различал: `claude_shell_call` адресовал по паре
-- «роль + каталог» и брал самую свежую по пингу (`ORDER BY last_seen_at DESC LIMIT 1`),
-- поэтому вторая и следующие оболочки простаивали, а два круга одной роли ушли бы в
-- одну и ту же — второй промпт прилетел бы агенту посреди чужого хода.
--
-- Почему таблица, а не колонка в реестре сессий. Строка на оболочку одна (первичный
-- ключ — её `session_uuid`), а захват это `UPDATE ... WHERE свободна`: InnoDB держит
-- строку под замком, и `rowcount` честно говорит, досталась ли она нам. В колонке
-- пришлось бы читать-проверять-писать, а между этими тремя шагами успевает чужой тик.
-- Тот же приём, что у `team_llm_lock`, и по той же причине.
--
-- Реестр сессий сюда не годится ещё и потому, что он чужой: строки в нём заводит и
-- чистит сама оболочка своими пингами, а захват принадлежит конвейеру. Смешав их, мы
-- отдали бы внешнему процессу право снимать наши блокировки.
--
-- Захват живёт круг: кончился — оболочка свободна и её берёт следующая работа. Строка
-- при этом не удаляется, гаснет `locked_at`: в ней остаётся `task_id`, и следующий
-- круг той же задачи стараются отдать той же оболочке — её контекст помнит прошлый
-- ход, и агента не придётся вводить в курс заново.
--
-- `locked_at` — срок протухания: оболочку закрыли посреди круга, воркер убили по
-- таймауту, — и без срока роль осталась бы без оболочек навсегда.
--
-- Идемпотентность: `CREATE TABLE IF NOT EXISTS`.
CREATE TABLE IF NOT EXISTS `team_shell_lock` (
    `session_uuid` CHAR(36) NOT NULL COMMENT 'Оболочка из ai_claude_session_registry',
    `project_id` INT NOT NULL DEFAULT '0' COMMENT 'Чей проект; 0 — «Без проекта»',
    `role` VARCHAR(50) NOT NULL DEFAULT '' COMMENT 'Роль оболочки',
    `task_id` INT DEFAULT NULL COMMENT 'Задача, для которой взяли — по ней прилипание',
    `locked_at` DATETIME DEFAULT NULL COMMENT 'Когда взяли; NULL — свободна',
    PRIMARY KEY (`session_uuid`),
    INDEX `idx_tsl_task` (`task_id`),
    INDEX `idx_tsl_project_role` (`project_id`, `role`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
