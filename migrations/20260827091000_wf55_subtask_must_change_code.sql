-- Менеджер не заводит подзадач без кода (workflow #55, шаг «Промпт: разбиение»).
--
-- Что было. Промпт разбиения прямо велел: «Разведка нашла, что поведение уже
-- реализовано? Тогда подзадача ровно одна — подтвердить поведение и закрыть задачу».
-- Такая подзадача идёт с `final: false`, то есть уходит разработчику — а менять ему
-- нечего.
--
-- Чем это кончалось. Разработчик честно ничего не писал, ветка оставалась пустой, и
-- круг уходил впустую вместе с попыткой и двадцатью минутами оболочки. Дальше хуже:
-- QA видел пустой `master..HEAD`, читал это как «работа не сделана» и возвращал
-- подзадачу разработчику, которому по-прежнему нечего было делать. Наблюдалось на
-- #2038 и #2040: по три-четыре круга каждая, часы на пустой ветке.
--
-- Что делаем. Требуем правку кода у каждой подзадачи с `final: false`, а работу
-- «подтвердить и закрыть» отправляем туда, где ей место, — в приёмку (`final: true`).
--
-- Это профилактика, а не гарантия: пустая ветка остаётся возможной (работу мог
-- сделать сосед, прошлый круг или человек руками). Ловит её конвейер — состояние
-- `no_code_for_testing`, миграция `20260827090000`: перед кругом QA он смотрит
-- каталог подзадачи и, если правок нет, закрывает её без запуска агента.
--
-- Идемпотентность. `REPLACE` ищет исходную формулировку: повторный прогон её уже не
-- найдёт и ничего не изменит.

-- ─── До: строка, которую тронем ───────────────────────────────────────────────
SELECT `id`, `workflow_id`, `position`, `title`
FROM `agent_workflow_step`
WHERE `id` = 424;

-- ─── Промпт: разбиение ────────────────────────────────────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    'Разведка нашла, что поведение уже реализовано? Тогда подзадача ровно одна —\\nподтвердить поведение и закрыть задачу.',
    '=== КАЖДАЯ ПОДЗАДАЧА МЕНЯЕТ КОД ===\\n\\nПодзадача уходит разработчику, а он пишет код. Работа, в которой менять нечего, до\\nнего доходить не должна: он честно ничего не напишет, ветка останется пустой, и круг\\nуйдёт впустую — вместе с попыткой и двадцатью минутами оболочки.\\n\\nПоэтому у каждой подзадачи с `final: false` в плане обязана быть правка кода: какие\\nфайлы и функции трогать. «Проверить», «убедиться», «сверить», «зафиксировать» —\\nне подзадача разработчика.\\n\\nРазведка нашла, что поведение уже реализовано и делать нечего? Тогда подзадача ровно\\nодна и она **приёмка** — `final: true`: подтвердить поведение доказательствами и\\nзакрыть задачу. Не заводи под это работающую подзадачу: менять ей нечего.')
WHERE `id` = 424;

-- ─── После: правило на месте, старой формулировки нет ─────────────────────────
SELECT `id`,
       `metadata` LIKE '%КАЖДАЯ ПОДЗАДАЧА МЕНЯЕТ КОД%' AS `has_rule`,
       `metadata` LIKE '%подтвердить поведение и закрыть задачу.%' AS `still_old`
FROM `agent_workflow_step`
WHERE `id` = 424;

-- Ожидаемо: has_rule = 1, still_old = 0.
