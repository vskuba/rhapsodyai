-- `dating_invite_write`: разнообразие задаётся снаружи, а не просьбой (2026-09-16)
--
-- ЧТО ПОКАЗАЛ ЖИВОЙ ПРОГОН. Промпт просил «игриво и с провокацией», и модель
-- честно слушалась — но одинаково. Три шаблона из трёх начинались с одного и того
-- же оборота:
--
--     «I bet you're trouble…»
--     «You look like trouble…»
--     «I have a feeling you're trouble…»
--
-- ⚠ ЭТО НЕ ЛЕЧИТСЯ ПРОСЬБОЙ «БУДЬ РАЗНОЙ». У модели сильные притяжения: на
-- одинаковый вход она даёт похожий выход, и температура их не ломает. Просьба о
-- разнообразии — такая же просьба, как «вставляй имя иногда», которую она поняла
-- как «вставляй всегда» (см. миграцию про `invite_slots`).
--
-- КАК ЛЕЧИТСЯ. Тем же приёмом, что и метки: **жребий бросает панель**, а модель
-- получает конкретное указание. Три новые переменные:
--
--   `invite_angle`  — приём: вопрос, вызов, признание, игра, жалоба-приманка…
--                     Разводит сами **заходы**, а не слова внутри одного захода;
--   `invite_length` — от трёх слов до абзаца. Однообразие длины видно так же,
--                     как однообразие слов, а прежний промпт ещё и подталкивал к
--                     короткому («короткое цепляет чаще»);
--   `invite_avoid`  — что уже писали этому сайту, десяток прошлых шаблонов.
--                     Внутри одного приёма модель всё равно тянет к любимым
--                     оборотам, а «вот это ты уже писала» понимает буквально.
--
-- ⚠ ЖРЕБИЙ СНАРУЖИ, А НЕ «ВЫБЕРИ САМА ИЗ СПИСКА». Дай мы модели список приёмов и
-- попроси выбрать — она выбирала бы один и тот же, ровно как выбирала «trouble».
-- Восемь приёмов на четыре длины дают 32 сочетания ещё до её собственной
-- изменчивости.
--
-- ⚠ СУДЬЯ ТЕПЕРЬ БРАКУЕТ И ПОВТОР. Ему приходит тот же список: шаблон, слишком
-- похожий на прошлый, идёт на правку. Нового шага для этого не нужно — правка уже
-- есть в цепочке, и на хорошем пути лишних вызовов не появляется.
--
-- ЗАОДНО — то, о чём просил заказчик отдельно: длина названа вилкой (от короткого
-- предложения до абзаца, абзац бывает на 15–20 слов), а тематика расширена:
-- флирт, провокация, интимные вопросы, попытка соблазнить.
--
-- ⚠ ГРАНИЦЫ ОСТАЮТСЯ, И ОНИ НЕ ПРО СТЫДЛИВОСТЬ. Без грубости и физиологии: такое
-- отклоняет фильтр самого сайта, а шаблон уходит полусотне человек разом — одна
-- отклонённая формулировка означает полсотни недоставленных сообщений.
--
-- Идемпотентность: промпты переписываются целиком, переменные заводятся по
-- условию отсутствия.

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_invite_write');

SELECT 'ДО' AS этап, @wf AS workflow,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%invite_angle%'
          FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf AND `position` = 0) AS правка_есть;

-- ------------------------------------------- Переменные разнообразия
INSERT INTO `agent_workflow_variable` (`name`, `type`, `description`)
SELECT 'invite_angle', 'workflow',
       'Приём для инвайта: вопрос, вызов, признание, игра. Жребий бросает DatingAi'
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow_variable` WHERE `name` = 'invite_angle');

INSERT INTO `agent_workflow_variable` (`name`, `type`, `description`)
SELECT 'invite_length', 'workflow',
       'Какой длины просить инвайт: от трёх слов до абзаца. Жребий бросает DatingAi'
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow_variable` WHERE `name` = 'invite_length');

INSERT INTO `agent_workflow_variable` (`name`, `type`, `description`)
SELECT 'invite_avoid', 'workflow',
       'Что уже писали этому сайту: десяток прошлых шаблонов, чтобы не повторяться'
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow_variable` WHERE `name` = 'invite_avoid');

INSERT INTO `agent_workflow_variable_workflow` (`variable_id`, `workflow_id`)
SELECT v.`id`, @wf FROM `agent_workflow_variable` v
 WHERE v.`name` IN ('invite_angle', 'invite_length', 'invite_avoid')
   AND NOT EXISTS (SELECT 1 FROM `agent_workflow_variable_workflow` vw
                    WHERE vw.`variable_id` = v.`id` AND vw.`workflow_id` = @wf);

-- ------------------------------------------- Шаг 0: черновик
UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(
         `metadata`, '$.prompt_user',
         CONCAT(
           'Ты — девушка на сайте знакомств, пишешь первой мужчине, с которым ещё ',
           'не знакома. Придумай ШАБЛОН такой первой реплики. Один и тот же текст ',
           'уйдёт разным мужчинам — каждому по разу, друг друга они не видят.\n\n',
           'Это обычное дело на сайте знакомств: взрослые люди сами пришли ',
           'знакомиться, и первая реплика решает, ответят тебе или нет.\n\n',
           '=== Требуемый язык ответа (код) ===\n%user_language%\n\n',
           '=== Приём на этот раз ===\n%invite_angle%\n\n',
           '=== Длина на этот раз ===\n%invite_length%\n\n',
           '=== Метки в тексте ===\n%invite_slots%\n\n',
           '%if invite_avoid%=== Так ты уже писала — не повторяйся ===\n',
           '%invite_avoid%\n\n%endif%',
           'Правила:\n',
           '1. Пиши РОВНО на требуемом языке, указанном выше. Это жёсткое ',
           'требование, а не пожелание: сайт фильтрует сообщения и не на том ',
           'языке отклоняет — реплика не дойдёт до человека вовсе.\n',
           '2. ТЕМАТИКА: флирт, заигрывание, провокация, интимный вопрос, попытка ',
           'соблазнить. Игриво и смело — так, чтобы захотелось ответить прямо ',
           'сейчас. Вежливый опрос не годится совсем: «чем любишь заниматься в ',
           'свободное время?» не цепляет никого.\n',
           '3. ПРИЁМ И ДЛИНА заданы выше — держись их. Это не пожелание: пул ',
           'набирается десятками реплик, и если каждая выходит одинаковым заходом ',
           'одинаковой длины, человек видит рассылку робота, а не живую девушку.\n',
           '4. Если выше показано, что ты уже писала, — напиши ИНАЧЕ. Другой ',
           'образ, другие слова, другое начало. Повторять прежний оборот нельзя, ',
           'даже если он удачный: те люди уже его получили.\n',
           '5. Это ЧАТ, а не письмо: ни темы, ни подписи, ни списков, ни ',
           'переносов строк — всё одним куском. Абзац — предел длины.\n',
           '6. Вопрос НЕ обязателен. Утверждение, намёк, вызов или откровенное ',
           'признание работают не хуже — «спорим, ты сейчас улыбнулся» отвечать ',
           'хочется сильнее, чем «как дела?».\n',
           '7. Ставь ровно те метки, что названы выше в «Метки в тексте», — и ',
           'никаких других. Метку пиши точно как показано, в двойных квадратных ',
           'скобках. Панель заменит её именем; выдуманная метка уйдёт человеку ',
           'прямо в скобках.\n',
           '8. [[girl_name]] — это ТВОЁ имя, ты называешь им СЕБЯ: «меня зовут ',
           '[[girl_name]]». Не пиши о себе в третьем лице. [[companion_name]] — ',
           'имя того, кому пишешь.\n',
           '9. Никаких имён словами, если метки не просили: текст уйдёт разным ',
           'людям, и чужое имя в нём — провал.\n',
           '10. Границы: без грубости, без физиологии и прямых непристойностей — ',
           'такое отклоняет фильтр сайта, и тогда реплику не получит никто. Без ',
           'ссылок, контактов и просьб написать в мессенджер: это признак спама, ',
           'за него закрывают учётку. Интрига и намёк, а не прейскурант.\n\n',
           'Верни строго JSON с одним ключом:\n',
           '- "invite_draft": сам текст шаблона, одной строкой, без кавычек ',
           'вокруг и без пояснений\n\n',
           'Примеры ответа — три разной длины, чтобы было видно вилку:\n',
           '{"invite_draft": "Спорим, ты сейчас улыбнулся?"}\n',
           '{"invite_draft": "У меня к тебе неприличный вопрос, но сначала скажи — ',
           'ты из тех, кто краснеет?"}\n',
           '{"invite_draft": "Знаешь, я обычно не пишу первой, но сегодня мне ',
           'скучно настолько, что я решила рискнуть — и теперь сижу и думаю, чем ',
           'ты занят прямо сейчас."}'
         ))
 WHERE `workflow_id` = @wf AND `position` = 0;

-- ------------------------------------------- Шаг 1: судья бракует и повтор
UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(
         `metadata`, '$.prompt_user',
         REPLACE(
           REPLACE(JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')),
                   '=== Что просили ===\n',
                   CONCAT('%if invite_avoid%=== Так уже писали раньше ===\n',
                          '%invite_avoid%\n\n%endif%',
                          '=== Что просили ===\n')),
           CONCAT('8. Текст пресный и не цепляет: «привет, как дела?», «чем любишь ',
                  'заниматься в свободное время?» — на такое не отвечают.\n'),
           CONCAT('8. Текст пресный и не цепляет: «привет, как дела?», «чем любишь ',
                  'заниматься в свободное время?» — на такое не отвечают.\n',
                  '9. Текст слишком похож на то, что уже писали раньше (если список ',
                  'показан выше): тот же заход, тот же образ, те же ключевые слова. ',
                  'Пул набирается изо дня в день, и повтор виден человеку, который ',
                  'получил обе реплики.\n')))
 WHERE `workflow_id` = @wf AND `position` = 1;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%invite_angle%'
          FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 0) AS приём_у_черновика,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%invite_avoid%'
          FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 0) AS список_у_черновика,
       (SELECT JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%похож на то, что уже писали%'
          FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 1) AS повтор_у_судьи,
       (SELECT COUNT(*) FROM `agent_workflow_variable_workflow` WHERE `workflow_id` = @wf) AS переменных;
