-- Workflow `dating_invite_write`: приветственный вопрос в чат (2026-09-10)
--
-- ЗАЧЕМ. Панель заводит «инвайты» — первое сообщение в чат тому, с кем разговора
-- ещё не было. Не письмо: письмо человек открывает в почте сайта и читает
-- абзацами, а это одна реплика, которая всплывёт у него в окне чата.
--
-- ⚠ ПОЧЕМУ НЕ `dating_mail_write` И НЕ `dating_mail_question`. Первый пишет
-- **письмо** — с темой, абзацами и подписью; в чате такой текст выглядит
-- вставленным из документа. Второй сочиняет **вопрос без обращения**: имя стоит
-- в письме своей переменной, и внутри абзаца оно было бы вторым обращением. Здесь
-- ровно наоборот — имя обязано быть внутри реплики, потому что реплика и есть
-- всё сообщение. Три разных требования к тексту, и один промпт их не выражает.
--
-- ⚠ ИМЯ СОБЕСЕДНИКА В ТЕКСТЕ — ТРЕБОВАНИЕ, А НЕ УКРАШЕНИЕ. Обращение по имени
-- отличает написанное человеку от рассылки, а первая реплика — единственное место,
-- где это решает, ответят или нет. Поэтому имя приходит **отдельной переменной**
-- (`invite_companion_name`), а не только внутри карточки: карточку модель читает целиком
-- и обращение из неё берёт не всегда.
--
-- ⚠ ПОЧЕМУ ИМЯ ПОДСТАВЛЯЕТ МОДЕЛЬ, А НЕ ПАНЕЛЬ. Подстановка `[[girl_name]]`-стилем
-- по шаблону, как в письмах, здесь не годится: место имени в реплике зависит от
-- самой реплики. «Michael, а вы правда...» и «Давно катаетесь, Michael?» — обе
-- живые, а шаблон с зашитым местом даёт одну и ту же рамку на весь пул, и двадцать
-- инвайтов подряд читаются как двадцать копий.
--
-- ЧЕМУ УЧИТ ПРОМПТ.
--
-- 1. **Одна реплика, а не письмо.** Ни темы, ни подписи, ни абзацев: это чат.
-- 2. **Имя внутри текста, один раз.** Два обращения в двух предложениях читаются
--    как сбой подстановки.
-- 3. **Вопрос или предложение, на которое легко ответить.** «Привет, как дела?»
--    отвечать нечем; вопрос про то, что у него в профиле, даёт повод.
-- 4. **Профиля нет — общий вопрос.** Молчать нельзя: пустой ответ означает, что
--    инвайт не попадёт в пул вовсе, и человек остаётся вообще без приглашения.
-- 5. **Язык — тот, на котором написан его профиль.**
--
-- Идемпотентность: всё вставляется по условию отсутствия.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow`
         WHERE `name` = 'dating_invite_write') AS workflow_есть,
       (SELECT COUNT(*) FROM `agent_workflow_variable`
         WHERE `name` = 'invite_companion_name') AS переменная_есть;

-- ------------------------------------------- Сам workflow
INSERT INTO `agent_workflow` (`node_id`, `name`, `title`, `description`, `position`, `subflow`)
SELECT 2, 'dating_invite_write', 'Инвайт-менеджер',
       'Сочиняет первую реплику в чат незнакомому собеседнику: приветственный '
       'вопрос или предложение с обращением по имени. Для пула инвайтов на '
       '«Профилях»',
       0, 0
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow` WHERE `name` = 'dating_invite_write');

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_invite_write');

-- ------------------------------------------- Переменная под имя
--
-- ⚠ Своя, а не из карточки: карточку модель читает целиком, и обращение из неё
-- берёт не всегда. Имя в отдельной переменной названо в промпте по имени — мимо
-- него не пройти.
--
-- ⚠ ИМЯ `invite_companion_name`, А НЕ `companion_name`, И ЭТО НЕ ПЕДАНТИЗМ.
-- `companion_name` в этой базе **уже есть дважды** — #73 (`global`) и #81
-- (`input`, вход sub-workflow), обе от старых занятий бота. Привязка по имени
-- взяла бы обе, а подстановка стала бы неоднозначной: какая из двух подставится,
-- зависело бы от порядка строк. Найдено при накате — первая версия миграции
-- сослалась на общее имя и получила две привязки на одну переменную.
INSERT INTO `agent_workflow_variable` (`name`, `type`, `description`)
SELECT 'invite_companion_name', 'workflow',
       'Имя того, кому пишут первую реплику. Обращение по имени — требование к инвайту'
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow_variable`
                    WHERE `name` = 'invite_companion_name');

-- ------------------------------------------- Единственный шаг
INSERT INTO `agent_workflow_step` (`workflow_id`, `type_id`, `title`, `position`, `metadata`)
SELECT @wf, 1, 'Инвайт', 0,
       JSON_OBJECT(
         'transitions_after', JSON_ARRAY(),
         'prompt_user',
         CONCAT(
           'Ты пишешь ПЕРВУЮ реплику в чате на сайте знакомств. Девушка пишет ',
           'мужчине, они не знакомы и до этого не говорили.\n\n',
           '=== Кому пишем ===\n',
           'Имя: %invite_companion_name%\n%companion_card%\n\n',
           '=== Кто пишет ===\n%girl_card%\n\n',
           'Правила:\n',
           '1. Это ЧАТ, а не письмо. Одна реплика, одно-два предложения. Ни темы, ',
           'ни подписи, ни абзацев: текст всплывёт у него в окне чата как ',
           'сообщение от живого человека.\n',
           '2. Обратись к нему по имени — ровно один раз и внутри текста. Место ',
           'обращения выбирай сам: «%invite_companion_name%, а вы...» и «Давно этим ',
           'занимаетесь, %invite_companion_name%?» звучат по-разному, и одинаковая рамка ',
           'у всех реплик выдаёт рассылку. Два обращения в двух предложениях ',
           'читаются как сбой подстановки.\n',
           '3. Заканчивай вопросом или предложением, на которое легко ответить. ',
           '«Привет, как дела?» отвечать нечем. Спроси про то, что есть в его ',
           'профиле, — так видно, что профиль прочли.\n',
           '4. О нём ничего не известно — задай живой общий вопрос про его ',
           'занятия. Промолчать нельзя: без текста инвайт не попадёт в пул вовсе, ',
           'и человек останется без приглашения.\n',
           '5. Пиши на том же языке, на котором написан его профиль.\n',
           '6. Без комплиментов внешности, без «я увидела твоё фото», без просьб ',
           'написать первым. Первая реплика — повод для разговора, а не признание.\n',
           '7. Ответ — только сам текст реплики. Без кавычек, пояснений, markdown ',
           'и размышлений: всё, что ты напишешь, уйдёт в чат как есть.'
         ))
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow_step`
                    WHERE `workflow_id` = @wf AND `position` = 0);

-- ------------------------------------------- Привязка переменных
--
-- `companion_card` и `girl_card` уже заведены соседними workflow: переменные в
-- этой базе общие, и вторая с тем же именем сделала бы подстановку неоднозначной.
-- Привязываем существующие, `invite_companion_name` — только что заведённую.
INSERT INTO `agent_workflow_variable_workflow` (`variable_id`, `workflow_id`)
SELECT v.`id`, @wf FROM `agent_workflow_variable` v
 WHERE v.`name` IN ('companion_card', 'girl_card', 'invite_companion_name')
   AND NOT EXISTS (SELECT 1 FROM `agent_workflow_variable_workflow` vw
                    WHERE vw.`variable_id` = v.`id` AND vw.`workflow_id` = @wf);

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_invite_write') AS workflow_id,
       (SELECT COUNT(*) FROM `agent_workflow_step` WHERE `workflow_id` = @wf) AS шагов,
       (SELECT COUNT(*) FROM `agent_workflow_variable_workflow`
         WHERE `workflow_id` = @wf) AS переменных;
