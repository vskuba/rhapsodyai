-- Промпт письма ужимается под контекст `qwen-small` (2026-09-07)
--
-- ЧТО БЫЛО. После сборки цикла проверок письмо перестало генерироваться вовсе:
-- «request (3940 tokens) exceeds the available context size». Устойчиво, все три
-- прогона.
--
-- ⚠ ПРИЧИНА НЕ В ЦИКЛЕ, А В РАЗМЕРЕ. У ноды Dating стоит `qwen-small` — и стоит
-- правильно: письма это поток, а не разовая работа, и гонять их через большую
-- модель незачем. Значит уложиться должен промпт.
--
-- Промпт рос постепенно и незаметно: карточка анкеты (с биографией до 1500
-- знаков), карточка получателя, список переменных, пожелание, блок «два условия»,
-- восемь правил с объяснениями причин, требование JSON, блок доработки. Каждая
-- добавка была осмысленной, сумма — нет.
--
-- ЧТО ВМЕСТО. Правила ужаты до существа. ⚠ **Объяснения причин убраны
-- намеренно** — они писались для большой модели, которой довод помогает; малой
-- они занимают место, вытесняя сам ответ. Осталось «что делать», без «почему».
--
-- Порядок сохранён: язык и переменные впереди — на этом уже обжигались
-- (`20260907100000`), модель держит первые пункты лучше.
--
-- Карточки урезаны на стороне DatingAi (`DATING_MAIL_AGENT_ABOUT_MAX` 1500 → 400,
-- столько же получателю): предел в промпте бесполезен, если данные приходят
-- длиннее.
--
-- Идемпотентность: условие на то, что старая формулировка ещё на месте.

-- ---------------------------------------------------------------- До
SET @nl = CONCAT(CHAR(92), 'n');
SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_mail_write');
SET @a = (SELECT `id` FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 0);

SELECT 'ДО' AS этап, @a AS шаг,
       (SELECT CHAR_LENGTH(JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')))
          FROM `agent_workflow_step` WHERE `id` = @a) AS знаков_было;

-- ------------------------------------------- Короткий промпт
UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(`metadata`, '$.prompt_user', CONCAT(
        '%if write_hint%НЕ ГОДИТСЯ: %write_hint%', @nl,
        'Перепиши, устранив это.', @nl, @nl, '%endif%',
        'Напиши первое письмо от девушки мужчине на сайте знакомств.', @nl, @nl,
        'От кого:', @nl, '%girl_card%', @nl, @nl,
        'Кому:', @nl, '%companion_card%', @nl, @nl,
        'Переменные (вставляй как [[имя]]):', @nl, '%mail_vars%', @nl, @nl,
        'Пожелание: %mail_hint%', @nl, @nl,
        'Обязательно:', @nl,
        '- язык письма: %user_language%;', @nl,
        '- имена и город — только переменной [[имя]] из списка, не словами;', @nl,
        '- есть переменная с вопросом (question_to_companion) — поставь её вместо ',
        'вопроса, свой текст не пиши.', @nl, @nl,
        'Ещё:', @nl,
        '- до четырёх абзацев;', @nl,
        '- задай вопрос про его интересы;', @nl,
        '- обращение — к получателю, чья переменная подписана как имя получателя;',
        @nl,
        '- живо и просто, без признаний в любви.', @nl, @nl,
        'Верни JSON: {"letter": "текст письма"}'))
 WHERE `id` = @a
   AND JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')) LIKE '%ДВА УСЛОВИЯ%';

-- ------------------------------------------- Проверка языка тоже короче
--
-- Она получает всё письмо целиком, и своих слов у неё должно быть немного.
SET @c = (SELECT `id` FROM `agent_workflow_step` WHERE `workflow_id` = @wf AND `position` = 2);

UPDATE `agent_workflow_step`
   SET `metadata` = JSON_SET(`metadata`, '$.prompt_user', CONCAT(
        'Требуемый язык (код): %user_language%', @nl, @nl,
        'Письмо:', @nl, '%letter%', @nl, @nl,
        'Письмо целиком на требуемом языке? Имена, города и [[переменные]] не в счёт.',
        @nl, 'Верни JSON: {"letter_lang_ok": 1} или {"letter_lang_ok": 0}'))
 WHERE `id` = @c;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT CHAR_LENGTH(JSON_UNQUOTE(JSON_EXTRACT(`metadata`, '$.prompt_user')))
          FROM `agent_workflow_step` WHERE `id` = @a) AS знаков_стало,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `id` = @a AND `metadata` LIKE '%user_language%') AS язык_на_месте,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `id` = @a AND LOCATE(CONCAT(CHAR(92), CHAR(92), 'n'), `metadata`) > 0)
         AS задвоенных;
