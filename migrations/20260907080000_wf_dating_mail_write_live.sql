-- `dating_mail_write` учится оставлять вопрос переменной (2026-09-07)
--
-- ЧТО МЕНЯЕТСЯ. У писем появилась переменная `[[question_to_companion]]`: сам
-- вопрос сочиняется при рассылке, под того, кому письмо уходит
-- (`dating_mail_question`). Агент письма должен **вставить переменную и не
-- сочинять текст на её месте**.
--
-- ⚠ ОТЧЕГО ЭТО НЕ ОЧЕВИДНО ДЛЯ МОДЕЛИ. Второе правило промпта требует «обязательно
-- задай вопрос про интересы собеседника», и оно остаётся верным — но выполняется
-- теперь двумя разными способами. Если сведения о получателе есть, вопрос уместен
-- прямо в тексте: письмо пишется под него. Если письмо общее (рассылка многим) —
-- вопрос должен быть переменной, иначе он окажется одинаковым для всех, а это и
-- есть то, что выдаёт рассылку.
--
-- Прямо сказать «всегда вставляй переменную» нельзя: у сайта её может не быть в
-- реестре вовсе, и тогда письмо сослалось бы на несуществующее имя и не
-- сохранилось. Поэтому правило условное — «если такая переменная есть в списке».
--
-- Идемпотентность: условие на то, что правила ещё нет.

-- ---------------------------------------------------------------- До
SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_mail_write');

SELECT 'ДО' AS этап,
       @wf AS workflow_id,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND `metadata` LIKE '%сочиняется при отправке%') AS правило_есть;

-- ------------------------------------------- Правило про вычисляемые переменные
--
-- ⚠ Перенос строки собираем через `CHAR(92)`, а не литералом `\n`: yoyo подаёт
-- файл драйверу как есть, и обратный слэш в SQL-строке доезжает парой — на этом
-- уже попались (`20260907050000`).
SET @nl = CONCAT(CHAR(92), 'n');

UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(
        `metadata`,
        CONCAT('2. Обязательно задай вопрос про интересы собеседника — опирайся на то, ',
               'что о нём известно выше. Письмо без вопроса не получает ответа.', @nl),
        CONCAT('2. Обязательно задай вопрос про интересы собеседника — опирайся на то, ',
               'что о нём известно выше. Письмо без вопроса не получает ответа.', @nl,
               '2а. Если в списке переменных есть та, чья подпись говорит, что вопрос ',
               'сочиняется при отправке (например question_to_companion), — поставь ',
               'вместо вопроса её. Свой текст на её месте не пиши: письмо уходит многим, ',
               'и один и тот же вопрос всем сразу выдаёт рассылку. Переменная же ',
               'заменится вопросом, придуманным под каждого получателя.', @nl))
 WHERE `workflow_id` = @wf
   AND `metadata` LIKE '%Письмо без вопроса не получает ответа.%'
   AND `metadata` NOT LIKE '%сочиняется при отправке%';

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND `metadata` LIKE '%сочиняется при отправке%') AS правило_новое,
       (SELECT COUNT(*) FROM `agent_workflow_step`
         WHERE `workflow_id` = @wf
           AND LOCATE(CONCAT(CHAR(92), CHAR(92), 'n'), `metadata`) > 0) AS задвоенных;
