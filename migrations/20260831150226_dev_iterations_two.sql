-- Круг самопроверки разработчика становится полезным: `max_dev_iterations` 1 -> 2.
--
-- Разбор по подзадаче #5235. Шаг самопроверки отработал честно: рецензент нашёл три
-- замечания — 185 строк продублированы из `project_task_question.py`, контракт ответа
-- не по `api_rules.md`, потерян контекст докстрингов — и вынес `dev_ok: no`.
--
-- И всё это пропало. Переходы шага 509 проверяются по порядку, и условие лимита
-- (`dev_iteration >= max_dev_iterations`) стоит **раньше**, чем `dev_ok != yes`. При
-- лимите в единицу первый же круг самопроверки его достигает: критика написана,
-- прочитана человеком в журнале и выброшена, а работа ушла к QA как есть.
--
-- То есть шаг существовал в режиме, где он не мог сработать ни разу. Токены на него
-- тратились (у #5235 — шесть минут работы агента), польза была нулевая по построению.
--
-- Два круга дают циклу замкнуться: `dev_ok != yes` уводит на шаг 441 «Замечания на
-- доработку», тот кладёт `dev_critique_new` в `dev_critique` и возвращает на шаг 435
-- «Промпт: реализация» — разработчик получает свои же замечания на вход и правит.
-- Второй круг упрётся в лимит и отдаст работу QA, что бы он ни ответил.
--
-- Почему именно 2, а не больше. Круг реализации — самый дорогой шаг конвейера
-- (у #5235 он занял 26 минут), и каждый лишний виток удваивает стоимость подзадачи.
-- Два — это «дать исправить найденное», три и выше — «шлифовать до бесконечности»,
-- а на шлифовку есть QA с его собственными кругами.
--
-- `max_qa_iterations` не трогаем: у QA другая роль — он выносит вердикт, а не правит
-- код, и второй круг проверки того же самого ничего не добавит.
--
-- Идемпотентность: условие на текущее значение — повторный прогон и уже поднятый
-- лимит не тронет.
UPDATE `agent_workflow_variable`
   SET `default` = '2',
       `description` = 'Максимум кругов самопроверки разработчика (workflow task_developer). '
                       'Меньше двух шаг бесполезен: замечания находятся, но применить их негде'
 WHERE `name` = 'max_dev_iterations'
   AND `default` = '1';
