-- Workflow `dating_mail_question`: вопрос получателю про его интересы (2026-09-07)
--
-- ЗАЧЕМ. Письмо рассылки должно спрашивать про интересы получателя, но шаблон
-- пишется до того, как известно, кому он уйдёт. Выходило одно из двух: письмо под
-- конкретного человека (годно ровно ему) либо общее письмо без вопроса — а письмо
-- без вопроса не получает ответа.
--
-- Развязка: вопрос стал переменной `[[question_to_companion]]`. Шаблон пишется
-- общим и на неё ссылается, а этот workflow сочиняет сам вопрос — в момент
-- рассылки, по профилю того, кому письмо уходит.
--
-- ⚠ ПОЧЕМУ ОТДЕЛЬНЫЙ WORKFLOW, А НЕ ШАГ В `dating_mail_write`. Тот пишет письмо
-- **один раз**, когда человек нажал кнопку; этот работает **на каждую пару**,
-- когда идёт рассылка. Разная частота, разная цена, разный повод: письмо
-- перечитывают и правят, вопрос уходит как есть.
--
-- ⚠ ЧЕМУ УЧИТ ПРОМПТ.
--
-- 1. **Один вопрос, не два.** Он встраивается в готовый абзац письма; два вопроса
--    подряд превращают письмо в анкету.
-- 2. **Про то, что в профиле.** Вопрос «а чем вы увлекаетесь?» человек читал
--    сотню раз и не отвечает; «давно ли реставрируете мотоциклы?» показывает, что
--    его профиль прочли.
-- 3. **Без обращения по имени.** Имя уже стоит в письме своей переменной, и
--    второе обращение внутри абзаца читается как сбой подстановки.
-- 4. **Профиля нет — общий вопрос.** Молчать нельзя: пустая переменная означает,
--    что письмо не уйдёт вовсе. Лучше вежливый общий вопрос, чем несостоявшаяся
--    рассылка.
--
-- Идемпотентность: всё вставляется по условию отсутствия.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM `agent_workflow` WHERE `name` = 'dating_mail_question') AS workflow_есть;

-- ------------------------------------------- Сам workflow
INSERT INTO `agent_workflow` (`node_id`, `name`, `title`, `description`, `position`, `subflow`)
SELECT 2, 'dating_mail_question', 'Вопрос получателю',
       'Сочиняет один вопрос про интересы получателя по его профилю — для переменной question_to_companion в письмах рассылки',
       0, 0
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow` WHERE `name` = 'dating_mail_question');

SET @wf = (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_mail_question');

-- ------------------------------------------- Единственный шаг
INSERT INTO `agent_workflow_step` (`workflow_id`, `type_id`, `title`, `position`, `metadata`)
SELECT @wf, 1, 'Вопрос', 0,
       JSON_OBJECT(
         'transitions_after', JSON_ARRAY(),
         'prompt_user',
         CONCAT(
           'Ты придумываешь ОДИН вопрос для письма на сайте знакомств. ',
           'Письмо пишет девушка мужчине, они не знакомы.\n\n',
           '=== Что известно о получателе ===\n%companion_card%\n\n',
           '=== Кто пишет ===\n%girl_card%\n\n',
           'Правила:\n',
           '1. Ровно один вопрос, одно-два предложения. Он встанет внутрь готового ',
           'абзаца письма, а два вопроса подряд превращают письмо в анкету.\n',
           '2. Спрашивай про то, что есть в его профиле. Вопрос «чем вы ',
           'увлекаетесь?» он читал сотню раз и не ответит; вопрос про его дело ',
           'показывает, что профиль прочли.\n',
           '3. Не обращайся по имени: оно уже стоит в письме отдельно, и второе ',
           'обращение внутри абзаца читается как сбой подстановки.\n',
           '4. О получателе ничего не известно — задай общий, но живой вопрос про ',
           'его занятия. Промолчать нельзя: без вопроса письмо не уйдёт вовсе.\n',
           '5. Пиши на том же языке, на котором написан профиль получателя.\n',
           '6. Ответ — только сам вопрос. Без кавычек, пояснений, markdown и ',
           'размышлений: всё, что ты напишешь, встанет в письмо как есть.'
         ))
 WHERE NOT EXISTS (SELECT 1 FROM `agent_workflow_step`
                    WHERE `workflow_id` = @wf AND `position` = 0);

-- ------------------------------------------- Переменные
--
-- Обе уже заведены соседними workflow (`dating_mail_vars`, `dating_mail_write`):
-- переменные в этой базе общие, и вторая с тем же именем сделала бы подстановку
-- неоднозначной. Привязываем существующие.
INSERT INTO `agent_workflow_variable_workflow` (`variable_id`, `workflow_id`)
SELECT v.`id`, @wf FROM `agent_workflow_variable` v
 WHERE v.`name` IN ('companion_card', 'girl_card')
   AND NOT EXISTS (SELECT 1 FROM `agent_workflow_variable_workflow` vw
                    WHERE vw.`variable_id` = v.`id` AND vw.`workflow_id` = @wf);

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT `id` FROM `agent_workflow` WHERE `name` = 'dating_mail_question') AS workflow_id,
       (SELECT COUNT(*) FROM `agent_workflow_step` WHERE `workflow_id` = @wf) AS шагов,
       (SELECT COUNT(*) FROM `agent_workflow_variable_workflow` WHERE `workflow_id` = @wf) AS переменных;
