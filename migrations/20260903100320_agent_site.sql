-- Агент получает сайт: `agent.site`.
--
-- Зачем. `POST /agent/create` заводит агента по именам узла и workflow, но не даёт
-- указать, какому сайту агент принадлежит, — вызывающий сервис (анкеты, боты) живёт
-- на своём сайте, а у записи агента про сайт молчать неоткуда. Колонка и есть ответ
-- на «откуда этот агент»; заполняется с момента создания, правится только записью.
--
-- Строкой, а не ссылкой на справочник сайтов: здесь, в RhapsodyAi, своего справочника
-- сайтов нет (сайты живут у соседей), а имя сайта — короткая латинская метка, её и
-- принимает точка создания под проверкой формата (`^[a-z0-9]+$`).
--
-- NULL для существующих записей: поле обязательное при заведении нового агента,
-- а задним числом сайт выдумывать некому.
--
-- Идемпотентность: `ADD COLUMN IF NOT EXISTS` MySQL не поддерживает, поэтому через
-- `information_schema` и `PREPARE` — тем же приёмом, что в `20260902125514`.

SET @exists := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
     WHERE TABLE_SCHEMA = DATABASE()
       AND TABLE_NAME = 'agent'
       AND COLUMN_NAME = 'site'
);

SET @sql := IF(@exists = 0,
    'ALTER TABLE `agent`
        ADD COLUMN `site` CHAR(50) DEFAULT NULL
            COMMENT ''Сайт-владелец агента: строчная латиница и цифры, без пробелов''
            AFTER `group_name`',
    'SELECT 1');

PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
