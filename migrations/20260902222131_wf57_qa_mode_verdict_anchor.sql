-- Шаг 451 (вердикт QA) всё-таки узнаёт про режим Lite: якорь прошлой миграции не совпал.
--
-- `20260831185747_wf57_qa_mode` развела по режимам четыре шага WF57, и три из них
-- поправила. Четвёртый, вердикт, искал в промпте строку
-- «3. Ничего рядом не сломано и правила проекта не нарушены?», а там стоит
-- «3. Ничего рядом не сломано, а правила проекта не нарушены в том, что изменила эта
-- подзадача?» — союз другой и хвост длиннее. `REPLACE` по несуществующей подстроке
-- ничего не делает и ошибки не даёт, поэтому правка молча не состоялась.
--
-- Почему этого не заметили. На машине разработчика блок в шаге 451 есть — его положила
-- ранняя редакция той же миграции, `20260831182922_wf57_qa_mode`, которую потом
-- переписали под новым именем, а файл убрали. В базе разработчика остались обе записи,
-- и вторая выглядела сработавшей за счёт первой. На установке, где ранней миграции не
-- было, шаг 451 остался без развилки: проверено на рабочей установке — блока нет.
--
-- Чем это грозит. Вердикт судит по четырём вопросам, и третий спрашивает про
-- поломки рядом. Без оговорки QA в режиме Lite считает непрогнанные тесты дефектом и
-- отвечает `qa_ok=no` за то, что прогонов не было по условиям самого режима, — то есть
-- Lite не работает ровно там, где он и нужен.
--
-- Якорь взят из живого промпта, включая перенос строки внутри пункта. Признак «уже
-- применено» — фраза из собственной вставки, как и у остальных правок WF57.
UPDATE `agent_workflow_step`
   SET `metadata` = REPLACE(`metadata`,
        '3. Ничего рядом не сломано, а правила проекта не нарушены в том, что\\n   изменила эта подзадача?',
        '3. Ничего рядом не сломано, а правила проекта не нарушены в том, что\\n   изменила эта подзадача?\\n%if !subtask_qa_full%   Режим Lite: непрогнанные тесты здесь не порок. Ничего и не запускалось по\\n   условиям прогона — это не дефект и не повод для qa_ok=no. Суди по коду,\\n   спецификации и документации.\\n%endif%')
 WHERE `id` = 451 AND `workflow_id` = 57
   AND `metadata` LIKE '%3. Ничего рядом не сломано, а правила проекта не нарушены в том, что%'
   AND `metadata` NOT LIKE '%непрогнанные тесты здесь не порок%';
