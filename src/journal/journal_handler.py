"""Застава журнала этой установки: кто пишет, чьи записи пропускаем мимо.

Сама застава — в общем слое (`py_modules/journal_/journal_catch.py`): обработчик
на корневом логгере, список оторванных логгеров, защита от круга, выбор своего
кадра из трассировки. Она нужна любому проекту с базой, и у соседей её
недоставало.

Здесь остаются три вещи, которые знает только этот проект: чем писать
(`journal_write` — наша таблица и наш отпечаток), чьи записи пропускать мимо и
где заставу ставить.

## ⚠ Ставится один раз на процесс, и его надо поставить

Обработчик не появляется сам: `logging_init()` живёт в общем слое и про таблицы
этого проекта не знает. Поэтому каждая точка входа зовёт
`journal_handler_install` рядом со своим `logging_init()`: `main_uvicorn`,
`main_telegram`, воркеры `rq`, кронджобы. Забытая точка входа не ломается — она
просто молчит в журнале.

⚠ `main_browser` намеренно **не** в этом списке: у контейнера-браузера нет базы
(та же причина, по которой ошибки окна пишет `uvicorn`, — см. `browser_error`).
"""

from journal_.journal_catch import (JournalCatch, journal_catch_install,
                                    journal_catch_remove)

from src.journal.journal import journal_write

# Чьи записи пропускаем мимо журнала. Сам журнал о своих неудачах говорит через
# `logger_info` (INFO до заставы не доходит), но если модуль когда-нибудь
# пожалуется на уровне ERROR — запись о недоступной базе пошла бы в ту же
# недоступную базу.
JOURNAL_HANDLER_SKIP = ('src.error.', 'journal')


def journal_handler_install(source: str) -> JournalCatch | None:
    """Подвешивает журнал к логгерам процесса. Зовётся рядом с `logging_init()`.

    Args:
        source: чей это процесс — ключ из `JOURNAL_SOURCES`
            (`uvicorn`, `worker`, `telegram`, `cronjob`).

    Returns:
        JournalCatch: поставленный обработчик; `None` — если он уже стоял.

    ⚠ **Идемпотентна** (это свойство слоя): второй вызов не ставит второй
    обработчик — у uvicorn lifespan запускается заново при перезагрузке кода, и
    каждая ошибка считалась бы дважды.

    ⚠ Неизвестный `source` не отвергается, а пишется как есть: журнал не место
    для проверки словаря — потерянная запись хуже незнакомой подписи. Но подпись
    для человека возьмётся только у известных (`JOURNAL_SOURCES`).
    """
    return journal_catch_install(source, journal_write,
                                 skip=JOURNAL_HANDLER_SKIP)


def journal_handler_remove() -> None:
    """Снимает обработчик — нужно тестам и разовым скриптам, не приложению."""
    journal_catch_remove()
