"""
Порог автосжатия контекста у оболочек ролей — настройка, а не константа.

Что это. Claude Code, упершись в окно модели, сжимает разговор и продолжает
работать по пересказу. Флаг `--autocompact` говорит, на каком объёме это начинать.

Почему числу нельзя быть в коде. Оно зависит от модели, а модель меняют: у GX10
окно 131072 токена, у следующей будет другое. Замеры показывают, что и внутри
одной модели порог хочется двигать — работа после сжатия идёт по пересказу, то
есть вслепую, и чем позже оно случится, тем лучше; но слишком поздний порог
упирается в потолок окна, и прогон падает с `exceed_context_size_error`, а
конвейер засчитывает это как состоявшийся круг и жжёт попытку впустую.

Подставляется **при показе карточки**, а не при её создании. Команда лежит в
`project_team.command` и переживает правку настройки: подставь мы значение один
раз при заведении проекта — смена настройки не дошла бы до уже созданных карточек,
и человек копировал бы кнопкой старое число, не подозревая об этом.

Отсюда же следствие: правка настройки видна сразу, но **действует со следующего
запуска оболочки**. Работающая роль свой флаг уже получила при старте.
"""
import re

from setting_.setting_ import setting_get

# Ключ в таблице `setting`. Правится на `/admin/setting`.
TEAM_SETTING_AUTOCOMPACT_KEY = 'gx10_autocompact_limit'

# Значение по умолчанию — то, что раньше было зашито в командах карточек. Окно
# модели GX10 — 131072 токена, 115k оставляет запас под ответ до этой границы.
TEAM_SETTING_AUTOCOMPACT_DEFAULT = '115k'

# Что считаем допустимым значением: число токенов с суффиксом `k`/`m` или `auto`.
# Тот же разбор, что у самой оболочки (`_autocompact_normalize` в claude-shell):
# разойдись они — настройка молча превратилась бы в «флаг не передан».
TEAM_SETTING_AUTOCOMPACT_RE = re.compile(r'^(auto|\d+[km]?)$')

# Флаг в команде запуска. Ищем его вместе со значением, чтобы заменить целиком.
TEAM_SETTING_AUTOCOMPACT_FLAG = '--autocompact'
_AUTOCOMPACT_IN_COMMAND = re.compile(r'--autocompact(?:[= ]\S+)?')


async def team_setting_autocompact_get() -> str:
    """
    Текущий порог автосжатия. Настройки нет или она испорчена — значение по умолчанию.

    Мусор в настройке не пробрасываем в команду: Claude Code на непонятном
    значении откажется стартовать вовсе, и роль просто не поднимется. Молчаливый
    откат к умолчанию здесь безопаснее — оболочка работает, а неверное значение
    видно на странице настроек.
    """
    raw = str(await setting_get(TEAM_SETTING_AUTOCOMPACT_KEY,
                                TEAM_SETTING_AUTOCOMPACT_DEFAULT) or '').strip().lower()

    return raw if TEAM_SETTING_AUTOCOMPACT_RE.match(raw) else TEAM_SETTING_AUTOCOMPACT_DEFAULT


async def team_setting_autocompact_apply(command: str) -> str:
    """
    Подставить в команду запуска текущий порог.

    Заменяем существующий флаг, а не дописываем второй: Claude Code взял бы
    последний, и команда читалась бы человеком неверно — в ней стояло бы два
    разных числа.

    Команды без флага не трогаем. Их две породы, и обеим флаг не нужен: команда
    без `--llm` (оболочка ходит в облако, там своё окно) и команда, которую
    человек правил руками, сознательно убрав автосжатие.
    """
    command = str(command or '')
    if TEAM_SETTING_AUTOCOMPACT_FLAG not in command:
        return command

    return _AUTOCOMPACT_IN_COMMAND.sub(
        f'{TEAM_SETTING_AUTOCOMPACT_FLAG} {await team_setting_autocompact_get()}', command, count=1)
