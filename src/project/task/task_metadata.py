"""
Произвольные данные задачи — колонка `project_task.metadata`.

Мешок «ключ -> значение» для того, под что заводить колонку рано: пометки агентов,
ссылки на внешние сущности, счётчики попыток чего-нибудь частного. Схема о составе
ничего не знает, контракт держит код, который пишет конкретный ключ, — поэтому
читатель всегда готов к тому, что ключа нет.

Не путать с `trace_meta`: тот — след интеграции, привязка задачи к источнику ошибки,
по нему идёт дедуп баг-задач (`task_bug_dedup`). Сюда его данные не переезжают.

Пустое значение — всегда `{}`, а не None: колонка допускает NULL (у задач, заведённых
до появления поля, там NULL), и разбирать эти два случая по коду смысла нет.

Правки идут через `task_metadata_update` — MySQL сливает патч в существующий JSON
одним UPDATE. Читать-править-писать на стороне Python нельзя: над одной задачей
одновременно работают оркестратор, воркеры и страница задач, и второй писатель
затёр бы ключ первого.
"""
import json

from json_.json_ import json_from_string
from mysql_.mysql_ import mysql_get_db_async

# Пометка «в разработку»: человек ставит её флажком на вкладке «Планирование» ещё до
# того, как план написан, — этим он говорит, что решение «делаем» уже принято и второй
# раз утверждать готовый план не потребуется. Ставит страница `/admin/task`, снимает
# `task_state_plan_to_development`, когда пометка сработала.
#
# Ключа нет — пометки нет: отдельного `false` не пишем, чтобы в мешке не копился след
# от каждой задачи, которую когда-то отметили и передумали.
TASK_METADATA_KEY_DEV = 'to_development'

# Пометка «в тестирование»: флажок на вкладке «Разработка». Хранится наизнанку по
# сравнению с `to_development` — умолчание здесь «включено», потому что сделанная
# работа обязана попадать на проверку сама, а решением человека является как раз
# отказ от неё. Поэтому ключа нет = пометка стоит, а снятый флажок пишется явным
# `false`; читатель обязан отличать «нет ключа» от `false` (`<> FALSE`, а не `= TRUE`).
#
# Пометка не одноразовая, в отличие от `to_development`: она не «согласие на один
# переход», а постоянное свойство задачи — так и остаётся в мешке после срабатывания.
# Читает `task_state_dev_to_testing`.
TASK_METADATA_KEY_TEST = 'to_testing'

# Пометка «в планирование»: флажок на вкладке «Планирование» и в окошке фиксера.
# Хранится наизнанку, как `to_testing`, и по той же причине: заведённая задача по
# умолчанию идёт к менеджеру за планом, а решением человека является как раз отказ —
# «пусть полежит, пока не дойдут руки». Ключа нет = задача планируется, снятый флажок
# пишется явным `false`.
#
# Читает захват (`task_metadata_plan_free_sql` в `task_claim_task_unplanned`): пометка
# запрещает не сам конвейер, а только первый его шаг — написание плана. Уже написанный
# план она не отменяет, и задачу, ушедшую дальше планирования, не трогает вовсе.
TASK_METADATA_KEY_PLAN = 'to_planning'

# Пометка «в багфикс»: флажок на вкладке «Баги». Хранится наизнанку, как `to_planning`
# и `to_testing`, и по той же причине: заведённый баг по умолчанию идёт в работу сам,
# а решением человека является отказ — «этот пока не чинить». Ключа нет = баг чинится,
# снятый флажок пишется явным `false`.
#
# Читает захват (`task_metadata_bugfix_free_sql` в `task_claim_task_bug`), снимает
# остановка (`task_stop._task_stop_patch`) — на вкладке «Баги» этот флажок и есть
# выключатель фазы, как «в тестирование» на «Тестировании».
TASK_METADATA_KEY_BUGFIX = 'to_bugfix'

# Ветка и merge request подзадачи — то, что разработчик отдаёт вместе с отчётом. Живут
# в мешке, а не в колонках: пишет их один шаг конвейера, читает одна ячейка страницы
# задач, и половина установок вообще работает без внешнего хостинга репозитория.
#
# Ключи только у подзадач: ветку заводят под конкретную работу, а родитель — это план,
# у него своего кода нет.
TASK_METADATA_KEY_BRANCH = 'branch'
TASK_METADATA_KEY_MR = 'mr_url'

# Отметка «работа задачи влита в главную ветку» — её ставит кнопка
# «mr2master&rm_worktree» после удавшегося слияния. Значение — словарь
# `{'at', 'by', 'base', 'branches'}`: странице нужно не только «влито», но и куда и
# чьими руками, иначе серая кнопка ничего не объясняет.
#
# Отметка нужна именно здесь, а не в git: повторное слияние той же ветки git считает
# законным (`Already up to date`) и молча делает вид, что всё в порядке, — по
# репозиторию «уже влито» не отличить от «ещё можно влить». Каталоги при этом уже
# сняты, и второе нажатие вернуло бы человеку ошибку про пропавшую ветку вместо
# честного «принято такого-то числа».
#
# Ключ только у главной задачи: сливают её целиком, всеми ветками плана сразу, и
# кнопка стоит на её строке.
TASK_METADATA_KEY_MERGED = 'merged'

# Счётчик сорвавшихся прогонов строки: `{'count', 'total', 'role', 'error', 'at'}`.
# Пишет и читает `task_retry.py` — там же описано, чем этот счётчик отличается от
# `pipeline_attempt_count` и почему живёт в мешке, а не в колонке.
TASK_METADATA_KEY_RETRY = 'retry'

# Пометка «остановлено человеком» — снятый флажок «в разработку» рядом со статусом.
# Человеческий `status` для этого не годится: захват его не смотрит вовсе (см.
# `task_claim`), и «Ожидает», выставленное руками, продержалось бы ровно до следующего
# тика. Поэтому запрет живёт отдельной пометкой, и её проверяет сам захват
# (`task_metadata_stop_free_sql` в `_task_claim`), а `task_state_kanban_sql` заодно
# не даёт конвейеру перебить статус остановленной строки своим.
#
# Ключа нет — задача идёт своим ходом. Снимает пометку возврат флажка
# «в разработку» или флажка фазы «в разработку»/«в тестирование» (`task_stop.py`).
TASK_METADATA_KEY_STOP = 'stopped'

# Подзадача-приёмка: та, что проверяет результат остальных. Её нельзя брать в
# работу, пока соседи не закрыты, — иначе она честно отвечает «не сошлось»,
# изменить это не может и жжёт свои круги на чужой невыполненной работе.
# Наступали дважды за день: #900 в задаче #895 и #1031 в #1027, обе ушли в
# `blocked`, не сделав ничего плохого.
TASK_METADATA_KEY_FINAL = 'final'


def task_metadata_parse(value) -> dict:
    """
    Разобрать значение колонки в dict.

    Для строк задачи, которые уже прочитаны (`SELECT * FROM project_task`), — незачем
    ходить в БД второй раз. NULL, пустая строка и не-объект дают `{}`.
    """
    return json_from_string(value) if value else {}


def task_metadata_stop_sql(column: str = 'metadata') -> str:
    """
    Условие «строку остановил человек» — кусок SQL без параметров.

    Без параметров намеренно: путь в JSON — константа, а условие подставляется в
    `where`, который в захвате повторяется дважды (SELECT и UPDATE, см. `_task_claim`),
    и второй список параметров пришлось бы тянуть через все вызовы.

    Битый JSON приравниваем к пустому (`JSON_VALID`), отсутствующий ключ — к снятой
    пометке: без `COALESCE` `JSON_EXTRACT` вернул бы NULL, а NULL в `WHERE` отсеял бы
    заодно все строки, которые никто не останавливал.

    `COALESCE` обёрнут вокруг сравнения, а не вокруг `JSON_EXTRACT`: у второго
    аргумента тип не JSON, и MySQL приводит к нему всё выражение — JSON-значение
    `true` становится строкой, сравнение с `TRUE` даёт 0, и остановленная строка
    выглядит свободной. Ошибка тихая: условие остаётся верным по синтаксису и
    ложным по смыслу для всех строк разом.
    """
    return (f"COALESCE(JSON_EXTRACT(IF(JSON_VALID({column}), {column}, '{{}}'), "
            f"'$.{TASK_METADATA_KEY_STOP}') = TRUE, FALSE)")


def task_metadata_stop_free_sql(column: str = 'metadata', parent_column: str = 'parent_id') -> str:
    """
    Условие «не остановлена ни сама строка, ни её родитель» — фильтр для захвата.

    Родителя проверяем потому, что останавливают задачу целиком: у строки в
    `processing` своей работы нет, вся она идёт у подзадач плана, и пометка на
    родителе обязана гасить их тоже — иначе разработчик продолжил бы писать код
    задачи, которую человек только что остановил.

    Подзапрос обёрнут в производную таблицу — MySQL 1093 запрещает читать в UPDATE ту
    же таблицу, которую пишет. `COALESCE(parent_id, 0)`: у корневой задачи родителя
    нет, а `NULL NOT IN (...)` дал бы NULL и выбросил её из отбора.
    """
    stopped = task_metadata_stop_sql(column)
    return (f'NOT ({stopped}) '
            f'AND COALESCE({parent_column}, 0) NOT IN '
            f'(SELECT pid FROM (SELECT id AS pid FROM project_task WHERE {stopped}) AS _stopped)')


def task_metadata_plan_free_sql(column: str = 'metadata') -> str:
    """
    Условие «планирование не запрещено человеком» — кусок SQL без параметров.

    Умолчание здесь «разрешено», поэтому и проверяется отклонение от него: явный
    `false` в `$.to_planning`. Отсутствующий ключ, NULL и битый JSON — это задача,
    которую никто не откладывал, и она к менеджеру идёт.

    Родителя, в отличие от остановки, не смотрим: план пишется только листьям, и
    строки с подзадачами захват отбрасывает раньше этого условия.
    """
    return _key_free_sql(TASK_METADATA_KEY_PLAN, column)


def task_metadata_bugfix_free_sql(column: str = 'metadata') -> str:
    """
    Условие «починка бага не запрещена человеком» — фильтр захвата в `task_claim_task_bug`.

    Устроено как `task_metadata_plan_free_sql`, отличается только ключом: умолчание
    «разрешено», проверяется отклонение — явный `false` в `$.to_bugfix`.

    Родителя не смотрим: баг всегда корневая строка, подзадач у него не бывает.
    """
    return _key_free_sql(TASK_METADATA_KEY_BUGFIX, column)


def task_metadata_test_free_sql(parent_column: str = 'parent_id') -> str:
    """
    Условие «проверка родителем не запрещена» — фильтр захвата подзадач для QA.

    Пометку `to_testing` человек снимает флажком на вкладке «Разработка», и означает
    это ровно «на проверку не отдавать». Без этого условия снятый флажок не давал
    задаче сменить вкладку (`task_state_dev_to_testing`), но QA всё равно разбирал
    очередь `qa_pending` — запрет выглядел бы не сработавшим.

    Смотрим родителя, а не саму строку: флажок стоит у задачи, у подзадач плана
    своих пометок фазы нет. Подзадача с запретом остаётся в `qa_pending` и дожидается
    возвращённой галки — терять её не за что, работа разработчиком уже сделана.

    Умолчание здесь «разрешено», поэтому проверяется отклонение от него: явный `false`.
    `COALESCE` обёрнут вокруг сравнения, а не вокруг `JSON_EXTRACT`, — та же ловушка с
    приведением типа, что в `task_metadata_stop_sql`. Подзапрос обёрнут в производную
    таблицу: MySQL 1093 запрещает читать в UPDATE ту же таблицу, которую пишет, а
    условие захвата повторяется и в UPDATE (`_task_claim`).
    """
    forbidden = ("COALESCE(JSON_EXTRACT(IF(JSON_VALID(metadata), metadata, '{}'), "
                 f"'$.{TASK_METADATA_KEY_TEST}') = FALSE, FALSE)")
    return (f'COALESCE({parent_column}, 0) NOT IN '
            f'(SELECT pid FROM (SELECT id AS pid FROM project_task WHERE {forbidden}) AS _no_testing)')


def task_metadata_final_wait_sql(column: str = 'metadata') -> str:
    """
    Условие «подзадача-приёмка ждёт, пока соседи не закрыты».

    Приёмка проверяет чужую работу, и до её готовности вердикт у неё один —
    «не сошлось». Круги при этом жгутся: три отказа подряд, и она в `blocked`,
    не сделав ничего плохого. Поэтому в отбор она попадает только тогда, когда
    все соседи по плану уже `done`.

    Обычная подзадача условию удовлетворяет всегда: ключа в мешке у неё нет.

    Подзапрос обёрнут в производную таблицу — MySQL не даёт читать в UPDATE ту
    же таблицу, которую пишет (ошибка 1093), а отбор идёт именно UPDATE-ом.
    """
    return (f"(NOT COALESCE(JSON_EXTRACT(IF(JSON_VALID({column}), {column}, '{{}}'), "
            f"'$.{TASK_METADATA_KEY_FINAL}') = TRUE, FALSE) "
            " OR NOT EXISTS (SELECT 1 FROM (SELECT id, parent_id, pipeline_state, metadata "
            "                                 FROM project_task) AS _sib "
            "                 WHERE _sib.parent_id = project_task.parent_id "
            "                   AND _sib.id <> project_task.id "
            f"                   AND NOT COALESCE(JSON_EXTRACT(IF(JSON_VALID(_sib.metadata), "
            f"                       _sib.metadata, '{{}}'), '$.{TASK_METADATA_KEY_FINAL}') = TRUE, FALSE) "
            "                   AND COALESCE(_sib.pipeline_state, '') <> 'done'))")


def task_metadata_row_apply(row) -> dict:
    """
    Строка задачи -> dict для ответа API с разобранным `metadata`.

    Из MySQL JSON-колонка приходит строкой, а внутрь API приходит объектом. Без
    разбора контракт эндпоинта разъезжается: клиент отправил `{...}`, а в ответе
    получил строку с экранированным юникодом. Применяется на границе API — всюду,
    где строка `project_task` уходит наружу.
    """
    task = dict(row)
    if 'metadata' in task:
        task['metadata'] = task_metadata_parse(task['metadata'])
    return task


async def task_metadata_get(task_id: int) -> dict:
    """Прочитать metadata задачи. Нет задачи или нет данных — `{}`."""
    if not task_id:
        return {}

    async with mysql_get_db_async() as db:
        await db.execute("SELECT metadata FROM project_task WHERE id = %s", (task_id,))
        row = await db.fetchone()

    return task_metadata_parse(row['metadata']) if row else {}


async def task_metadata_set(task_id: int, data: dict | None) -> None:
    """
    Записать metadata целиком, затерев прежнее содержимое.

    Для точечной правки одного ключа есть `task_metadata_update` — он не сносит
    чужие ключи. `None` или `{}` очищают поле в NULL.
    """
    if not task_id:
        return

    dumped = _task_metadata_dump(data)
    async with mysql_get_db_async() as db:
        await db.execute("UPDATE project_task SET metadata = %s WHERE id = %s", (dumped, task_id))
        await db.connection.commit()


async def task_metadata_update(task_id: int, patch: dict | None) -> None:
    """
    Слить патч в metadata задачи: свои ключи перезаписать, чужие оставить.

    Значение `None` в патче удаляет ключ — так работает JSON_MERGE_PATCH, и отдельная
    функция «удалить ключ» поэтому не нужна. Слияние поверхностное только на верхнем
    уровне вложенных объектов: словарь-значение сливается рекурсивно, список
    заменяется целиком.
    """
    if not task_id or not patch:
        return

    async with mysql_get_db_async() as db:
        await db.execute(
            "UPDATE project_task "
            "   SET metadata = JSON_MERGE_PATCH(COALESCE(metadata, '{}'), CAST(%s AS JSON)) "
            " WHERE id = %s",
            (json.dumps(patch, ensure_ascii=False), task_id),
        )
        await db.connection.commit()


def _task_metadata_dump(data: dict | None) -> str | None:
    """dict -> строка для колонки. Пустое и не-словарь дают NULL."""
    if not data or not isinstance(data, dict):
        return None
    return json.dumps(data, ensure_ascii=False)


def _key_free_sql(key: str, column: str) -> str:
    """
    Условие «пометка `key` не снята явным `false`» — общий вид для ключей с
    умолчанием «разрешено» (`to_planning`, `to_bugfix`).

    Без параметров намеренно: путь в JSON — константа, а условие подставляется в
    `where`, который в захвате повторяется дважды (SELECT и UPDATE, см. `_task_claim`),
    и второй список параметров пришлось бы тянуть через все вызовы.

    `COALESCE` обёрнут вокруг сравнения, а не вокруг `JSON_EXTRACT`, — та же ловушка,
    что в `task_metadata_stop_sql`: у второго аргумента тип не JSON, MySQL привёл бы к
    нему всё выражение, и условие стало бы ложным для всех строк разом. Ошибка тихая:
    синтаксис верный, смысл потерян.
    """
    return (f"NOT COALESCE(JSON_EXTRACT(IF(JSON_VALID({column}), {column}, '{{}}'), "
            f"'$.{key}') = FALSE, FALSE)")
