"""
Диалог Claude Code внутри оболочки: почему круг встал и что с этим делать.

Что происходит. Claude Code иногда останавливается и ждёт клавишу: спрашивает
разрешение на действие, предлагает выбор, сообщает об упёршемся лимите. На экране
это вопрос с пронумерованными вариантами, а для всего, что снаружи, — тишина: хода
нет и не будет, пока кто-нибудь не ответит.

Чем это кончалось. Оболочка вопрос распознавала и слала его человеку в чат, но
ждущее задание конвейера не трогала — оно висело до своего таймаута и падало с
«не смогла получить ответ агента». Для конвейера это неотличимо от зависшей
оболочки, а зависшую он лечит перезапуском. Перезапуск сносит диалог вместе с
ходом, следующий круг упирается в тот же вопрос — и так по кругу: на планировании
#1027 так сгорело четыре круга и час времени.

Что сделано. Оболочка теперь отпускает задание сразу и помечает отказ
(`DIALOG_MARKER` в `claude-shell/shell.py`). Этот модуль метку узнаёт и переводит
диалог в обычный вопрос человеку — тот самый, что роли задают полем `question`
(`task_question`). Дальше всё уже работает: строка встаёт с кнопкой, человек
отвечает попапом, ответ ложится в решения и уходит в промпт следующего круга.

Почему именно вопрос, а не повтор. Повтор помогает, когда прогон сорвался
случайно. Диалог — не случайность: за ним стоит развилка, которую агент не вправе
пройти сам, и без ответа человека следующий круг встанет ровно там же.
"""
import re

# Метка в начале отказа — её ставит оболочка (`DIALOG_MARKER` в `shell.py`).
# Строковая договорённость между двумя репозиториями: другого канала у них нет,
# результат вызова инструмента — это текст.
TASK_SHELL_DIALOG_MARKER = '[[dialog]]'

# Строка варианта в тексте диалога: «1. Stop and wait for limit to reset».
# Номер — ключ ответа: по нему потом видно, какую клавишу ждал Claude Code.
TASK_SHELL_DIALOG_OPTION = re.compile(r'^\s*(\d{1,2})[.)]\s+(.+?)\s*$')

# Служебные строки уведомления, которым в вопросе не место: заголовок и подсказка
# «ответь номером» написаны для чата, а в попапе варианты человек выбирает мышью.
TASK_SHELL_DIALOG_SKIP = ('🔐', 'Ответь номер', 'Ответь номерами', 'Номер вопроса можно',
                          'Пропустить вопрос')

# Потолок текста вопроса — тот же, что у вопроса роли (`TASK_QUESTION_TEXT_MAX`),
# но здесь он не страховка от болтливой модели, а обрезка экранного мусора:
# в текст диалога попадает и рамка TUI, если разбор экрана вышел неточным.
TASK_SHELL_DIALOG_TEXT_MAX = 1200


def task_shell_dialog_has(error) -> bool:
    """Отказ пришёл из-за открытого диалога, а не из-за молчащей оболочки."""
    return TASK_SHELL_DIALOG_MARKER in str(error or '')


def task_shell_dialog_question(error, role: str = '') -> dict:
    """
    Вопрос человеку по тексту диалога. Метки нет — `{}`.

    Форма та же, что у вопроса роли (`task_question_parse` её и разбирает):
    `{text, options}`. Варианты берём прямо из диалога, вместе с их номерами —
    номер и есть клавиша, которой отвечает Claude Code, и в решении он куда
    понятнее подписи без контекста.

    Args:
        error: текст отказа вызова оболочки целиком, с меткой.
        role: чья оболочка встала — уходит в первую строку вопроса. Человеку
            важно, кто именно упёрся: у ролей разные оболочки и разные экраны.

    Returns: `{'text', 'options', 'multi', 'dialog'}` — или `{}`, если метки нет.
        `dialog: True` отличает его от вопроса роли: спросил не агент, а мы за
        него, и текст вопроса написан не им.
    """
    if not task_shell_dialog_has(error):
        return {}

    body = str(error).split(TASK_SHELL_DIALOG_MARKER, 1)[1]
    lines = [line.rstrip() for line in body.splitlines()]

    options, question = [], []
    for line in lines:
        if not line.strip() or line.strip().startswith(TASK_SHELL_DIALOG_SKIP):
            continue
        found = TASK_SHELL_DIALOG_OPTION.match(line)
        if found:
            options.append({'key': found.group(1), 'label': found.group(2)})
        else:
            question.append(line.strip())

    head = (f'Оболочка {role} остановилась на вопросе Claude Code и ждёт ответа — '
            f'до него круг не пойдёт.' if role else
            'Оболочка остановилась на вопросе Claude Code и ждёт ответа.')
    text = '\n\n'.join([head, *question]) if question else head

    return {
        'text':    text[:TASK_SHELL_DIALOG_TEXT_MAX],
        'options': options,
        'multi':   False,
        'dialog':  True,
    }
