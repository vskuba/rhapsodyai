"""
Заглушки Developer и QA — шов, через который подставятся настоящие исполнители.

Оркестратор (`task_pipeline.py`) читает только документированные ключи возврата
и ничего не знает о том, как результат получен, поэтому реальная реализация
встанет на место, не потребовав правок машины состояний.

Manager заглушкой уже не является — он в `task_agent_manager.py`.

Ориентиры для будущей реализации:
  * Developer — либо агент внутри приложения, либо внешняя сессия Claude Code;
                выбор ещё не сделан, сигнатура рассчитана на оба варианта.
  * QA        — прогон существующего набора тестов (`pytest tests/`), без
                исполнения произвольного сгенерированного кода.
"""


async def task_agent_developer_run(task: dict, subtask: dict, last_error: str = '') -> dict:
    """
    Выполнить одну подзадачу. `last_error` непуст, если предыдущая попытка не прошла QA.

    Returns:
        ok: удалось ли выполнить.
        output: что сделано (для истории попыток).
        error: причина неудачи при ok=False.
    """
    # STUB: работу не выполняет, сразу отдаёт подзадачу на проверку.
    retry_note = f' (повтор после ошибки QA: {last_error[:200]})' if last_error else ''
    return {
        'ok': True,
        'output': f'[ЗАГЛУШКА] Разработчик отработал подзадачу «{subtask.get("title")}»{retry_note}.',
        'error': '',
    }


async def task_agent_qa_run(task: dict, subtask: dict) -> dict:
    """
    Проверить результат подзадачи прогоном тестов.

    Returns:
        ok: прошли ли проверки.
        output: вывод прогона.
        error: краткая причина падения при ok=False.
    """
    # STUB: тесты не запускаются. Настоящая реализация — subprocess с
    # `.venv/bin/python3 -m pytest tests/ -v` и разбор кода возврата.
    return {
        'ok': True,
        'output': f'[ЗАГЛУШКА] QA принял подзадачу «{subtask.get("title")}».',
        'error': '',
    }
