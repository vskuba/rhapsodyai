"""
Теги ошибки браузера: род сбоя, выведенный из её текста.

Зачем. `source` говорит, **кто** прислал ошибку, а не **что** случилось: под одним
словом `dating` в журнале лежат и таймауты, и отказы входа, и упавшие сценарии — восемь
тысяч записей под одной подписью. Разбирать такой журнал можно только чтением подряд.

Тег отвечает на второй вопрос. Ставится он сам, по тексту сообщения: просить клиента
размечать свои ошибки бесполезно — соседние проекты шлют то, что у них упало, и лишнего
поля не заполнят. Правило простое: подстрока в тексте → тег.

Двуязычно намеренно. Половина журнала — сообщения от роли на русском («нужен вход»,
«не отвечает»), половина — исключения библиотек на английском (`TimeoutError`,
`ECONNREFUSED`). Один список примет и то, и другое.

Список короткий и закрытый. Тег полезен, пока по нему можно щёлкнуть и увидеть класс
ошибок; два десятка тегов превращают фильтр в поиск, а поиск у нас уже есть — текст
сообщения. Не опознали — тегов нет, запись видна в «все».
"""

# Слова, по которым узнаётся род ошибки. Ключ — тег, значение — подстроки в нижнем
# регистре: русские для сообщений ролей, английские для исключений библиотек.
#
# Порядок ключей — порядок чипсов на странице: от самых частых к редким. Одна ошибка
# может получить несколько тегов, и это правильно: «таймаут при входе» — и `auth`, и
# `timeout`, найтись она должна по обоим.
BROWSER_ERROR_TAG_RULES = {
    'auth':     ('нужен вход', 'не авторизован', 'авториз', 'доступ запрещ', 'войти',
                 'unauthorized', 'forbidden', '401', '403', 'permission denied'),
    'timeout':  ('таймаут', 'не дождал', 'истекло время', 'превышено время',
                 'timeout', 'timed out', 'deadline'),
    'network':  ('сокет', 'соединение', 'сеть недоступна', 'не отвечает', 'оборвал',
                 'socket', 'connection', 'econnrefused', 'econnreset', 'network',
                 'dns', 'ssl'),
    'notfound': ('не найден', 'не найдена', 'не найдено', 'отсутствует', 'нет такого',
                 'not found', '404', 'no such element', 'no element'),
    'selector': ('селектор', 'элемент не', 'кнопк', 'поле не', 'xpath',
                 'selector', 'locator', 'element is not'),
    'data':     ('не разобра', 'разбор', 'неверный формат', 'json',
                 'parse', 'invalid', 'unexpected token', 'decode', 'typeerror'),
    'server':   ('500', '502', '503', '504', 'internal server', 'bad gateway',
                 'server error', 'ошибка сервера'),
    'crash':    ('упал', 'аварийно', 'закрылось', 'crash', 'target closed',
                 'browser has disconnected', 'session closed'),
}

# Потолок длины поля в базе (`browser_error.tags`). Проверка, а не срез: обрезанный
# посередине тег превратился бы в чужой и находился не тем фильтром, а строка без
# закрывающей запятой не нашлась бы вовсе. Все восемь тегов разом дают 57 символов, так
# что до потолка отсюда не дотянуться, — он сторожит правку списка, а не сегодняшний
# день: тег, который в поле не влезает, лучше не поставить, чем поставить обрубком.
BROWSER_ERROR_TAGS_MAX = 255


def browser_error_tags(message: str, source: str = '') -> str:
    """
    Теги ошибки строкой для колонки `tags`: `,auth,network,`. Ничего не узнали — пусто.

    Обрамляющие запятые — часть формата, а не украшение: по ним фильтр находит тег
    целиком (`LIKE '%,net,%'` не должен ловить `,network,`).

    `source` участвует наравне с текстом: клиент называет им своё происхождение
    («proxy», «scenario»), и слово оттуда бывает единственной приметой рода сбоя.

    Порядок тегов — как в `BROWSER_ERROR_TAG_RULES`, а не как нашлись: одинаковые
    ошибки должны давать одинаковую строку, иначе в журнале рядом лежат `,auth,network,`
    и `,network,auth,` — глазу это два разных вида.
    """
    text = f'{message or ""} {source or ""}'.lower()
    if not text.strip():
        return ''

    found = [tag for tag, words in BROWSER_ERROR_TAG_RULES.items()
             if any(word in text for word in words)]
    if not found:
        return ''

    marked = f',{",".join(found)},'

    return marked if len(marked) <= BROWSER_ERROR_TAGS_MAX else ''


def browser_error_tags_list(value: str) -> list:
    """Строка `,auth,network,` -> `['auth', 'network']`. Пусто -> `[]`."""
    return [tag for tag in str(value or '').split(',') if tag]
