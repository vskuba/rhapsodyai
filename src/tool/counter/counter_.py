async def counter_increment(value: int = 0, step: int = 1) -> int:
    """
    Увеличивает счетчик на step и возвращает новое значение.
    Инструмент для циклов в workflow: результат сохраняется в переменную,
    а переход с оператором < / >= по лимиту решает, повторять ли цикл.
    """
    return int(value) + int(step)
