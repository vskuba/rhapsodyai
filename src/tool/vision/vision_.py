"""Зрение для workflow: картинка на вход, названные поля на выход.

У движка шага, передающего картинку модели, нет: `llm_to_image` — это
**генерация** (текст → картинка), обратного типа не существует. Приём
изображения знает только реестр моделей (колонка `input_type`), но до шагов это
не доходит.

Инструмент закрывает дыру, не трогая движок: `tool_invoke` вызывает его как
обычный инструмент, а картинку он получает переменной workflow.

Сам разбор делает общий слой (`ai.vision.ai_vision_json`): нормализация кадра,
просьба вернуть JSON, разбор грязного ответа и один переспрос. Здесь остаётся
то, что делает это инструментом, — докстринг для модели и приведение ответа к
виду, удобному следующему шагу.

⚠ **Картинка едет переменной, то есть попадает в трассу прогона.** Кадр в 800
пикселей по длинной стороне — это ~70 КБ base64; кадр в 1600 — уже 367 КБ на
каждый вызов. Просить у вызывающего большой кадр незачем: модель всё равно
ужимает его до `AI_VISION_MAX_SIDE`.

⚠ **`data:`-URI обязателен.** Путь к файлу и ссылка не работают: vision-сервер
не имеет доступа к чужой файловой системе и сам за картинками не ходит
(`py_modules/docs/vision_llm.md`, §3).
"""

import json

from ai.vision.ai_vision_json import ai_vision_json

# Сколько знаков картинки пускать в сообщение об ошибке. Сам `data:`-URI в текст
# отказа не годится: сотня килобайт base64 в журнале прогона — это не причина
# отказа, а шум, за которым её не видно.
VISION_SHOW_MAX = 80


async def vision_describe(image: str, prompt: str, model_name: str = '') -> dict:
    """
    Описывает изображение и возвращает названные в просьбе поля как JSON.

    Применять, когда ответ модели о картинке нужен **данными**: описание и теги
    снимка, перечень найденного, замеры. Для свободного пересказа своими словами
    инструмент не нужен — это умеет обычный шаг с vision-моделью.

     - image: картинка как `data:`-URI (`data:image/jpeg;base64,...`). Путь к
       файлу или ссылка не работают: сервер за картинками не ходит.
     - prompt: о чём спрашиваем. **Перечисли нужные поля прямо в тексте** —
       не назовёшь, модель придумает свои, и каждый раз другие.
     - model_name: какой моделью смотреть. Называть не нужно: движок сам
       подставляет первую модель **этой ноды**, умеющую изображения.

    Returns:
        dict: Словарь с результатом, содержащий:
            ok (str): '1' — разобрано, '0' — не вышло.
            json (str): ответ модели как строка JSON, готовая к передаче дальше.
            error (str): причина неудачи словами; при удаче пусто.
    """
    picture = str(image or '').strip()
    if not picture.startswith('data:'):
        return {'ok': '0', 'json': '',
                'error': f'нужен data:-URI картинки, пришло: {picture[:VISION_SHOW_MAX]}'}

    # ⚠⚠ Модель называет нода, а не окружение. Пусто здесь значит, что у ноды
    # нет ни одной модели со зрением, — и это ответ человеку, а не повод взять
    # умолчание общего слоя. Прежде брали именно его (`AI_VISION_MODEL_NAME`,
    # иначе `gx10/qwen-large`), и на проде, где такой модели нет, 80 прогонов
    # подряд умерли на «All connection attempts failed» — при живой модели со
    # зрением в списке той же ноды.
    if not str(model_name or '').strip():
        return {'ok': '0', 'json': '',
                'error': 'у ноды агента нет модели со зрением: добавьте модель '
                         'с input_type «image» в её список'}

    try:
        got = await ai_vision_json(_bytes(picture), str(prompt or ''),
                                   model_name=str(model_name).strip())
    except (RuntimeError, ValueError) as err:
        # Ошибку возвращаем результатом, а не исключением: шаг workflow должен
        # дойти до конца и дать следующему шагу прочитать причину
        # (`tools.md`, §4, правило 9).
        return {'ok': '0', 'json': '', 'error': str(err)}

    return {'ok': '1', 'json': json.dumps(got, ensure_ascii=False), 'error': ''}


def _bytes(picture: str) -> bytes:
    """Байты из `data:`-URI.

    ⚠ Режем по первой запятой, а не по известной приставке: тип и кодировка в
    `data:` бывают разные (`image/png`, `image/jpeg`, иногда с `charset`), и
    зашитая приставка отвалилась бы на первом же непривычном.
    """
    import base64

    return base64.b64decode(picture.partition(',')[2])
