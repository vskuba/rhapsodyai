"""Жребий на стороне workflow: разнообразие, которое модель сама себе не даёт.

## ⚠⚠ Зачем инструмент, а не строчка в промпте

«Будь разной» модель не исполняет — это измеренный закон, а не осторожность. Три
шаблона инвайтов из трёх начинались с «you're trouble». Вилка «от абзаца до трёх»
дала девять писем из двенадцати ровно в три абзаца: верх вилки читается как цель.
Единственный пример в конце промпта работает выкройкой — пять писем прода из
восьми открывались его оборотом («вспомнила… как ты рассказывал»).

Вывод один и тот же каждый раз: **выбирать должен кто-то снаружи модели**. Раньше
выбирала панель и присылала готовое, но тогда каждая новая грань разнообразия
стоила четырёх мест — настройка в реестре, код панели, объявление переменной,
правка промпта. Здесь она стоит одного: жребий живёт рядом с промптом, который им
и пользуется.

## ⚠ Имена выходов — с приставкой `dice_`

Соглашение проекта, и оно про чтение, а не про порядок. Встретив в промпте
`%dice_mail_story%`, человек сразу знает: значение не прислали снаружи и не
придумала модель — его бросил шаг жребия, и настроено оно там же. Без приставки
переменная неотличима от входящей, и искать её начинают в панели, которая о ней
не знает.
"""
import json
import random
import re

# Сумма долей одной переменной. Больше сотни — ошибка описания, и тихо делить
# «как-нибудь» нельзя: человек задал доли, которые не значат того, что он думает.
DICE_PERCENT_TOTAL = 100

# Нераскрытая метка: `%имя%` там, где ждали число.
#
# ⚠⚠ Доля вправе приходить переменной — из настройки сайта, из входящей
# переменной workflow, — и подставляет её **движок**, до вызова инструмента
# (`ai_workflow_variables_render` правит метаданные шага целиком, вместе с
# `inputs_map`). Значит сюда доезжает уже значение. Метка, уцелевшая до этого
# места, значит одно: такой переменной в заходе нет.
#
# ⚠ Внутри метки допускаем **что угодно, кроме пробела и самого `%`**, а не
# только латиницу с подчёркиванием: имя с опечаткой на кириллице — ровно тот
# случай, ради которого это сообщение и написано. Узкое выражение отвечало бы на
# него общим «доля не число» и прятало причину.
DICE_MARK_RE = re.compile(r'^%[^%\s]+%$')

# Доля-«остаток»: всё, что не разобрали соседи по переменной.
#
# ⚠⚠ **Без неё доля из настройки сайта не выражается вовсе.** Пара «да/нет»
# требует, чтобы сумма укладывалась в сотню, а второй половины мы не знаем:
# напиши `{вопрос: %percent%, без вопроса: 75}` — и при настройке 40 выйдет 115,
# то есть отказ прямо на заходе. Считать дополнение в панели значило бы держать
# одну настройку в двух местах и ловить их расхождение уже по письмам.
#
# ⚠ «Остаток» на переменную один: два таких делили бы неизвестно как.
DICE_REST = 'rest'

# Потолок серии бросков (`times`). Пачка инвайтов — полтора десятка реплик, и
# полсотни хватает с запасом; число приходит из workflow-переменной, то есть
# от панели, и без потолка опечатка в ней уехала бы в промпт списком на тысячу
# строк.
DICE_TIMES_MAX = 50


# ⚠⚠ Доли можно задавать меткой — `"%favorite_mail_name_percent%"`. Значение
# приезжает из настройки сайта или входящей переменной, и подставляет его
# **движок**, до вызова инструмента: сюда доходит уже число. Так посайтовая
# настройка остаётся живой, а описание жребия лежит одним куском рядом с
# промптом, которым и пользуется. Сумму таких долей редактор проверить не
# может — их значения известны только в заходе; проверяет её инструмент.
#
# ⚠⚠ Недобор до ста — это «иногда ничего», и так задумано. `{"а": 30, "б": 30}`
# законно: в оставшихся 40% не выпадает ничего, переменная приходит пустой, и
# `[<if …>]` читает её как ложь. Так пишется «в 60% случаев добавь приём, иначе
# не добавляй» — без варианта-пустышки, который пришлось бы придумывать.
#
# ⚠ Перебор, наоборот, запрещён: при сумме 130 доли уже не проценты, и любое
# «умное» приведение соврало бы человеку о том, что он задал.
#
# ⚠ Докстринг ниже короткий намеренно: он уезжает в базу и показывается
# человеку в панели шага. Там нужно «что делает», а не рассуждение — его место
# здесь.
async def dice(spec: dict) -> dict:
    """
    Бросить жребий по каждой переменной и вернуть выпавшие значения.

    Одно решение на весь заход. Решение на каждую единицу пачки — `dice_batch`.

    Args:
        spec: переменные и их варианты с долями в процентах, например
            `{"mail_opening": {"вспомнила о тебе": 40, "новость про себя": 60}}`.
            Переменных хотя бы одна, вариантов у каждой хотя бы два. Доля бывает
            числом, меткой `"%имя%"` или словом `"rest"` — всё, что осталось от
            сотни. Недобрали до ста и «остатка» нет — в разнице не выпадает
            ничего, и переменная приходит пустой.

    Returns:
        dict: по выпавшему значению на переменную —
        `{"mail_opening": "вспомнила о тебе"}`. Каждый ключ движок положит и в
        `%dice_<шаг>_result_<ключ>%`, и в то имя, которое задано `outputs_map`.

    Raises:
        ValueError: описание негодное — пусто, один вариант, доли не числа или
            их сумма больше ста.
    """
    return {name: _roll(options) for name, options in _spec_read(spec).items()}


# ## ⚠⚠ Отдельная функция, а не флаг у `dice`
#
# Сперва это был довод `times` у самого `dice`, и ответ менял тип: один бросок —
# значение, больше — список. Так делать нельзя: функция с ветвлением по значению
# аргумента — это две функции под одним именем, и зовущий не может положиться на
# её ответ, не зная, что он передал.
#
# Цена не теоретическая. Флаг `[<if dice_invite_man_name>]` читает **любой
# непустой текст** как истину, и серия из одних нулей («1. 0\n2. 0\n3. 0»)
# включила бы тег имени во всех пачках, включая те, где жребий выпал «не надо».
# Ошибки при этом нет ни одной.
#
# ## ⚠ Список нумерован и отдаётся строкой
#
# Нумерован, потому что промпт обращается по номерам: «строка 3 — приёмом 3».
# Без номера модель сопоставляет их на глаз и сбивается уже на пятой.
#
# Строкой, а не массивом, потому что уезжает прямо в промпт: массив движок
# сериализовал бы в JSON, и модель читала бы скобки с кавычками вместо списка.
#
# ⚠⚠ Броски независимы, повторы законны: доли заданы человеком, и «без повторов»
# молча исказило бы их тем сильнее, чем длиннее серия. Промпт просит разные
# приёмы словами, а не подтасовкой жребия.
#
# ⚠ Докстринг ниже короткий намеренно: он уезжает в базу и показывается
# человеку в панели шага. Там нужно «что делает и чем отличается от соседа», а
# не история решения — её место здесь.
async def dice_batch(spec: dict, times: int) -> dict:
    """
    Бросить жребий `times` раз по каждой переменной — список на всю пачку.

    Одно решение на весь заход — `dice`; решение на каждую единицу пачки —
    `dice_batch`. Форма ответа и флаги бросаются первым, приём и длина каждой
    реплики — вторым.

    Args:
        spec: описание жребия — ровно такое же, как у `dice`.
        times: сколько бросков на переменную; меньше одного и мусор — один.

    Returns:
        dict: по НУМЕРОВАННОМУ СПИСКУ строкой на переменную —
        `{"mail_opening": "1. вспомнила о тебе\\n2. новость про себя"}`.

    Пример:
        await dice_batch('{"angle": {"игра": 50, "вызов": 50}}', 3)
        # {"angle": "1. вызов\\n2. игра\\n3. игра"}
    """
    # ⚠ Число приходит workflow-переменной, то есть строкой, и бывает пустым:
    # `%invite_count%` у пакета из одной реплики доезжает как «1», а у шага без
    # этого входа — как None. Приведение по аннотации делает движок, но
    # инструмент зовут и из кода.
    try:
        rolls = int(times or 1)
    except (TypeError, ValueError):
        rolls = 1

    rolls = max(1, min(rolls, DICE_TIMES_MAX))

    return {
        name: '\n'.join(f'{number}. {_roll(options)}'
                        for number in range(1, rolls + 1))
        for name, options in _spec_read(spec).items()
    }


def _spec_read(spec) -> dict:
    """Разобрать описание жребия и проверить его целиком.

    ⚠ Проверяем **до** первого броска, а не по ходу: иначе половина переменных
    выпадет, а на кривой описание упадёт — и шаг оставит после себя полработы.
    """
    if isinstance(spec, str):
        try:
            spec = json.loads(spec) if spec.strip() else {}
        except (ValueError, TypeError):
            raise ValueError('описание жребия не разбирается как JSON')

    if not isinstance(spec, dict) or not spec:
        raise ValueError('нужна хотя бы одна переменная: {"имя": {"вариант": доля}}')

    out = {}

    for name, options in spec.items():
        title = str(name).strip()
        if not title:
            raise ValueError('у переменной пустое имя')
        out[title] = _options_read(title, options)

    return out


def _options_read(name: str, options) -> dict:
    """Варианты одной переменной: вариант → доля."""
    if isinstance(options, str):
        try:
            options = json.loads(options)
        except (ValueError, TypeError):
            raise ValueError(f'«{name}»: варианты не разбираются как JSON')

    if not isinstance(options, dict):
        raise ValueError(f'«{name}»: нужен объект «вариант: доля»')

    if len(options) < 2:
        raise ValueError(f'«{name}»: вариантов должно быть хотя бы два,'
                         f' иначе это не жребий, а постоянное значение')

    out, total, rest = {}, 0.0, ''

    for value, share in options.items():
        title = str(value)

        if _is_rest(share):
            if rest:
                raise ValueError(f'«{name}»: «{DICE_REST}» может быть только у'
                                 f' одного варианта — два делили бы остаток'
                                 f' неизвестно как')
            # ⚠ Место занимаем сразу, значение кладём после: порядок вариантов
            # решает, какой из них достанется броску, и «остаток» обязан стоять
            # там, где его записал человек, а не последним.
            rest, out[title] = title, 0.0
            continue

        percent = _percent_read(name, title, share)
        out[title] = percent
        total += percent

    if total > DICE_PERCENT_TOTAL:
        raise ValueError(f'«{name}»: доли в сумме дают {total:g}%,'
                         f' а больше {DICE_PERCENT_TOTAL} быть не может')

    if rest:
        out[rest] = DICE_PERCENT_TOTAL - total

    return out


def _is_rest(share) -> bool:
    """Доля-«остаток» ли это.

    ⚠ Сравниваем без учёта регистра и пробелов: значение приходит из формы
    редактора, а «Rest» с заглавной — обычная человеческая описка, и отвечать на
    неё отказом «доля не число» значило бы прятать причину.
    """
    return isinstance(share, str) and share.strip().lower() == DICE_REST


def _percent_read(name: str, value: str, share) -> float:
    """Доля одного варианта числом — своя или приехавшая переменной.

    ⚠⚠ **Пусто — это ноль, а не отказ.** Доля приходит и из настройки сайта, а
    незаполненная настройка значит «этот вариант не выпадает». Ронять из-за неё
    весь заход нельзя: письмо не ушло бы вовсе из-за необязательной настройки.

    Молчаливого искажения тут нет, и это свойство самого устройства: доли
    независимы, и обнулённый вариант **не меняет шансов остальных** — он лишь
    прибавляет к недобору, то есть к «не выпало ничего».

    ⚠ Нераскрытая метка — наоборот, отказ: `%имя%` в этом месте значит, что
    переменной в заходе нет вовсе. Это опечатка в описании либо забытое
    объявление, и оба чинятся, а не обходятся.

    ⚠ Хвост `%` принимается: человек, задающий проценты, пишет «40%» чаще, чем
    «40», и спорить с этим дороже, чем отрезать знак.
    """
    if share is None:
        return 0.0

    if isinstance(share, bool):
        raise ValueError(f'«{name}» → «{value}»: доля не число ({share!r})')

    if isinstance(share, (int, float)):
        percent = float(share)
    else:
        text = str(share).strip().rstrip('%').strip()

        if not text:
            return 0.0

        if DICE_MARK_RE.match(str(share).strip()):
            raise ValueError(
                f'«{name}» → «{value}»: переменная {share} не доехала —'
                f' её нет среди переменных захода')

        try:
            percent = float(text)
        except ValueError:
            raise ValueError(f'«{name}» → «{value}»: доля не число ({share!r})')

    if percent < 0:
        raise ValueError(f'«{name}» → «{value}»: доля отрицательная')

    return percent


def _roll(options: dict) -> str:
    """Один бросок: вариант по его доле либо пустая строка на недоборе.

    ⚠ Бросаем **одно** число на всю переменную и идём по накопленной доле — так
    вероятность каждого варианта ровно та, что задана. Перебор вариантов с
    отдельным броском на каждый дал бы совсем другое распределение: у первого в
    списке шанс был бы его собственный, у последнего — сильно меньше заданного.
    """
    edge = random.uniform(0, DICE_PERCENT_TOTAL)
    seen = 0.0

    for value, percent in options.items():
        seen += percent
        if edge < seen:
            return value

    return ''
