"""Решения прогона, не вошедшие в текст: ключ и значение в ответ `/chat/ask`.

Ответ ручки нёс три вещи: текст, номер обмена и намерения — то есть *что
сказали* и *что пообещали*. Но прогон принимает и другие решения, о которых
текст молчит: прикладывать ли к письму снимок, сколько их, задавать ли личный
вопрос. Вызывающему их было не узнать ничем.

⚠⚠ **Решает это workflow, а не вызывающий, и в этом вся соль.** Жребий жил в
двух местах разом — доля в настройке панели и доля в шаге `dice` у нас, — и
доли складывались: приём «писать первой неловко» выпадал девяти заготовкам из
двадцати при ожидаемых четырёх. Цена размена измерена, и решение принято:
жребий живёт **здесь**, а панель читает его исход.

## Как пользоваться

Шагом `tool_invoke` после жребия:

    chat_response_extra_set(key='img_attach', value='%dice_img_attach%')

Ответ ручки получит:

    {"result": "…", "message_id": 42, "intentions": {}, "extra": {"img_attach": "1"}}

## ⚠ Ключи свободные, как и форма контекста намерения

Закрой мы набор — каждое новое решение требовало бы правки инструмента, то
есть выкладки ради того, что должно задаваться в workflow. Цена названа:
опечатка в имени ключа (`img_attah`) отсюда не видна и всплывёт на стороне,
которая его читает, — молча, выключив занятие. Поэтому читающий обязан
смотреть на **своё** имя и не падать, не найдя его.

## ⚠⚠ Побеждает последний вызов, а не первый

У намерения контекст **складывается**: подпоток собирает его по частям. Здесь
наоборот — два вызова с одним ключом значат, что ветка workflow переменила
решение, и взять надо последнее. Сложи мы их, переменить решение было бы
нечем.

## ⚠ Значение уезжает строкой, а приводит его читающий

Шаг жребия отдаёт текст (`'1'`, `'0'`), и приводить его к числу здесь значило
бы решать за вызывающего, что это число. Сегодня `img_attach` — «да/нет»,
завтра «сколько снимков»: форма значения принадлежит той стороне, которая по
нему работает.
"""

# Предел длины ключа, знаков. Ключ — имя решения (`img_attach`), а не его
# описание: длинное означает, что в него пишут фразу, и сопоставить такое на
# другой стороне не с чем.
#
# ⚠ Тот же предел и по той же причине, что у метки намерения.
CHAT_EXTRA_KEY_MAX = 100

# Предел длины значения, знаков. Значение — число или короткое слово; текст
# ответа едет своей дорогой (`result`), и дублировать его здесь незачем.
CHAT_EXTRA_VALUE_MAX = 500


async def chat_response_extra_set(key: str, value=None) -> dict:
    """Положить решение прогона — оно уедет в ответ `/chat/ask` в `extra`.

    Args:
        key: имя решения (`img_attach`). Пусто — класть не под что.
        value: само решение. Число, строка, пустое — всё законно: что с ним
            делать, знает читающая сторона.

    Returns:
        dict: `key` — под какое имя легло (пусто — не легло), `value` — что
        легло, `saved` — легло ли (1/0), `why` — причина отказа словами.

    ⚠ Ответ отдаётся **полями, а не одним значением**: его читает движок по
    имени инструмента (`ai_framework_manager.py`), и ему нужны оба — имя и
    значение.

    ⚠ Отказ не бросается исключением: шаг жребия мог отдать пустоту, и ронять
    из-за этого весь прогон незачем. Причина едет словами и видна в журнале
    шага.
    """
    said = str(key or '').strip()

    if not said:
        return {'key': '', 'value': '', 'saved': 0,
                'why': 'ключ не назван: класть не под что'}

    if len(said) > CHAT_EXTRA_KEY_MAX:
        return {'key': '', 'value': '', 'saved': 0,
                'why': f'ключ длиннее {CHAT_EXTRA_KEY_MAX} знаков: '
                       'это имя решения, а не его описание'}

    # ⚠ `None` ложится пустой строкой, а не теряется: «шаг отработал, а решения
    # нет» — законный исход, и отличать его от «ключа не было» читающей стороне
    # незачем.
    said_value = '' if value is None else str(value)

    if len(said_value) > CHAT_EXTRA_VALUE_MAX:
        return {'key': said, 'value': '', 'saved': 0,
                'why': f'значение длиннее {CHAT_EXTRA_VALUE_MAX} знаков: '
                       'текст ответа едет своей дорогой'}

    return {'key': said, 'value': said_value, 'saved': 1, 'why': ''}
