"""Намерения прогона: что агент пометил словом, чтобы это уехало вызывающему.

Ответ `/chat/ask` до этого нёс только текст и номер обмена — то есть *что
сказали*. А решения, принятые по ходу разговора, оставались внутри прогона:
«она обещала прислать фото», «он просил не писать до вечера». Вызывающему их
было не узнать ничем, кроме разбора текста ответа своими силами.

Инструмент даёт workflow положить такую пометку словом, а ручке — отдать их
списком.

## ⚠⚠ Две дороги у одного намерения, и обе нужны

**В ответ прогона** — накопитель на модели (`model.chat_intentions`), куда
кладёт движок по ответу этого инструмента. Своего хранилища на процесс здесь
нет и быть не может: инструменту не передают ни модель, ни сессию, а словарь по
`session_uuid` означал бы вторую жизнь накопителя мимо прогона — с утечкой
между запросами и чисткой, которую некому позвать.

**В разговор** — строка с отметкой времени (`companion_intention`), и она
решает другую задачу: отличить новое обещание от уже найденного. История
накапливается, и без отметки одно обещание уезжало бы на каждом ответе, пока
реплика не выпадет из окна. Подробности — `companion_intention.py`.

⚠ Вторая дорога включается, только если шаг назвал пару разговора. Это не
«необязательная мелочь»: без неё дедупликация между прогонами не работает.

## ⚠ Почему ответ читает движок, а не `outputs_map` шага

Та дорога уже ломалась молча: редактор workflow пишет `outputs_map` пустым
безусловно, и первое сохранение шага человеком стирает псевдоним. Счёт —
в `ai_framework_manager.py` у `AI_FRAMEWORK_SESSION_TOOL`, там же разобрано,
почему не годится и чтение склеенного имени переменной.
"""

# Предел длины намерения, знаков. Намерение — метка словом (`she_promised_send_photo`),
# а не текст: длинное означает, что в него пишут пересказ разговора, и такую метку
# на другой стороне не сопоставить ни с чем.
CHAT_INTENTION_LENGTH_MAX = 100


async def chat_intention_add(intention: str, owner_unique_id: str = '',
                             companion_unique_id: str = '') -> dict:
    """Запомнить намерение этого прогона — оно уедет в ответ `/chat/ask`.

    Args:
        intention: намерение одним словом-меткой, вида
            `she_promised_send_photo`. Пусто — нечего запоминать.
        owner_unique_id: ключ нашей стороны разговора. Пусто — намерение уедет
            в ответ, но в разговоре не запомнится (см. ⚠⚠ ниже).
        companion_unique_id: ключ той стороны.

    Returns:
        dict: `intention` — принятое намерение (пусто, если не приняли),
        `saved` — приняли ли (1/0), `at` — отметка времени записи в разговоре
        (пусто, если пару не назвали), `why` — причина отказа словами.

    ## ⚠⚠ Пара названа — намерение попадает в разговор, и это важнее выдачи

    Отметка времени (`companion_intention`) — то, чем следующий прогон отличит
    **новое** обещание от уже найденного: история режется ею надвое, и модель
    ищет новое только в свежей половине. Не назови пару — выдача сработает
    один раз, а на следующем ответе то же обещание приедет снова.

    ⚠ Пара необязательна намеренно: инструмент зовут и там, где разговора нет
    (пробный прогон, чужой workflow). Молчаливой потери при этом не выйдет —
    пустой `at` в ответе виден и в трассе шага.

    ## ⚠ Повтор в одном прогоне безопасен

    Одно и то же намерение, положенное дважды, в ответе окажется один раз:
    отсев повторов делает накопитель движка. Шаг может стоять внутри
    `repeat`-цикла или подпотока, который зовут по разу на тему.

    ⚠⚠ А вот в **разных** прогонах повтор законен и отсеиваться не должен:
    обещание, данное снова через две реплики, — новое намерение. Поэтому запись
    в разговор повтора не проверяет: там каждая находка своя строка.
    """
    said = str(intention or '').strip()

    if not said:
        return {'intention': '', 'saved': 0, 'at': '', 'why': 'намерение пустое'}

    if len(said) > CHAT_INTENTION_LENGTH_MAX:
        return {'intention': '', 'saved': 0, 'at': '',
                'why': (f'намерение длиннее {CHAT_INTENTION_LENGTH_MAX} знаков '
                        f'({len(said)}): нужна метка словом, а не пересказ')}

    kept = {'id': 0, 'at': '', 'why': ''}

    if str(owner_unique_id or '').strip() and str(companion_unique_id or '').strip():
        from src.tool.companion.companion_intention import companion_intention_add

        kept = await companion_intention_add(owner_unique_id, companion_unique_id, said)

    return {'intention': said, 'saved': 1, 'at': kept.get('at') or '',
            'why': kept.get('why') or ''}
