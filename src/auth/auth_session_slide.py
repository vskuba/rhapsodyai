"""Скользящее окно сессии админки: срок считается от последнего запроса.

`SessionMiddleware` Starlette отдаёт куку один раз — на входе, — и окно выходит
фиксированным: срок с момента входа, сколько бы человек ни работал. Кончалось
оно посреди работы, и выглядело это не как «сессия истекла», а как поломка
сервера: страница админки остаётся открытой (её маршрут проверяет вход только при
переходе), а запросы к API начинают отвечать 401 — панели молча пустеют. Дважды
приняли за отказ базы.

## Как продлевается

Starlette переустанавливает куку, только если сессия **изменилась**
(`Session.modified`). Значит достаточно что-нибудь в неё записать — и на ответе
уедет свежий `Set-Cookie` с новым `Max-Age` и новой подписью, от которой и
считается срок.

⚠ **Версия Starlette тут важна.** В 1.6.0 (она в контейнере) условие
`if session.modified and session`; в старых (0.52.1) — просто
`if scope["session"]`, то есть кука уходит на каждом ответе и так. Приём с
записью верен для обеих: лишняя метка старой версии не мешает.

## ⚠ Почему метка огрублена, а не «просто время»

Присваивание помечает сессию изменённой **всегда**, даже тем же значением. Пиши
мы точное время — `Set-Cookie` уходил бы с каждым ответом, включая каждую
картинку и каждый файл статики: лишние сотни байт на запрос и лишняя подпись на
каждый чих.

С огрублением до `AUTH_SESSION_SLIDE_STEP` кука обновляется не чаще раза в шаг, а
окно всё равно скользит: любой запрос внутри шага продлевает срок до конца
следующего. Цена — окно «дребезжит» на величину шага, что при сроке в часы
роли не играет.
"""

import time

# Насколько часто обновляем куку, секунды. Минута ничего не меняет по сути (окно
# и так в часах), а число ответов с `Set-Cookie` уменьшает на порядки.
AUTH_SESSION_SLIDE_STEP = 60

# Ключ метки в сессии. С подчёркиванием — чтобы не спутали с полями входа
# (`user_id`, `username`, `role`), которые кладёт `/auth/login`.
AUTH_SESSION_SLIDE_KEY = '_seen'


def auth_session_slide_touch(session, now: float | None = None) -> bool:
    """Отмечает активность в сессии, продлевая её срок. Возвращает — обновилась ли кука.

    Args:
        session: словарь сессии (`request.session`).
        now: момент отсчёта, секунды эпохи. Пусто — текущее время. Нужен тестам:
            иначе проверка скольжения ждала бы целый шаг.

    Returns:
        bool: `True` — метка изменилась, и Starlette пришлёт свежий `Set-Cookie`;
        `False` — обновлять нечего.

    ⚠ **Пустую сессию не трогает.** Запись в неё завела бы куку анониму — каждому,
    кто открыл страницу входа или дёрнул ручку без авторизации.

    ⚠ Признак входа — `user_id`, а не сам факт непустого словаря: в сессии может
    лежать что-то служебное и без авторизации.
    """
    if not isinstance(session, dict) or not session.get('user_id'):
        return False

    seen = int(now if now is not None else time.time()) // AUTH_SESSION_SLIDE_STEP
    if session.get(AUTH_SESSION_SLIDE_KEY) == seen:
        return False

    session[AUTH_SESSION_SLIDE_KEY] = seen
    return True
