async def seed(force: bool = False) -> None:
    await mysql_pool_get()

    async with mysql_get_db_async() as db:
        await db.execute("SELECT id FROM node WHERE name = %s", (BLOG_NODE,))
        row = await db.fetchone()
        if row:
            node_id = int(row["id"])
        else:
            await db.execute("INSERT INTO node (name) VALUES (%s)", (BLOG_NODE,))
            node_id = int(db.lastrowid)
            print(f"  нода {BLOG_NODE} заведена: #{node_id}")

        for item in BLOG_AGENTS:
            await _one(db, node_id, item, force)


async def _one(db, node_id: int, item: dict, force: bool) -> None:
    name = item["name"]
    wf_name = item["wf"]

    await db.execute("SELECT id FROM agent_workflow WHERE name = %s", (wf_name,))
    row = await db.fetchone()
    if row:
        wf_id = int(row["id"])
    else:
        await db.execute("INSERT INTO agent_workflow (name) VALUES (%s)", (wf_name,))
        wf_id = int(db.lastrowid)

    await db.execute("SELECT COUNT(*) AS n FROM agent_workflow_step WHERE workflow_id = %s",
                     (wf_id,))
    if int((await db.fetchone())["n"]) == 0:
        for step in item["steps"]:
            await db.execute(
                "INSERT INTO agent_workflow_step (workflow_id, type_id, title, position, metadata) "
                "VALUES (%s, %s, %s, %s, %s)",
                (wf_id, int(step["type_id"]), step["title"], int(step["position"]),
                 step["metadata"] if isinstance(step["metadata"], str)
                 else json.dumps(step["metadata"], ensure_ascii=False)))

    await db.execute("SELECT id FROM agent WHERE name = %s", (name,))
    row = await db.fetchone()
    if row:
        if force:
            await db.execute("UPDATE agent SET prompt_system = %s, title = %s, description = %s "
                             "WHERE id = %s",
                             (item["prompt_system"], item["title"], item["description"],
                              int(row["id"])))
            print(f"  {name}: промпт обновлён (--force)")
        else:
            print(f"  {name}: уже есть, не трогаю")
        return

    await db.execute(
        "INSERT INTO agent (node_id, name, title, description, workflow_id, prompt_system, "
        "position, group_name, dynamic) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, 0)",
        (node_id, name, item["title"], item["description"], wf_id, item["prompt_system"],
         int(item["position"]), item["group_name"]))
    print(f"  {name}: заведён (#{db.lastrowid}, workflow #{wf_id})")


if __name__ == "__main__":
    asyncio.run(seed("--force" in sys.argv))
