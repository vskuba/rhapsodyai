-- Чем именно QA пишет данные в базу (workflow #57)
--
-- Зачем вручную: правка данных (`agent_workflow_step`.`metadata`), а не схемы.
--
-- Что было: `2026-08-14_wf57_qa_test_data_insert.sql` потребовал заводить данные
-- «прямым INSERT», не сказав чем. Прогон проверок на #562 показал, почему это тупик:
-- в отчёте QA стоит «MySQL CLI недоступен» — клиента в окружении агента нет. Он ушёл
-- в API приложения, создал два проекта, и следом поднялись прогоны workflow #19
-- «Анализ идеи» — ровно то, что правило и должно было предотвратить.
--
-- Что делаем: называем инструмент, который в чекаутe ветки есть всегда, — `mysql_` из
-- `py_modules` под `.venv/bin/python3`. Ссылаемся на `tests/conftest.py`: там уже решён
-- вопрос адреса (с хоста база видна не как `mysql`, а как `localhost:3302`), и агенту
-- не нужно это выводить заново.
--
-- Идемпотентность: REPLACE ищет формулировку предыдущей миграции. Повторный прогон её
-- не найдёт. Прогонять после `2026-08-14_wf57_qa_test_data_insert.sql`.
--
-- На проде перед прогоном снять свежий бэкап через /admin/backup.

-- ─── До: строки, которые тронем ───────────────────────────────────────────────
SELECT `id`, `workflow_id`, `position`, `title`
FROM `agent_workflow_step`
WHERE `id` IN (447, 516);

-- ─── Инструмент записи в базу (оба промпта QA) ────────────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    '- Нет данных под сценарий — заведи их сам, прямым INSERT в базу проекта. Через\\n  интерфейс — только если проверяешь сам интерфейс:',
    '- Нет данных под сценарий — заведи их сам, записью прямо в базу. Клиента `mysql` в\\n  окружении нет, пиши из чекаута ветки скриптом на `.venv/bin/python3` с\\n  `mysql_.mysql_` — как это делает `tests/conftest.py`, там же решён вопрос адреса\\n  базы с хоста. Через интерфейс или API приложения — только если проверяешь сам\\n  интерфейс:')
WHERE `id` IN (447, 516);

-- ─── После: проверить, что правило на месте ───────────────────────────────────
SELECT `id`,
       `metadata` LIKE '%Клиента `mysql` в%' AS `has_rule`
FROM `agent_workflow_step`
WHERE `id` IN (447, 516);
