-- QA гоняет сюиту против сервера ветки, а не против общего :8011 (workflow #57)
--
-- Зачем вручную: правка данных (`agent_workflow_step`.`metadata`), а не схемы.
--
-- Что было: промпт велит проверять фоновую логику «прогоном существующих тестов
-- проекта из tests/», но не говорит, куда эти тесты стучатся. На подзадаче #562 QA
-- запустил `tests/test_team_task_pages.py`, получил 13 ошибок ConnectError и записал
-- в отчёт: «BASE_URL захардкожен на localhost:8011, сервер задачи на :8013 — тесты не
-- выполнены». То есть проверка фоновой логики просто выпала из круга.
--
-- Что делаем: называем команду. Сюита теперь читает адрес из переменной `BASE_URL`
-- (`tests/conftest.py` и тестовые модули), поэтому прогон против сервера ветки — это
-- одна переменная перед `pytest`. Без этой строки агент видит захардкоженный адрес в
-- исходнике и делает верный вывод, что прогон невозможен.
--
-- Заодно просим короткий ответ по цели: ход `QA: проверка цели` вернул на #562
-- markdown с заголовками и разделами на 1300 символов там, где нужен вердикт по одной
-- цели, — а ответ уходит дальше в вердикт.
--
-- Идемпотентность: REPLACE ищет исходную формулировку. Повторный прогон её уже не
-- найдёт и ничего не изменит.
--
-- На проде перед прогоном снять свежий бэкап через /admin/backup.

-- ─── До: строки, которые тронем ───────────────────────────────────────────────
SELECT `id`, `workflow_id`, `position`, `title`
FROM `agent_workflow_step`
WHERE `id` IN (447, 516);

-- ─── Прогон сюиты против сервера ветки (оба промпта QA) ───────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    '- Фоновая логика — прогон существующих тестов проекта из tests/.',
    '- Фоновая логика — прогон существующих тестов проекта из tests/. Адрес сервера\\n  сюита берёт из переменной окружения, поэтому гони её на сервер ветки:\\n  BASE_URL=%subtask_server_url% .venv/bin/python3 -m pytest tests/<файл> -q')
WHERE `id` IN (447, 516);

-- ─── #57 Промпт: проверка цели — короткий вердикт ─────────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    'Отвечай обычным текстом: что сделал, что увидел, закрыта цель или нет.',
    'Отвечай обычным текстом, не длиннее 6 строк: что запустил, что увидел, закрыта\\nцель или нет. Без заголовков, таблиц и значков — этот ответ уходит в вердикт.')
WHERE `id` = 516;

-- ─── После: проверить, что правила на месте ───────────────────────────────────
SELECT `id`,
       `metadata` LIKE '%BASE_URL=%'            AS `has_base_url`,
       `metadata` LIKE '%не длиннее 6 строк%'   AS `has_short_goal`
FROM `agent_workflow_step`
WHERE `id` IN (447, 516);
