-- Цели только из текста задачи, без додуманной техники (workflow #55)
--
-- Зачем вручную: правка данных (`agent_workflow_step`.`metadata`), а не схемы.
--
-- Что было: задача #560 сформулирована человеком в одну строку — «на странице
-- „Команда“ отображать проекты, отсортированные по полю position». Менеджер выдал
-- четыре цели: сортировка по position (эта из задачи), порядок по id при равных
-- position, положение блока «Без проекта», стабильность порядка при перезагрузке.
-- Три из четырёх человек не заказывал.
--
-- Цена этого не в лишней строке списка. Каждую цель QA обязан закрыть
-- воспроизведением, и цель «равные position → порядок по id» встала: в базе двух
-- проектов с одинаковым position нет, воспроизвести нечем. Движок увидел незакрытую
-- цель и вернул подзадачу разработчику — на второй круг разработки и проверки из-за
-- требования, которого в задаче не было.
--
-- Что делаем: правило «цели — про то, что просил заказчик» уже есть, но оно не
-- срабатывает: модель считает техническое усиление частью той же просьбы. Называем
-- вслух, что именно не цель — крайние случаи, равные значения, устойчивость, соседние
-- элементы, — и куда это девать: в план, а не в критерии приёмки.
--
-- Идемпотентность: REPLACE ищет исходную формулировку. Повторный прогон её уже не
-- найдёт и ничего не изменит.
--
-- На проде перед прогоном снять свежий бэкап через /admin/backup.

-- ─── До: строка, которую тронем ───────────────────────────────────────────────
SELECT `id`, `workflow_id`, `position`, `title`
FROM `agent_workflow_step`
WHERE `id` = 412;

-- ─── #55 Промпт: цели ─────────────────────────────────────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    '- Цели — про то, что просил заказчик. Своих требований не добавляй: их никто не\\n  заказывал, а проверять и чинить их придётся наравне с настоящими.',
    '- Цели — про то, что просил заказчик. Своих требований не добавляй: их никто не\\n  заказывал, а проверять и чинить их придётся наравне с настоящими.\\n- Техническое усиление, которого в задаче нет, целью не становится: поведение при\\n  равных значениях, крайние случаи, устойчивость после перезагрузки, соседние\\n  элементы страницы. Считаешь это важным — напиши в плане, но не в целях: каждую\\n  цель QA обязан закрыть воспроизведением, а нечего воспроизводить — подзадача\\n  уйдёт на новый круг разработки из-за требования, которого никто не ставил.')
WHERE `id` = 412;

