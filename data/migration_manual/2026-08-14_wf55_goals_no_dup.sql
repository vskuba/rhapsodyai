-- Цели без дублей: правила в промптах менеджера (workflow #55)
--
-- Зачем вручную: правка данных (`agent_workflow_step`.`metadata`), а не схемы.
--
-- Что было: у задачи #462 менеджер выдал две цели, различающиеся только местом
-- проверки — «панель раскрывается и схлопывается» на вкладке Блоки/Виджеты и она же
-- на вкладке Страницы. Формально дублем это не было (строки разные), и правило
-- «дублей нет» LLM не нарушила; на деле человек видит две галочки об одном, а QA
-- гоняет отдельный круг проверки на каждую.
--
-- Что делаем: в шаге «Промпт: цели» (id 412) и в шаге «Промпт: судья целей» (id 416)
-- проговариваем, что близкие формулировки — это один дубль, и его надо схлопнуть в
-- одну цель. Код страхует то же самое независимо от LLM: `task_plan_goals_normalize`
-- сверяет цели по нормализованному тексту с порогом `TASK_PLAN_GOAL_SIMILAR_RATIO`.
--
-- Идемпотентность: REPLACE ищет исходную формулировку. Повторный прогон её уже не
-- найдёт и ничего не изменит.
--
-- На проде перед прогоном снять свежий бэкап через /admin/backup.

-- ─── До: строки, которые тронем ───────────────────────────────────────────────
SELECT `id`, `workflow_id`, `position`, `title`
FROM `agent_workflow_step`
WHERE `id` IN (412, 416);

-- ─── Промпт: цели ─────────────────────────────────────────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    '- Обязательно минимум 1 цель, всего 2-7, дублей нет.',
    '- Обязательно минимум 1 цель, всего 2-7.\\n- Дублей нет. Две цели, различающиеся только местом проверки или порядком слов, — это одна цель: объедини их в одну формулировку, места перечисли внутри неё.\\n- Если две цели закрываются одной проверкой, оставь одну.')
WHERE `id` = 412;

-- ─── Промпт: судья целей ──────────────────────────────────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    '1. Целей 2-7, дублей нет, каждая — одна строка без нумерации.',
    '1. Целей 2-7, каждая — одна строка без нумерации. Дублем считается и пара целей, различающихся только местом проверки или порядком слов, — такие надо объединить.')
WHERE `id` = 416;

-- ─── После: проверить, что правила на месте ───────────────────────────────────
SELECT `id`,
       `metadata` LIKE '%Дублей нет%'   AS `has_rule_412`,
       `metadata` LIKE '%Дублем считается%' AS `has_rule_416`
FROM `agent_workflow_step`
WHERE `id` IN (412, 416);
