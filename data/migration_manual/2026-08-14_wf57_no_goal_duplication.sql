-- Прогон проверок не закрывает цели — их закрывает цикл по целям (workflow #57)
--
-- Зачем вручную: правка данных (`agent_workflow_step`.`metadata`), а не схемы.
--
-- Что было: в прогоне 446 (подзадача #562) шаг «QA: прогон проверок» занял 617 секунд
-- из 1111 всего прогона — больше половины. Его ответ заканчивается словами «Обе цели
-- подзадачи закрыты»: агент завёл тестовые проекты, воспроизвёл обе цели, прибрал за
-- собой. После чего движок пошёл штатным циклом и спросил те же цели по одной — и
-- агент воспроизвёл их заново, снова заведя проекты. Двойная работа стоила не только
-- времени: созданные во второй раз проекты подняли прогоны workflow #19 и #20
-- (447–454), а один из них ещё и упал.
--
-- Почему так вышло: цели подставлены в промпт прогона как контекст, а рядом сказано
-- «поведение доказывается воспроизведением». Модель прочла это как задание, и по
-- букве она права — ей никто не сказал, что цели спросят отдельно.
--
-- Что делаем: разделяем ходы по предмету. Прогон проверок — общая приёмка: изменения
-- отвечают плану, лишнего не внесено, существующий набор тестов проходит, побочных
-- эффектов нет. Доказательство целей — только в ходе по цели, где ответ и так
-- укладывается в 50–80 секунд против 617.
--
-- Цели из промпта не убираем: по ним видно, что вообще проверяется, и без них приёмка
-- слепая. Меняется не состав контекста, а что с ним делать.
--
-- Идемпотентность: REPLACE ищет заголовок «Правила прогона», который есть только в
-- шаге 447 (в 516 его нет — проверено). Повторный прогон вставит блок второй раз,
-- поэтому условие сверху отсекает уже обработанную строку.
--
-- На проде перед прогоном снять свежий бэкап через /admin/backup.

-- ─── До: строка, которую тронем ───────────────────────────────────────────────
SELECT `id`, `workflow_id`, `position`, `title`
FROM `agent_workflow_step`
WHERE `id` = 447;

-- ─── #57 Промпт: прогон проверок — границы хода ───────────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    'Правила прогона, они не обсуждаются:',
    'Границы этого хода:\\n- Цели подзадачи здесь не закрываешь. Каждую из них я спрошу отдельным ходом, по\\n  одной, и доказательство попрошу там же. Здесь выше они даны как контекст — чтобы\\n  ты понимал, вокруг чего изменения, а не как список к исполнению.\\n- Твоё дело на этом ходе — общая приёмка: изменения отвечают плану, лишнего в них\\n  нет, существующий набор тестов проходит, побочных эффектов у соседнего поведения\\n  не видно.\\n- Воспроизводить цели сейчас — двойная работа: ход уйдёт на то, что через минуту\\n  придётся повторить поимённо. Тестовые данные под цель заводятся тоже там.\\n\\nПравила прогона, они не обсуждаются:')
WHERE `id` = 447
  AND `metadata` NOT LIKE '%Границы этого хода%';

-- ─── После: проверить, что правило на месте и ровно в одном экземпляре ────────
SELECT `id`,
       `metadata` LIKE '%Границы этого хода%' AS `has_rule`,
       (CHAR_LENGTH(`metadata`) - CHAR_LENGTH(REPLACE(`metadata`, 'Границы этого хода', ''))) / 18 AS `cnt`
FROM `agent_workflow_step`
WHERE `id` = 447;
