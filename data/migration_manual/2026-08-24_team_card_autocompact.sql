-- `--autocompact 115k` в команду запуска уже заведённых карточек команды
--
-- Зачем вручную: правка данных, а не схемы. `TEAM_MEMBER_ROLE_CARD`
-- (`src/project/team/team_member.py`) — заготовка для **новых** проектов, её читает
-- только `team_member_cards_ensure()` при создании проекта. Существующие строки
-- `project_team` она не трогает, и seed их тоже не обновит: он применяется через
-- `INSERT IGNORE` (см. `seed.md`).
--
-- Что чиним. Подзадачи одной задачи идут в общем контексте shell-оболочки —
-- `task_agent_developer` перезапускает её только на смене задачи, — и разговор растёт
-- от круга к кругу. Окно модели GX10 — 131072 токена. По задаче #895 счётчик рос
-- 134k → 139k → 145k → 150k → 155k → 161k, и каждый прогон после потолка возвращал
-- `exceed_context_size_error` вместо работы. Автокомпакт на 115k сжимает разговор
-- заранее, оставляя запас под ответ.
--
-- Значение разбирает `set_autocompact()` в отдельном репозитории `claude-shell`
-- (`shell.py`): принимает `auto` или число токенов, суффикс `k` понимает.
--
-- Правка дополняющая: команда на карточке — поле, которое правит человек, поэтому
-- дописываем флаг в хвост, а не перезаписываем строку целиком. Прогон идемпотентен —
-- строки с уже дописанным флагом отбор пропускает. Обратная правка: убрать из
-- `command` подстроку ' --autocompact 115k'.
--
-- Отбираем через INSTR, а не LIKE: в LIKE `_` значит любой один символ, и шаблон
-- вида '%claude-shell%' пришлось бы экранировать при каждом изменении. У INSTR
-- подстрока сравнивается как есть.
--
-- Проверено локально: снял флаг со всех восьми карточек, прогнал этот файл, получил
-- те же значения, что записывал ручной UPDATE; повторный прогон данных не изменил.

-- ─── До: какие карточки поменяются ────────────────────────────────────────────
SELECT `t`.`id`, `t`.`project_id`, `p`.`title` AS `project`, `t`.`role`, `t`.`command`,
       INSTR(`t`.`command`, '--autocompact') = 0 AS `will_change`
FROM `project_team` `t`
         LEFT JOIN `project` `p` ON `p`.`id` = `t`.`project_id`
WHERE INSTR(`t`.`command`, 'claude-shell') > 0
ORDER BY `t`.`project_id`, `t`.`id`;

-- ─── Правка ───────────────────────────────────────────────────────────────────
-- TRIM на случай хвостового пробела в отредактированной руками команде: без него
-- в строке оказалось бы два пробела подряд.
UPDATE `project_team`
SET `command` = CONCAT(TRIM(`command`), ' --autocompact 115k')
WHERE INSTR(`command`, 'claude-shell') > 0
  AND INSTR(`command`, '--autocompact') = 0;

-- ─── После: флаг должен стоять у всех карточек с оболочкой ────────────────────
SELECT `t`.`id`, `t`.`project_id`, `t`.`role`, `t`.`command`,
       INSTR(`t`.`command`, '--autocompact 115k') > 0 AS `has_flag`
FROM `project_team` `t`
WHERE INSTR(`t`.`command`, 'claude-shell') > 0
ORDER BY `t`.`project_id`, `t`.`id`;
