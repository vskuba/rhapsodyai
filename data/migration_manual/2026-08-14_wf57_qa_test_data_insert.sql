-- QA заводит данные INSERT-ом, а не через интерфейс (workflow #57)
--
-- Зачем вручную: правка данных (`agent_workflow_step`.`metadata`), а не схемы.
--
-- Что было: правило `2026-08-14_wf57_qa_test_data.sql` разрешило QA завести
-- недостающие данные «через интерфейс приложения или прямым INSERT» — и QA выбрал
-- интерфейс. На подзадаче #562 он создал два проекта «Test sort A» и «Test sort B»,
-- чтобы проверить порядок при равных `position`. Создание проекта — не запись строки:
-- следом поднялись два прогона workflow #19 «Анализ идеи» (агент `planning_analyzer`,
-- прогоны 447 и 448), то есть на проверку сортировки ушли два лишних прогона LLM плюс
-- строки фаз планирования, которых никто не заказывал.
--
-- Что делаем: называем предпочтительный способ прямо — INSERT. Интерфейс остаётся,
-- но только там, где проверяется сам интерфейс: если цель про поведение страницы при
-- создании, кликать по ней и надо.
--
-- Почему не запрет: сценарий «проверить форму создания» существует, и запретить UI
-- целиком значит запретить проверять половину задач. Разделяем по признаку «что
-- проверяем», а не по способу.
--
-- Идемпотентность: REPLACE ищет формулировку, которую поставила предыдущая миграция.
-- Повторный прогон её уже не найдёт и ничего не изменит. Прогонять после
-- `2026-08-14_wf57_qa_test_data.sql`.
--
-- На проде перед прогоном снять свежий бэкап через /admin/backup.

-- ─── До: строки, которые тронем ───────────────────────────────────────────────
SELECT `id`, `workflow_id`, `position`, `title`
FROM `agent_workflow_step`
WHERE `id` IN (447, 516);

-- ─── Способ заведения данных (оба промпта QA) ─────────────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    '- Нет данных под сценарий — заведи их сам: через интерфейс приложения или прямым\\n  INSERT в базу проекта.',
    '- Нет данных под сценарий — заведи их сам, прямым INSERT в базу проекта. Через\\n  интерфейс — только если проверяешь сам интерфейс: создание сущности в приложении\\n  часто тянет фоновую обработку (новый проект уходит в планирование), и на проверку\\n  сортировки уедут чужие прогоны агентов.')
WHERE `id` IN (447, 516);

-- ─── После: проверить, что правило на месте ───────────────────────────────────
SELECT `id`,
       `metadata` LIKE '%прямым INSERT в базу проекта. Через%' AS `has_rule`
FROM `agent_workflow_step`
WHERE `id` IN (447, 516);
