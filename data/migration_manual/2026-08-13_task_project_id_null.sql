-- «Без проекта» в `project_task`.`project_id` — это NULL, а не 0
--
-- Зачем вручную: правка данных, а не схемы. Колонка и так `INT DEFAULT NULL`
-- (`migrations/0001.sql`), менять её не нужно — нужно перевести уже накопленные строки.
--
-- Откуда взялись нули: страница задач передаёт «Без проекта» нулём в пути
-- (`POST /tasks/0`), и роутер до этого изменения клал этот ноль в колонку как есть.
-- Получилось два способа сказать «никакой проект», и каждый запрос вида «проект задачи
-- совпадает с проектом оболочки» приходилось писать с оговоркой на оба
-- (`task_role_project_type_sql`, список задач). Теперь запись нормализует ноль в NULL
-- (`project_task_create`, `_task_bug_insert`), и этот скрипт приводит старые строки
-- к тому же виду.
--
-- Чтение нуля код пока переживает — установку, где скрипт ещё не прогнан, это не ломает.
--
-- Локально на момент выпуска: 14 строк с `project_id = 0` из 15.
-- На проде перед прогоном сверить блоком «до» и снять свежий бэкап через /admin/backup.

-- ─── До: сколько строк тронем ─────────────────────────────────────────────────
SELECT `project_id`, COUNT(*) AS `cnt`
FROM `project_task`
GROUP BY `project_id`
ORDER BY `project_id`;

-- ─── Правка (идемпотентно: повторный прогон не найдёт ни одной строки) ─────────
UPDATE `project_task`
SET `project_id` = NULL
WHERE `project_id` = 0;

-- ─── После: нулей быть не должно ──────────────────────────────────────────────
SELECT COUNT(*) AS `zero_left`
FROM `project_task`
WHERE `project_id` = 0;
