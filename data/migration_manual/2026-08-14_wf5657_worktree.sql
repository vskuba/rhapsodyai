-- Свой рабочий каталог на подзадачу: промпты разработчика (#56) и QA (#57)
--
-- Зачем вручную: правка данных (`agent_workflow_step`.`metadata`), а не схемы.
--
-- Что было: разработчик и QA работали в общем каталоге проекта и переключали в нём
-- ветки. Один чекаут на всех — это чужая ветка под руками у человека (у задачи #492
-- ветку срезали с `feature/task_355`, потому что в каталоге была она), и проверка
-- QA на общем сервере :8011, где в этот момент может быть код вообще другой задачи.
--
-- Что стало: конвейер заводит подзадаче свой каталог `.claude/worktrees/feature_task_N`
-- с уже выкаченной веткой (`src/project/task/task_worktree.py`) и отдаёт его адрес
-- промптам переменной `subtask_work_dir`. Сервер над этим каталогом поднимает
-- `./task_server.sh up N` — отдельный uvicorn на :8013 (`subtask_server_url`).
-- Ветку в промптах теперь называет код (`subtask_branch`), а не склейка «task/N»:
-- настоящее имя ветки — `feature/task_N`, и склейка с ним расходилась.
--
-- Идемпотентность: REPLACE ищет исходную формулировку. Повторный прогон её уже не
-- найдёт и ничего не изменит.
--
-- На проде перед прогоном снять свежий бэкап через /admin/backup.

-- ─── До: строки, которые тронем ───────────────────────────────────────────────
SELECT `id`, `workflow_id`, `position`, `title`
FROM `agent_workflow_step`
WHERE `id` IN (433, 435, 445, 447, 516);

-- ─── #56, «Промпт: разбор подзадачи»: где смотреть код ────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    'Сейчас только разбор: код НЕ меняй, файлы не правь, коммитов не делай.',
    'Сейчас только разбор: код НЕ меняй, файлы не правь, коммитов не делай.\\n%if subtask_work_dir%\\nКод своей подзадачи смотри в каталоге %subtask_work_dir% — это отдельная выкладка\\nрепозитория, твоя ветка в ней уже выкачена. Начни с перехода в этот каталог.\\n%endif%')
WHERE `id` = 433;

-- ─── #56, «Промпт: реализация»: каталог вместо git checkout ───────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    '- Работаешь ТОЛЬКО в своей ветке %subtask_branch%: git checkout -b %subtask_branch%\\n  (или git checkout %subtask_branch%, если она уже есть). В master не коммитишь и\\n  master не мержишь: слияние делает человек, приняв merge request.',
    '- Работаешь ТОЛЬКО в каталоге своей подзадачи%if subtask_work_dir% %subtask_work_dir%%endif%:\\n  начни с перехода в него. Твоя ветка %subtask_branch% там уже выкачена — создавать\\n  и переключать ветки не нужно, git checkout здесь только навредит: у соседних\\n  подзадач свои каталоги, а общий чекаут держит человек. В master не коммитишь и\\n  master не мержишь: слияние делает человек, приняв merge request.')
WHERE `id` = 435;

UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    '- После правки .py перезапусти uvicorn (docker compose restart uvicorn), иначе QA\\n  проверит старый код. Правки шаблонов, JS и CSS перезапуска не требуют.',
    '- После правки .py подними сервер своей задачи: ./task_server.sh up %subtask_id%\\n  из каталога проекта — он поднимает отдельный uvicorn поверх твоего каталога, на\\n  нём же потом проверяет QA. Общий uvicorn на :8011 не трогай: на нём работает\\n  человек. Правки шаблонов, JS и CSS перезапуска не требуют.')
WHERE `id` = 435;

-- ─── #57, «Промпт: разбор изменений»: настоящее имя ветки и каталог ───────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    'Отчёта разработчика нет — изменения ищи сам: ветка task/%subtask_id%, git status, git diff.',
    'Отчёта разработчика нет — изменения ищи сам: ветка %subtask_branch%, git status, git diff.')
WHERE `id` = 445;

UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    '1. Найди сами изменения: ветка task/%subtask_id%, git diff относительно master.',
    '1. Найди сами изменения:%if subtask_work_dir% каталог подзадачи %subtask_work_dir%,%endif% ветка %subtask_branch%,\\n   git diff относительно origin/master.')
WHERE `id` = 445;

-- ─── #57, «Прогон проверок» и «Проверка цели»: где запущено приложение ────────
-- Один и тот же абзац в двух шагах — правим обоими UPDATE по одному тексту.
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    '- Проверяешь то, что отдаёт приложение: ветка разработчика выкачена в рабочем\\n  каталоге проекта, сервер запущен (обычно http://localhost:8011). Копия файла в\\n  /tmp и чтение исходника доказательством не считаются.',
    '%if subtask_work_dir%- Проверяешь то, что отдаёт приложение. Код подзадачи лежит в каталоге\\n  %subtask_work_dir%, нужная ветка в нём уже выкачена — переключать её не нужно.\\n  Сервер над этим каталогом поднимается командой ./task_server.sh up %subtask_id%\\n  из каталога проекта, адрес %subtask_server_url%. Общий :8011 доказательством не\\n  считается: на нём код основного чекаута, а не проверяемой ветки. Копия файла в\\n  /tmp и чтение исходника доказательством не считаются.%else%- Проверяешь то, что отдаёт приложение: ветка разработчика выкачена в рабочем\\n  каталоге проекта, сервер запущен (обычно http://localhost:8011). Копия файла в\\n  /tmp и чтение исходника доказательством не считаются.%endif%')
WHERE `id` IN (447, 516);

UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    '- Проверяешь ветку разработчика task/%subtask_id%, а не master.',
    '- Проверяешь ветку разработчика %subtask_branch%, а не master.')
WHERE `id` = 447;

-- ─── После: убедиться, что новые формулировки на месте ────────────────────────
SELECT `id`, `title`,
       `metadata` LIKE '%subtask_work_dir%' AS `has_work_dir`,
       `metadata` LIKE '%task_server.sh%'   AS `has_task_server`
FROM `agent_workflow_step`
WHERE `id` IN (433, 435, 445, 447, 516);
