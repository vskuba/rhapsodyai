-- Заглушки «агент недоступен» обязаны отдавать `env_ok: false`
--
-- Зачем вручную: правка данных workflow, а не схемы. Seed применяется через
-- `INSERT IGNORE` (`seed.md`) и существующие строки не обновляет — на инсталляции,
-- где шаги уже заведены, новое значение не появится ни при деплое, ни при рестарте.
--
-- Что чиним. Когда shell-оболочка не отвечает, workflow не бросает исключение, а сам
-- возвращает отчёт шагом-заглушкой: «Разработчик недоступен» (#56), «QA недоступен»
-- (#57), «Оболочка недоступна» (фикс бага). Отчёт был такой:
--
--     json:{"ok": false, "report": {}, "error": "Разработчик не ответил. Статус: ..."}
--
-- Для `_result_parse` это неотличимо от «агент поработал и не справился»: `env_ok`
-- по умолчанию `true`, и `task_pipeline` закрывает круг Developer→QA через
-- `task_state_subtask_fail`, сжигая попытку из отведённых `timeout_attempt_max`.
-- В итоге `no_session`, `timeout`, мёртвый Claude Code и «Prompt is too long»
-- приближали подзадачу к `blocked` наравне с настоящей неудачей.
--
-- С `env_ok: false` тот же ответ уходит в `_retry_subtask`: работы не было, круг не
-- закрывается, оболочка перезапускается, счётчик повторов растит `metadata.retry`
-- с потолком `timeout_retry_max`. Ровно тот путь, что уже был у проверки среды
-- (шаг 536) — см. `.claude/docs/project_task.md`, «Несостоявшийся прогон против
-- состоявшейся неудачи».
--
-- Замерено на живой установке (задача #895): девять прогонов «агент не ответил»,
-- `metadata.retry` пустой у всех подзадач, в отчёте задачи ноль строк «Перезапуск
-- оболочки и повтор N из 3» — механизм повторов не сработал ни разу.
--
-- Ищем по содержимому, а не по id: номера шагов на разных инсталляциях свои.
-- Прогон идемпотентен: отбор идёт по наличию `json:{"ok": false` в начале ответа,
-- и у поправленного шага там уже `json:{"env_ok": false, "ok": false`.
-- Правка обратима: в `metadata` меняется одна вставка в начале `prompt_user`.
--
-- Отбираем через INSTR, а не LIKE. В LIKE обратный слеш — свой escape-символ, и
-- шаблон разбирается дважды: сначала как строковый литерал, потом как шаблон. Из-за
-- второго слоя `LIKE '%json:{\\"ok%'` ищет `json:{"ok` без слеша и не находит ничего;
-- у INSTR второго слоя нет. Первая версия этого файла молча не меняла ни строки.
--
-- Шаг «Менеджер недоступен» (workflow планировщика) сюда намеренно не попадает: его
-- заглушка возвращает не отчёт, а пустой план, а пустой план у менеджера конвейер и
-- так считает несостоявшимся прогоном и уводит в `_retry_task`.
--
-- Проверено локально: откатил три шага к прежним значениям, прогнал этот файл,
-- сверил результат со значением, записанным Python-скриптом, — совпало побайтово;
-- повторный прогон данные не изменил.

-- ─── До: какие шаги поменяются ────────────────────────────────────────────────
SELECT `s`.`id`, `s`.`workflow_id`, `w`.`name` AS `workflow`, `s`.`title`,
       INSTR(`s`.`metadata`, 'json:{\\"ok\\": false') > 0 AS `will_change`
FROM `agent_workflow_step` `s`
         LEFT JOIN `agent_workflow` `w` ON `w`.`id` = `s`.`workflow_id`
WHERE INSTR(`s`.`metadata`, 'не ответил') > 0
ORDER BY `s`.`id`;

-- ─── Правка ───────────────────────────────────────────────────────────────────
-- В колонке лежит JSON, внутри него `prompt_user` со своим экранированным JSON.
-- Двойной слеш здесь — экранирование строкового литерала: в данных слеш один.
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(`metadata`,
                         'json:{\\"ok\\": false',
                         'json:{\\"env_ok\\": false, \\"ok\\": false')
WHERE INSTR(`metadata`, 'не ответил') > 0
  AND INSTR(`metadata`, 'json:{\\"ok\\": false') > 0;

-- ─── После: у трёх заглушек ролей должно стоять env_ok ────────────────────────
SELECT `s`.`id`, `s`.`title`,
       INSTR(`s`.`metadata`, '\\"env_ok\\": false') > 0 AS `has_env_ok`,
       SUBSTRING(`s`.`metadata`, 1, 120) AS `head`
FROM `agent_workflow_step` `s`
WHERE INSTR(`s`.`metadata`, 'не ответил') > 0
ORDER BY `s`.`id`;
