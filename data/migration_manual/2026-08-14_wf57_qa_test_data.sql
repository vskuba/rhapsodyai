-- QA заводит данные под сценарий, если их нет (workflow #57)
--
-- Зачем вручную: правка данных (`agent_workflow_step`.`metadata`), а не схемы.
--
-- Что было: цель подзадачи #562 «проекты с одинаковым position идут по возрастанию
-- id» QA закрыть не смог и записал причину: «в БД всего 2 проекта с разными position,
-- вставлять тестовые данные нельзя, правила запрещают менять состояние приложения».
-- Прочтение верное по букве: в промпте есть «рабочее дерево не меняешь», а про данные
-- не сказано ничего. Итог — цель осталась открытой, движок вернул подзадачу
-- разработчику (`Цели не закрыты` → `Проверки не прошли`), но чинить там нечего: код
-- правильный, не хватало второй строки в таблице. Следующий круг разработчика и QA
-- упрётся туда же, и так до лимита кругов.
--
-- Что делаем: разрешаем завести недостающие данные и требуем убрать за собой. Запрет
-- на правки — про код и рабочее дерево, а не про содержимое таблиц: сценарий «две
-- строки с одинаковым position» иначе не воспроизвести ничем.
--
-- Границы оставляем жёсткими: только свои строки, чужие не трогать, прод не трогать.
-- Удалять или править существующие записи QA по-прежнему нельзя — это данные человека,
-- а не тестовый стенд.
--
-- Идемпотентность: REPLACE ищет исходную формулировку. Повторный прогон её уже не
-- найдёт и ничего не изменит.
--
-- На проде перед прогоном снять свежий бэкап через /admin/backup.

-- ─── До: строки, которые тронем ───────────────────────────────────────────────
SELECT `id`, `workflow_id`, `position`, `title`
FROM `agent_workflow_step`
WHERE `id` IN (447, 516);

-- ─── Подготовка данных под сценарий (оба промпта QA) ──────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    '- Не удалось воспроизвести — так и пиши: проверка не сделана.',
    '- Нет данных под сценарий — заведи их сам: через интерфейс приложения или прямым\\n  INSERT в базу проекта. Это разрешено: запрет на правки касается кода и рабочего\\n  дерева, а не содержимого таблиц. После проверки удали ровно то, что завёл.\\n  Чужие строки не правишь и не удаляешь — они принадлежат человеку, а не стенду.\\n- Не удалось воспроизвести — так и пиши: проверка не сделана.')
WHERE `id` IN (447, 516);

-- ─── После: проверить, что правило на месте ───────────────────────────────────
SELECT `id`,
       `metadata` LIKE '%заведи их сам%' AS `has_rule`
FROM `agent_workflow_step`
WHERE `id` IN (447, 516);
