-- Короткие текстовые ответы разработчика и QA (workflow #56, #57)
--
-- Зачем вручную: правка данных (`agent_workflow_step`.`metadata`), а не схемы.
--
-- Что было: текстовые ходы конвейера отвечают отчётом на страницу — заголовки,
-- markdown-таблицы, эмодзи. Разбор QA по подзадаче #562 (правка одной строки
-- `ORDER BY`) занял 176с и вернул таблицу соответствия плану со значками и тремя
-- разделами. Дело не только в этих 176с: ответ хода целиком подставляется в промпт
-- следующего хода (`%dev_recon%`, `%qa_recon%`, `%qa_report_json%`), поэтому каждая
-- лишняя строка разбора оплачивается ещё раз — на прогоне проверок, а потом на
-- вердикте.
--
-- Что делаем: в трёх текстовых ходах просим короткий ответ и запрещаем оформление.
-- Ровно там, где ответ идёт дальше по цепочке:
--   #56 id 433 — разбор подзадачи разработчиком (уходит в промпт реализации);
--   #57 id 445 — разбор изменений QA (уходит в промпт прогона проверок);
--   #57 id 447 — прогон проверок QA (уходит в отчёт и в вердикт).
-- Ходы, где просят JSON, не трогаем: там формат задан схемой ответа.
--
-- Чего не делаем: не сокращаем сами правила проверки. Короче должен стать отчёт
-- агента, а не работа — «синтаксис чистый» вместо прогона стоит дороже лишних строк.
--
-- Идемпотентность: REPLACE ищет исходную формулировку. Повторный прогон её уже не
-- найдёт и ничего не изменит.
--
-- На проде перед прогоном снять свежий бэкап через /admin/backup.

-- ─── До: строки, которые тронем ───────────────────────────────────────────────
SELECT `id`, `workflow_id`, `position`, `title`
FROM `agent_workflow_step`
WHERE `id` IN (433, 445, 447);

-- ─── #56 Промпт: разбор подзадачи ─────────────────────────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    'Отвечай обычным текстом: сначала разбор — файлы, паттерны и правила проекта,\\nна которые опираешься; затем ход работы по шагам: файл — что меняю — чем проверю.\\nJSON сейчас не нужен.',
    'Отвечай обычным текстом: сначала разбор — файлы, паттерны и правила проекта,\\nна которые опираешься; затем ход работы по шагам: файл — что меняю — чем проверю.\\nJSON сейчас не нужен.\\n\\nКоротко: не длиннее 15 строк, строка на мысль. Без заголовков, таблиц и значков —\\nэтот ответ целиком уходит в следующий промпт, и каждая лишняя строка там читается\\nзаново. Пересказывать прочитанный код не нужно, назови путь и строку.')
WHERE `id` = 433;

-- ─── #57 Промпт: разбор изменений ─────────────────────────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    'Отвечай обычным текстом: сначала изменённые файлы и что в них поменялось,\\nзатем проверки по пунктам — что запускаю и что считаю успехом. JSON сейчас не нужен.',
    'Отвечай обычным текстом: сначала изменённые файлы и что в них поменялось,\\nзатем проверки по пунктам — что запускаю и что считаю успехом. JSON сейчас не нужен.\\n\\nКоротко: не длиннее 15 строк, строка на файл и строка на проверку. Без заголовков,\\nтаблиц и значков — этот ответ целиком уходит в следующий промпт. Код не пересказывай,\\nназывай путь и строку.')
WHERE `id` = 445;

-- ─── #57 Промпт: прогон проверок ──────────────────────────────────────────────
UPDATE `agent_workflow_step`
SET `metadata` = REPLACE(
    `metadata`,
    'Отвечай обычным текстом. JSON я попрошу отдельным шагом — сейчас его не пиши.',
    'Отвечай обычным текстом, по строке на проверку: «команда — результат». Без\\nзаголовков, таблиц и значков, без пересказа кода. Замечания разработчику — отдельным\\nсписком в конце, по пункту на замечание. JSON я попрошу отдельным шагом — сейчас его\\nне пиши.')
WHERE `id` = 447;

-- ─── После: проверить, что правила на месте ───────────────────────────────────
SELECT `id`,
       `metadata` LIKE '%строка на мысль%'        AS `has_rule_433`,
       `metadata` LIKE '%строка на файл%'         AS `has_rule_445`,
       `metadata` LIKE '%по строке на проверку%'  AS `has_rule_447`
FROM `agent_workflow_step`
WHERE `id` IN (433, 445, 447);
