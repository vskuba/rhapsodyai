/**
 * Дороги веток: какие подпотоки кто-то зовёт своей дорогой.
 *
 * ## ⚠⚠ Вопрос здесь ОБРАТНЫЙ, и потому модуль существует
 *
 * «Какая дорога у этого шага» спрашивать не надо — она лежит в метаданных самого
 * шага, и граф читает её там же, где движок. Здесь отвечают на другое: **этот
 * workflow — он чья-то дорога?** Ответ на это лежит в ЧУЖИХ шагах, в других
 * workflow, которых страница не грузит; собрать его может только сервер
 * (`/workflow_topic/road/list`).
 *
 * Спрашивают двое, и оба про одно: список переменных — показывать ли группу
 * «🌿 Branch переменные», и сторож «Undefined» — снимать ли с `topic_*` красный.
 *
 * ⚠ Прежде источником был реестр веток (`branch.workflow_id`), и карта была
 * «ветка → подпоток». Дорога переехала на шаг, и у ветки спрашивать стало нечего.
 *
 * ## ⚠⚠ Реестр один на страницу, и читается ДО первой отрисовки списка
 *
 * Прежде он читался по ноде и при каждом открытии workflow **перетирался**. Левая
 * колонка рисуется раньше, чем откроется первый workflow, — и на холодной
 * перезагрузке рисовалась с пустым реестром: у подпотока-дороги все живые
 * `topic_action_*` оказывались «нигде не заведены», и он получал красный «!».
 * Стоило ткнуть в этот подпоток — реестр к тому времени был уже прочитан, кэш
 * сторожа сбрасывался, и значок пропадал. То есть значок говорил не про поломку,
 * а про то, во что успели ткнуть; а значку, который врёт, перестают верить и
 * тогда, когда он прав.
 *
 * ⚠ Отсюда: `topicRoadsLoad()` — **без ноды и один раз за жизнь страницы**
 * (повторный зов отдаёт тот же промис). Нода тут и не нужна: карусель слева
 * листает их все, и дорога соседней ноды нужна списку ровно так же, как дорога
 * открытой. Дороги изменились на самой странице — `topicRoadsReload()`.
 *
 * ## ⚠⚠ Почему отдельным файлом, а не внутри `branch.js`
 *
 * Карту читает `variable-undefined.js`, а его **гоняют тестами через node**
 * (`tests/test_workflow_undefined_index.py` и соседние — 23 теста). Лежи карта
 * во вкладке, импорт потянул бы за собой `/static/js/notification.js` — путь
 * браузерной раздачи, которого в node нет вовсе, и все 23 падали бы на
 * `ERR_MODULE_NOT_FOUND`. Так и случилось, пока файл был один.
 *
 * ⚠ Отсюда правило для этого модуля: **никаких импортов**. `fetch` — глобальный
 * и в браузере, и в node; больше ничего здесь быть не должно.
 */

const roads = {workflowIds: new Set()};

let _loadPromise = null;

/**
 * Прочитать дороги всей установки. Молчит при отказе: нет ответа — нет и дорог.
 *
 * Returns:
 *     Promise: тот же, что и у первого зова, — сеть беспокоят один раз. Сбой не
 *     запоминается: следующий зов пробует снова.
 */
export function topicRoadsLoad() {
    if (!_loadPromise) {
        _loadPromise = fetch('/workflow_topic/road/list')
            .then(response => response.json())
            .then(body => {
                roads.workflowIds = new Set((body.result || []).map(String));
            })
            .catch(() => {
                // Ответа нет — ни группы, ни снятия красного, а страница работает дальше
                _loadPromise = null;
            });
    }
    return _loadPromise;
}

/** Перечитать реестр: дорогу шага правили на этой же странице. */
export function topicRoadsReload() {
    _loadPromise = null;
    return topicRoadsLoad();
}

/** Этот workflow — дорога какого-нибудь шага `branch`? */
export function topicRoadIs(workflowId) {
    return roads.workflowIds.has(String(workflowId));
}
