// Лестница отступов по вложенности `[<if …>]` и `[<for …>]`.
//
// Промпт на четыре тысячи знаков с десятком условий читается как простыня: где
// кончается внешний блок и начинается соседний, видно только пересчётом
// `[<endif>]` сверху вниз. Отступ отвечает на тот же вопрос формой строки —
// глазу, без счёта.
//
// ⚠⚠ Это **переписывание текста**, а не показ. Пробелы уедут в модель вместе с
// промптом: окно пишет значение в поле шага, а страница его сохраняет. Для
// промпта это безобидно — пробел в начале строки модель не читает смыслом, —
// но внутри `[<for …>]…[<endfor>]` отступ попадёт в **каждый** виток списка, и
// нумерованная простыня станет нумерованной простынёй с полями. Если это
// однажды помешает, лечится переносом тела цикла к левому краю: своего отступа
// лестница не навяжет, см. ниже про «шире нужного».
//
// ⚠ Отступ считается **только** по блокам разметки. `[<set …>]` вложенности не
// заводит — это действие, а не блок, — и на лестницу не влияет.

import {TEXT_MODAL_BLOCK_RE} from './text-modal-syntax.js';

// Ширина ступени. Четыре пробела, как в Python и в самих шаблонах проекта: два
// теряются на фоне `[<`, восемь уводят глубокий блок за середину окна.
//
// ⚠ Наружу вынесена ради направляющих в подсветке (`text-modal.js`): черта
// уровня рисуется ровно по ступени, и разойдись два числа — черта встала бы
// мимо отступа, который сама же и размечает.
export const TEXT_INDENT_STEP = 4;


/** Расставляет отступы по вложенности блоков разметки.
 *
 * Строка корневого уровня остаётся как была, строка внутри блока отодвигается
 * на ступень за каждый блок вокруг неё — вместе с содержимым:
 *
 *     [<if mail_mode>]
 *         [<if talk_history_mail>]=== Correspondence ===
 *             %talk_history_mail%
 *         [<endif>]
 *     [<else>]
 *         …
 *     [<endif>]
 *
 * ⚠ `[<else>]` и `[<endif>]` печатаются на ступень левее своего содержимого:
 * они про **границу** блока, и встань они вровень с нутром — граница пропала бы
 * из виду ровно там, где её и ищут.
 *
 * ⚠⚠ Лестница **не сужает** отступ, который уже шире нужного. Иначе она
 * сносила бы чужую разметку внутри промпта — образец JSON, список, кусок кода, —
 * а это не пробелы, это смысл. Платой идёт застарелый отступ: снимешь
 * `[<if …>]` снаружи — нутро останется отодвинутым. Лечится руками (убрать
 * пробелы и открыть окно снова), и это дешевле потерянного образца.
 *
 * ⚠ Текст без единого блока возвращается **байт в байт**: окно открывают и над
 * обычными полями шага, и трогать их незачем.
 *
 * @param {string} text Текст поля как есть.
 * @returns {string} Тот же текст с лестницей отступов.
 */
export function textIndentFormat(text) {
    const source = String(text ?? '');
    const out = [];

    let depth = 0;
    let seen = 0;

    for (const line of source.split('\n')) {
        const body = line.replace(/^[ \t]+/, '');

        // Пустая строка остаётся пустой: отступ на ней не виден никому, а
        // хвостовые пробелы потом ловятся глазами в diff'е как правка.
        if (!body) {
            out.push('');
            continue;
        }

        const tags = [...body.matchAll(TEXT_MODAL_BLOCK_RE)];
        seen += tags.length;

        // ⚠ Левее на ступень — только если закрывающая метка **начинает**
        // строку. `…текст[<endif>]` закрывает блок там же, где текст, и
        // двигать эту строку значило бы оторвать её от текста, к которому она
        // приклеена.
        const first = tags[0];
        const edge = Boolean(first) && first.index === 0 && Boolean(first[2]);
        const need = TEXT_INDENT_STEP * (edge ? Math.max(0, depth - 1) : depth);

        const lead = line.length - body.length;
        out.push(lead >= need ? line : ' '.repeat(need) + body);

        for (const tag of tags) {
            if (tag[1]) depth += 1;
            // ⚠ `[<else>]` глубины не меняет: это середина блока, а не его
            // конец. Левее она уже сдвинута выше, как граница.
            else if (tag[2] !== 'else') depth = Math.max(0, depth - 1);
        }
    }

    return seen ? out.join('\n') : source;
}
