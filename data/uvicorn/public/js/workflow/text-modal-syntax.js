// Разметка блоков `[<…>]` — одним объявлением на всех, кто её читает в браузере.
//
// Читают двое: подсветка (`text-modal.js`) и лестница отступов
// (`text-indent.js`). Третьего быть не должно — не из опрятности, а потому что
// копии этого правила уже расходились: условие пишут то как «всё, кроме `>`»,
// то как нежадное `.+?`, и обе записи ломаются (`ai_workflow.py`, шапка).
//
// ⚠⚠ Источник правды — **движок** (`src/ai/ai_workflow.py`): здесь его повтор
// для браузера, и расхождение означает, что окно показывает одно, а модель
// получает другое. Менять эти строки, не сверившись с `WORKFLOW_IF_BLOCK_RE`,
// нельзя.

// Нутро открывающей метки: условие, заголовок цикла или присваивание.
//
// ⚠⚠⚠ «Любой знак, кроме `>` перед `]` и кроме `[`» — ни «всё кроме `>`», ни
// `.+?` здесь не годятся:
//
//     [^>]+     ломает сравнение: `[<if count > 5>]` обрывается на операторе
//     .+?       перескакивает через `>]` к следующему и съедает чужой блок
//
// `>` разрешён, только если за ним не `]`. Запрет `[` держит условие внутри
// своей метки.
export const TEXT_MODAL_COND_SRC = '(?:[^>\\[]|>(?!\\]))+?';

// Метки, заводящие вложенность. ⚠ `[<set …>]` сюда не входит намеренно: это
// действие внутри строки, а не блок, и глубины оно не меняет.
//
// Группа 1 — открывающая метка (`if`, `for`), группа 2 — закрывающая или
// `[<else>]`. По ним читающий и решает, в какую сторону шагнуть.
export const TEXT_MODAL_BLOCK_RE = new RegExp(
    '\\[<\\s*(if|for)\\s+' + TEXT_MODAL_COND_SRC + '\\s*>\\]'
    + '|\\[<\\s*(else|endif|endfor)\\s*>\\]',
    'g');

// Заголовок секции промпта: `=== Current time ===`.
//
// ⚠ Движок о нём не знает и знать не должен — это не разметка, а соглашение
// того, кто пишет промпт: так человек делит задание на части, и так же его
// читает модель. Подсветка здесь единственная, кто может сделать деление
// видимым.
//
// ⚠⚠ Заголовок ловится **куском строки, а не строкой целиком**: в живых
// промптах он сплошь и рядом сросся с разметкой —
// `[<if prompt_user>]=== %companion_title% writes ===`. Запрет `[` внутри
// держит заголовок по свою сторону от метки блока.
export const TEXT_MODAL_HEAD_RE = /===(?:[^=\n[]|=(?!==))+===/g;

// Прежние синтаксисы блока. ⚠⚠ Список — **копия движка**
// (`WORKFLOW_BLOCK_OLD` в `ai_workflow.py`), и это тот редкий случай, когда
// копия оправдана: там она ловит остаток уже на прогоне, здесь — в редакторе,
// до сохранения. Разойдись они — редактор промолчит о том, на чём прогон
// откажет.
//
// ⚠ `%if ` и `[[if ` — с пробелом: имя условия от них неотделимо, а `%ifx%`
// это обычная метка.
export const TEXT_MODAL_OLD_RE =
    /%if\s[^%\n]*%|%else%|%endif%|\[\[if\s[^\]\n]*\]\]|\[\[else\]\]|\[\[endif\]\]/g;

// Связки, которых у движка нет. ⚠ Это **примета, а не разбор условия**:
// `&&` и `||` движок не понимает ни в каком виде, и блок с ними уедет в модель
// словами целиком (`[<if a && b>]` — пример прямо в `workflow.md`). Разбирать
// условие здесь нельзя — третья копия правила разойдётся с двумя первыми.
export const TEXT_MODAL_BAD_OP_RE = /&&|\|\|/;
