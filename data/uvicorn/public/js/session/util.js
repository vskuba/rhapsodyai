// Мелочь, общая двум вкладкам страницы «Сессии». Сети здесь нет: всё нужное
// приходит аргументами, наружу уходит строка или готовый `<select>`.
//
// Своей копии в каждой вкладке эти функции не заводят: экранирование,
// повторённое дважды, рано или поздно расходится в одной из копий — и
// расхождение заметно не как ошибка, а как «у одной вкладки текст поехал».
//
// ⚠ Исключение из «ни состояния» одно — пара `filterSave`/`filterLoad`: память
// страницы. Она здесь ровно по тому же доводу: вкладки запоминали свой выбор
// каждая сама, и хранилище у них разъехалось с тем, где лежит выбранная
// подвкладка (`main.js`), — см. докстринг `filterSave`.

// Приставка хранилища. Общая, чтобы всю память страницы было видно одним
// `localStorage` в консоли и чтобы чистить её можно было разом.
const SESSION_STORE_PREFIX = 'session_';

/** Запомнить выбор человека. Значение — строка; пустая строка это ВЫБОР.
 *
 * Через эту дверь идёт вся память страницы: выбранная подвкладка
 * (`session_tab`), отборы обеих вкладок и открытый разговор «Чата».
 *
 * ## ⚠⚠ `localStorage`, а не `sessionStorage`, и это правка по жалобе
 *
 * Сперва отборы обеих вкладок лежали в `sessionStorage`. Перезагрузку страницы
 * (`F5`) он переживает, и выглядело это работающим — но хранилище у него своё
 * **на каждую вкладку браузера**: открой «Сессии» в новой вкладке или закрой
 * браузер, и отбор возвращается к умолчанию шаблона. При этом выбранная
 * подвкладка («Агенты» / «Чат») запоминалась в `localStorage` (`main.js`) —
 * то есть страница открывалась там, где её оставили, но с чужим отбором.
 *
 * Отбор здесь — это рабочая постановка, а не случайность одной вкладки: человек
 * выбирает свою сторону и собеседника, чтобы смотреть на них днями. Сроком
 * жизни он равен выбору подвкладки, и держать их в разных хранилищах значит
 * обещать память и отдавать половину.
 *
 * ⚠ Долгая память требует проверки при чтении — её делает `selectValueRestore`:
 * запомненного агента или собеседника могли удалить, и присвоение
 * несуществующего значения молча сбрасывает `<select>` в первый вариант.
 */
export function filterSave(key, value) {
    localStorage.setItem(SESSION_STORE_PREFIX + key, value);
}

/** Запомненное значение или `null`, если ничего не запоминали.
 *
 * ⚠⚠ Разница между `null` и пустой строкой здесь значащая: пустая строка — это
 * выбор «любая доставка» / «все каналы», `null` — «человек тут ничего не
 * выбирал». Склей их, и снятый отбор возвращался бы умолчанием шаблона;
 * подробнее — в `selectValueRestore`.
 */
export function filterLoad(key) {
    return localStorage.getItem(SESSION_STORE_PREFIX + key);
}

/** Текст, пригодный для вставки в `innerHTML`.
 *
 * ⚠⚠ Содержимое сессии — это ответы модели, промпты и реплики людей: в них
 * бывает и разметка, и кавычки. Без экранирования такой текст не «показывается
 * как есть», а разбирается браузером: лента рвётся на первом же `<` и
 * проглатывает всё до следующего `>`.
 */
export function htmlEscape(value) {
    return String(value ?? '')
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;');
}

/** Заполнить `<select>` списком `[{value, text, title}]` заново.
 *
 * `title` необязателен — это подсказка при наведении. Нужна там, где видимые
 * названия повторяются: заголовок записи `companion` не уникален, и без
 * подсказки с ключом два разных варианта выглядят одним.
 */
export function selectFill(select, items) {
    select.innerHTML = '';
    items.forEach(item => {
        const option = new Option(item.text, item.value);

        if (item.title) option.title = item.title;

        select.add(option);
    });
}

/** Выставить значение, если такой вариант есть. Вернёт — получилось ли.
 *
 * ⚠ Проверка обязательна: запомненный отбор мог остаться с прошлого захода, а
 * агента или собеседника с тех пор удалили. Присвоение несуществующего
 * значения молча сбрасывает `<select>` в первый вариант, и человек видит не
 * тот отбор, который видит скрипт.
 *
 * ⚠⚠ Пустая строка — это ВЫБОР («любая доставка», «все каналы»), а `null` —
 * «ничего не запомнено». Отбрось здесь пустую строку как ложь, и отбор, у
 * которого умолчание не первый вариант, терял бы снятие: выбрали «любая»,
 * перезашли — вернулось умолчание шаблона.
 */
export function selectValueRestore(select, value) {
    if (value == null) return false;

    const found = [...select.options].some(one => one.value === value);

    if (found) select.value = value;

    return found;
}

/** Время в списке: `ЧЧ:ММ ДД-ММ-ГГГГ` — сперва часы, потом дата.
 *
 * В ленте и в шапке время стоит машинным порядком (`ГГГГ-ММ-ДД ЧЧ:ММ`): там
 * его читают как метку. В списке иначе — там выбирают разговор, и первый
 * вопрос «во сколько», а год почти всегда сегодняшний.
 *
 * ⚠ Считает не сама, а переставляет готовый ответ `fmtTz`: пояс берётся из
 * настройки `timezone`, и второй расчёт смещения разошёлся бы с первым на
 * первой же правке. Нераспознанное `fmtTz` отдаёт прочерком — его и вернём.
 */
export function stampList(value) {
    const [date, time] = String(fmtTz(value)).split(' ');

    if (!time) return date;

    const [year, month, day] = date.split('-');

    return `${time} ${day}-${month}-${year}`;
}

/** Обрезать подпись до `max` знаков, пометив обрез многоточием.
 *
 * ⚠⚠ Нужна потому, что `<select>` обрезает длинный вариант САМ — справа и без
 * многоточия. Обрезанное имя при этом выглядит как целое, а всё, что стояло за
 * ним (счётчик сообщений), пропадает молча. Явный обрез оставляет хвост строки
 * на месте и честно говорит, что имя длиннее; целиком оно есть в подсказке.
 */
export function labelClip(text, max) {
    const value = String(text ?? '');

    return value.length > max ? `${value.slice(0, max - 1)}…` : value;
}

/** Целое из значения `<select>`; не число — ноль.
 *
 * ⚠ Ноль здесь значит «отбор снят»: пустая строка в `value` — это вариант
 * «Все», и вызывающий превращает ноль в `null` для запроса.
 */
export function numberOf(value) {
    const number = parseInt(value, 10);

    return isNaN(number) ? 0 : number;
}

/** Сумма числового поля по строкам — счётчик для варианта «Все».
 *
 * ⚠ Поле приходит аргументом, потому что считают разное: у вкладки «Агенты»
 * это `sessions` (сколько сессий у пары), у «Чата» — `exchange_count`
 * (сколько обменов у разговора). Правило сложения одно, и держать его двумя
 * копиями значит однажды поправить одну.
 */
export function sumOf(rows, field) {
    return rows.reduce((sum, one) => sum + Number(one[field] || 0), 0);
}

/** Имя записи для списка: заголовок, иначе ключ, иначе номер.
 *
 * ⚠ Пустой номер — это «поля в строке нет» (`user_id` у сессии от соседнего
 * сервиса, например), и прочерк честнее, чем `#null`. Запись не нашлась при
 * непустом номере — показываем номер: удалённого агента в журнале видно, и
 * прятать его за прочерком значило бы терять след.
 */
export function labelOf(entity, id) {
    if (!id) return '—';

    if (!entity) return `#${id}`;

    return entity.title || entity.name || entity.unique_id || entity.username
        || `#${id}`;
}

/** Слово в числе по счёту: `pluralOf(1, 'намерение', 'намерения', 'намерений')`.
 *
 * ⚠ Формы приходят доводами, а не зашиты: правило счёта одно на язык, а слов
 * много. Третье такое место (у жребия своё `_optionsWord`, приватное в чужой
 * подсистеме) — повод вынести именно **правило**, оставив слова вызывающему.
 *
 * ⚠⚠ Одиннадцать–четырнадцать проверяются ПЕРВЫМИ: по последней цифре они
 * выглядят как «1», «2», «3», и без этой ветки получилось бы «11 намерение».
 */
export function pluralOf(qty, one, few, many) {
    const tail100 = Math.abs(qty) % 100;
    const tail10 = Math.abs(qty) % 10;

    if (tail100 > 10 && tail100 < 20) return many;
    if (tail10 === 1) return one;
    if (tail10 > 1 && tail10 < 5) return few;

    return many;
}
